TEST(Zip_archive_is_recognized_by_content) {
    const std::string good = WriteFixture("good.zip", kGoodZip, sizeof(kGoodZip));
    CHECK_TRUE(sage::assets::IsZip(good));

    // По СОДЕРЖИМОМУ, а не по расширению: тот же архив приезжает и как .zip, и
    // без расширения вовсе, а обычный текст с именем .zip архивом не является.
    const std::string notZip = WriteFixture("plain.zip", (const unsigned char*)"not an archive", 14);
    CHECK_TRUE(!sage::assets::IsZip(notZip));
    std::remove(good.c_str());
    std::remove(notZip.c_str());
}

TEST(Zip_unpacks_files_and_nested_folders) {
    const std::string good = WriteFixture("unpack.zip", kGoodZip, sizeof(kGoodZip));
    const fs::path dest = fs::temp_directory_path() / "sage_test_unpack_dir";
    std::error_code ec;
    fs::remove_all(dest, ec);

    std::string err;
    const int written = sage::assets::ExtractZip(good, dest, err);
    CHECK_EQ(written, 2);
    CHECK_TRUE(err.empty());
    CHECK_TRUE(fs::exists(dest / "readme.txt"));
    // Вложенная папка создаётся сама: без этого текстуры модели легли бы рядом
    // с ней, и ссылка «tex/wall.png» перестала бы вести куда надо.
    CHECK_TRUE(fs::exists(dest / "tex" / "wall.txt"));
    CHECK_EQ(ReadAll(dest / "readme.txt"), std::string("hello sage"));

    fs::remove_all(dest, ec);
    std::remove(good.c_str());
}

// ЗАПИСЬ, ВЫХОДЯЩАЯ ЗА ПАПКУ НАЗНАЧЕНИЯ, НЕ РАСПАКОВЫВАЕТСЯ.
//
// Имя внутри архива придумал не тот, кто его вносит: «../escaped.txt»
// распаковался бы ПОВЕРХ файла рядом с папкой проекта (zip slip). Остальные
// записи при этом обязаны доехать: чаще это мусор архиватора, а не нападение,
// и отказывать из-за него во всём архиве значит наказывать не того.
TEST(Zip_refuses_to_escape_the_destination_folder) {
    const std::string evil = WriteFixture("evil.zip", kEvilZip, sizeof(kEvilZip));
    const fs::path base = fs::temp_directory_path() / "sage_test_evil_base";
    const fs::path dest = base / "inside";
    std::error_code ec;
    fs::remove_all(base, ec);
    fs::create_directories(dest, ec);

    std::string err;
    std::vector<std::string> skipped;
    const int written = sage::assets::ExtractZip(evil, dest, err, &skipped);
    CHECK_EQ(written, 1);                       // доехал только ok.txt
    CHECK_EQ(skipped.size(), (size_t)1);
    CHECK_TRUE(fs::exists(dest / "ok.txt"));
    CHECK_TRUE(!fs::exists(base / "escaped.txt"));   // наружу не вышли
    CHECK_TRUE(!fs::exists(dest / "escaped.txt"));

    fs::remove_all(base, ec);
    std::remove(evil.c_str());
}
