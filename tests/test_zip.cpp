// Пишет встроенный архив во временный файл и отдаёт путь.
std::string WriteFixture(const char* name, const unsigned char* bytes, size_t size) {
    const fs::path p = fs::temp_directory_path() / (std::string("sage_test_") + name);
    std::ofstream out(p, std::ios::binary);
    out.write(reinterpret_cast<const char*>(bytes), (std::streamsize)size);
    out.close();
    return p.string();
}

std::string ReadAll(const fs::path& p) {
    std::ifstream in(p, std::ios::binary);
    return std::string((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
}

