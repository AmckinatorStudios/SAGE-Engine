#pragma once
#include <string>
#include <vector>

// ---------------------------------------------------------------------------
// Эталонные кадры (golden images) — единственный вид тестов, который проверяет
// КАРТИНКУ, а не логику.
//
// Зачем отдельно от sage_tests: 128 обычных тестов проверяют математику,
// сериализацию и анимацию — то есть всё, кроме того, ради чего движок написан.
// Ошибка в шейдере (перепутанный канал, потерянный множитель, съехавшая
// гамма) не роняет ни один из них: код собирается, значения считаются, а кадр
// выглядит иначе. Ловится это только сравнением с образцом.
//
// Как устроено: сцена/проход рисуется в offscreen-буфер фиксированного размера,
// пиксели читаются и сравниваются с PNG из tests/render/references.
//
// ЧЕСТНОЕ ОГРАНИЧЕНИЕ. Разные драйверы и видеокарты дают чуть разные пиксели
// (порядок операций с плавающей точкой, фильтрация, точность). Поэтому:
//   • сравнение идёт с ДОПУСКОМ по средней и максимальной разнице, а не побитно;
//   • эталоны сгенерированы программным рендерером (llvmpipe/Mesa) — тем же,
//     что стоит на CI-раннере, где тест и является обязательным;
//   • на машине с другой видеокартой тест может показать расхождение, которое
//     не является регрессией. Поэтому он собирается отдельной целью и не входит
//     в обычный `ctest` по умолчанию — см. SAGE_BUILD_RENDER_TESTS.
//
// Эталоны обновляются осознанно: `sage_render_tests --update` перезаписывает
// PNG. Делать это следует, только когда картинка изменилась НАМЕРЕННО, и diff
// эталонов в коммите — это ровно то место, где такое изменение видно ревьюеру.
// ---------------------------------------------------------------------------
namespace sage::rendertest {

// Результат сравнения кадра с эталоном.
struct Comparison {
    bool ReferenceExisted = false;
    double MeanDiff = 0.0; // средняя разница по каналам, 0..255
    int MaxDiff = 0;       // худший канал одного пикселя, 0..255
    double DiffFraction = 0.0; // доля пикселей, отличающихся заметно (>2/255)
};

// Кадр в памяти: RGB, слева направо и СВЕРХУ вниз (в отличие от того, как
// отдаёт GPU, — переворот делает Capture).
struct Image {
    int Width = 0;
    int Height = 0;
    std::vector<unsigned char> Pixels; // размер = Width*Height*3

    bool Empty() const { return Pixels.empty(); }
};

// Читает текущий привязанный буфер в Image (с переворотом строк).
Image Capture(int width, int height);

bool SavePng(const std::string& path, const Image& image);
bool LoadPng(const std::string& path, Image& out);

// Сравнивает кадр с эталоном по имени теста. Если эталона нет ИЛИ включён
// режим обновления — пишет его и возвращает ReferenceExisted=false.
// При расхождении рядом с эталоном кладётся <name>.actual.png и <name>.diff.png,
// чтобы было что посмотреть, а не только цифру в логе.
Comparison CompareWithReference(const std::string& name, const Image& image);

// Каталог эталонов (tests/render/references) и режим обновления.
void SetReferenceDir(const std::string& dir);
void SetUpdateMode(bool update);
bool UpdateMode();

} // namespace sage::rendertest
