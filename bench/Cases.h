#pragma once
#include <functional>

// ---------------------------------------------------------------------------
// Один замер: имя, что считается единицей, сколько их за прогон и само тело.
//
// Items/Unit нужны не для красоты. «12 мс» не сравнить ни с чем; «84 нс на
// сущность» сравнивается и с прошлым запуском, и со здравым смыслом — сразу
// видно, разумная это цифра или там что-то лишнее на каждый элемент.
// ---------------------------------------------------------------------------
namespace sage::bench {

using Body = std::function<void()>;

struct Case {
    const char* Name;
    const char* Unit;
    long long Items;   // 0 — стоимость на единицу не считается
    Body Run;
};

void Register(const char* name, const char* unit, long long items, Body body);

// Регистрация всех замеров. Явным вызовом, а не статическими объектами:
// порядок инициализации статиков между единицами трансляции не определён, и
// набор замеров зависел бы от порядка линковки.
void RegisterAllCases();

} // namespace sage::bench
