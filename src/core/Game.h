#pragma once

class Engine;

// ---------------------------------------------------------------------
// Game — интерфейс игры, который «крутит» движок. Это и есть ГЛАВНЫЙ ШОВ
// между движком и конкретной игрой: движок (класс Engine) владеет окном,
// главным циклом и таймингом и вызывает эти хуки в нужном порядке, но НИЧЕГО
// не знает о самой игре — только об этом интерфейсе. Чтобы сделать другую
// игру на SAGE Engine, реализуешь Game и запускаешь тем же Engine::Run(),
// не трогая ни строчки кода движка.
//
// Часть ЯДРА движка. Пример реализации — src/game/TheBoat.* (игра The Boat).
//
// Порядок вызовов за жизнь приложения:
//   OnStart(engine)                 — один раз, окно/GL-контекст уже созданы
//   каждый кадр:
//     OnUpdate(engine, dt)          — реакция на ввод (уже опрошен движком) + симуляция
//     OnRender(engine)              — отрисовка кадра (сцена + UI)
//   OnShutdown(engine)              — один раз при выходе, окно/GL-контекст ещё живы
//
// Разделение OnUpdate/OnRender намеренное: сначала полностью считается кадр
// логики, затем полностью рисуется — как это и было в исходном цикле игры.
// ---------------------------------------------------------------------
class Game {
public:
    virtual ~Game() = default;

    // Начало сессии: привязать скрипты/ввод, применить стартовые настройки,
    // сгенерировать/разместить мир. GL-контекст и окно уже существуют
    // (Engine создаётся раньше игры), поэтому саму загрузку GPU-ресурсов
    // конкретная игра обычно делает ещё в своём конструкторе — см. TheBoat.
    virtual void OnStart(Engine& engine) = 0;

    // Один кадр логики. Ввод за этот кадр движок уже опросил (engine.GetInput());
    // dt — время кадра в секундах (ограничено сверху движком от рывков).
    virtual void OnUpdate(Engine& engine, float dt) = 0;

    // Отрисовка кадра. Вызывается движком после OnUpdate, до swap/скриншота.
    virtual void OnRender(Engine& engine) = 0;

    // Необязательная очистка перед закрытием (пока окно/GL-контекст ещё живы —
    // здесь безопасно освобождать GL-ресурсы, например ResourceManager::Clear).
    virtual void OnShutdown(Engine& engine) { (void)engine; }
};
