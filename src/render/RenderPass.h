#pragma once

struct RenderContext;

// ---------------------------------------------------------------------
// RenderPass — один этап кадра (тени, отрисовка сцены, что угодно ещё).
// Часть ЯДРА рендера. Реализации ничего не обязаны знать друг о друге —
// связь между ними идёт только через RenderContext (см. RenderContext.h),
// который RenderPipeline прогоняет по всем зарегистрированным проходам
// по порядку.
// ---------------------------------------------------------------------
class RenderPass {
public:
    virtual void Execute(RenderContext& ctx) = 0;
    virtual ~RenderPass() = default;
};
