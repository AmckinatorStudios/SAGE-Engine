// ---------------------------------------------------------------------------
// Общая часть Vulkan-бэкенда: заголовки, проверка кодов возврата, мелкие
// помощники. Ничего из этого не торчит наружу — за пределами
// engine/src/rhi/vulkan/ о Vulkan не знает никто (см. scripts/check_rhi_boundary.py).
//
// ЗАГОЛОВОК ТОЛЬКО ЧЕРЕЗ VOLK. volk.h сам включает vulkan.h и подменяет ВСЕ
// точки входа указателями, которые заполняются в рантайме. Включить vulkan.h
// напрямую значит получить обычные прототипы, требующие линковки с
// vulkan-1.lib, — то есть ровно ту зависимость от SDK, ради избавления от
// которой volk и взят.
// ---------------------------------------------------------------------------
#include <volk.h>

#include <string>

#include "sage/core/Log.h"

namespace sage::rhi::vk {

// Человекочитаемое имя кода возврата. Нужно затем, что VkResult в логе числом
// («ошибка -9») не говорит ничего, а расшифровка кода — первое, что нужно, когда
// драйвер отказал.
const char* ResultName(VkResult result);

// Проверка результата: пишет в лог и возвращает false. НЕ бросает и НЕ падает.
//
// Отказ драйвера — обычное дело: не хватило памяти, нет нужного формата,
// устройство потеряно при спящем режиме. Единственное разумное поведение
// движка — сказать об этом и откатиться на OpenGL, а не уронить редактор с
// чужой работой в несохранённой сцене.
bool Check(VkResult result, const char* what);

// То же, но без сообщения при успехе — для мест, где вызов ожидаемо может не
// удаться (запрос необязательного расширения).
inline bool Ok(VkResult result) { return result == VK_SUCCESS; }

} // namespace sage::rhi::vk
