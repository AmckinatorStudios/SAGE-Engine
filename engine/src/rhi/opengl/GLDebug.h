#pragma once
#include <glad/glad.h>

// Проверяет glGetError() после произвольного GL-вызова и, если есть
// ошибка, пишет её в лог с точным местом (файл:строка) и самим вызовом
// как текстом — обычно этого достаточно, чтобы сразу понять, что сломалось.
//
// Использование: оборачиваем подозрительный вызов целиком —
//   GL_CHECK(glDrawElements(GL_TRIANGLES, count, GL_UNSIGNED_INT, 0));
//
// В релизной сборке (SAGE_DEBUG не определён) макрос ничего не проверяет
// и превращается просто в сам вызов — нулевые накладные расходы.
void CheckGlError(const char* expr, const char* file, int line);

#ifdef SAGE_DEBUG
    #define GL_CHECK(expr) do { expr; CheckGlError(#expr, __FILE__, __LINE__); } while (0)
#else
    #define GL_CHECK(expr) expr
#endif

// ---------------------------------------------------------------------------
//  Диагностика видеокарты и канал сообщений драйвера
//
//  ЗАЧЕМ ЭТО ЕСТЬ. Отказы рендера почти никогда не одинаковы на двух разных
//  видеокартах, и разбор чужой машины упирался в то, что движок о ней МОЛЧАЛ.
//  Живой случай: у человека на NVIDIA вся геометрия в редакторе оказалась
//  чёрной, а в логе не было ни строчки — потому что GL_CHECK (см. выше) в
//  релизной сборке не проверяет ничего, а больше проверять было нечему.
//  Разбор превращался в переписку «пришлите скриншот» вместо чтения лога.
//
//  Здесь два разных инструмента, и путать их не надо:
//
//    • ОТЧЁТ О ВИДЕОКАРТЕ (GpuReport) — что это за карта и что она умеет.
//      Пишется один раз на старте, всегда. По нему видно, укладывается ли
//      движок в лимиты ИМЕННО ЭТОЙ карты, и его можно сравнить с отчётом
//      машины, где всё работает.
//
//    • КАНАЛ СООБЩЕНИЙ ДРАЙВЕРА (GL_KHR_debug) — что драйвер думает о наших
//      вызовах. Это единственный источник, который называет причину словами:
//      «сэмплеры разных типов на одном юните», «шейдер пересобран из-за
//      состояния», «текстура неполна». Раньше эти сообщения драйвер писал в
//      никуда.
// ---------------------------------------------------------------------------

// Полный отчёт о видеокарте в лог: производитель, модель, версии GL и GLSL,
// лимиты, формат экранного буфера и расширения, от которых зависит рендер.
void LogGpuReport();

// Подключает канал сообщений драйвера к логу движка, если карта его умеет.
// verbose — писать и уведомления с подсказками (иначе только ошибки и
// предупреждения: на некоторых драйверах уведомлений сотни за кадр).
void EnableGlDebugOutput(bool verbose);

// Разовая проверка ошибок GL за кадр — ДЛЯ РЕЛИЗНОЙ СБОРКИ ТОЖЕ.
//
// GL_CHECK обвешивает вызовы и потому выключен в релизе; эта проверка стоит
// один glGetError на кадр и включена всегда. Смысл простой: сборка, у которой
// рендер отказал, обязана об этом СКАЗАТЬ, а не показывать чёрный экран молча.
// Повторы душатся — иначе сломанный кадр залил бы лог одинаковыми строками.
void SweepGlErrorsOncePerFrame(unsigned long long frame);
