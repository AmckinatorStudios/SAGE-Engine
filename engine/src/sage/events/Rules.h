#pragma once
#include <functional>
#include <string>
#include <vector>

#include "sage/events/Events.h"

// ---------------------------------------------------------------------------
// ПРАВИЛА: «КОГДА — ЕСЛИ — ТО» (§16, §17, §31, §33 ТЗ).
//
//     КОГДА  Игрок.Взаимодействие
//     ЕСЛИ   Дверь.Заперта == false
//     ТО     послать «ДверьОткрылась», вызвать Дверь.Открыть()
//
// Это ДАННЫЕ, а не код: правило описывается структурой, хранится в сцене и
// однажды будет рисоваться графом в редакторе. Ради этого оно и отделено от
// обработчика на C++ — обработчик нельзя ни показать в инспекторе, ни
// сохранить, ни собрать мышью.
//
// Правило ничего не выполняет само. Оно СЛУШАЕТ событие и, если условия
// сошлись, шлёт другие события — то есть цепочка (§17) получается сама собой:
// «то» одного правила становится «когда» другого, и ни одно из них не знает о
// существовании соседа. Что именно означает «Дверь.Открыть()», решают
// подписчики шины — скрипт, C++-подсистема или интерфейс.
//
// Отдельно стоит сказать, чего здесь НЕТ. Правила не читают состояние мира
// сами: значение переменной им приносит Resolver — функция, которую даёт
// хозяин (сцена, редактор, тест). Иначе события затянули бы за собой ECS,
// и подписаться на «дверь открылась» стало бы нельзя ниоткуда, кроме сцены.
// ---------------------------------------------------------------------------
namespace sage::events {

// Как сравнивать. IsTrue/IsFalse — отдельно, потому что «если заперта» пишут
// именно так, а не «== true»: сравнение с true через Value превращается в
// вопрос «а строка "да" это true?», которого лучше не задавать.
enum class Compare : uint8_t {
    IsTrue,
    IsFalse,
    Equal,
    NotEqual,
    Less,
    LessOrEqual,
    Greater,
    GreaterOrEqual,
};

const char* CompareName(Compare op);
Compare ParseCompare(const std::string& name);

// Одно условие правила. Var — имя, которое понимает Resolver: как правило
// «Объект.Переменная».
struct Condition {
    std::string Var;
    Compare Op = Compare::IsTrue;
    sage::vars::Value Value;
};

// Чем правило берёт значение переменной. Пустая функция означает «мир
// недоступен» — тогда условия, которым нужно значение, считаются НЕ
// выполненными: правило, не сумевшее проверить условие, обязано молчать, а не
// срабатывать наугад.
using Resolver = std::function<sage::vars::Value(const std::string& var)>;

// Проверка одного условия и всего списка. Публично, потому что то же самое
// нужно редактору для подсветки «условие сейчас выполнено».
bool TestCondition(const Condition& condition, const Resolver& resolver);
bool TestAll(const std::vector<Condition>& conditions, const Resolver& resolver);

// ПРАВИЛО. «То» — это уже существующий Binding (событие + адресат + аргумент):
// заводить рядом второй такой же тип значило бы настраивать одно и то же
// дважды и рассинхронизировать половины при первой правке.
struct Rule {
    std::string Name;      // для редактора и логов; на работу не влияет
    std::string When;      // имя события-повода
    std::vector<Condition> If;
    Bindings Then;
    bool Enabled = true;
};

// Набор правил, живущий на шине. Подписки заводятся один раз в Install и
// снимаются в Uninstall: правила принадлежат сцене и обязаны исчезнуть вместе
// с ней, иначе выгруженный уровень продолжает открывать свои двери.
class RuleSet {
public:
    ~RuleSet();

    RuleSet() = default;
    RuleSet(const RuleSet&) = delete;
    RuleSet& operator=(const RuleSet&) = delete;

    std::vector<Rule>& All() { return m_rules; }
    const std::vector<Rule>& All() const { return m_rules; }
    void Add(Rule rule);
    void Clear();

    // Откуда брать значения для условий. Меняется на ходу (сцену
    // перезагрузили) — подписки при этом не пересоздаются.
    void SetResolver(Resolver resolver) { m_resolver = std::move(resolver); }

    // Подписать правила на шину. Повторный вызов сначала снимает прежние
    // подписки: иначе правило, добавленное после Install, либо не работает,
    // либо срабатывает дважды — и то и другое находят не сразу.
    void Install(Bus& bus);
    void Uninstall();

    // Сколько раз сработало — для отладки и для теста, который иначе не может
    // отличить «правило сработало» от «событие никто не услышал».
    int FiredCount() const { return m_fired; }

private:
    void Fire(const Rule& rule, const Event& cause);

    std::vector<Rule> m_rules;
    Resolver m_resolver;
    Bus* m_bus = nullptr;
    std::vector<int> m_subscriptions;
    int m_fired = 0;
};

} // namespace sage::events
