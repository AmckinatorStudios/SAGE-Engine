#pragma once
#include <string>

#include <glm/glm.hpp>

// ---------------------------------------------------------------------------
// СОБЫТИЯ ДВИЖКА КАК ТИПЫ — общий словарь для подсистем (§15 ТЗ).
//
// Эти структуры не принадлежат ни одной подсистеме и ни одной игре: их шлёт
// физика, а слушают звук, интерфейс и логика — при том, что физика ни о ком из
// них не знает. Ровно ради этого и заведена шина (см. TypedBus.h).
//
// Сущность здесь — ЧИСЛО (тот же идентификатор, что у sage::vars::EntityRef),
// а не тип ECS. Иначе события затянули бы за собой entt и сцену, и подписаться
// на «кто-то умер» стало бы нельзя из звука, который про ECS ничего не знает.
//
// Свои события игра объявляет своими структурами — регистрировать их где-либо
// не нужно: шина типизирована шаблоном, а не списком.
// ---------------------------------------------------------------------------
namespace sage::events {

// Столкновение тел. Point/Normal — в мировых координатах.
struct CollisionEvent {
    int A = 0;
    int B = 0;
    glm::vec3 Point{0.0f};
    glm::vec3 Normal{0.0f, 1.0f, 0.0f};
    float Impulse = 0.0f;
};

// Урон. Отдельно от смерти: получить урон и умереть — разные вещи, и
// подписчики у них разные (по урону мигает экран, по смерти играет ролик).
struct DamageEvent {
    int Source = 0;
    int Target = 0;
    float Amount = 0.0f;
    glm::vec3 Position{0.0f};
    std::string DamageType; // "fire", "fall", ... — строкой: свои виды урона
                            // приносит игра, перечисление в движке пришлось бы
                            // править ради каждой
};

struct DeathEvent {
    int Entity = 0;
    int Killer = 0;
};

struct SceneLoadedEvent {
    std::string Name;
};

struct EntityCreatedEvent {
    int Entity = 0;
};

// Шлётся ДО фактического удаления — иначе подписчик получает номер, по
// которому уже ничего не найти, и не может ни прибрать за собой, ни спросить,
// что это было.
struct EntityDestroyedEvent {
    int Entity = 0;
};

} // namespace sage::events
