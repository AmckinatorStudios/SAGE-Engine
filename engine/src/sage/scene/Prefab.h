#pragma once
#include <string>

#include <entt/entt.hpp>
#include <glm/glm.hpp>

class Scene;
class GameObject;

// ---------------------------------------------------------------------------
// Префабы — сущность-поддерево, сохранённое как шаблон (`.sageprefab`).
//
// ЗАЧЕМ ЭТО ЖИВЁТ В ДВИЖКЕ, А НЕ В РЕДАКТОРЕ. Формально префабы были: в
// иерархии есть «Save as Prefab», двойной клик по файлу ставит копию в сцену.
// Но код жил внутри EditorLayer.cpp, в безымянном пространстве имён, и потому
// был недоступен НИКОМУ, кроме редактора. Для игры про постройку из блоков это
// значит, что главной операции — «поставить заготовленный объект в мир» — из
// скрипта не существует: игра либо собирает объект по компонентам вручную при
// каждом спавне, либо не собирает вовсе.
//
// Это ровно тот разрыв, которым движок болел уже несколько раз: возможность в
// движке есть, а из игры до неё не дотянуться. Поэтому реализация переехала
// сюда, а редактор стал ЕЩЁ ОДНИМ её потребителем, наравне с Lua.
//
// ФОРМАТ. Префаб — это мини-сцена: та же JSON-сериализация, тот же загрузчик,
// та же миграция версий. Отдельный формат означал бы второй сериализатор,
// который надо держать в согласии с первым, и первое же новое поле компонента
// разошлось бы между ними.
// ---------------------------------------------------------------------------
namespace sage::scene {

// Копирует ВСЕ движковые компоненты (кроме имени и иерархии) с одной сущности
// на другую — можно между разными сценами. Рантайм-поля копии сбрасываются:
// тело физики, сустав, поза анимации, снятая карта отражений и накопитель
// частиц принадлежат ЭКЗЕМПЛЯРУ, а не шаблону, и делить их нельзя.
void CopyAllComponents(GameObject& src, GameObject& dst);

// Рекурсивно копирует поддерево (srcRoot и потомков) в dst под dstParent,
// сохраняя иерархию. Новые сущности получают новые id. Возвращает корень копии.
GameObject CopySubtree(Scene& src, entt::entity srcRoot, Scene& dst, entt::entity dstParent);

// Сохраняет сущность с потомками в файл префаба. false + err при ошибке.
bool SavePrefab(Scene& scene, entt::entity root, const std::string& path, std::string& err);

// Ставит префаб в сцену. Возвращает id корня (или -1). Все корни файла
// переносятся, иерархия сохраняется.
//
// Разобранный префаб КЭШИРУЕТСЯ по пути: игра, которая ставит тысячу блоков,
// иначе тысячу раз разбирала бы один и тот же JSON — а это самая частая
// операция такой игры. Кэш сбрасывается Clear() при смене проекта и при
// пересохранении префаба.
int InstantiatePrefab(Scene& scene, const std::string& path);

// То же, но корень ставится в заданную мировую точку. Отдельной функцией, а не
// «поставь и потом подвинь»: между этими двумя шагами успевает пройти кадр, и
// блок на мгновение появляется в начале координат — заметно как мигание.
int InstantiatePrefabAt(Scene& scene, const std::string& path, const glm::vec3& position);

// Сбросить кэш разобранных префабов (смена проекта, правка файла на диске).
void ClearPrefabCache();

} // namespace sage::scene
