#pragma once
#include <entt/entt.hpp>
#include <glm/glm.hpp>

// ---------------------------------------------------------------------------
// У ЧЕГО НЕТ РАЗМЕРА — ТО НЕ МАСШТАБИРУЕТСЯ.
//
// Камера, свет, источник звука, зонд отражений и папка списка — это точки с
// направлением, а не предметы: их масштаб ничего не значит для игры. Редактор
// при этом давал тянуть их ручками масштаба и рамкой, и последствия были
// хуже, чем «ничего не произошло»: масштаб уходил в мировую матрицу, и у
// камеры с масштабом 3 искажался вид (матрица вида — обратная мировой), у
// прожектора уезжал конус, а всё, что положено ВНУТРЬ такой точки, вдруг
// становилось втрое больше. Отменить это можно было, только заметив.
//
// Предмет, у которого есть ФОРМА (меш, коллайдер, декаль, частицы, элемент
// интерфейса), масштабируется всегда, даже если на нём висит свет: лампа-
// модель со встроенным светом — это модель, и её размер настоящий.
// ---------------------------------------------------------------------------
namespace sage::scene {

// Почему масштаб недоступен (None — доступен). Редактор переводит это в
// подсказку: «Камеру нельзя масштабировать» понятнее, чем серое поле.
enum class ScaleLock { None, Camera, Light, Audio, Probe, Folder };

ScaleLock ScaleLockOf(const entt::registry& reg, entt::entity e);
inline bool CanScale(const entt::registry& reg, entt::entity e) {
    return ScaleLockOf(reg, e) == ScaleLock::None;
}

// Масштаб, который объекту позволено иметь после правки: прежний, если
// масштабировать его нельзя, иначе новый. Им пользуются все, кто меняет
// Transform целой матрицей (гизмо, рамка, групповые правки): перенос и
// поворот в той же матрице проходят, масштаб — нет.
inline glm::vec3 AllowedScale(const entt::registry& reg, entt::entity e, const glm::vec3& before,
                              const glm::vec3& after) {
    return CanScale(reg, e) ? after : before;
}

} // namespace sage::scene
