// (ScriptEngine::UpdateAiAgents): при первом кадре Play у объекта появляется
// экземпляр ИИ, в его память кладутся Memory, и запускается граф Graph.
// Объект удалили — экземпляр уходит вместе с задачами.
//
// Memory — начальная память экземпляра (область Instance), правится в
// инспекторе: у каждого стража свой пост и своя дальность обзора при одном
// общем графе. Shared — имя общей области: стражи одного отряда — «guards».
// ---------------------------------------------------------------------------
struct AiAgentComponent {
    std::string Graph;              // путь к .aigraph относительно проекта
    std::string Shared = "world";   // общая область
    bool AutoStart = true;          // запускать граф сам при Play
    sage::vars::Table Memory;       // начальные значения Instance
};

