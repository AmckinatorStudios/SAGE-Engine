#pragma once
#include <functional>
#include <string>

// ---------------------------------------------------------------------------
// ИМЯ ДЛЯ КОПИИ.
//
// К имени просто дописывалось « Copy», и это работает ровно один раз. Дальше
// копия копии становилась «Куб Copy Copy», её копия — «Куб Copy Copy Copy», и
// через пять нажатий Ctrl+D имя переставало помещаться в строку списка. Хуже
// того, читать такое имя нельзя вовсе: единственное, что в нём есть полезного
// — слово «Куб» в начале, — тонет в хвосте из одинаковых слов.
//
// Правило здесь одно: хвост «Copy»/«Copy N» у исходного имени ОТБРАСЫВАЕТСЯ, а
// к настоящей основе приписывается первый свободный номер. «Куб» -> «Куб Copy»
// -> «Куб Copy 2» -> «Куб Copy 3». Имя остаётся коротким на любой глубине
// копирования, и по нему по-прежнему видно, от чего оно произошло.
//
// В ДВИЖКЕ, А НЕ В РЕДАКТОРЕ, и без Scene в параметрах: это правило о СТРОКАХ,
// и проверяется оно строками. Занятость имени приходит ответом на вопрос —
// так одна и та же функция обслуживает и сцену, и список файлов, и что угодно
// ещё, где нужна копия с человеческим именем.
// ---------------------------------------------------------------------------
namespace sage::scene {

// Свободное имя для копии `sourceName`. `taken` отвечает, занято ли имя.
std::string CopyName(const std::string& sourceName,
                     const std::function<bool(const std::string&)>& taken);

} // namespace sage::scene
