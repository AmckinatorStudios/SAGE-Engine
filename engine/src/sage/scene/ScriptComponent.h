#pragma once
#include <string>

#include "sage/vars/Table.h"

// ---------------------------------------------------------------------------
// Компоненты живут рядом со своей системой, а не в общем файле.
//
// Раньше всё это лежало в scene/Components.h — 583 строки, где соседствовали
// интерфейс, обратная кинематика, зонды отражений, физика, частицы и анимация.
// Такой файл растёт при КАЖДОЙ фиче, и это не эстетика: правка одного поля
// перекомпилирует всё, что вообще знает про ECS, а найти нужный компонент
// глазами можно только поиском. Здесь — только то, что читает и пишет одна
// система.
//
// scene/Components.h остался ЗОНТИКОМ: он включает эти файлы, и старый
// `#include "sage/scene/Components.h"` продолжает работать. Ломать три десятка
// включений ради перестановки — незачем.
//
// Система: sage/scripting/ScriptEngine.h.
// ---------------------------------------------------------------------------

// ПОВЕДЕНИЕ СУЩНОСТИ — ФАЙЛ СКРИПТА И ЕГО ПУБЛИЧНЫЕ ПЕРЕМЕННЫЕ. Больше в нём
// нет ничего, и это главное решение здесь.
//
// Настроек «выполнять ли Update», «звать ли Start», «в каком режиме
// исполнять» тут нет намеренно: на них нет ни одного осмысленного ответа со
// стороны человека, собирающего уровень. Порядок хуков, перезагрузка,
// изоляция и обработка ошибок — забота системы скриптинга
// (sage/scripting/ScriptingSystem.h), а не галочек в инспекторе. Каждая такая
// галочка — это ещё одно состояние, в котором игра «не работает, хотя скрипт
// правильный».
//
// ЯЗЫК ОПРЕДЕЛЯЕТСЯ ФАЙЛОМ, а не полем компонента: ".lua" ведёт в Lua-бэкенд,
// и когда появится второй язык, ни компонент, ни сцены, ни инспектор не
// изменятся ни на строку.
//
// Публичные переменные ЗДЕСЬ, а не в VarsComponent: они объявлены скриптом и
// принадлежат этой паре «объект + скрипт». Снял скрипт — исчезли вместе с ним,
// и это правильно: настройка без того, кто её читает, — мусор в файле сцены.
// VarsComponent остаётся для переменных, которые человек завёл сам, объекту
// без всякого скрипта.
struct ScriptComponent {
    std::string Path;

    // Значения ЭТОГО объекта: имена и виды приходят из объявления в скрипте
    // (`Player.public = { ... }`), значения — из инспектора и файла сцены.
    // Слияние с объявлением (Table::MergeDeclaration) устроено так, чтобы
    // правка скрипта не сбрасывала уже расставленные настройки.
    sage::vars::Table Fields;
};
