namespace sage::scene {

// Текущая версия формата сцены. Растёт при ЛОМАЮЩЕМ изменении: добавление
// необязательного поля версию не двигает, потому что старые файлы читаются без
// него как раньше.
//
// ЗДЕСЬ, а не в сериализаторе: номер и цепочка миграций — одно целое, и
// разъехаться им значит либо прогнать лишнюю миграцию, либо не прогнать нужную.
inline constexpr int kSceneVersion = 15;

// Прогоняет дерево через цепочку миграций до текущей версии, правя его НА
// МЕСТЕ. Возвращает версию, с которой файл пришёл. Бросает, если файл сохранён
// более новым движком (открыть его — значит потерять часть данных) или если
// номер версии повреждён.
int MigrateJsonInPlace(nlohmann::json& root);

} // namespace sage::scene
