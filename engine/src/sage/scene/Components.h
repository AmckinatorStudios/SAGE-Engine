// ---------------------------------------------------------------------------
// Компоненты ECS — простые data-структуры, навешиваемые на сущности (entity)
// в sage::Scene (поверх entt). Системы (см. sage/ecs/*) итерируют сущности по
// набору компонентов. Движок не зашивает «толстый» объект с фиксированными
// полями — состав сущности собирается из компонентов, что и делает архитектуру
// расширяемой: своя игра добавляет свои компоненты, не трогая ядро.
//
// ЭТОТ ФАЙЛ — ЗОНТИК, а не место, где компоненты живут.
//
// Раньше он был монолитом на 583 строки, где соседствовали интерфейс, обратная
// кинематика, зонды отражений, физика, частицы и анимация. Такой файл растёт
// при КАЖДОЙ фиче — и последние коммиты это ровно и делали. Беда не
// эстетическая: правка одного поля перекомпилирует всё, что вообще знает про
// ECS, а найти нужный компонент можно только поиском по файлу, потому что
// соседство в нём ничего не значит.
//
// Теперь компоненты лежат РЯДОМ СО СВОЕЙ СИСТЕМОЙ — там же, где код, который
// их читает и пишет. Новая фича добавляет поле в файл своей системы, а не в
// общий.
//
// Зонтик оставлен намеренно: три десятка файлов включают именно его, и ломать
// их ради перестановки — цена без выгоды. Новому коду лучше включать нужный
// заголовок напрямую; старому ничего делать не нужно.
// ---------------------------------------------------------------------------

