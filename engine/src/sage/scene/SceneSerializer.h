#pragma once
#include "Scene.h"
#include <string>

// Сохраняет/загружает Scene в человекочитаемый JSON.
// Сохраняются: имя сцены, все сущности (имя, transform, ссылка на меш, цвет,
// скрипт) и освещение. GPU-ресурсы (Mesh) при загрузке пересоздаются через
// ResourceManager.
//
// Строковые варианты (SaveToString/LoadFromString) — та же сериализация без
// файла: снапшоты сцены в памяти (undo/redo и Play-режим редактора).
namespace SceneSerializer {
    void Save(const Scene& scene, const std::string& path);

    // Возвращает загруженную сцену. Бросает std::runtime_error при ошибке чтения/парсинга.
    std::unique_ptr<Scene> Load(const std::string& path);

    // Сериализация в строку JSON (без обращения к диску).
    std::string SaveToString(const Scene& scene);

    // Восстановление сцены из строки JSON. Бросает std::runtime_error при ошибке парсинга.
    std::unique_ptr<Scene> LoadFromString(const std::string& jsonText);

    // Текущая версия формата сцены. Растёт при ЛОМАЮЩЕМ изменении — добавление
    // необязательного поля версию не двигает, потому что старые файлы читаются
    // без него как раньше.
    int CurrentVersion();

    // Приводит JSON сцены к текущей версии, применяя цепочку миграций, и
    // возвращает результат СТРОКОЙ.
    //
    // Строка, а не объект JSON, намеренно: тип библиотеки JSON не должен
    // торчать из публичного заголовка движка — иначе её замена станет
    // ломающим изменением для всех, кто этот заголовок включает.
    //
    // Проверять миграции надо именно так — на тексте файла, а не на готовой
    // сцене: иначе тест проверял бы не «старый файл прочитался правильно», а
    // «компоненты сегодня выглядят вот так».
    //
    // Бросает, если файл НОВЕЕ движка: читать формат из будущего нельзя, и
    // молча потерять половину сцены хуже, чем честно отказаться.
    std::string MigrateSceneJson(const std::string& jsonText);
}
