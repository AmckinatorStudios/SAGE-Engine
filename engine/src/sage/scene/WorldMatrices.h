#pragma once
#include <cstdint>
#include <vector>

#include <entt/entt.hpp>
#include <glm/glm.hpp>

namespace sage {

// ---------------------------------------------------------------------------
// Мировые матрицы кадра — ПЛОТНОЙ таблицей, а не хэш-картой.
//
// Здесь стояла unordered_map<entt::entity, glm::mat4>, и она обходилась дороже
// самой математики: на каждую сущность приходились хэш, поиск ведра и вставка
// с возможной перестройкой таблицы — при том что перемножить две матрицы это
// шестнадцать умножений. Замер: 80 нс на сущность, из которых на матрицу
// уходили единицы.
//
// Идентификатор сущности в entt — это индекс плюс версия, и ИНДЕКСЫ ПЛОТНЫ:
// реестр раздаёт их подряд и переиспользует освободившиеся. Значит массив по
// индексу — правильная структура, а хэш-карта была решением задачи, которой
// нет. Версия при этом хранится рядом: без неё запись от давно удалённой
// сущности выдавалась бы за живую, потому что индекс тот же.
//
// Ёмкость переиспользуется между кадрами: массив только растёт, и на втором
// кадре выделений нет вовсе.
// ---------------------------------------------------------------------------
class WorldMatrices {
public:
    // Очистка за постоянное время: не трогаем ни одну ячейку, а меняем НОМЕР
    // ПОКОЛЕНИЯ. Записи прошлого кадра остаются в памяти, но перестают
    // считаться своими — их поколение больше не совпадает с текущим.
    //
    // Обходить массив и гасить отметки было бы не только лишней работой на
    // каждый кадр, но и удвоением механизма: одного поколения достаточно, а
    // два способа сказать «этой записи нет» рано или поздно разойдутся.
    void Clear() {
        m_count = 0;
        ++m_stamp;
        if (m_stamp == 0) {
            // Раз в четыре миллиарда очисток номер обнуляется, и старые записи
            // снова совпали бы с текущим поколением. Единственное место, где
            // без обхода не обойтись, — и единственное, где он оправдан.
            for (Slot& s : m_slots) s.Stamp = 0;
            m_stamp = 1;
        }
    }

    bool Has(entt::entity e) const {
        const std::size_t i = (std::size_t)entt::to_entity(e);
        return i < m_slots.size() && m_slots[i].Stamp == m_stamp
               && m_slots[i].Entity == e;
    }

    // Матрица или nullptr. Указателем, а не парой (bool, матрица): вызывающему
    // почти всегда нужна ссылка на неё, а не копия шестнадцати float.
    const glm::mat4* Find(entt::entity e) const {
        const std::size_t i = (std::size_t)entt::to_entity(e);
        if (i >= m_slots.size() || m_slots[i].Stamp != m_stamp || m_slots[i].Entity != e)
            return nullptr;
        return &m_slots[i].World;
    }

    void Set(entt::entity e, const glm::mat4& world) {
        const std::size_t i = (std::size_t)entt::to_entity(e);
        if (i >= m_slots.size()) m_slots.resize(i + 1);
        if (m_slots[i].Stamp != m_stamp) ++m_count;
        m_slots[i] = Slot{world, e, m_stamp};
    }

    // Сколько записей в ТЕКУЩЕМ поколении. Не размер массива: ёмкость живёт
    // между кадрами, и по ней нельзя отличить «кадр ничего не записал» от
    // «кадр записал двадцать тысяч». Ровно на этом различии стоит история
    // скоростей для смаза движения.
    std::size_t Size() const { return m_count; }
    bool Empty() const { return m_count == 0; }

private:
    struct Slot {
        glm::mat4 World{1.0f};
        entt::entity Entity = entt::null;
        std::uint32_t Stamp = 0;
    };
    std::vector<Slot> m_slots;
    std::uint32_t m_stamp = 1;
    std::size_t m_count = 0;
};

} // namespace sage
