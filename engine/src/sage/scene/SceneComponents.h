#include <vector>
#include <entt/entt.hpp>

// ---------------------------------------------------------------------------
// Компоненты живут рядом со своей системой, а не в общем файле.
//
// Раньше всё это лежало в scene/Components.h — 583 строки, где соседствовали
// интерфейс, обратная кинематика, зонды отражений, физика, частицы и анимация.
// Такой файл растёт при КАЖДОЙ фиче, и это не эстетика: правка одного поля
// перекомпилирует всё, что вообще знает про ECS, а найти нужный компонент
// глазами можно только поиском. Здесь — только то, что читает и пишет одна
// система.
//
// scene/Components.h остался ЗОНТИКОМ: он включает эти файлы, и старый
// `#include "sage/scene/Components.h"` продолжает работать. Ломать три десятка
// включений ради перестановки — незачем.
//
// ЭТИ компоненты принадлежат самой сцене: как сущность зовут, под каким id её
// знают Lua и файл сцены, и кто кому родитель. Ими пользуются все системы, но
// не владеет ни одна.
// ---------------------------------------------------------------------------

// Человекочитаемое имя сущности (для поиска, иерархии, инспектора редактора).
struct NameComponent {
    std::string Name;
};

// Стабильный целочисленный id сущности в пределах сцены. entt::entity несёт в
// себе биты версии и не годится как «простой id» для Lua/сериализации, поэтому
// движок раздаёт свои последовательные id (1,2,3...) и держит карту id->entity
// в Scene. Так сохраняется прежний контракт GameObject.Id / DestroyObject(id).
struct IdComponent {
    int Id = 0;
};

// Иерархия сцены: родитель + список детей. Мировая матрица сущности =
// worldMatrix(Parent) * Transform.GetMatrix() — так дети наследуют перенос/
// поворот/масштаб родителя (см. sage::ecs::WorldMatrix). Связи двусторонние
// (Parent у ребёнка и Children у родителя) и поддерживаются Scene::SetParent.
// Отсутствие компонента = корневая сущность без родителя и детей.
struct HierarchyComponent {
    entt::entity Parent = entt::null;
    std::vector<entt::entity> Children;
};
