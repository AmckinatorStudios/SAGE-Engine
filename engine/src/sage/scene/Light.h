#pragma once
#include <glm/glm.hpp>
#include <glm/trigonometric.hpp>
#include <string>
#include <vector>

// Направленный свет — "солнце". На сцену обычно один: светит из бесконечности
// в одном направлении, не затухает с расстоянием. Используется и для
// вокселей, и для обычных объектов, и для воды — единый источник правды
// о том, "куда светит день".
struct DirectionalLight {
    glm::vec3 Direction{-0.4f, -1.0f, -0.3f}; // направление, КУДА летит свет (не откуда)
    glm::vec3 Color{1.0f, 0.95f, 0.85f};
    float Intensity = 1.0f;
    bool CastShadows = true; // каскадные карты (см. ShadowMap.h)
};

// Точечный источник света — фонарь, факел, лампа. Затухает с расстоянием
// по классической формуле 1/(constant + linear*d + quadratic*d^2).
// Constant/Linear/Quadratic выводятся из Range, чтобы дизайнеру уровня
// не приходилось подбирать три магических числа — только "как далеко светит".
struct PointLight {
    glm::vec3 Position{0.0f};
    glm::vec3 Color{1.0f};
    float Intensity = 1.0f;
    float Range = 12.0f;
    // Просит ли источник тень. ПРОСИТ, а не получает: мест в атласе конечное
    // число (см. render/ShadowAtlas.h), и кто их занял, решает распределитель.
    bool CastShadows = true;
    // Занятое место в атласе теней, -1 — тени нет. Заполняется покадрово при
    // раздаче мест и НЕ сериализуется: это состояние кадра, а не свойство
    // источника. Держится здесь, потому что шейдеру нужно знать номер места
    // ровно для того источника, чей вклад он считает, — а связывает их индекс
    // в этом же массиве.
    int ShadowSlot = -1;

    float Constant() const { return 1.0f; }
    float Linear() const { return 4.5f / Range; }
    float Quadratic() const { return 75.0f / (Range * Range); }
};

// Прожектор (spot) — точечный источник, светящий КОНУСОМ вдоль Direction:
// фонарик, лампа-спот, сценический прожектор. Внутри внутреннего угла
// (InnerAngle) светит на полную, между внутренним и внешним (OuterAngle)
// плавно гаснет, за внешним — темно. Затухание с расстоянием — как у точечного
// (из Range). Направление обычно берётся из поворота сущности (см. LightSystem).
struct SpotLight {
    glm::vec3 Position{0.0f};
    glm::vec3 Direction{0.0f, -1.0f, 0.0f}; // КУДА светит конус
    glm::vec3 Color{1.0f};
    float Intensity = 1.0f;
    float Range = 12.0f;
    float InnerAngleDeg = 20.0f; // полная яркость внутри этого полуугла
    float OuterAngleDeg = 30.0f; // край конуса (яркость -> 0)
    bool CastShadows = true;     // см. PointLight::CastShadows
    int ShadowSlot = -1;         // место в атласе теней кадра, -1 — нет

    float Constant() const { return 1.0f; }
    float Linear() const { return 4.5f / Range; }
    float Quadratic() const { return 75.0f / (Range * Range); }
    // Косинусы углов — шейдер сравнивает через dot(), а не через arccos.
    float CosInner() const { return glm::cos(glm::radians(InnerAngleDeg)); }
    float CosOuter() const { return glm::cos(glm::radians(OuterAngleDeg)); }
};

// Полное описание освещения сцены: фоновая засветка (ambient) + солнце +
// произвольное число точечных источников (до MaxPointLights одновременно
// видимых шейдеру — остальные игнорируются, этого достаточно для одного
// уровня среднего размера).
//
// Ambient — полусферический (hemisphere ambient), а не плоский цвет:
// верхние грани (нормаль смотрит вверх) освещаются SkyColor, нижние —
// GroundColor, между ними — плавный переход по вертикальной компоненте
// нормали. Так небо реально подсвечивает верх объектов холодным цветом,
// а низ — теплее (отражённый свет воды/палубы), вместо одинаковой засветки
// со всех сторон, которая делает объекты плоскими на вид.
//
// AmbientColor/AmbientStrength оставлены для обратной совместимости со
// старыми сохранёнными сценами (.sage) и просто задают Sky/Ground разом,
// если кто-то предпочитает старый плоский ambient — см. SetFlatAmbient().
// Линейный туман: фрагменты дальше Start плавно уходят в Color к End. Часть
// атмосферы сцены (сериализуется вместе с окружением).
struct FogSettings {
    bool Enabled = false;
    glm::vec3 Color{0.55f, 0.62f, 0.72f};
    float Start = 12.0f;
    float End = 60.0f;
};

// Небо сцены. Два режима, выбор — по наличию CubemapDir:
//
//   • процедурный градиент — переход от TopColor (зенит) к HorizonColor
//     (горизонт) по вертикали луча взгляда, без единого ассета;
//   • кубическая текстура — набор из шести граней px/nx/py/ny/pz/nz в одном
//     каталоге (см. Skybox::LoadFromDirectory).
//
// Enabled == false — фон просто очищается сплошным цветом.
struct SkyboxSettings {
    bool Enabled = false;

    // ОТКУДА БЕРЁТСЯ НЕБО — явным выбором, а не угадыванием.
    //
    // Раньше режим выводился из того, пуст ли путь к каталогу: «есть путь —
    // значит текстура». Угадывание стоило дорого: чтобы посмотреть, как сцена
    // выглядит с процедурным небом, приходилось СТИРАТЬ путь к своему набору —
    // то есть терять его, — а вернуться обратно значило искать папку заново.
    // И наоборот: очищенный по ошибке путь молча превращал небо в градиент, и
    // выглядело это как «текстуры неба перестали грузиться».
    enum class Source {
        Procedural = 0, // градиент со светилами, без единого файла
        Cubemap,        // каталог с шестью гранями px/nx/py/ny/pz/nz
        Faces,          // шесть отдельных файлов, выбранных поштучно
        Image,          // ОДИН файл: крест, полоса или панорама
        // ОДНИМ ЦВЕТОМ. Небо без градиента, без светил и без времени суток —
        // ровная заливка заданного цвета.
        //
        // Нужно там, где небо не предмет разговора, а ФОН: схема уровня,
        // студийная подложка под предмет, стилизованная игра с плоской
        // картинкой, интерфейсная сцена. Сделать это процедурным небом нельзя:
        // придётся вручную свести шесть цветов (день, ночь, закат) к одному и
        // следить, чтобы они не разъехались; а выключить небо совсем — значит
        // остаться без окружающего света (см. ResolveAmbient) и получить
        // черноту, а не свой цвет.
        //
        // Числом идёт ПОСЛЕДНИМ: номер режима лежит в .sage, и вставка в
        // середину переназначила бы небо во всех уже сохранённых сценах.
        Solid,
    };
    Source Kind = Source::Procedural;

    // --- Процедурное небо ---------------------------------------------------
    //
    // Цвета ДНЁМ. Ночные — отдельной парой ниже: одна пара означала бы небо, у
    // которого нет времени суток, и ровно это в движке и было — на закате
    // менялись только звёзды и луна, а само небо и освещение сцены оставались
    // полуденными.
    // TopColor в режиме Solid — ЦВЕТ ВСЕГО НЕБА. Отдельного поля под него нет
    // намеренно: два цвета «верх неба» в одной структуре путают и в панели, и
    // в файле сцены, а переключение режима туда-обратно теряло бы один из них.
    glm::vec3 TopColor{0.30f, 0.45f, 0.75f};
    glm::vec3 HorizonColor{0.70f, 0.80f, 0.92f};

    // СМЕНА ВРЕМЕНИ СУТОК. Небо и свет следуют за высотой солнца: опустилось за
    // горизонт — стемнело по-настоящему, а не «стало то же самое плюс звёзды».
    // Выключается для сцен, где солнце стоит под сценическим углом и темнеть не
    // должно ни при каких обстоятельствах.
    bool DayNight = true;
    glm::vec3 NightTopColor{0.015f, 0.025f, 0.06f};
    glm::vec3 NightHorizonColor{0.05f, 0.07f, 0.13f};
    // Подсветка горизонта на закате и рассвете. Отдельный цвет, а не смешение
    // дневного с ночным: закат — не «полдень потемнее», у него своя палитра, и
    // без неё переход выглядит как выключение света рубильником.
    glm::vec3 DuskColor{0.95f, 0.45f, 0.20f};

    // Лунный свет — то, чем освещена сцена ночью. Слабый и холодный: ночь
    // обязана быть тёмной, но не чёрной, иначе играть в неё нельзя.
    glm::vec3 MoonlightColor{0.55f, 0.62f, 0.85f};
    float MoonlightIntensity = 0.12f;

    // --- Светила на процедурном небе ----------------------------------------
    //
    // Направление не дублируется: небо берёт его у того же DirectionalLight,
    // который освещает мир, поэтому тени и положение солнца не могут разойтись.
    bool Celestials = false;
    glm::vec3 SunColor{1.00f, 0.95f, 0.85f};
    float SunSize = 0.045f;      // угловой радиус диска, радианы
    bool Moon = true;
    glm::vec3 MoonColor{0.78f, 0.82f, 0.95f};
    float MoonSize = 0.030f;
    float StarIntensity = 1.0f;  // 0 — без звёзд

    // --- Текстурное небо ----------------------------------------------------
    // Каталог с гранями px/nx/py/ny/pz/nz (Source::Cubemap).
    std::string CubemapDir;
    // Шесть отдельных файлов в том же порядке (Source::Faces). Нужны, когда
    // набор пришёл россыпью с чужими именами: раскладывать чужие файлы по
    // нашему соглашению об именах — работа, которой можно не быть.
    std::string FacePaths[6];
    // ОДНА картинка со всем небом сразу (Source::Image). Скачанные наборы почти
    // всегда так и устроены: крест 4:3 или 3:4, полоса 6:1, столбец 1:6 либо
    // панорама 2:1. Требовать под каждое такое небо каталог с шестью файлами по
    // нашим именам — значит требовать ручной нарезки чужого файла.
    std::string ImagePath;
    // Раскладка: 0 — определить по соотношению сторон (обычный случай), дальше
    // по порядку Skybox::Layout. Ручной выбор нужен потому, что 4:3 бывает и
    // крестом, и просто широкой картинкой, и ошибиться молча тут нельзя.
    int ImageLayout = 0;
    float Intensity = 1.0f;    // яркость неба (экспозиция окружения)
    float RotationDeg = 0.0f;  // поворот вокруг вертикали

    // Готовы ли шесть отдельных граней (все пути заданы).
    bool HasFaces() const {
        for (int i = 0; i < 6; ++i)
            if (FacePaths[i].empty()) return false;
        return true;
    }

    // Есть ли ТЕКСТУРНОЕ небо, готовое к показу. Отвечает по выбранному режиму,
    // а не по наличию строки: путь, оставшийся от прежнего выбора, больше не
    // означает, что небо текстурное.
    bool HasCubemap() const {
        if (Kind == Source::Cubemap) return !CubemapDir.empty();
        if (Kind == Source::Faces) return HasFaces();
        if (Kind == Source::Image) return !ImagePath.empty();
        return false;
    }
};

// Тени сцены: то, что зависит от МАСШТАБА МИРА, а не от мощности видеокарты.
//
// Дальность теней жила только в настройках движка (EngineConfig::ShadowDistance)
// — то есть игра не могла её задать вовсе, а игрок мог. Но это не настройка
// качества: сто двадцать метров осмысленны в открытом мире и разорительны в
// игре, где весь мир — тридцать метров в поперечнике. Карта фиксированного
// разрешения растягивается на заданную дальность, и лишние девяносто метров
// съедают ЧЕТЫРЕ ПЯТЫХ её текселей: тень становится крупнозернистой, а вместе
// с ней растут отступ по нормали и запас по глубине — и тень отрывается от
// предмета. Тот самый «зазор между ящиком и его тенью», который видно в игре.
//
// Ноль означает «взять из настроек движка»: сцена, где про тени ничего не
// сказано, ведёт себя ровно как раньше.
struct ShadowSettings {
    float Distance = 0.0f;
};

struct LightingEnvironment {
    static constexpr int MaxPointLights = 8;
    static constexpr int MaxSpotLights = 8;

    // ОТКУДА БЕРЁТСЯ ОКРУЖАЮЩИЙ СВЕТ — выбор автора сцены, а не правило движка.
    //
    // Раньше правило было жёстким и невидимым: включён скайбокс — ambient
    // считается из его цветов, выключен — из полей ниже. Оба поведения нужны, и
    // ни одно не годится всегда. «От неба» — то, чего ждёшь: небо потемнело,
    // объекты потемнели вместе с ним. «Своими значениями» — то, без чего не
    // сделать сцену с художественным светом (подземелье с зелёной подсветкой,
    // где небо вообще ни при чём). Когда правило подразумевается, второй случай
    // выглядит как «поля ambient ничего не делают».
    enum class AmbientSource {
        FromSky = 0, // из неба: цвета берутся у него и меняются вместе с ним
        Custom,      // ровно то, что задано ниже
    };
    AmbientSource AmbientMode = AmbientSource::FromSky;

    glm::vec3 SkyColor{0.55f, 0.65f, 0.85f};    // засветка верхних граней (свет неба)
    glm::vec3 GroundColor{0.20f, 0.18f, 0.16f}; // засветка нижних граней (отражённый свет)
    float AmbientStrength = 0.3f;

    DirectionalLight Sun;

    std::vector<PointLight> PointLights;
    std::vector<SpotLight> SpotLights;

    // Атмосфера сцены — туман и скайбокс. Живут здесь же, потому что это часть
    // окружения (сериализуются одним блоком с освещением, см. SceneSerializer).
    FogSettings Fog;
    SkyboxSettings Skybox;
    ShadowSettings Shadows;

    // --- РАЗРЕШЁННОЕ СОСТОЯНИЕ КАДРА (НЕ сериализуется) ---------------------
    //
    // Считается один раз на кадр из настроек выше и высоты солнца (см.
    // sage/render/SkyModel.h) и дальше читается всеми: небом, ambient, тенями,
    // отражениями. Держится ЗДЕСЬ, а не пересчитывается на месте, ровно
    // поэтому: вычисленное в двух местах время суток однажды разойдётся, и
    // сцена окажется освещена полуднем под ночным небом.
    //
    // По умолчанию совпадает с дневными значениями — сцена, собранная кодом без
    // вызова ApplySky (тесты, превью ассета), ведёт себя как прежде.
    glm::vec3 SkyTopNow{0.30f, 0.45f, 0.75f};
    glm::vec3 SkyHorizonNow{0.70f, 0.80f, 0.92f};
    // Направление НА СОЛНЦЕ (откуда светит) — для диска на небе. Отдельно от
    // Sun.Direction, потому что ночью Sun описывает ЛУНУ: светит она, а диск
    // солнца обязан остаться там, куда его поставил автор, иначе солнце
    // всходило бы на западе.
    glm::vec3 SkySunDirection{0.0f};
    // 1 — день, 0 — ночь. По нему гаснут звёзды и меняется всё остальное.
    float DayFactor = 1.0f;

    // ПОСЧИТАНО ЛИ состояние выше. Не педантизм: окружение собирают КОДОМ и
    // мимо сбора кадра — превью ассета со студийным светом, тест, инструмент.
    // У такого окружения поля выше содержат значения по умолчанию, то есть
    // ЧУЖОЕ небо, и потребитель, читающий их напрямую, рисовал бы не то, что
    // ему задали, — молча и без единой ошибки. Флаг переводит этот случай в
    // «состояния нет, бери авторские настройки».
    bool SkyResolved = false;

    // Цвета неба, которые надо рисовать СЕЙЧАС. Через эти две функции ходят
    // все — небо, отражения, окружающий свет, — и других способов узнать цвет
    // неба быть не должно.
    glm::vec3 SkyTop() const { return SkyResolved ? SkyTopNow : Skybox.TopColor; }
    glm::vec3 SkyHorizon() const {
        // ОДНИМ ЦВЕТОМ — значит и здесь один: горизонт совпадает с зенитом.
        // Проверка стоит ПЕРЕД разрешённым состоянием намеренно: окружение
        // сплошь и рядом собирают кодом, без ApplySky (превью ассета, съёмка в
        // текстуру, тест), и там SkyHorizon() отдавал бы поле ЧУЖОГО режима —
        // то есть «одноцветное» небо уходило бы в градиент.
        if (Skybox.Kind == SkyboxSettings::Source::Solid) return SkyTop();
        return SkyResolved ? SkyHorizonNow : Skybox.HorizonColor;
    }

    // Обратная совместимость / удобный шорткат: выставляет Sky и Ground
    // в один и тот же цвет — эквивалент старого плоского ambient.
    void SetFlatAmbient(const glm::vec3& color, float strength) {
        SkyColor = color;
        GroundColor = color;
        AmbientStrength = strength;
    }

    // Старые геттеры для кода/сериализации, который ещё думает в терминах
    // единого AmbientColor (например, .sage файлы, сохранённые до этого апдейта)
    glm::vec3 AmbientColorApprox() const { return (SkyColor + GroundColor) * 0.5f; }

    // Итоговые цвета полусферического ambient. Если включён скайбокс —
    // засветка берётся ИЗ НЕГО (верх объектов тянется к цвету зенита/неба,
    // низ — к приглушённому цвету горизонта), чтобы освещение согласовывалось
    // с видимым небом. Без скайбокса — заданные Sky/GroundColor.
    void ResolveAmbient(glm::vec3& outSky, glm::vec3& outGround) const {
        // Своими значениями — значит РОВНО ими, независимо от неба. Это выбор
        // автора сцены (см. AmbientMode), и переопределять его «потому что
        // скайбокс включён» — ровно то, из-за чего поля ambient выглядели
        // неработающими.
        if (AmbientMode == AmbientSource::Custom) {
            outSky = SkyColor;
            outGround = GroundColor;
            return;
        }

        // НЕБА НЕТ — И СВЕТА ОТ НЕГО НЕТ.
        //
        // Раньше выключенное небо молча подставляло сюда поля SkyColor/
        // GroundColor, а они по умолчанию голубые и ненулевые. Получалось
        // невозможное: человек выключил небо, удалил из сцены ВСЕ источники
        // света — и сцена всё равно освещена. Найти причину нечем: света в
        // списке нет, неба нет, а предметы видно. Ровно об этом и сообщали.
        //
        // «От неба» означает ровно то, что написано: свет берётся у неба.
        // Нет неба — нет и его света, и сцена честно становится чёрной.
        // Художественный свет без неба никуда не делся — он живёт в режиме
        // «Свои значения», где автор задаёт цвета САМ и осознанно (подземелье
        // с зелёной подсветкой). Разница между двумя режимами в этом и есть.
        if (!Skybox.Enabled) {
            outSky = glm::vec3(0.0f);
            outGround = glm::vec3(0.0f);
            return;
        }
        // От неба — от ТОГО, КОТОРОЕ СЕЙЧАС: цвета берутся из разрешённого
        // состояния кадра, поэтому вместе с закатом темнеет и освещение
        // объектов. Раньше здесь стояли дневные цвета из настроек, и ночью
        // сцена оставалась освещена полуднем.
        //
        // Верхняя полусфера видит и зенит, и горизонт — смещаемся к зениту;
        // нижняя (отражённый свет земли) — приглушённый горизонт.
        outSky = glm::mix(SkyHorizon(), SkyTop(), 0.6f);
        outGround = SkyHorizon() * 0.5f;
    }
};
