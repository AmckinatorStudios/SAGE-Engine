// ---------------------------------------------------------------------------
// VISUAL SCRIPT ОБЪЕКТА — игровая логика графом (.vgraph), а не файлом Lua.
//
// Только данные — граф выполняет движок скриптов (ScriptEngine::
// UpdateAiAgents): в Play объект получает свой экземпляр выполнения, в его
// память кладутся Vars, и граф идёт по своим входам — On Start, On Update,
// On Event. Объект удалили — выполнение уходит вместе с ним.
//
// Отдельно от компонента AI намеренно: у объекта может быть и поведение ИИ, и
// своя игровая логика (дверь с ИИ-стражем внутри — это два графа с разным
// назначением и разными наборами узлов).
// ---------------------------------------------------------------------------
struct VisualScriptComponent {
    std::string Graph;          // путь к .vgraph относительно проекта
    sage::vars::Table Vars;     // переменные объекта (область instance графа)
};

