// ---------------------------------------------------------------------------
// ЧТО СКРИПТ ОБЪЯВЛЯЕТ ПУБЛИЧНЫМ.
//
// Скрипт пишет в начале файла:
//
//     Vars = {
//         speed  = 3.0,                                  -- коротко
//         damage = { 10, min = 0, max = 100, label = "Урон" },
//         target = { kind = "entity", label = "Цель" },
//         sound  = { kind = "asset" },
//     }
//
// и получает их у объекта: `obj:Vars().speed`. Редактор показывает их в
// инспекторе с подписями и границами, значения хранятся в сцене у КАЖДОГО
// объекта отдельно.
//
// РАЗБОР ТЕКСТОМ, А НЕ ЗАПУСКОМ СКРИПТА, и это главное решение здесь.
// Редактор обязан показать переменные, ПОКА ИГРА НЕ ЗАПУЩЕНА: инспектор — это
// то, чем настраивают уровень перед запуском. Выполнить ради этого чужой файл
// нельзя: скрипт объекта на верхнем уровне может делать что угодно — открыть
// сокет, начать грузить уровень, уронить редактор ошибкой в коде, до которого
// в игре дело дошло бы через час. Поэтому объявление читается как ДАННЫЕ:
// разбирается только литеральная таблица Vars, всё остальное игнорируется.
//
// Цена честная и записана здесь: `Vars = MakeVars()` не разберётся, и это
// правильно — объявление обязано быть видно глазами в файле, иначе инспектор
// показывает одно, а игра делает другое.
// ---------------------------------------------------------------------------
namespace sage::vars {

// Разбирает объявление Vars из текста Lua-скрипта. Возвращает пустую таблицу,
// если объявления нет, — это не ошибка: большинству скриптов настройки не нужны.
Table ParseDeclaration(const std::string& luaSource);

} // namespace sage::vars
