// ---------------------------------------------------------------------------
// ГДЕ У СУЩНОСТИ ЛЕЖАТ ССЫЛКИ НА ДРУГИЕ СУЩНОСТИ.
//
// Ссылок в объекте несколько видов и живут они в разных местах: публичная
// переменная вида «объект», адресат связи события у части интерфейса, а завтра
// — поле своей части игры. Каждому, кому нужно их обойти, приходилось бы знать
// весь этот список: копированию поддерева (переписать ссылки внутрь копии),
// удалению объекта (найти, кто на него смотрит), проверке сцены.
//
// Один обход здесь — и все они получают полный список сразу. Новый носитель
// ссылок дописывается ОДИН раз, а не в трёх местах, из которых два забудут.
// ---------------------------------------------------------------------------
namespace sage::vars {

// Зовёт visit для КАЖДОЙ ссылки сущности, отдавая её по ссылке — visit волен
// её переписать.
void VisitEntityRefs(entt::registry& reg, entt::entity e,
                     const std::function<void(EntityRef&)>& visit);

} // namespace sage::vars
