#pragma once
#include "sage/vars/Table.h"

// ---------------------------------------------------------------------------
// ПУБЛИЧНЫЕ ПЕРЕМЕННЫЕ ОБЪЕКТА — то, что настраивают в инспекторе, а не в коде.
//
// ЗАЧЕМ. Настройка объекта жила в двух местах, и оба плохи. Либо число вписано
// в скрипт — тогда две двери с разной скоростью открывания требуют двух
// скриптов, а «подобрать скорость» означает правку кода и перезапуск. Либо
// связь между объектами ищется по ИМЕНИ (`FindByName("Player")`) — тогда
// переименование объекта тихо ломает уровень, а ошибка в букве не видна ни
// компилятору, ни редактору.
//
// Публичная переменная убирает и то, и другое: скрипт объявляет, ЧТО ему
// нужно, а чему это равно у ЭТОГО объекта — видно и правится в инспекторе,
// хранится в сцене и переживает правку скрипта. Ссылка на другой объект —
// такая же переменная, только перетаскиваемая мышью из дерева, и она
// переживает переименование, потому что держится за Id.
//
// Компонент ОТДЕЛЬНЫЙ, а не поле ScriptComponent, намеренно: публичные данные
// нужны и объекту без скрипта — точка появления с именем волны, зона с
// названием следующего уровня, кнопка с аргументом события. Скрипт лишь
// ОБЪЯВЛЯЕТ часть из них (см. Table::MergeDeclaration).
// ---------------------------------------------------------------------------
struct VarsComponent {
    sage::vars::Table Values;
};
