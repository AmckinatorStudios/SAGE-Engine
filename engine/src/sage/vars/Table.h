#pragma once
#include <string>
#include <vector>

#include "sage/vars/Value.h"

// ---------------------------------------------------------------------------
// ТАБЛИЦА ПУБЛИЧНЫХ ПЕРЕМЕННЫХ — «что у этого объекта можно настроить».
//
// Порядок УПОРЯДОЧЕННЫЙ, а не по хешу имени: переменные показываются человеку,
// и «скорость, урон, цель» каждый запуск редактора в новом порядке — это не
// мелочь, а невозможность запомнить, где что.
//
// У переменной есть ОПИСАНИЕ (Var::Meta): подпись, подсказка, границы. Оно
// приходит из объявления в скрипте и нужно инспектору; при этом его отсутствие
// не мешает ничему — переменную, добавленную руками в редакторе, показывают по
// её имени. Именно поэтому описание живёт РЯДОМ со значением, а не в отдельной
// схеме: схема, которую можно потерять, — это переменная, которая однажды
// покажется без подписи и границ, и понять почему будет нечем.
// ---------------------------------------------------------------------------
namespace sage::vars {

struct Var {
    std::string Name;   // имя в коде: по нему переменную берёт скрипт
    Value Data;

    // --- Описание (необязательное) -----------------------------------------
    std::string Label;   // подпись в инспекторе; пусто — показывается Name
    std::string Tooltip; // подсказка при наведении
    float Min = 0.0f;    // границы ползунка; Min == Max — без ползунка
    float Max = 0.0f;
    // Объявлена скриптом (а не добавлена руками). Такую нельзя переименовать в
    // инспекторе — имя принадлежит коду, и правка здесь означала бы, что
    // скрипт молча перестал её находить.
    bool Declared = false;

    const std::string& Title() const { return Label.empty() ? Name : Label; }
};

// Набор переменных объекта. Обычный вектор, а не map: их единицы, порядок
// значим, а поиск по имени на десятке элементов быстрее хеша.
class Table {
public:
    bool Empty() const { return m_vars.empty(); }
    size_t Size() const { return m_vars.size(); }
    const std::vector<Var>& All() const { return m_vars; }
    std::vector<Var>& All() { return m_vars; }

    const Var* Find(const std::string& name) const;
    Var* Find(const std::string& name);

    // Значение по имени с подстановкой: спрашивать «есть ли переменная» перед
    // каждым чтением — это две строки вместо одной у каждого читателя.
    Value Get(const std::string& name) const;

    // Записывает значение, заводя переменную, если её не было. ВИД СОХРАНЯЕТСЯ
    // существующим: скрипт, присвоивший строку числовой переменной, не должен
    // менять её тип в инспекторе — иначе тип объекта зависит от порядка кадров.
    void Set(const std::string& name, const Value& value);

    // Добавляет или заменяет переменную ЦЕЛИКОМ, вместе с описанием.
    Var& Put(const Var& var);

    bool Remove(const std::string& name);
    void Clear() { m_vars.clear(); }

    // Переставляет переменную: порядок в инспекторе — это порядок здесь.
    bool Move(size_t from, size_t to);

    // --- Слияние с объявлением скрипта --------------------------------------
    //
    // Скрипт объявляет, ЧТО у него есть; сцена помнит, ЧЕМУ это равно у данного
    // объекта. Слияние обязано сохранить второе и обновить первое:
    //   • переменная есть и там, и там — остаётся ЗНАЧЕНИЕ ИЗ СЦЕНЫ (иначе
    //     правка скрипта сбрасывала бы настройку каждого объекта на уровне);
    //   • переменной нет в сцене — берётся значение по умолчанию из скрипта;
    //   • переменной нет в скрипте — она остаётся, но помечается как НЕ
    //     объявленная: молча стереть настройку из-за опечатки в имени хуже,
    //     чем показать лишнюю строку.
    // Порядок берётся из объявления: он задан автором скрипта.
    void MergeDeclaration(const Table& declaration);

private:
    std::vector<Var> m_vars;
};

} // namespace sage::vars
