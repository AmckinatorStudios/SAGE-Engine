#pragma once
#include <glm/glm.hpp>

class Scene;

namespace sage::physics {

// ---------------------------------------------------------------------------
// Ragdoll — сборщик тряпичной куклы поверх компонентов физики. Строит из
// ECS-сущностей связный гуманоид: капсульные кости (RigidBody Dynamic +
// Capsule Collider) соединены суставами (JointComponent) — плечи/бёдра/шея
// конусами (Cone, болтаются в пределах угла), локти/колени петлями (Hinge, с
// пределами). Кукла симулируется обычным PhysicsScene (соединения строятся его
// вторым проходом), поэтому падает и складывается как настоящий ragdoll на
// бэкенде Jolt. На встроенном бэкенде кости просто падают по отдельности
// (соединения не поддержаны — предупреждение в лог).
//
// Демонстрирует всю новую физику разом: составные/сочленённые тела + все виды
// constraints. Вызывается из редактора/игры/скриптов (SpawnRagdoll в Lua).
// Возвращает id корневой сущности (таз) — за него куклу можно двигать/удалять.
// ---------------------------------------------------------------------------
int BuildRagdoll(Scene& scene, const glm::vec3& origin, float scale = 1.0f);

} // namespace sage::physics
