#pragma once
#include <functional>
#include <glm/glm.hpp>
#include "sage/physics/PhysicsTypes.h"

// ---------------------------------------------------------------------------
// CharacterMotor — контроллер персонажа как ЧИСТЫЙ АЛГОРИТМ, без физического
// мира под ним.
//
// ЗАЧЕМ ОН ОТДЕЛЬНО ОТ PhysicsWorld::CreateCharacter. Контроллер персонажа был
// у движка ровно в одном месте — внутри Jolt-бэкенда. Из этого следовали три
// вещи, каждая из которых видна невооружённым глазом:
//
//  1. Сборка без Jolt оставалась вообще без персонажа: SupportsCharacters()
//     возвращал false, и любая игра на встроенном бэкенде писала ходьбу сама.
//  2. Проверить контроллер в тестах можно было только там, где собран Jolt, —
//     то есть логика ходьбы, ступенек и опоры не покрывалась ничем в базовой
//     сборке.
//  3. Главное: игра, чей мир НЕ ЛЕЖИТ В ФИЗИКЕ, контроллером воспользоваться
//     не могла в принципе. Воксельная палуба, собранная скриптом, качается
//     вместе с корпусом и живёт в своих, корабельных координатах; заводить на
//     каждый кубик кинематическое тело и двигать их все каждый кадр — это
//     тысячи тел ради задачи, которая решается одним вопросом «занят ли этот
//     объём». В итоге игра писала СВОЮ ходьбу — и вместе с ней свои ошибки
//     (см. ниже про ступеньку).
//
// Здесь контроллер знает о мире ровно один вопрос — SolidQuery: «есть ли
// твердь в этом AABB?». Отвечать на него может физический бэкенд (так делает
// BuiltinWorld), а может Lua-скрипт игры со своей воксельной сеткой. Алгоритм
// ходьбы, ступенек, опоры и застревания при этом ОДИН на всех, и правится он
// в одном месте.
//
// ПРО ФОРМУ. Тело здесь — вертикальная коробка (AABB) со стороной 2·Radius и
// высотой Height, а не капсула. Это не упрощение «на скорую руку»: запрос к
// миру — объёмный AABB, и точная капсула внутри него всё равно проверялась бы
// по коробке. Для воксельного мира коробка ещё и ПРАВИЛЬНЕЕ капсулы —
// скруглённые бока соскальзывают с краёв кубов там, где игрок ожидает стоять.
// Ровно поэтому так устроены почти все воксельные игры.
//
// ПРО СКОРОСТЬ. Она ЗАДАЁТСЯ каждый шаг, а не накапливается: тяготение,
// прыжок, ускорение и трение — правила игры, а не физики. Мотор отвечает
// только за то, что персонаж не пройдёт сквозь стену, взойдёт на ступеньку
// НЕ ВЫШЕ ПОЛОЖЕННОЙ и не зависнет в воздухе после подъёма.
//
// ПРО СТУПЕНЬКУ — то, ради чего этот файл написан аккуратно. Наивный шаг
// «упёрлись — подняться и попробовать снова» превращает персонажа в
// скалолаза: он повторяет подъём каждый кадр и взбирается по отвесной стене
// любой высоты. Здесь подъём ограничен тремя условиями сразу (высотой,
// свободой над головой и НАЛИЧИЕМ ОПОРЫ после спуска), и ни одно из них
// выкинуть нельзя — см. StepMove в .cpp.
// ---------------------------------------------------------------------------
namespace sage::physics {

// «Занят ли объём». true — в этом AABB есть твердь, туда нельзя.
//
// Границы даются в тех же координатах, в которых живёт персонаж: мировых, если
// мир мировой, и корабельных, если игра считает палубу в системе корпуса.
// Мотору всё равно — он ни разу не обращается к «низу мира» или к «оси Y
// сцены» иначе как через переданную скорость.
using SolidQuery = std::function<bool(const glm::vec3& min, const glm::vec3& max)>;

class CharacterMotor {
public:
    // Позиция персонажа — ПОДОШВА (низ коробки), как и у CharacterDesc.
    // Совпадает с соглашением Jolt-бэкенда, чтобы игра, переехавшая с одного
    // на другой, не искала полметра разницы.
    void Configure(const CharacterDesc& desc);
    const CharacterDesc& Desc() const { return m_desc; }

    // Телепорт: перенос мимо симуляции (респавн, переход по уровню). Скорость
    // не трогает — прыжок, прерванный телепортом, останется прыжком.
    void SetPosition(const glm::vec3& feet) { m_state.Position = feet; }
    void SetVelocity(const glm::vec3& v) { m_state.Velocity = v; }

    // Шаг движения. velocity — желаемая скорость (ед/с), dt — секунды.
    // solid может быть пустым: тогда персонаж летит свободно (мира нет).
    void Move(const SolidQuery& solid, const glm::vec3& velocity, float dt);

    const CharacterState& State() const { return m_state; }

    // --- События последнего шага -------------------------------------------
    //
    // Считаются здесь, а не игрой по разнице флагов: «приземлился» и «шагнул на
    // ступеньку» — это КРАЙ, а край, вычисленный снаружи по опросу раз в кадр,
    // теряется ровно тогда, когда кадр длинный. Звук шага и пыль из-под ног
    // пропадают на просадке — и найти это потом невозможно.
    bool Landed() const { return m_landed; }        // коснулся опоры в этом шаге
    bool LeftGround() const { return m_leftGround; } // оторвался от опоры
    bool Blocked() const { return m_blocked; }       // упёрся в стену
    float StepUp() const { return m_stepUp; }        // на сколько взошёл ступенькой (0 — не всходил)

    // Габариты тела в текущей позиции (для отладочной отрисовки и запросов).
    void Bounds(glm::vec3& min, glm::vec3& max) const { BoundsAt(m_state.Position, min, max); }

    // Влезет ли тело подошвами в эту точку. Нужно ДО телепорта: перенос внутрь
    // стены оставляет персонажа замурованным, и выбирается он оттуда только
    // через Unstick, то есть рывком вверх на глазах у игрока.
    bool Fits(const SolidQuery& solid, const glm::vec3& feet) const;

private:
    void BoundsAt(const glm::vec3& feet, glm::vec3& min, glm::vec3& max) const;
    // Двигает по одной оси, останавливаясь вплотную к препятствию.
    // Возвращает пройденное расстояние (со знаком d).
    float SlideAxis(const SolidQuery& solid, int axis, float d);
    // Горизонтальный шаг с попыткой ступеньки. grounded — была ли опора: в
    // воздухе на ступеньку не всходят (иначе получается подтягивание на стену).
    void StepMove(const SolidQuery& solid, float dx, float dz, bool grounded);
    // Выталкивает наверх, если тело оказалось внутри тверди (замуровали блоком,
    // родился в стене). Без этого любое движение упирается в самого себя и
    // персонаж замирает навсегда — молча.
    void Unstick(const SolidQuery& solid);

    CharacterDesc m_desc;
    CharacterState m_state;
    bool m_landed = false;
    bool m_leftGround = false;
    bool m_blocked = false;
    bool m_stepped = false;
    float m_stepUp = 0.0f;
};

} // namespace sage::physics
