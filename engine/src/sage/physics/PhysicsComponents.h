// Физическое тело сущности (см. sage/physics). Тип задаёт роль:
// Static (пол/стены), Dynamic (падает/сталкивается), Kinematic (двигается
// скриптом, толкает динамику). Форму столкновения задаёт ColliderComponent
// (если его нет — берётся единичный бокс по масштабу сущности). Симуляция идёт
// в Play-режиме редактора и в игре (PhysicsScene): позиция/поворот Dynamic-тел
// пишутся обратно в Transform. Данные сериализуются; RuntimeBody — рантайм.
struct RigidBodyComponent {
    sage::physics::BodyType Type = sage::physics::BodyType::Dynamic;
    float Mass = 1.0f;
    float Friction = 0.5f;
    float Restitution = 0.1f;

    // Слой столкновений — по нему тело находят (или не находят) лучи и запросы.
    // Без слоёв луч из камеры первым делом упирается в самого игрока, и
    // «выстрел» не выходит за собственную капсулу.
    sage::physics::LayerMask Layer = sage::physics::kLayerDefault;

    // Сенсор (триггер-зона): обнаруживает касание, но не отталкивает. «Вошёл в
    // зону», «наступил на кнопку», «поднял предмет» — это он. Без сенсоров
    // зону приходится каждый кадр проверять расстоянием в скрипте, и работает
    // она только для шара.
    bool Sensor = false;
    // Какие слои замечает зона. Кнопка, которую нажимает только персонаж, и
    // зона урона, которой нет дела до летящих обломков, — без маски каждый
    // скрипт отсеивал бы гостей сам, и забытая проверка давала «дверь
    // открылась от упавшего ящика».
    sage::physics::LayerMask TriggerMask = sage::physics::kAllLayers;

    sage::physics::BodyHandle RuntimeBody = sage::physics::kInvalidBody; // не сериализуется
};

// Контроллер персонажа — УНИВЕРСАЛЬНОЕ ФИЗИЧЕСКОЕ ТЕЛО, которым можно
// управлять. Не «игрок», не «враг» и не «ходьба»: движок не знает таких слов.
//
// Отдельно от RigidBodyComponent намеренно: управляемый персонаж физически
// неправдоподобен по замыслу — мгновенно меняет скорость, не опрокидывается,
// взбирается на ступеньку и держится на склоне, с которого бочка съехала бы.
// Выжимать это из динамического тела — известный тупик: выходит либо ватное
// управление, либо тело, заваливающееся набок.
//
// ЧТО ИЗМЕНИЛОСЬ И ПОЧЕМУ. Раньше контроллер был «капсулой, которую двигают
// снаружи»: тяготение, падение, прилипание к земле и прыжок писал КАЖДЫЙ
// скрипт заново. Это не выбор, а обязанность — потому что без них персонаж
// просто висит в воздухе. Значит, каждая игра на движке начиналась с
// собственной, чуть-чуть неправильной физики персонажа: у одного падение
// линейное, у другого прыжок зависит от кадра, у третьего на ступеньке
// дрожание. Теперь тяготение, опора, склон, ступенька и скольжение — внутри
// контроллера, а скрипт говорит только НАПРАВЛЕНИЕ и «прыгнуть».
//
// ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ: скорости ходьбы, бега, приседания, кнопок и
// камеры. Это правила игры, а не физики; их место — в скрипте.
struct CharacterControllerComponent {
    // --- Форма и правила движения (то, что видно в инспекторе) -------------
    float Radius = 0.35f;
    float Height = 1.8f;
    // Смещение тела относительно точки объекта. Нужен, когда начало координат
    // модели — не подошвы: без него персонаж либо утоплен в пол, либо висит.
    glm::vec3 Center{0.0f, 0.0f, 0.0f};
    float SlopeLimit = 50.0f;      // круче — не идёт, а соскальзывает (градусы)
    float StepOffset = 0.35f;      // на какую ступеньку всходит без прыжка
    // Зазор, на который тело «не доезжает» до поверхности. Без него контакт
    // вычисляется ровно на границе, и персонаж то проваливается на волосок, то
    // цепляется за стык двух плит.
    // Значение по умолчанию — то, на котором мотор персонажа проверен тестами
    // (tests/test_character.cpp): подошва садится на грань пола с точностью до
    // этого зазора, и менять его «на красивое число» значит сдвинуть всех
    // существующих персонажей на сантиметры.
    float SkinWidth = 0.002f;
    // СВОЁ тяготение у каждого персонажа: «луна», «вода», «полёт» — это
    // настройка объекта, а не мира. 0 — не падает вовсе.
    float Gravity = -9.81f;
    float Mass = 70.0f;            // с какой силой толкает динамику
    sage::physics::LayerMask Layer = sage::physics::kLayerDefault;

    // --- Что запросил скрипт в этом кадре (рантайм) ------------------------
    //
    // ЗАПРОС, А НЕ ДЕЙСТВИЕ: скрипт зовёт Move из Update, а двигать персонажа
    // надо вместе с остальной физикой — иначе он ходит по миру, который в этот
    // момент ещё не шагнул, и на быстрых платформах это видно.
    glm::vec3 DesiredVelocity{0.0f}; // горизонтальная часть, ед/с
    bool HasRequest = false;         // Move позвали в этом кадре
    float VerticalVelocity = 0.0f;   // падение и прыжок; ведёт контроллер
    // Движением ведает ДВИЖОК. false — игра двигает контроллер сама
    // (sage.physics.MoveCharacter старых скриптов): там своё тяготение, и
    // второе, движковое, удваивало бы падение.
    bool Managed = true;

    // --- СВОЙ МИР персонажа (рантайм) --------------------------------------
    //
    // Когда Solid задан, персонаж ходит НЕ по физическому миру, а по тому,
    // который описывает сама игра: она отвечает на вопрос «занят ли этот
    // объём». Тогда движок берёт общий CharacterMotor вместо контроллера
    // бэкенда, а физика о таком персонаже не знает вовсе.
    //
    // Без этого игра с собственной геометрией мира контроллером воспользоваться
    // не могла. Воксельная палуба, которую строит скрипт, качается вместе с
    // корпусом и живёт в корабельных координатах — заводить на каждый кубик
    // кинематическое тело и двигать их все каждый кадр значит платить тысячами
    // тел за вопрос, на который скрипт отвечает одной строкой.
    //
    // Ставится из скрипта (sage.physics.SetCharacterWorld) или из C++.
    sage::physics::SolidQuery Solid;
    std::shared_ptr<sage::physics::CharacterMotor> Motor;

    // --- рантайм (не сериализуется) ---
    sage::physics::CharacterHandle Runtime = sage::physics::kInvalidCharacter;
    bool Grounded = false;
    glm::vec3 GroundNormal{0.0f, 1.0f, 0.0f};
    // Действительная скорость последнего шага — то, что персонаж прошёл, а не
    // то, что просили. Стена, склон и ступенька видны именно здесь, и на ней
    // же стоит анимация: «Speed» у аниматора обязан падать до нуля, когда
    // персонаж упёрся, хотя кнопка всё ещё нажата.
    glm::vec3 Velocity{0.0f};
    // Края последнего шага — «приземлился», «оторвался», «упёрся», «взошёл на
    // ступеньку». Их считает мотор, а не игра по разнице флагов: край,
    // вычисленный снаружи опросом раз в кадр, теряется ровно на длинном кадре,
    // и звук шага пропадает именно на просадке.
    bool Landed = false;
    bool LeftGround = false;
    bool Blocked = false;
    float StepUp = 0.0f;
};

// Форма коллайдера. Размеры — ЛОКАЛЬНЫЕ (для единичной сущности); при создании
// тела умножаются на Transform.Scale. Без RigidBodyComponent коллайдер не
// участвует в симуляции (но редактор рисует его гизмо).
struct ColliderComponent {
    sage::physics::ShapeType Shape = sage::physics::ShapeType::Box;
    glm::vec3 HalfExtents{0.5f, 0.5f, 0.5f}; // Box
    float Radius = 0.5f;                     // Sphere / Capsule
    float HalfHeight = 0.5f;                 // Capsule

    // СОСТАВНАЯ форма: если Parts непусто, тело строится из этих дочерних форм
    // (каждая со своим локальным смещением/поворотом), а поля выше игнорируются.
    // Так один твёрдый объект получает несколько примитивов — «молоток»,
    // Т/Г-образные детали, грубая аппроксимация модели кластером примитивов.
    struct Part {
        sage::physics::ShapeType Shape = sage::physics::ShapeType::Box;
        glm::vec3 HalfExtents{0.5f, 0.5f, 0.5f};
        float Radius = 0.5f;
        float HalfHeight = 0.5f;
        glm::vec3 Offset{0.0f};   // локальное смещение внутри тела
        glm::vec3 EulerDeg{0.0f}; // локальный поворот (градусы, XYZ)
    };
    std::vector<Part> Parts;
};

// Соединение (constraint/joint) сущности с ДРУГИМ телом или с миром. У сущности
// должен быть RigidBodyComponent (её тело — BodyA). TargetId — id сущности с
// телом-партнёром (BodyB); -1 -> прикрепить к неподвижному миру. Anchor —
// смещение точки крепления от МИРОВОЙ позиции этой сущности; Axis — ось в
// мировых координатах (петля/ползун — вдоль неё, конус — twist-ось). Строится
// PhysicsScene вторым проходом (после всех тел). RuntimeJoint — рантайм.
struct JointComponent {
    sage::physics::JointType Type = sage::physics::JointType::Point;
    int TargetId = -1;                  // id партнёра; -1 -> к миру
    glm::vec3 Anchor{0.0f, 0.0f, 0.0f}; // смещение pivot от позиции сущности (мир)
    glm::vec3 Axis{0.0f, 1.0f, 0.0f};   // ось (Hinge/Slider/Cone)
    bool UseLimits = false;
    float MinLimit = 0.0f;              // Hinge °: [-180..0]; Slider: ед.
    float MaxLimit = 0.0f;
    float MinDistance = 0.0f;           // Distance
    float MaxDistance = 1.0f;
    float ConeHalfAngle = 45.0f;        // Cone °
    sage::physics::JointHandle RuntimeJoint = sage::physics::kInvalidJoint; // не сериализуется
};
