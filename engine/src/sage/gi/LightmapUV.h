#pragma once
#include <vector>
#include <glm/glm.hpp>

#include "sage/render/MeshData.h"

// ---------------------------------------------------------------------------
// Развёртка лайтмап-UV и упаковка атласа (sage/gi).
//
// Развёртка — «box-projection»: треугольники группируются по доминантной оси
// МИРОВОЙ нормали грани (6 бинов: ±X, ±Y, ±Z) и планарно проецируются на
// соответствующую плоскость — классический подход, дающий развёртку без
// растяжений для архитектурной/боксовой геометрии (комнаты, платформы) и
// приемлемую для криволинейной. Вершины, попавшие в разные бины, дублируются
// (у каждого чарта — свои UV2). Все шаги ДЕТЕРМИНИРОВАНЫ: при загрузке сцены
// развёртка восстанавливается пересчётом и обязана побайтово совпасть с той,
// под которую запечены страницы.
//
// Упаковка — shelf-упаковщик («полки» по убыванию высоты) по страницам
// фиксированного размера. Чистый CPU, юнит-тестируется.
// ---------------------------------------------------------------------------
namespace sage::gi {

// Внутренний паддинг чарта: 1 тексель рамки с каждой стороны (защита от
// протекания соседних чартов при билинейной фильтрации) + дилатация бейкера.
constexpr int kChartPadding = 1;

// Чарт: группа треугольников одной оси + прямоугольник в атласе.
struct Chart {
    int Axis = 0;                 // 0..5 = +X,-X,+Y,-Y,+Z,-Z (доминантная ось нормали)
    glm::vec2 WorldMin{0.0f};     // границы проекции в мировых «плоскостных» координатах
    glm::vec2 WorldSize{0.0f};
    int W = 0, H = 0;             // размер в текселях (с паддингом)
    int Page = -1, X = 0, Y = 0;  // назначается упаковщиком
    std::vector<int> Tris;        // индексы треугольников меша (i*3 в Indices)
};

// Проекция мировой точки на плоскость чарта оси axis (0..5).
inline glm::vec2 ProjectAxis(const glm::vec3& p, int axis) {
    switch (axis / 2) {
        case 0: return {p.z, p.y};  // ±X
        case 1: return {p.x, p.z};  // ±Y
        default: return {p.x, p.y}; // ±Z
    }
}

// Доминантная ось нормали: 0..5 = +X,-X,+Y,-Y,+Z,-Z.
inline int DominantAxis(const glm::vec3& n) {
    glm::vec3 a = glm::abs(n);
    if (a.x >= a.y && a.x >= a.z) return n.x >= 0.0f ? 0 : 1;
    if (a.y >= a.z) return n.y >= 0.0f ? 2 : 3;
    return n.z >= 0.0f ? 4 : 5;
}

// Строит чарты меша (mesh — ЛОКАЛЬНАЯ геометрия, world — мировая матрица) и
// ДУБЛИРУЕТ вершины, попавшие в чарты разных осей (правит mesh на месте).
// texelsPerUnit — плотность лайтмапы; maxChartSide — потолок стороны чарта
// (крупные чарты равномерно ужимаются). UV2 после этого шага — ЛОКАЛЬНЫЕ
// координаты чарта 0..1 (в атлас переводит ApplyAtlasTransform после упаковки).
std::vector<Chart> BuildCharts(sage::render::MeshData& mesh, const glm::mat4& world,
                               float texelsPerUnit, int maxChartSide);

// Shelf-упаковка чартов (по убыванию высоты, стабильно — детерминирована) в
// страницы pageSize×pageSize. Пишет Page/X/Y каждого чарта; возвращает число
// страниц. charts может содержать чарты РАЗНЫХ мешей (общий атлас сцены).
int PackCharts(std::vector<Chart*>& charts, int pageSize);

// Переводит локальные UV2 чарта в финальные атласные координаты его страницы.
void ApplyAtlasTransform(sage::render::MeshData& mesh, const std::vector<Chart>& charts,
                         int pageSize);

} // namespace sage::gi
