// ---------------------------------------------------------------------------
// Открытие .gltf/.glb — ОДНА дверь на весь движок.
//
// ЗАЧЕМ. Раньше файл открывали четыре места (Model, SkinnedModel,
// ModelMaterial, GltfImporter), и каждое решало «двоичный ли это файл» по
// расширению, а потом звало tinygltf напрямую. Отсюда две беды.
//
// ПЕРВАЯ — ФОРМАТ ПО ИМЕНИ. Расширение к содержимому отношения не имеет:
// текстовый glTF, сохранённый как .glb (так делают конвертеры и выгрузки
// «одним файлом»), уходил в двоичный разбор и падал на «Invalid magic», хотя
// файл целый. Здесь формат определяется по первым четырём байтам.
//
// ВТОРАЯ — ЗАГОЛОВОК GLB. В шапке GLB лежит поле «общая длина», и в живых
// файлах оно врёт: упаковщики ассетов дописывают выравнивание в конец, режут
// хвост или оставляют поле от файла ДО правки. tinygltf сверяет это поле с
// размером файла и на любом расхождении отвечает ровно одним словом —
// «Invalid glTF binary». Для человека это значит «модель не загрузилась,
// причина неизвестна», хотя и куски (JSON, BIN) на месте, и читать их можно.
// Поэтому GLB здесь ПЕРЕСОБИРАЕТСЯ: куски вынимаются, выравнивание и длина
// пишутся заново — и tinygltf получает канонический файл.
//
// Что НЕ чинится: обрезанный файл (кусок обещает больше байт, чем есть). Такое
// молча «чинить» нельзя — из-под геометрии пропадут данные. Здесь это
// сообщение с числами: сколько обещано и сколько на самом деле.
// ---------------------------------------------------------------------------

namespace sage::assets {

// Читает модель по пути. err/warn — сообщения ДЛЯ ЧЕЛОВЕКА, по-русски.
// Возвращает false, только если модель прочитать не удалось.
bool LoadGltfFile(tinygltf::TinyGLTF& loader, tinygltf::Model& out, const std::string& path,
                  std::string& err, std::string& warn);

// KHR_materials_pbrSpecularGlossiness -> обычный металл-шероховатость, прямо в
// модели. Старое расширение до сих пор пишут выгрузки магазинов моделей и конвертеры из
// FBX; не читая его, движок получал материал по умолчанию — БЕЛЫЙ металл без
// текстур, и модель целиком выходила белой. Возвращает число переведённых
// материалов. LoadGltfFile зовёт её сам.
int ConvertSpecularGlossiness(tinygltf::Model& model);

// Пересборка GLB из памяти: вынуть куски, выровнять, переписать длину.
// Отдельно от загрузки — чтобы проверять её без tinygltf и без диска.
// Возвращает false с err, если файл не GLB или обрезан.
bool RepackGlb(const std::string& data, std::string& out, std::string& err, std::string& warn);

} // namespace sage::assets
