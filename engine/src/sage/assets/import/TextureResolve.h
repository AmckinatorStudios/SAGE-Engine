// ЗАЧЕМ ОТДЕЛЬНЫЙ ПОИСК. Ссылка в файле модели почти никогда не годится как
// путь. Причины разные у каждого формата, а итог один — «модель загрузилась,
// но стала белой»:
//
//   • glTF ТРЕБУЕТ процентного кодирования в URI, и текстура «body normal.png»
//     записана как «body%20normal.png». Файла с таким именем на диске нет;
//   • экспортёры пишут АБСОЛЮТНЫЕ пути чужой машины
//     («C:\Users\artist\Desktop\tex\body.png») — в .mtl из 3ds Max это норма;
//   • разделитель каталогов бывает обратным слэшем даже в файлах, которые потом
//     открывают на Linux;
//   • набор текстур приезжает отдельной папкой (textures/, maps/), а ссылка
//     указывает только имя файла — или наоборот, ссылка ведёт в папку, которой
//     у получателя нет;
//   • регистр имени не совпадает: «Body.PNG» против «body.png». На Windows это
//     один файл, на Linux — разные, и половина чужих моделей теряет карты
//     ровно здесь.
//
// Поэтому поиск — ОДИН на все форматы и записан один раз. Порядок шагов важен и
// идёт от точного к приблизительному: сначала пробуем то, что сказано, и только
// потом ищем по имени рядом. Найденное возвращается путём НА ДИСКЕ; ссылкой
// проекта его делает вызывающий (Project::AssetRef) — абсолютный путь в ассете
// не переживает ни переезд проекта, ни сборку игры.
// ---------------------------------------------------------------------------
namespace sage::assets {

// Раскодирует %XX в URI. glTF требует кодировать пробелы и не-ASCII, и без
// обратного перевода файл не находится никогда.
std::string DecodeUri(const std::string& uri);

// Ищет файл текстуры. modelDir — папка модели, reference — то, что написано в
// файле (URI, относительный или абсолютный путь).
//
// Возвращает путь на диске или пустую строку. warnings (если дан) получает
// строку о ненайденной карте: молчаливая потеря текстуры хуже отказа — «модель
// белая» человек видит, а причину нет.
std::string ResolveTexturePath(const std::filesystem::path& modelDir, const std::string& reference,
                               std::vector<std::string>* warnings = nullptr);

} // namespace sage::assets
