// Дешёвый ответ на вопрос «есть ли в файле модели скелет» — БЕЗ разбора модели.
//
// ЗАЧЕМ. Редактор, поставив модель в сцену, спрашивает скелетную версию: если
// кости есть, модели нужен компонент Animation и клипы. Ответ добывался полным
// скелетным разбором — и это было плохо трижды:
//   • .obj (а это просто треугольники) уходил в разбор glTF, и в консоль
//     падало «Скиннинг-модель не загрузилась … parse error» — ОШИБКА на совершенно
//     нормальной декорации;
//   • статический .gltf разбирался целиком, с декодированием всех текстур
//     (дерево из набора — две картинки 2048² и одна 1024²), только чтобы
//     выяснить, что скина в нём нет;
//   • ответ «нет» писался в лог ошибкой, хотя это обычное состояние декорации.
//
// Здесь — только оглавление файла: JSON у glTF (без буферов и картинок),
// дерево записей у FBX (без геометрии). Остальные форматы скелета не несут.
// ---------------------------------------------------------------------------
namespace sage::assets {

// true — в файле есть скин (glTF: непустой skins; FBX: Deformer «Skin»).
// Непонятный или нечитаемый файл — false: скелетный разбор ему всё равно не
// поможет, а сообщение о битом файле даст обычная загрузка модели.
bool ModelHasSkeleton(const std::string& path);

} // namespace sage::assets
