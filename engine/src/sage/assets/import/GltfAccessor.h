#include <cstddef>
#include <vector>

namespace tinygltf { class Model; }

// ---------------------------------------------------------------------------
// Чтение аксессоров glTF — ОДИН раз на весь движок.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Аксессоры читали два места и по-разному: статический
// импорт (assets/import/GltfImporter.cpp) — с проверкой границ, скелетный
// разбор (render/SkinnedModel.cpp) — без единой. Расхождение стоило дорого:
// одна и та же модель открывалась в панели ассетов и РОНЯЛА редактор, когда её
// клали в сцену, — потому что в сцене её читал второй путь.
//
// ПОЧЕМУ РОНЯЛА: РАЗРЕЖЕННЫЙ АКСЕССОР. По спецификации glTF поле bufferView у
// аксессора НЕОБЯЗАТЕЛЬНО: если его нет, аксессор целиком нулевой, а реальные
// значения лежат в блоке sparse (пары «номер вершины — значение»). Так 3D-редактор
// пишет КАЖДЫЙ ключ формы (shape key): деталь из тысячи вершин, у которой
// сдвинуты три, — это три числа вместо трёх тысяч. tinygltf такой аксессор
// разворачивать не умеет и оставляет bufferView = -1 (у него в заголовке так и
// написано: «bufferView could be null(-1) for sparse morph target»).
//
// Чтение по -1 — это `bufferViews[-1]`: обращение за начало вектора, дальше
// индекс буфера из мусора и указатель в никуда. Не «модель загрузилась криво»,
// а падение процесса на месте. У проверочной модели (Spring Bonnie, экспорт из
// 3D-редактор) таких аксессоров 29 из 535 — то есть редактор падал на ней всегда.
//
// ЧТО ДЕЛАЕТ ЭТОТ ЧИТАТЕЛЬ. Отдаёт ПЛОТНЫЙ массив запрошенной длины и никогда
// не читает за границей буфера:
//   • аксессора нет, он битый или его тип не тот — пустой результат, вызывающий
//     сам решает, пропустить часть или подставить своё;
//   • bufferView нет — массив нулей нужной длины (ровно это велит спецификация);
//   • есть sparse — поверх нулей (или поверх плотных данных) подставляются
//     значения по своим номерам, с проверкой каждого номера;
//   • шаг (byteStride) и смещения проверяются так, чтобы ПОСЛЕДНИЙ элемент
//     целиком помещался в буфер.
//
// Нормализованные целые (byte/short) разворачиваются в float по правилу
// спецификации: экспортёры пакуют так UV и веса, и без этого модель приезжает
// с развёрткой в тысячи единиц.
// ---------------------------------------------------------------------------

namespace sage::assets::gltf {

// Аксессор -> плотный массив float длиной count*components.
// Пусто, если аксессора нет, он битый или его тип не приводится к float.
std::vector<float> ReadFloats(const tinygltf::Model& model, int accessorIndex, int components);

// Аксессор -> плотный массив беззнаковых целых длиной count*components
// (индексы треугольников, JOINTS_0). Пусто по тем же причинам.
std::vector<unsigned int> ReadUInts(const tinygltf::Model& model, int accessorIndex,
                                    int components);

// Сколько элементов в аксессоре (count). 0 — аксессора нет.
size_t AccessorCount(const tinygltf::Model& model, int accessorIndex);

} // namespace sage::assets::gltf
