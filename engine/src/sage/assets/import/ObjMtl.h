#pragma once
#include <string>
#include <unordered_set>

// ---------------------------------------------------------------------------
// То, чего не сообщает tinyobjloader о файле .mtl.
//
// ЗАЧЕМ. Материал с картой цвета (map_Kd) и без строки Kd — обычное дело:
// Blender не пишет Kd, когда цвет взят из текстуры. tinyobj в этом случае
// МОЛЧА подставляет Kd = 0.6 («приличное значение по умолчанию»), и текстура
// умножается на 0.6: кора и листва из .obj выходили на 40 % темнее той же
// модели в glTF, где множитель — честная единица. Отличить подставленные 0.6
// от записанных в файле по material_t нельзя — признака там нет, поэтому
// .mtl просматривается здесь ещё раз, только на предмет строк Kd.
// ---------------------------------------------------------------------------
namespace sage::assets {

// Имена материалов из .mtl, подключённых к objPath (mtllib), у которых есть
// map_Kd, но нет Kd. Файл не читается — пустой набор.
std::unordered_set<std::string> MtlTexturedWithoutKd(const std::string& objPath);

} // namespace sage::assets
