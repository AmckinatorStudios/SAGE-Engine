// ---------------------------------------------------------------------------
// Разбиение многоугольника грани на треугольники — одно на все форматы.
//
// ЗАЧЕМ. FBX и .blend хранят грани многоугольниками (четырёх-, пяти-, сколько
// угодно угольными), а видеокарта рисует только треугольники. Разбивались они
// ВЕЕРОМ от первой вершины — это верно лишь для выпуклой грани. Вогнутый
// четырёхугольник (у листа, у изгиба коры, у любой «стрелки») веер режет по
// диагонали, лежащей СНАРУЖИ грани: один треугольник вылезает за контур,
// другой накрывает его сверху. На модели это выглядит как рваные, торчащие
// лоскуты — «часть модели искажена», — хотя все вершины прочитаны верно.
//
// КАК. Грань проецируется на свою плоскость (нормаль по Ньюэллу — она верна и
// для неплоских и вогнутых граней), и от неё отрезаются «уши» — выпуклые
// вершины, в треугольник которых не попадает ни одна другая вершина. Это
// правильная триангуляция любого простого многоугольника.
//
// Четырёхугольник — самый частый случай — режется по той же диагонали, что и
// раньше (0-2), если она внутри грани: у выпуклых квадов результат не меняется
// ни на треугольник, меняются только те, что прежде были испорчены.
// ---------------------------------------------------------------------------
namespace sage::assets {

// Тройки индексов В МНОГОУГОЛЬНИКЕ (0..n-1). Обход треугольников совпадает с
// обходом грани: лицевая сторона остаётся лицевой. Меньше трёх точек — пусто.
std::vector<uint32_t> TriangulatePolygon(const std::vector<glm::vec3>& points);

} // namespace sage::assets
