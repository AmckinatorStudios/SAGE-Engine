#pragma once
#include <vector>

#include <glm/glm.hpp>

// ---------------------------------------------------------------------------
// Отбор влияний костей на вершину — ОДИН на все форматы.
//
// ЗАЧЕМ ОТДЕЛЬНО. В шейдере на вершину ровно ЧЕТЫРЕ места (uBones + vec4
// весов), а в файле влияний бывает сколько угодно: glTF разрешает несколько
// наборов JOINTS_n/WEIGHTS_n, FBX хранит веса кластерами и не ограничивает их
// число вовсе. Сведение «много влияний -> четыре» делали два разбора и
// по-разному: glTF брал ПЕРВЫЙ набор и нормировал его, то есть терял главную
// кость, если она оказалась во втором наборе (одежда и волосы у персонажей
// риггятся именно так); FBX отбирал четыре самых весомых, но не проверял номер
// кости. Снаружи это выглядело как «рука тянется не туда» и «деталь улетела в
// начало координат».
//
// Правила здесь одни для всех:
//   • влияние с неположительным весом или с номером кости за пределами скелета
//     не влияет ни на что — его отбрасываем (а НЕ переносим на кость 0: вес,
//     подаренный корню, тянет вершину к тазу персонажа);
//   • из оставшихся берём четыре самых весомых;
//   • сумму приводим к единице — иначе вершина уезжает к началу координат
//     ровно на недостачу веса.
// ---------------------------------------------------------------------------

namespace sage::assets {

// Одно влияние: кость и её вес. Joint — индекс в Skeleton::Joints.
struct SkinInfluence {
    int Joint = -1;
    float Weight = 0.0f;
};

// Сводит список влияний к четырём местам шейдера.
// jointCount — сколько костей реально есть (номера >= него считаются битыми).
// false — годных влияний не нашлось; чем заполнить вершину, решает вызывающий:
// у формата к формату это разные правила (см. разборы glTF и FBX).
bool ResolveInfluences(std::vector<SkinInfluence>& influences, int jointCount,
                       glm::vec4& outJoints, glm::vec4& outWeights);

} // namespace sage::assets
