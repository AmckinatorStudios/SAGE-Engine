// СКЕЛЕТНАЯ МОДЕЛЬ ИЗ FBX: скин, кости и клипы анимации.
//
// ЗАЧЕМ. FBX — формат, в который экспортируют по умолчанию Blender, Maya, Max,
// Mixamo и любой ассет-стор, и персонажи оттуда приходят СО СКИНОМ. Пока скин
// не читался, движок отвечал «экспортируйте в .glb»: человеку со скачанным
// набором это означало «твоя модель не подходит» — притом что ровно эти кости и
// эти клипы лежат прямо в файле.
//
// ЧТО БЕРЁТСЯ: скелет (Model/LimbNode + иерархия из Connections), веса
// (Deformer::Skin -> Cluster с Indexes/Weights), матрицы привязки (TransformLink
// кластера) и клипы (AnimationStack -> Layer -> CurveNode -> Curve) с именами
// стеков. Меш разбирается тем же общим кодом, что и статический путь.
//
// ЧТО НЕ БЕРЁТСЯ: блендшейпы (Deformer::BlendShape) и кривые с нелинейной
// интерполяцией — последние читаются как линейные. Об этом сообщается в лог, а
// не замалчивается.
// ---------------------------------------------------------------------------
namespace sage::assets {

// Разбирает .fbx в скелетную модель. false — файла нет, он не разобрался или в
// нём НЕТ скина (err объясняет, что именно); модель без скина — не ошибка
// формата, а обычная статическая модель, и грузить её надо другим путём.
bool ImportFbxSkinned(const std::string& path, sage::render::ModelData& out, std::string& err);

} // namespace sage::assets
