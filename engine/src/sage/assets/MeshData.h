#pragma once
#include <string>
#include <vector>

#include <glm/glm.hpp>

// ---------------------------------------------------------------------------
// Геометрия на стороне процессора: вершины, индексы, разметка по материалам.
//
// ПОЧЕМУ ЗДЕСЬ, А НЕ В РЕНДЕРЕ. Это то, что ВЫДАЁТ импорт (разбор .obj, .gltf,
// .fbx, .blend, .bbmodel) и что читает и пишет свой формат .sagemesh. Пока
// типы жили в sage/render, слой ресурсов зависел от слоя мира: разобрать файл
// без рендера было нельзя даже в теории. Теперь ресурсы готовят данные, а
// рендер берёт их и строит из них своё (Mesh — геометрию на видеокарте,
// sage/render/Mesh.h). Имена в sage::render и глобальный Vertex остались
// псевдонимами этих типов — код и раскладка в памяти те же.
// ---------------------------------------------------------------------------
namespace sage::assets {

// Раскладку не менять: её байтами пишут .sagemesh и кэш, по ней строят
// атрибуты вершин в рендере (offsetof).
struct Vertex {
    glm::vec3 Position;
    glm::vec3 Normal;
    glm::vec2 TexCoords;
    // Касательная для normal mapping (TBN). w — знак ориентации (handedness):
    // бинормаль в шейдере = cross(N, T.xyz) * T.w. Без него зеркальные по UV
    // грани получали бы инвертированный рельеф нормал-карты.
    glm::vec4 Tangent{1.0f, 0.0f, 0.0f, 1.0f};
    // Второй UV-канал — координаты в атласе лайтмапы (глобальное освещение,
    // см. sage/gi). Заполняется бейкером; у незапечённой геометрии (0,0).
    glm::vec2 TexCoords2{0.0f, 0.0f};
};

// Часть геометрии, которая красится СВОИМ материалом, — подмеш.
//
// ЗАЧЕМ. Модель из редактора почти никогда не одноматериальна: у персонажа
// отдельно кожа, отдельно ткань, отдельно глаза и зубы. Раньше весь файл
// сливался в один буфер без разметки, сущность держала один материал, и
// четырнадцать материалов модели превращались в один.
//
// Граница — это отрезок общего индексного буфера. Именно отрезок, а не
// отдельный буфер на материал: геометрия остаётся ОДНОЙ загрузкой на
// видеокарту, инстансинг сохраняется, а «нарисовать только эту часть» стоит
// смены смещения.
struct Submesh {
    std::string Name;            // имя примитива/узла в исходном файле — для инспектора
    unsigned int FirstIndex = 0; // смещение в индексном буфере
    unsigned int IndexCount = 0;
    // Индекс материала в списке материалов ИСТОЧНИКА (ImportedScene::Materials,
    // он же порядок ExtractMaterials). -1 — у части нет материала в файле.
    int Material = -1;
};

struct MeshData {
    std::vector<Vertex> Vertices;
    std::vector<unsigned int> Indices;
    // Разметка по материалам. ПУСТО — законное состояние: вся геометрия
    // считается одним подмешем. Так процедурные примитивы и старые форматы
    // ничего про подмеши не знают и знать не обязаны.
    std::vector<Submesh> Submeshes;

    bool Empty() const { return Vertices.empty() || Indices.empty(); }

    // Разметка, годная для отрисовки: если её нет — один подмеш на всё.
    // Единственное место, где записано это правило: разложить его по
    // потребителям значило бы получить столько трактовок пустого списка,
    // сколько потребителей.
    std::vector<Submesh> SubmeshesOrWhole() const {
        if (!Submeshes.empty()) return Submeshes;
        return {Submesh{{}, 0u, (unsigned int)Indices.size(), -1}};
    }
};

} // namespace sage::assets
