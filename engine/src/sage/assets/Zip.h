#pragma once
#include <vector>
#include <filesystem>
#include <string>

// ---------------------------------------------------------------------------
// Чтение обычных .zip.
//
// ЗАЧЕМ ОТДЕЛЬНО ОТ .sagepak. Пакет игры (sage/assets/Pack.h) — СВОЙ формат: он
// заточен под то, чтобы движок читал из него ассеты, не распаковывая. Zip здесь
// нужен ровно для обратного — чтобы человек мог внести в проект то, что скачал.
// А скачивают ассеты именно так: одним архивом с моделью, набором текстур и
// лицензией внутри. Требовать «сначала распакуйте где-нибудь, потом принесите
// файлы по одному» значит требовать делать руками то, что программа делает за
// секунду.
//
// БЕЗОПАСНОСТЬ — НЕ ФОРМАЛЬНОСТЬ. Имя внутри архива придумал не пользователь:
// запись «../../.bashrc» или «/etc/passwd» распаковалась бы ПОВЕРХ чужих файлов
// за пределами папки назначения (zip slip). Поэтому каждая запись проверяется,
// а подозрительная пропускается — архив при этом распаковывается дальше: чаще
// это мусор от архиватора, а не нападение.
// ---------------------------------------------------------------------------
namespace sage::assets {

// Похоже ли на zip ПО СОДЕРЖИМОМУ (сигнатура "PK"), а не по расширению: тот же
// zip приезжает как .zip, .love, .fbxz и вовсе без расширения.
bool IsZip(const std::filesystem::path& file);

// Распаковывает архив в destDir (папка создаётся). Возвращает число
// распакованных файлов или -1 при ошибке — тогда причина в err.
//
// skipped (если передан) получает имена записей, которые распаковывать
// отказались: пустые каталоги тут ни при чём, это именно опасные пути.
int ExtractZip(const std::filesystem::path& archive, const std::filesystem::path& destDir,
               std::string& err, std::vector<std::string>* skipped = nullptr);

} // namespace sage::assets
