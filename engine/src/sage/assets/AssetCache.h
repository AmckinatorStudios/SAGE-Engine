#pragma once
#include <string>

#include "sage/render/ModelData.h"

// ---------------------------------------------------------------------------
// Кэш разобранных ресурсов — «запечённый» бинарный формат рядом с исходником.
//
// ЗАЧЕМ. Исходные форматы (glTF, PNG) сделаны для ОБМЕНА: они компактны,
// самоописательны и читаются любой программой. Ровно поэтому они дороги при
// загрузке — JSON разбирается посимвольно, PNG распаковывается и
// дефильтровывается попиксельно. Игра платит эту цену при каждом запуске, хотя
// файл не менялся с прошлого раза.
//
// Кэш платит её ОДИН раз. Второй запуск читает готовые вершины и готовые
// пиксели одним блоком: без разбора, без распаковки, без пересборки.
//
// КОГДА КЭШ НЕДЕЙСТВИТЕЛЕН. Если исходник изменился (размер или время правки),
// если формат кэша новее или старше нашего, если файл повреждён. Во всех этих
// случаях загрузка молча возвращается к разбору исходника и перезаписывает
// кэш: неверный кэш никогда не должен приводить к неверной картинке, а
// отсутствие кэша — к отказу.
//
// ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. Сжатия текстур (BC/ASTC) нет: без него пиксели
// лежат сырыми, и кэш крупной модели весит больше исходника. Это осознанный
// первый шаг — сжатие требует кодировщика и поддержки формата в RHI, но
// ставится оно ИМЕННО СЮДА, в уже существующий пайплайн. Пока пайплайна не
// было, добавлять сжатие было некуда.
// ---------------------------------------------------------------------------
namespace sage::assets {

// Каталог, в котором лежат файлы кэша. По умолчанию ".sage-cache" рядом с
// рабочим каталогом. Отдельная папка, а не файл рядом с исходником: каталог
// ассетов может быть только для чтения (сетевая шара, содержимое пакета), и
// раскладывать в него служебные файлы — верный способ получить отказ записи
// там, где всё остальное работает.
void SetCacheDirectory(const std::string& directory);
const std::string& CacheDirectory();

// Выключить кэш целиком (проверки, сравнение «с кэшем и без»).
void SetCacheEnabled(bool enabled);
bool CacheEnabled();

// Путь к файлу кэша для исходника. Открыт наружу ради проверок и диагностики.
std::string CachePathFor(const std::string& sourcePath);

// Читает кэш, если он есть и соответствует исходнику. false — кэша нет, он
// устарел или повреждён; это НЕ ошибка, вызывающий разбирает исходник.
bool ReadModelCache(const std::string& sourcePath, sage::render::ModelData& out);

// Пишет кэш. false — не удалось (нет прав, нет места); тоже не ошибка,
// программа продолжает работать, просто медленнее.
bool WriteModelCache(const std::string& sourcePath, const sage::render::ModelData& data);

// Статистика за время работы — для строки состояния и проверок.
struct Stats {
    int Hits = 0;      // загрузок из кэша
    int Misses = 0;    // разборов исходника
    long long BytesRead = 0;
};
const Stats& CacheStats();
void ResetCacheStats();

} // namespace sage::assets
