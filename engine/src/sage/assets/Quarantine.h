#pragma once
#include <string>
#include <vector>

// ---------------------------------------------------------------------------
// КАРАНТИН: ОДИН БИТЫЙ ФАЙЛ НЕ ЗАПИРАЕТ РЕДАКТОР
//
// ЗАЧЕМ. Жалоба звучала так: «если с одним проектом что-то не пойдёт, я целый
// редактор открыть НЕ СМОГУ». И это правда, а не преувеличение. Цепочка
// замыкалась в кольцо:
//
//   открыл проект -> редактор сам грузит его сцену -> в сцене ссылка на битую
//   модель -> падение -> запустил редактор снова -> открыл тот же проект (он в
//   списке первым) -> та же сцена -> то же падение.
//
// Выйти из кольца человеку нечем: редактор не успевает дожить до состояния, в
// котором можно что-то нажать, а какой именно файл виноват — ему никто не
// сказал. Работа при этом цела, но недоступна.
//
// ПОЧЕМУ НЕ «ПОЙМАТЬ ИСКЛЮЧЕНИЕ». Падение здесь — не исключение, а обращение по
// негодному адресу внутри чужого кода (разбор чужого формата, драйвер
// видеокарты). Поймать его переносимо нельзя, и делать вид, что можно, —
// значит обещать надёжность, которой нет.
//
// ЧТО ДЕЛАЕМ ВМЕСТО. То же, что браузер с расширением, роняющим вкладку:
// запоминаем, ЧТО мы собирались сделать, до того как начали.
//
//   Begin(ref)  — перед разбором файла пишем его имя в файл-метку;
//   End()       — разобрали без падения, метку убираем.
//
// Метка, пережившая запуск, означает ровно одно: на этом файле процесс умер.
// Такой файл попадает в карантин, и следующая попытка его загрузить честно
// отказывает — с именем файла и причиной. Редактор при этом открывается,
// проект открывается, сцена открывается; не появляется одна модель, и про неё
// прямо сказано.
//
// КАРАНТИН СНИМАЕТСЯ, как только файл изменился на диске: человек переэкспортил
// модель — она снова обычный файл. Иначе карантин стал бы приговором, а он —
// предохранитель.
// ---------------------------------------------------------------------------
namespace sage::assets::quarantine {

// Где держать метку и список. Задаётся один раз при старте (рядом с
// редактором); пусто — карантин выключен, всё грузится как раньше.
void SetDirectory(const std::string& dir);

// Прочитать метку прошлого запуска и, если она есть, посадить её файл в
// карантин. Зовётся ОДИН раз при старте, до первой загрузки чего-либо.
// Возвращает попавший в карантин файл ("" — прошлый запуск закончился мирно).
std::string TakeUnfinished();

// Начали разбирать файл / закончили. End() обязателен на ВСЕХ путях выхода,
// включая ошибку разбора: несостоявшаяся загрузка — не падение.
void Begin(const std::string& ref);
void End();

// В карантине ли файл. Проверяется перед загрузкой.
bool Blocked(const std::string& ref);

// Всё, что сейчас в карантине (для сообщения человеку).
std::vector<std::string> List();

// Выпустить файл из карантина — руками («всё равно попробовать») или потому,
// что файл на диске изменился.
void Release(const std::string& ref);
void Clear();

} // namespace sage::assets::quarantine
