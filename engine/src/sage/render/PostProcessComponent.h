#pragma once
#include <entt/entt.hpp>

#include "sage/render/PostEffect.h"

// Сцена движка живёт в ГЛОБАЛЬНОМ пространстве имён (см. SystemScheduler.h):
// объявляем её здесь так же, иначе получили бы другой тип.
class Scene;

// ---------------------------------------------------------------------------
// «Пост-обработка» — КОМПОНЕНТ КАМЕРЫ.
//
// ПОЧЕМУ НЕ НАСТРОЙКА ПРОЕКТА. Обработка принадлежит КАДРУ, а кадр снимает
// камера. У сцены их бывает несколько и с разным назначением: вид от первого
// лица, орто-вид сверху для схемы, камера в текстуру для портала или
// мини-карты. Пока настройка была общей, «кинематографичный» вид главной
// камеры доставался и схеме, и мини-карте, а сделать иначе было нечем.
//
// Хуже того, настройка жила в `sage.cfg` — в файле ПРОЕКТА: её нельзя было ни
// сохранить в сцену, ни положить в префаб, ни скопировать на другую камеру, ни
// откатить через Ctrl+Z. Теперь это обычный компонент: он едет вместе с
// объектом камеры и лежит в файле сцены рядом с ней.
//
// НЕТ КОМПОНЕНТА — НЕТ ОБРАБОТКИ. Камера без него отдаёт кадр как есть. Это
// главное правило системы: не бывает «эффекта, который включён где-то ещё».
// ---------------------------------------------------------------------------
namespace sage::render {

struct PostProcessComponent {
    // Общий выключатель компонента. Нужен отдельно от удаления: «посмотреть,
    // как выглядит без обработки» — ежеминутное действие, и терять ради него
    // настройки нельзя.
    bool Enabled = true;

    // Сами эффекты. Порядок их исполнения задают ЭТАПЫ (PostStage), а не
    // порядок в этом списке — см. PostChain::Ordered.
    PostChain Chain = PostChain::Default();
};

// Тракт, которым снимает эта камера. false — обработки у камеры нет вовсе
// (компонента нет или он выключен), и кадр надо показать как есть.
//
// ЕДИНСТВЕННОЕ место, где это решается. Редактор и рантайм обязаны смотреть на
// камеру одинаково: «в редакторе одна картинка, в игре другая» начинается ровно
// с того, что правило записано в двух местах.
bool ResolvePostChain(Scene& scene, entt::entity camera, PostChain& out);

} // namespace sage::render
