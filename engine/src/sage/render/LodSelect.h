#pragma once
#include <algorithm>
#include <cmath>
#include <vector>

#include <glm/glm.hpp>

// ---------------------------------------------------------------------------
// Выбор уровня детализации.
//
// ПО ЧЕМУ ВЫБИРАТЬ. По ПРОЕКЦИОННОМУ РАЗМЕРУ на экране, а не по дальности.
// Дальность — заманчиво простая метрика и неверная: дом на ста метрах занимает
// пол-экрана, а болт на десяти — два пикселя. Один и тот же порог «50 метров»
// для них означает противоположное. Проекционный размер учитывает и габарит
// объекта, и угол обзора, и разрешение — то есть ровно то, от чего зависит,
// заметит ли человек подмену геометрии.
//
// Метрика — доля высоты экрана, которую занимает ограничивающая сфера. 1.0 —
// объект во весь экран, 0.01 — сотая часть высоты (десяток пикселей на 1080p).
// Числа не зависят ни от разрешения, ни от формата кадра, поэтому пороги можно
// задавать один раз и не пересматривать при смене монитора.
//
// ФОРМУЛА. Для точки в мире clip = viewProj · (center, 1). Тогда высота сферы
// радиуса r в нормализованных координатах ≈ r · |строка Y матрицы viewProj| /
// |clip.w|. Это работает и для перспективы (там clip.w — глубина в виде), и для
// ортографии (там clip.w = 1, и размер от дальности не зависит — как и должно
// быть). Отдельных веток на два вида проекции не нужно.
// ---------------------------------------------------------------------------
namespace sage::render {

// Доля высоты экрана, занимаемая сферой (center, radius) в мировых координатах.
// viewProj — матрица кадра (или света: для карты теней метрика означает долю
// карты, что тоже осмысленно).
inline float ProjectedScreenHeight(const glm::mat4& viewProj, const glm::vec3& center,
                                   float radius) {
    if (radius <= 0.0f) return 0.0f;
    const glm::vec4 clip = viewProj * glm::vec4(center, 1.0f);
    // Масштаб мира в координату Y отсечения — длина соответствующей строки.
    // Именно строки, а не столбца: glm хранит матрицы по столбцам, и Y-строка
    // это [0][1], [1][1], [2][1].
    const float scaleY =
        glm::length(glm::vec3(viewProj[0][1], viewProj[1][1], viewProj[2][1]));
    // Объект за спиной или в самой плоскости камеры: размер не определён,
    // считаем его максимальным — отсекать такое должен фрустум, а не LOD.
    const float w = std::fabs(clip.w);
    if (w < 1e-4f) return 1.0f;
    return radius * scaleY / w;
}

// Набор порогов уровней: от подробного к грубому, пороги по убыванию.
//
// Хранится отдельно от самих мешей намеренно. Пороги — это правило выбора, и
// оно одинаково для компонента сцены, для дерева анимации и для теста; меши же
// у каждого свои. Смешав их в один тип, пришлось бы тащить GPU-ресурсы в
// юнит-тест правила.
struct LodLevels {
    // Порог i-го уровня: он берётся, пока объект занимает НЕ МЕНЬШЕ этой доли
    // экрана.
    std::vector<float> ScreenHeights;
    // Ниже этой доли объект не рисуется вовсе. 0 — не отсекать. Это самая
    // дешёвая экономия из всех: объект в один пиксель стоит столько же, сколько
    // объект во весь экран, а виден не бывает.
    float CullBelow = 0.0f;

    void Add(float screenHeight) { ScreenHeights.push_back(screenHeight); }
    bool Empty() const { return ScreenHeights.empty(); }
    int Count() const { return (int)ScreenHeights.size(); }

    // Номер уровня для объекта такого экранного размера. -1 — не рисовать.
    //
    // Сравнение НЕСТРОГОЕ (>=): ровно на пороге берётся более подробный
    // уровень. Со строгим объект, замерший на границе, прыгал бы между
    // уровнями от дрожания последнего бита — в кадре это видно как мигание.
    int Select(float screenHeight) const {
        if (CullBelow > 0.0f && screenHeight < CullBelow) return -1;
        if (ScreenHeights.empty()) return 0; // уровней нет — рисуем как есть
        for (int i = 0; i < (int)ScreenHeights.size(); ++i) {
            if (screenHeight >= ScreenHeights[i]) return i;
        }
        return (int)ScreenHeights.size() - 1; // мельче последнего порога — самый грубый
    }
};

} // namespace sage::render
