#pragma once
#include <memory>
#include <vector>

#include "sage/render/LodSelect.h"
#include "sage/render/Mesh.h"

// ---------------------------------------------------------------------------
// LodComponent — уровни детализации сущности.
//
// Компонент, а не поле MeshRendererComponent: уровни есть у единиц объектов в
// сцене (у крупных и часто повторяющихся), а платить памятью за пустой вектор
// в каждом рендерящемся объекте незачем. Отсутствие компонента означает «этот
// объект рисуется как есть» — ровно то поведение, что было до LOD.
//
// ЧТО СЕРИАЛИЗУЕТСЯ. Пороги и признак автопостроения. Сами грубые меши — нет:
// они целиком выводятся из исходной геометрии, и хранить их в файле сцены
// значило бы дублировать модель столько раз, сколько уровней, и ловить
// рассинхрон, когда художник переэкспортировал исходник.
// ---------------------------------------------------------------------------
namespace sage::render {

struct LodComponent {
    // Грубые меши: [0] — первый упрощённый уровень (сам подробный меш живёт в
    // MeshRendererComponent и уровнем не считается). Заполняются на загрузке.
    std::vector<std::shared_ptr<Mesh>> Meshes;

    // Пороги. Число порогов = Meshes.size() + 1: первый порог принадлежит
    // исходному мешу.
    LodLevels Levels;

    // Строить уровни автоматически при загрузке (см. BuildAutoLods).
    bool Auto = true;
    int AutoCount = 2; // сколько ГРУБЫХ уровней добавить к исходному

    // Меш для выбранного уровня. level 0 — исходный (baseMesh), дальше — из
    // Meshes. Возвращает baseMesh, если уровня нет: лучше нарисовать подробно,
    // чем не нарисовать вовсе.
    Mesh* MeshFor(int level, Mesh* baseMesh) const {
        if (level <= 0) return baseMesh;
        const int i = level - 1;
        if (i < (int)Meshes.size() && Meshes[(size_t)i]) return Meshes[(size_t)i].get();
        return baseMesh;
    }
};

// Строит грубые уровни из подробного меша. Требует, чтобы меш хранил копию
// геометрии (Mesh с keepCpuData) — без неё вернёт false и НЕ будет молча
// делать вид, что уровни построены.
//
// Доли треугольников по уровням: каждый следующий примерно вчетверо грубее
// (1/4, 1/16, …). Вчетверо, а не вдвое: уровень, отличающийся вдвое, почти не
// экономит, зато удваивает число переключений и шансов увидеть подмену.
//
// Пороги экранного размера ставятся так, чтобы уровень менялся, когда объект
// уменьшается вдвое по высоте кадра. На 1080p первый переход приходится
// примерно на 200 пикселей высоты — там подмена ещё незаметна, а экономия уже
// заметна.
bool BuildAutoLods(LodComponent& lod, const Mesh& source, int coarseLevels = 2);

} // namespace sage::render
