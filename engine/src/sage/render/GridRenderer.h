#pragma once
#include <memory>

#include <glm/glm.hpp>

#include "sage/rhi/Resources.h"

// ---------------------------------------------------------------------------
// GridRenderer — опорная сетка сцены.
//
// Не отладочные линии, а полноценный элемент вида: по ней выравнивают объекты,
// от неё считают шаг привязки гизмо, ею оценивают масштаб сцены.
//
// Почему шейдер, а не набор линий. Линейная сетка задаёт вопрос, на который нет
// хорошего ответа: сколько линий рисовать? Мало — сетка кончается на середине
// кадра; много — тысячи вызовов и мерцающая рябь вдали, где линии сходятся
// ближе пикселя. Здесь вместо этого рисуется ОДИН полноэкранный треугольник:
// фрагментный шейдер пересекает луч с плоскостью и считает линию аналитически,
// по производной координаты (fwidth). Толщина получается постоянной в пикселях,
// сетка не рябит на любом удалении, а «бесконечная» она в буквальном смысле —
// её протяжённость ничего не стоит.
//
// Два режима протяжённости — не украшение, а два разных способа работы:
//   • Infinite — сетка уходит за горизонт с плавным затуханием. Так удобно
//     ставить сцену: видно направление и масштаб в любую сторону;
//   • Radius — сетка обрывается на заданном радиусе с мягким краем. Так
//     обозначают рабочую область: съёмочную площадку, границы уровня.
//
// Глубина пишется настоящая (из точки пересечения), поэтому сетка правильно
// перекрывается геометрией и уходит под пол, а не лежит поверх всего.
// ---------------------------------------------------------------------------
namespace sage::render {

struct GridSettings {
    bool Enabled = true;

    enum class Extent {
        Infinite, // до горизонта, с затуханием
        Radius,   // круг заданного радиуса с мягким краем
    };
    Extent Mode = Extent::Infinite;
    float Radius = 25.0f; // метры, значим при Mode == Radius

    // Шаг мелкой клетки в единицах мира и через сколько клеток идёт крупная
    // линия. Две частоты нужны, чтобы сетка оставалась читаемой и вблизи, и
    // издали: мелкие линии гаснут с расстоянием, крупные остаются.
    float CellSize = 1.0f;
    int MajorEvery = 10;

    float Height = 0.0f; // высота плоскости сетки по Y

    glm::vec3 MinorColor{0.32f, 0.34f, 0.38f};
    glm::vec3 MajorColor{0.46f, 0.49f, 0.55f};
    // Оси мира выделены цветом — иначе в сетке из одинаковых клеток теряется,
    // где начало координат и куда смотрит X.
    bool ShowAxes = true;
    glm::vec3 XAxisColor{0.78f, 0.32f, 0.34f};
    glm::vec3 ZAxisColor{0.34f, 0.46f, 0.82f};

    float Opacity = 1.0f;
    // Расстояние полного затухания для Infinite. 0 — считать автоматически от
    // высоты камеры: чем выше поднялись, тем дальше видно сетку.
    float FadeDistance = 0.0f;
};

class GridRenderer {
public:
    GridRenderer() = default;
    GridRenderer(const GridRenderer&) = delete;
    GridRenderer& operator=(const GridRenderer&) = delete;

    // Рисует сетку в ТЕКУЩИЙ буфер. Вызывать ПОСЛЕ непрозрачной геометрии:
    // сетка полупрозрачна и должна смешиваться с тем, что за ней, а глубину
    // пишет свою — чтобы объекты её перекрывали.
    void Draw(const glm::mat4& view, const glm::mat4& proj, const glm::vec3& cameraPos,
              const GridSettings& settings);

private:
    void EnsureGeometry();
    std::unique_ptr<sage::rhi::Geometry> m_fsTri;
};

} // namespace sage::render
