#pragma once
#include <vector>

// ---------------------------------------------------------------------------
// Цвет под прозрачностью — для текстур с вырезом по альфе (листва, трава).
//
// ЗАЧЕМ. У прозрачного пикселя всё равно есть цвет, и экспортёры кладут туда
// что придётся. У листвы из Stylized Nature MegaKit три четверти картинки
// прозрачны, и половина этих пикселей ЧЁРНАЯ. На экране их не видно, пока
// видеокарта не начинает смешивать соседей: билинейная выборка на краю листа
// и особенно мип-уровни (каждый — среднее четырёх пикселей предыдущего)
// подмешивают в лист чёрное и серое. Вблизи это тёмная кайма по контуру, вдали
// — потемневшая и выцветшая крона, а с выключенным вырезом — чёрные полосы по
// карточкам.
//
// КАК. Прозрачным пикселям отдаётся цвет листа: сперва несколько проходов
// «растекания» от непрозрачных соседей (края получают ТОЧНЫЙ цвет своего
// листа), потом остаток заливается средним цветом всего непрозрачного. Альфа
// не меняется — вырез остаётся ровно тем же. Применяется ТОЛЬКО к картам с
// вырезом: у обычной текстуры альфа бывает чем угодно (гладкость, маска), и
// переписывать под ней цвет значило бы испортить данные.
// ---------------------------------------------------------------------------
namespace sage::render {

// rgba — w*h*4 байт. Прозрачным считается альфа < 16. Ничего не делает, если
// прозрачных или непрозрачных пикселей нет вовсе.
void BleedTransparentColor(std::vector<unsigned char>& rgba, int w, int h, int passes = 4);

} // namespace sage::render
