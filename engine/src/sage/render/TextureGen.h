#include <vector>

#include <glm/glm.hpp>

#include "sage/render/Texture.h"

// ---------------------------------------------------------------------------
// Процедурные текстуры: картинка, посчитанная формулой, а не загруженная с
// диска.
//
// ЗАЧЕМ ЭТО В ДВИЖКЕ. Без текстур поверхность в кадре — это ровная заливка,
// одинаковая на всём протяжении. Освещение по ней читается плохо: у ровного
// цвета нет ни масштаба (непонятно, метр перед тобой или сто), ни мелкой
// формы, на которой видно блик. Обычный ответ — положить в проект файлы
// картинок, но у него есть цена, которая на прототипе перевешивает пользу:
// мегабайты в репозитории, лицензии на чужие изображения и невозможность
// поменять размер клетки, не открывая редактор изображений.
//
// Формула не стоит ничего на диске, читается как код («шахматка 2 метра,
// светлая и тёмная»), правится одним числом и отдаёт любое разрешение.
// Поэтому она и появилась здесь: не как замена художнику, а как то, на чём
// стоит ПРОТОТИП и на чём проверяется сам рендер — фильтрация, мипмапы,
// анизотропия, нормал-маппинг.
//
// ЧТО ВАЖНО В РЕАЛИЗАЦИИ: все узоры БЕСШОВНЫ по краям. Текстура на полу
// повторяется десятки раз, и шов, заметный на одном стыке, будет заметен на
// всех сразу — то есть узор, не сходящийся по краю, здесь просто непригоден.
// Ради этого число клеток округляется до целого, а шум считается на
// ПЕРИОДИЧЕСКОЙ решётке (см. ValueNoise).
// ---------------------------------------------------------------------------
namespace sage::render {

// Рецепт текстуры: что нарисовать и какого размера.
//
// Одна структура на все узоры, а не иерархия классов: узор выбирается полем
// Kind, а лишние для него поля просто не читаются. Так рецепт целиком
// описывается таблицей из скрипта (sage.texture.Generate) и сериализуется
// как есть — с иерархией классов и то и другое потребовало бы своего кода на
// каждый узор.
struct TextureRecipe {
    enum class Pattern {
        Solid,      // заливка ColorA: подложка и заглушка
        Checker,    // шахматка: масштаб виден без единой цифры
        Grid,       // сетка линий ColorB по фону ColorA: швы плитки, разметка
        Noise,      // фрактальный шум: грязь, разнотон, карта шероховатости
        Gradient,   // переход A->B: небо, затухание, градиентные пандусы
        Bricks,     // кирпичная кладка со смещением рядов
        Dots,       // точки/заклёпки по сетке
    };

    Pattern Kind = Pattern::Checker;

    // Размер в пикселях. Степень двойки — не суеверие: мипмапы для неё
    // строятся точным делением пополам, без округления и «плывущих» уровней.
    int Width = 512;
    int Height = 512;

    glm::vec4 ColorA{0.82f, 0.82f, 0.84f, 1.0f};   // основной цвет
    glm::vec4 ColorB{0.30f, 0.31f, 0.34f, 1.0f};   // второй цвет узора

    // Сколько клеток (кирпичей, точек) укладывается в текстуру по осям. Для
    // бесшовных узоров округляется до целого — половина клетки на краю и есть
    // тот самый шов.
    float TilesX = 8.0f;
    float TilesY = 8.0f;

    // Толщина линии сетки / шва кладки долей клетки. 0.04 — тонкий шов,
    // 0.2 — широкая расшивка.
    float LineWidth = 0.05f;

    // Насколько ряды кладки смещены друг относительно друга (0.5 — классика).
    float Offset = 0.5f;

    // Градиент: направление в градусах (0 — слева направо) и радиальность.
    float Angle = 90.0f;
    bool Radial = false;

    // Шум: сколько октав складывать, начальная частота (в клетках на
    // текстуру, целая ради бесшовности) и во сколько раз слабее каждая
    // следующая октава.
    int Octaves = 4;
    float Frequency = 4.0f;
    float Persistence = 0.5f;
    unsigned int Seed = 1u;

    // Зерно поверх любого узора: лёгкий шум, разбивающий ровную заливку.
    // Ноль — чистый узор. Ровный цвет без зерна на большой площади выглядит
    // пластиком, а не материалом.
    float Grain = 0.0f;

    // Выдать не цвет, а КАРТУ НОРМАЛЕЙ по тому же узору, считая его яркость
    // высотой. Один рецепт даёт и картинку, и рельеф к ней — иначе их пришлось
    // бы держать согласованными вручную, и первая же правка их развела бы.
    bool AsNormal = false;
    float NormalStrength = 1.0f;

    // Ключ кэша: рецепт, свёрнутый в строку. Две одинаковые текстуры не должны
    // считаться дважды, а сравнивать рецепты полями пришлось бы в каждом
    // вызывающем.
    std::string Key() const;
};

// Пиксели RGBA8, построчно сверху вниз. Отдельно от создания GPU-текстуры:
// на этом уровне генератор проверяется тестами без графического контекста.
std::vector<unsigned char> GenerateTexturePixels(const TextureRecipe& recipe);

// Готовая GPU-текстура. Требует текущего графического бэкенда.
std::shared_ptr<Texture> GenerateTexture(const TextureRecipe& recipe,
                                         TextureFilter filter = TextureFilter::Anisotropic,
                                         bool mipmaps = true);

// Разбор имени узора из строки ("checker", "noise", ...). false — имя
// незнакомо; молча подставлять заливку нельзя: человек будет смотреть на
// однотонный пол и думать, что сломан генератор.
bool ParseTexturePattern(const std::string& name, TextureRecipe::Pattern& out);

} // namespace sage::render
