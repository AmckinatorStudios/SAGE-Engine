// ---------------------------------------------------------------------------
// Отражения.
//
// ЗАЧЕМ. До этого непрямой свет в движке был только диффузным: ambient умножал
// albedo и на этом заканчивался. Металл в такой модели невозможен физически —
// у металла нет диффузной составляющей вообще, весь его вид и есть отражение
// окружения. Хромовый шар выходил ровным серым пятном, мокрый асфальт — сухим,
// вода — крашеной плоскостью. Настройками света это не лечится: отражать было
// нечего, потому что окружение нигде не хранилось.
//
// ЧЕМ ОТРАЖАТЬ. Ни один способ не годится в одиночку, поэтому их два, и они
// складываются по убыванию точности:
//
//   1. Карта окружения (cubemap) — знает всё вокруг, включая то, что за
//      камерой, но снята из ОДНОЙ точки и не обновляется каждый кадр. Это
//      фундамент: работает всегда и везде. Снимается либо с неба (открытые
//      сцены), либо со всей сцены зондом (ReflectionProbeComponent).
//   2. Плоское отражение — сцена, отрисованная зеркально относительно
//      плоскости. Точное и полное, ценой второго прохода геометрии, но ровно
//      для одной плоскости. Это способ для воды, зеркал и мокрого пола.
//
// Смешиваются они в шейдере (см. SpecularIBL в PbrShader.h): куб снизу,
// плоское — поверх, там где оно есть.
//
// ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. Экранных отражений (SSR). Они трассируют луч по
// буферу глубины кадра, и в ОТЛОЖЕННОМ рендере это почти бесплатно: нормаль и
// шероховатость уже лежат в G-буфере, а отражение подмешивается после сцены.
// У движка рендер прямой (forward), и оба доступных здесь варианта платят
// ровно теми артефактами, ради борьбы с которыми SSR и берут: считать SSR ДО
// сцены можно только по цвету ПРОШЛОГО кадра — отражение отстаёт от движения
// на кадр и «плавает»; считать ПОСЛЕ — не по чему, шейдер уже не знает, где
// какая шероховатость, пока не заведён G-буфер, то есть пока рендер не стал
// отложенным. Так что SSR — это не забытая галочка, а решение, которое стоит
// принимать вместе со сменой типа рендера.
// ---------------------------------------------------------------------------
namespace sage::render {

// Настройки отражений СЦЕНЫ — то, что задаёт игра (и что сохраняется в .sage),
// в отличие от ReflectionBinding, который живёт один кадр и держит GPU-ресурсы.
//
// Плоскость отражения здесь, а не в компоненте воды, намеренно: плоскость в
// сцене одна на проход (второй потребовал бы второго прохода геометрии), и
// принадлежит она сцене, а не какому-то одному объекту на ней.
struct ReflectionSettings {
    bool Enabled = true;
    float Intensity = 1.0f;

    // Плоское отражение: (нормаль, d), уравнение dot(n, p) + d = 0.
    // Для воды на высоте h это (0, 1, 0, -h).
    bool PlanarEnabled = false;
    glm::vec4 Plane{0.0f, 1.0f, 0.0f, 0.0f};
    float PlanarScale = 0.5f;   // доля разрешения кадра
};

// Карта окружения: cubemap с мипами, где мип — это шероховатость.
//
// Мипы не «уменьшенные копии для экономии», а шкала размытия: зеркало берёт
// нулевой, матовая краска — дальний. Строятся аппаратной фильтрацией
// (GenerateMips), а не сверткой по GGX: свёртка честнее, но стоит секунды на
// зонд, а разница видна только на средней шероховатости. Честная оговорка —
// это приближение, и именно поэтому мип выбирается по rough * MaxLod, а не по
// физически выведенному углу.
class EnvironmentMap {
public:
    // size — сторона грани. 128 хватает: отражение либо размыто шероховатостью,
    // либо его перекрывают SSR/плоское отражение, которые куда подробнее.
    explicit EnvironmentMap(int size = 128);

    bool Valid() const { return m_cube != nullptr; }
    void Bind(int unit) const { if (m_cube) m_cube->Bind(unit); }
    float MaxLod() const { return m_cube ? (float)(m_cube->MipLevels() - 1) : 0.0f; }
    int Size() const { return m_cube ? m_cube->Size() : 0; }

    // Точка, из которой снято, и коробка влияния — для параллакс-коррекции.
    const glm::vec3& Position() const { return m_position; }
    const glm::vec3& BoxMin() const { return m_boxMin; }
    const glm::vec3& BoxMax() const { return m_boxMax; }
    bool HasBox() const { return m_hasBox; }
    void SetBox(const glm::vec3& mn, const glm::vec3& mx) {
        m_boxMin = mn; m_boxMax = mx; m_hasBox = true;
    }
    void ClearBox() { m_hasBox = false; }

    // Что рисовать в грань: вызывающему дают матрицы вида и проекции этой
    // грани, он рисует сцену. Кто рисует — знает только он: движок не может
    // сам решить, входят ли в отражение частицы, интерфейс или отладочная
    // сетка.
    using FaceDraw = std::function<void(const glm::mat4& view, const glm::mat4& proj)>;

    // Снять окружение из точки pos. Внутри — шесть проходов сцены, поэтому
    // зовётся по событию (перестроили уровень, сменили время суток), а не
    // каждый кадр.
    void Capture(const glm::vec3& pos, float nearClip, float farClip, const FaceDraw& draw);

    // Быстрый путь: только небо, без геометрии. Для открытых сцен (океан,
    // поле) этого достаточно, и стоит он шесть заливок градиентом.
    void CaptureSky(SkyRenderer& sky, const LightingEnvironment& env);

    // Матрицы вида для граней куба в порядке +X,-X,+Y,-Y,+Z,-Z. Публичные,
    // потому что нужны и снаружи: захват зонда в редакторе показывает грани
    // по одной.
    static glm::mat4 FaceView(int face, const glm::vec3& pos);
    static glm::mat4 FaceProj(float nearClip, float farClip);

private:
    std::unique_ptr<sage::rhi::CubeRenderTarget> m_cube;
    glm::vec3 m_position{0.0f};
    glm::vec3 m_boxMin{0.0f}, m_boxMax{0.0f};
    bool m_hasBox = false;
};

// Зеркальное отражение относительно плоскости — то, чем делается вода.
//
// Работает так: камера отражается относительно плоскости, сцена рисуется
// повторно в отдельный буфер, и результат читается ПО ЭКРАННОЙ ПОЗИЦИИ
// пикселя. Читается именно так не для простоты: проекция у отражённого вида та
// же, поэтому точка на плоскости попадает в тот же пиксель, что и её отражение
// — совпадение точное, а не подогнанное.
//
// Два места, где это ломается, если не позаботиться:
//   • Порядок обхода. Отражение выворачивает пространство наизнанку, и лицевые
//     треугольники становятся изнаночными. Без смены отсечения отражение
//     показывает внутренности моделей.
//   • Геометрия ПОД плоскостью. Она в отражении не участвует, но честно
//     рисуется и перекрывает то, что нужно. Отсекается косой ближней
//     плоскостью (oblique near plane): проекция правится так, что ближней
//     плоскостью отсечения становится сама плоскость отражения.
class PlanarReflection {
public:
    // scale — доля от размера кадра. Половина почти незаметна: отражение и так
    // размывается рябью, а стоит вчетверо дешевле.
    explicit PlanarReflection(float scale = 0.5f) : m_scale(scale) {}

    // plane — (нормаль, d) в мировых координатах: dot(n, p) + d = 0.
    // Возвращает false, если камера с изнанки плоскости: снизу вода не
    // отражает, а показывает то, что над ней, и подсовывать туда отражение
    // значило бы рисовать заведомую неправду.
    // ПОСЛЕ вызова привязан экранный буфер, а viewport выставлен на
    // screenW x screenH: проход менял и то, и другое.
    bool Capture(const glm::vec4& plane, const glm::mat4& view, const glm::mat4& proj,
                 int screenW, int screenH, const EnvironmentMap::FaceDraw& draw);

    unsigned int Texture() const;
    void Reset() { m_valid = false; }
    bool Valid() const { return m_valid; }

    // Отражение точки/матрицы относительно плоскости — вынесено, потому что
    // это же преобразование нужно и вызывающему (отразить положение камеры для
    // отсечения по фрустуму).
    static glm::mat4 MirrorMatrix(const glm::vec4& plane);
    // Проекция с ближней плоскостью, совпадающей с plane (в пространстве вида).
    static glm::mat4 ObliqueNearPlane(const glm::mat4& proj, const glm::vec4& planeView);

private:
    std::unique_ptr<sage::rhi::RenderTarget> m_target;
    float m_scale = 0.5f;
    bool m_valid = false;
};

// Всё, что проход сцены отдаёт шейдерам про отражения. Одна структура, а не
// список аргументов: набор источников растёт, и каждый новый иначе пришлось бы
// протаскивать через все проходы поимённо.
struct ReflectionBinding {
    const EnvironmentMap* Env = nullptr;
    float Intensity = 1.0f;

    unsigned int PlanarTexture = 0;   // 0 — плоского отражения нет
    glm::vec2 ScreenTexel{0.0f};      // 1/размер кадра

    // Этот проход САМ снимает плоское отражение. Тогда из него выбрасываются
    // все зеркальные поверхности (Material::PlanarReflectivity > 0): зеркало не
    // должно попадать в собственное отражение.
    //
    // Без этого вода рисуется внутри своего же отражения и застилает его: в
    // зеркале оказывается слой воды, сквозь который корабль едва просвечивает.
    // На «Лодке» это видно сразу, если вывести буфер отражения на экран —
    // ровно так дефект и нашёлся.
    bool CapturingPlanar = false;

    // Текстурные юниты.
    //
    // Заняты: 0 albedo, 1 каскад тени 0, 2 нормали, 3 металличность,
    // 4 шероховатость, 5 AO, 6..8 объём GI, 9 лайтмапа, 10..12 каскады 1..3.
    // Свободны с 13 — отсюда и значения. Числа тут не «какие-нибудь»: на
    // занятом юните оказались бы ДВА РАЗНЫХ ТИПА сэмплера (sampler2D и
    // samplerCube), а это в GL некорректное состояние — драйвер вправе
    // выбросить весь вызов отрисовки. Ровно это и произошло при первой сборке:
    // куб встал на юнит объёма GI, и сцена перестала рисоваться целиком.
    static constexpr int kEnvUnit = 13;
    static constexpr int kPlanarUnit = 14;
};

// Владелец отражений одного вида (вьюпорта). По одному на камеру: карта
// окружения снимается из своей точки, и делить её между видами нельзя.
//
// Держит карту неба, выбирает активный зонд и решает, КОГДА пересчитывать.
// «Когда» здесь и есть вся суть: шесть проходов сцены на кадр не потянет
// никто, а раз в жизни — это неверное отражение сразу после первого заката.
// Поэтому пересчёт по ИЗМЕНЕНИЮ: небо переснимается, когда поменялись его
// цвета или солнце, зонды — по явной просьбе или по своему интервалу.
class ReflectionSystem {
public:
    // Небо как источник отражений. Для открытых сцен (океан, поле) этого
    // достаточно, и стоит оно шесть заливок градиентом на изменение.
    void UpdateSky(SkyRenderer& sky, const LightingEnvironment& env);

    // Снять окружение со всей сцены из точки pos: то же, но с геометрией.
    void CaptureScene(const glm::vec3& pos, float nearClip, float farClip,
                      const EnvironmentMap::FaceDraw& draw);

    // Коробка влияния для параллакс-коррекции (мировые границы помещения).
    void SetBox(const glm::vec3& mn, const glm::vec3& mx);
    void ClearBox();

    void SetEnabled(bool on) { m_enabled = on; }
    bool Enabled() const { return m_enabled; }
    void SetIntensity(float v) { m_intensity = v; }

    const EnvironmentMap* Env() const { return m_env && m_env->Valid() ? m_env.get() : nullptr; }

    // Готовая привязка для прохода сцены.
    ReflectionBinding Binding(int screenW, int screenH, unsigned int planarTexture = 0) const;

private:
    EnvironmentMap& Ensure();

    std::unique_ptr<EnvironmentMap> m_env;
    bool m_enabled = true;
    float m_intensity = 1.0f;
    // Слепок неба, по которому решается «пора пересчитывать». Хранится, а не
    // сравнивается по флагу «грязно»: цвета правит и редактор, и скрипт, и
    // таймлайн, и уговориться, что все они дёргают флаг, не выйдет.
    glm::vec3 m_skyTop{-1.0f}, m_skyHorizon{-1.0f};
    bool m_captured = false;
};

// Заливает uniform'ы отражений (имена совпадают с PbrShader.h). Выключенный
// источник обязан быть выключен ЯВНО: невыставленный bool в GLSL равен нулю
// только до первого кадра, а дальше в программе остаётся значение с прошлого
// объекта, и отражение «прилипало» бы к материалам, которым его не давали.
void UploadReflection(Shader& shader, const ReflectionBinding& binding);

} // namespace sage::render
