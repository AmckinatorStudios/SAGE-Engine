#pragma once
#include "sage/render/ParticleEffect.h"

// ---------------------------------------------------------------------------
// Компоненты живут рядом со своей системой, а не в общем файле (см. историю в
// scene/Components.h — он остался зонтиком и включает этот файл).
//
// Система: sage/render/ParticleECS.h.
// ---------------------------------------------------------------------------

// Эмиттер частиц на сущности. ВЕСЬ эффект — данными (sage::fx::ParticleEffect):
// форма, испускание, кривые, силы, текстура, отрисовка. Никаких «пресетов» —
// готовый эффект приходит файлом .sagefx (инспектор умеет загрузить его в
// компонент и сохранить компонент в файл) или собирается мышью.
struct ParticleEmitterComponent {
    sage::fx::ParticleEffect Effect;
    bool Playing = true;          // рождает ли новые частицы (живые доживают)

    // --- Команды скрипта на этот кадр (рантайм, не сериализуются) ---------
    int PendingEmit = 0;          // родить столько частиц немедленно
    bool RestartRequested = false;  // начать цикл заново (залпы, задержка)
    bool ClearRequested = false;    // убрать живые частицы
};
