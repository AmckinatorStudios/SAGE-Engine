#pragma once
#include <memory>

#include <glm/glm.hpp>

#include "sage/rhi/Resources.h"
#include "sage/render/Framebuffer.h"

// ---------------------------------------------------------------------------
// PostFX — полный проход пост-обработки движка поверх HDR-буфера сцены.
//
// Порядок цепочки (важен: каждый следующий шаг видит результат предыдущего):
//   1. SSAO           — screen-space ambient occlusion из depth-текстуры;
//   2. Depth of Field — глубина резкости по кругу нерезкости из глубины;
//   3. Motion Blur    — камерный, по репроекции глубины прошлым кадром;
//   4. Bloom          — свечение ярких участков (bright-pass + размытие);
//   5. Composite      — экспозиция, ACES тон-маппинг, AO, bloom, насыщенность/
//                       контраст, ХРОМАТИЧЕСКАЯ АБЕРРАЦИЯ, виньетка, гамма.
//
// DoF и Motion Blur стоят ДО bloom сознательно: свечение должно считаться по
// той картинке, которая уйдёт в кадр, иначе размытый фонарь давал бы резкий
// ореол — сам источник размыт, а его свечение нет.
//
// Владеет промежуточными буферами (ColorHDR) и встроенными шейдерами; консьюмер
// (редактор/игра/инструмент) просто зовёт Render с цветом+глубиной сцены.
// Реюзабелен — один экземпляр на вьюпорт (он же хранит матрицу прошлого кадра
// для motion blur, поэтому делить один PostFX между двумя вьюпортами нельзя).
// Часть ЯДРА рендера, не зависит от конкретной игры.
// ---------------------------------------------------------------------------
namespace sage::render {

struct PostFXSettings {
    bool Enabled = true;

    // Тон-маппинг / цвет.
    float Exposure = 1.05f;
    float Gamma = 2.2f;
    float Saturation = 1.16f;
    float Contrast = 1.06f;

    // Bloom (свечение).
    bool BloomEnabled = true;
    float BloomThreshold = 1.0f;  // яркость, выше которой пиксель «светится»
    float BloomIntensity = 0.55f; // сила добавляемого свечения

    // SSAO (ambient occlusion).
    bool AOEnabled = true;
    float AORadius = 0.5f;    // радиус выборки в мировых единицах (вид-пространство)
    float AOStrength = 1.0f;  // 0 — выкл, 1 — норма, >1 — сильнее затемнение

    // --- Глубина резкости (depth of field) ---
    // Размывает всё, что дальше или ближе плоскости фокуса. Радиус размытия —
    // круг нерезкости (circle of confusion): чем дальше от плоскости фокуса и
    // чем шире открыта диафрагма (МЕНЬШЕ f-число), тем он больше.
    bool DofEnabled = false;
    float FocusDistance = 10.0f;  // расстояние до плоскости фокуса, единицы мира
    float Aperture = 2.8f;        // f-число: 1.4 — сильное размытие, 16 — почти всё резко
    float DofMaxRadius = 12.0f;   // потолок радиуса в ПИКСЕЛЯХ (ограничивает цену прохода)

    // --- Motion blur (смаз движения) ---
    // Камерный: скорость пикселя берётся из репроекции его мировой позиции
    // матрицей прошлого кадра. Смазывается движение и поворот КАМЕРЫ; смаз от
    // движения самих объектов потребовал бы буфера скоростей на этапе геометрии.
    bool MotionBlurEnabled = false;
    float MotionBlurAmount = 0.5f; // 0 — выкл, 1 — полный вектор смещения за кадр
    int MotionBlurSamples = 12;    // выборок вдоль вектора скорости

    // --- Хроматическая аберрация ---
    // Радиальное расхождение каналов к краям кадра, как у реальной оптики.
    float ChromaticAberration = 0.0f; // 0 — выкл

    // Виньетка — затемнение к углам кадра.
    float Vignette = 0.35f;   // 0 — выкл

    // --- Сглаживание кромок (FXAA) ---
    // Идёт ПОСЛЕ тон-маппинга, по готовой LDR-картинке: FXAA ищет края по
    // воспринимаемой яркости, и в линейном HDR его пороги не работают.
    //
    // Это экранный фильтр: он сглаживает то, что видно, и ничего не знает о
    // геометрии, поэтому не убирает мерцание тонких деталей в движении (для
    // этого нужен TAA или сверхсэмплинг — см. накопительный режим у
    // инструментов рендера). Зато стоит один проход и не требует ни истории
    // кадров, ни буфера скоростей.
    bool FxaaEnabled = true;
    // Порог контраста, ниже которого пиксель считается не-кромкой. Слишком
    // низко — размывается текстура, слишком высоко — ступеньки остаются.
    float FxaaContrastThreshold = 0.0625f;
};

class PostFX {
public:
    PostFX();
    PostFX(const PostFX&) = delete;
    PostFX& operator=(const PostFX&) = delete;

    // Прогоняет всю цепочку и пишет результат в ТЕКУЩИЙ привязанный буфер
    // (экран или FBO), в прямоугольник (outX,outY,outW,outH).
    //   sceneColor — HDR-цвет сцены (Framebuffer::ColorTexture)
    //   sceneDepth — depth-текстура сцены (Framebuffer::DepthTexture); 0 — без
    //                SSAO, глубины резкости и motion blur (все трое читают глубину)
    //   w,h        — размер буфера сцены (внутреннее разрешение прохода эффектов)
    //   proj, view — матрицы камеры ЭТОГО кадра. proj нужна SSAO и DoF для
    //                реконструкции позиций из глубины; пара proj*view — motion
    //                blur, который сравнивает её с такой же парой прошлого кадра
    //                (PostFX хранит её сам, поэтому вызывающему ничего помнить
    //                не надо; при первом кадре и после смены размера смаз
    //                пропускается — сравнивать не с чем).
    // output != nullptr — composite пишется в этот Framebuffer (вьюпорт редактора);
    // output == nullptr — в экранный буфер, в прямоугольник (outX,outY,outW,outH).
    //
    // velocityTexture — буфер экранных СКОРОСТЕЙ (sage::ecs::RenderBatch::
    // RenderVelocity). Если он передан, смаз движения берёт вектор оттуда и
    // смазывает движение и камеры, И объектов. Ноль — старый путь: движение
    // восстанавливается из глубины матрицей прошлого кадра, что даёт смаз
    // ТОЛЬКО от камеры. Второй путь оставлен не для совместимости, а по делу:
    // он не требует лишнего прохода геометрии, и там, где камера — единственное,
    // что движется, он даёт тот же результат дешевле.
    void Render(unsigned int sceneColor, unsigned int sceneDepth, int w, int h,
                const glm::mat4& proj, const glm::mat4& view, const PostFXSettings& s,
                Framebuffer* output, int outX, int outY, int outW, int outH,
                unsigned int velocityTexture = 0);

    // Сбрасывает накопленную историю кадра (матрицу прошлой камеры). Нужен
    // после «телепорта» камеры — смены плана, перемотки таймлайна, загрузки
    // сцены: иначе первый кадр после скачка смазало бы через весь экран.
    void ResetHistory() { m_hasPrevFrame = false; }

private:
    void EnsureTargets(int w, int h);
    // Лениво создаёт полноразмерный вспомогательный буфер. DoF и motion blur
    // включают редко, а полноэкранный HDR-таргет стоит заметной VRAM — держать
    // их всегда только ради выключенной галочки незачем.
    sage::rhi::RenderTarget* EnsureAux(std::unique_ptr<sage::rhi::RenderTarget>& slot);

    std::unique_ptr<sage::rhi::Geometry> m_fsTri; // полноэкранный треугольник (без атрибутов)

    // Промежуточные буферы (ColorHDR). AO — полноразмерный, bloom — половинный.
    std::unique_ptr<sage::rhi::RenderTarget> m_ao, m_aoBlur;
    std::unique_ptr<sage::rhi::RenderTarget> m_bright, m_bloomA, m_bloomB;
    // Полноразмерные, создаются по факту включения эффекта (см. EnsureAux).
    std::unique_ptr<sage::rhi::RenderTarget> m_dof, m_motion;
    // Готовая LDR-картинка перед FXAA: сглаживание — отдельный проход после
    // composite, ему нужен вход, а не запись «в себя».
    std::unique_ptr<sage::rhi::RenderTarget> m_ldr;
    int m_w = 0, m_h = 0;

    // История для motion blur: view-projection прошлого кадра.
    glm::mat4 m_prevViewProj{1.0f};
    bool m_hasPrevFrame = false;
};

} // namespace sage::render
