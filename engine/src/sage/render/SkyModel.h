#include <glm/glm.hpp>

#include "sage/scene/Light.h"

// ---------------------------------------------------------------------------
// ВРЕМЯ СУТОК: как высота солнца превращается в цвет неба и в свет сцены.
//
// ЧТО БЫЛО НЕ ТАК. Процедурное небо было градиентом из двух ПОСТОЯННЫХ цветов
// плюс необязательные светила. Опускаешь солнце за горизонт — и не меняется
// НИЧЕГО: то же полуденное небо, та же полуденная засветка объектов, тот же
// направленный свет (теперь бьющий снизу, из-под земли), и только звёзды с
// луной проступают поверх дневной картинки. Ночи в движке не существовало —
// существовала дневная сцена с наклейками звёзд.
//
// ЧТО ЗДЕСЬ СЧИТАЕТСЯ. Одна величина — высота солнца над горизонтом — и всё,
// что из неё следует:
//
//   • цвета градиента: дневная пара переходит в ночную, у горизонта на закате
//     и рассвете добавляется своя тёплая полоса;
//   • ГЛАВНОЕ СВЕТИЛО кадра: днём это солнце, ночью — луна. Оно же освещает
//     сцену и отбрасывает тени, поэтому ночью тени идут от луны и они слабые;
//   • окружающий свет: он берётся из неба (см. ResolveAmbient), а небо к этому
//     моменту уже знает, который час.
//
// ПОЧЕМУ ОДНО СВЕТИЛО, А НЕ ДВА. Шейдер освещения знает ровно один направленный
// источник (и одна каскадная карта теней под него). Заводить второй ради луны —
// это плюс карта теней, плюс проход глубины и плюс ветка в каждом шейдере ради
// света, который по яркости в сотни раз слабее дневного. Вместо этого слот
// занимает тот, кто сейчас главный: переключение происходит в момент, когда оба
// вклада равны, то есть когда оба почти нулевые, — и увидеть его нельзя.
//
// ПОЧЕМУ НЕ ЗДЕСЬ ВРЕМЯ. Никаких «часов суток» и «скорости времени» в модели
// нет намеренно: время задаётся ПОВОРОТОМ объекта-солнца, как и всё остальное в
// сцене. Захочет игра цикл дня и ночи — она вращает солнце скриптом, и это
// работает уже сейчас; заведи движок собственные часы, их пришлось бы
// синхронизировать с этим поворотом, и первый же конфликт стоил бы дороже, чем
// всё удобство.
// ---------------------------------------------------------------------------
namespace sage::render {

// Состояние неба на данный момент — то, что читают все остальные.
struct SkyState {
    float DayFactor = 1.0f;   // 1 — день, 0 — ночь, между — сумерки
    float DuskFactor = 0.0f;  // 1 — солнце у самого горизонта (закат/рассвет)
    glm::vec3 Top{0.30f, 0.45f, 0.75f};
    glm::vec3 Horizon{0.70f, 0.80f, 0.92f};
    // Куда смотреть за диском солнца (направление НА него). Не зависит от
    // времени суток: диск обязан остаться там, куда его поставил автор.
    glm::vec3 SunDirection{0.4f, 1.0f, 0.3f};
    // Кто освещает сцену сейчас: днём солнце, ночью луна.
    DirectionalLight Light;
    // Светит ли луна (для неба: ночью её диск ярче).
    bool MoonLit = false;
};

// Считает состояние по настройкам окружения. Чистая функция: ни сцены, ни
// видеокарты, ни времени — только то, что передали. Поэтому её можно звать из
// теста, из превью ассета и из инструмента, а не только из кадра.
SkyState EvaluateSky(const LightingEnvironment& env);

// Записывает результат в окружение: разрешённые цвета неба, множитель дня и
// ГЛАВНОЕ СВЕТИЛО в env.Sun. Зовётся один раз за кадр, сразу после сбора
// освещения сцены (см. sage::ecs::CollectLighting) — до всего, что читает свет.
void ApplySky(LightingEnvironment& env);

} // namespace sage::render
