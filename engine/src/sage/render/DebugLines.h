#pragma once
#include <vector>

#include <glm/glm.hpp>

// ---------------------------------------------------------------------------
// ОТЛАДОЧНЫЕ ЛИНИИ, ЗАКАЗАННЫЕ ИГРОЙ.
//
// Debug:DrawLine из скрипта и DebugDraw из рендера — разные вещи, и между ними
// нарочно стоит этот буфер.
//
// ПОЧЕМУ НЕ НАПРЯМУЮ В DebugDraw. Тот умеет рисовать: у него шейдер, буфер
// вершин и живой контекст видеокарты. Скрипт же зовёт Debug:DrawLine из
// Update — то есть ДО кадра, а в headless-прогоне (тест, автопилот, сборка без
// окна) кадра нет вовсе. Прямой вызов означал бы, что отладочная строка в
// скрипте роняет игру там, где она безобидна, или требует от каждого скрипта
// знать, рисует ли кто-нибудь прямо сейчас.
//
// Здесь — только ДАННЫЕ: что нарисовать и сколько это живёт. Кто их рисует
// (редактор в своём вьюпорте, панель Game, собранная игра) и рисует ли вообще —
// не забота того, кто заказывает.
//
// ВРЕМЯ ЖИЗНИ. По умолчанию линия живёт ОДИН кадр: её перезаказывают каждый
// кадр, пока она нужна. duration > 0 оставляет её на столько секунд — это для
// того, что происходит раз и мгновенно (точка попадания, толчок, срабатывание
// триггера): линия, нарисованная на один кадр в момент выстрела, не видна
// человеческому глазу.
// ---------------------------------------------------------------------------
namespace sage::render {

struct DebugLine {
    glm::vec3 A{0.0f};
    glm::vec3 B{0.0f};
    glm::vec3 Color{1.0f};
    float TimeLeft = 0.0f; // 0 — только этот кадр
};

class DebugLines {
public:
    void Line(const glm::vec3& a, const glm::vec3& b, const glm::vec3& color,
              float duration = 0.0f);
    // Луч от точки В НАПРАВЛЕНИИ: длина берётся из самого направления, как и
    // везде в движке (направление, которое надо ещё и нормализовать, — источник
    // вечной путаницы «почему луч короткий»).
    void Ray(const glm::vec3& origin, const glm::vec3& direction, const glm::vec3& color,
             float duration = 0.0f);
    // Три больших круга — самый дешёвый узнаваемый шар. segments не выносится
    // в API скрипта: «сколько сегментов у отладочной сферы» — не тот вопрос,
    // который игра должна решать.
    void Sphere(const glm::vec3& center, float radius, const glm::vec3& color,
                float duration = 0.0f, int segments = 16);
    void Box(const glm::vec3& center, const glm::vec3& halfExtents, const glm::vec3& color,
             float duration = 0.0f);

    // Снимает отжившее. Зовётся РОВНО ОДИН раз за кадр тем, кто ведёт время
    // (система скриптинга): иначе линии с длительностью гасли бы вдвое быстрее
    // на машине, где кадр считают дважды.
    void Tick(float dt);

    const std::vector<DebugLine>& All() const { return m_lines; }
    bool Empty() const { return m_lines.empty(); }
    void Clear() { m_lines.clear(); }

    // Предел, за которым заказы перестают приниматься. Скрипт с отладочной
    // отрисовкой внутри цикла по всем объектам мира съедает память быстрее,
    // чем человек замечает, что что-то не так; потолок делает это заметным
    // (линии просто перестают появляться), но не смертельным.
    static constexpr size_t kMaxLines = 40000;

private:
    std::vector<DebugLine> m_lines;
    bool m_warned = false;
};

} // namespace sage::render
