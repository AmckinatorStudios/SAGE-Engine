#pragma once
#include <cstddef>

// ---------------------------------------------------------------------------
// Отладочные виды кадра: показать одну величину вместо результата освещения.
//
// «Слишком тёмно» — не диагноз. Причиной бывает albedo, нормаль,
// шероховатость, тень, AO или каскад не туда — и на готовом кадре все они
// выглядят одинаково. Разобрать кадр по слагаемым можно только показав каждое
// отдельно.
//
// Номера — это ЗНАЧЕНИЕ uShadingMode в шейдере (см. DebugShade в PbrShader.h).
// Менять порядок нельзя, не поправив шейдер: там числа зашиты.
// ---------------------------------------------------------------------------
namespace sage::render {

enum class DebugView {
    None = 0,        // обычная отрисовка
    Unlit = 1,       // цвет без освещения (albedo + свечение)
    Normals = 2,     // мировые нормали
    Albedo = 3,      // только базовый цвет
    Roughness = 4,
    Metallic = 5,
    Emissive = 6,
    AmbientOcclusion = 7,
    Shadow = 8,      // тень солнца: белое — освещено
    Depth = 9,       // расстояние от камеры
    Cascades = 10,   // в какой каскад тени попал фрагмент
    WorldGrid = 11,  // метровая клетка по мировым координатам
    Count
};

// Имя для интерфейса и для журнала.
const char* DebugViewName(DebugView view);

// Что именно смотреть в этом виде — строкой для подсказки в редакторе.
const char* DebugViewHint(DebugView view);

// Разбор имени из настроек/переменной окружения. Возвращает false, если имя
// незнакомо: молча включать «обычный вид» на опечатку нельзя — человек будет
// смотреть на нормальный кадр и думать, что режим сломан.
bool ParseDebugView(const char* text, DebugView& out);

} // namespace sage::render
