struct LightingEnvironment;

// ---------------------------------------------------------------------------
// Блики в объективе (lens flare).
//
// Что это такое на самом деле. Яркий источник в кадре переотражается между
// линзами объектива, и каждое переотражение даёт ПРИЗРАК — изображение
// диафрагмы, лежащее на прямой «источник — центр кадра» с той стороны от
// центра. Оттуда же берутся ореол (кольцо) и лучи-звезда (дифракция на
// лепестках диафрагмы). Это не украшение поверх кадра: положение каждого
// призрака однозначно задано положением солнца, и именно поэтому блик «живёт»
// вместе с камерой, а не плавает сам по себе.
//
// ПРОЦЕДУРНО, БЕЗ КАРТИНОК. Ни одной текстуры на диске: призраки — это
// многоугольники диафрагмы, посчитанные формулой. Так блик подстраивается под
// число лепестков и не тащит за собой ассет, который надо рисовать под каждое
// разрешение.
//
// ВИДИМОСТЬ СОЛНЦА СЧИТАЕТСЯ, А НЕ ПРЕДПОЛАГАЕТСЯ. Блик, который горит сквозь
// мачту, — самая заметная неправда этого эффекта. Отдельный проход берёт
// два десятка выборок вокруг солнца и спрашивает про каждую две вещи: небо ли
// там по ГЛУБИНЕ (иначе солнце закрыто геометрией) и ярко ли там по ЦВЕТУ
// (иначе солнце закрыто облаком, которого в буфере глубины нет). Ответ —
// одно число в текстуре 1x1, по нему гаснет весь блик.
//
// ПОРЯДОК. Рисуется ПОСЛЕ объёма (облака должны успеть закрыть солнце) и ДО
// пост-обработки, прямо в HDR-буфер сцены: блик обязан попасть в bloom и в
// тон-маппинг, иначе он выглядит наклейкой поверх готового кадра.
// ---------------------------------------------------------------------------
namespace sage::render {

struct LensFlareSettings {
    bool Enabled = false;

    // Общая сила. Всё остальное — доли от неё, чтобы «убавить блик» было одним
    // числом, а не шестью.
    float Intensity = 1.0f;

    // --- Призраки ------------------------------------------------------------
    int Ghosts = 6;             // сколько переотражений рисуем
    float GhostSpacing = 0.32f; // шаг по прямой «солнце — центр кадра»
    float GhostSize = 0.055f;   // размер первого призрака (доля высоты кадра)
    int ApertureBlades = 6;     // лепестков диафрагмы: 6 — шестиугольные призраки

    // --- Ореол ---------------------------------------------------------------
    float Halo = 0.55f;         // сила кольца (0 — нет)
    float HaloRadius = 0.42f;
    float HaloWidth = 0.10f;

    // --- Звезда и свечение вокруг источника -----------------------------------
    float Starburst = 0.5f;     // сила лучей
    int StarburstSpikes = 12;
    float Glare = 0.45f;        // мягкое свечение вокруг солнца
    float GlareSize = 0.05f;

    // Расхождение каналов: у настоящего блика края призраков цветные, потому
    // что стекло преломляет длины волн по-разному.
    float Chroma = 0.55f;

    // Яркость (в HDR), начиная с которой пиксель у солнца считается «солнцем».
    // По ней же отличают закрытое облаком солнце от открытого.
    float Threshold = 1.1f;
};

LensFlareSettings LensFlareFromConfig(const sage::EngineConfig& cfg);

class LensFlare {
public:
    LensFlare() = default;
    LensFlare(const LensFlare&) = delete;
    LensFlare& operator=(const LensFlare&) = delete;

    // Считает видимость солнца и подмешивает блик В target.
    //
    // sceneColor/sceneDepth — РАЗРЕШЁННЫЕ текстуры того же буфера, что и
    // target. Читать и писать одну текстуру за проход нельзя, поэтому проходов
    // два: сперва видимость уезжает в свою крошечную цель, и только потом блик
    // складывается с кадром — к этому моменту цвет сцены больше не нужен.
    void Render(Framebuffer& target, sage::rhi::TextureHandle sceneColor,
                sage::rhi::TextureHandle sceneDepth, int w, int h, const glm::mat4& proj,
                const glm::mat4& view, const LightingEnvironment& env,
                const LensFlareSettings& s);

private:
    std::unique_ptr<sage::rhi::Geometry> m_fsTri;
    std::unique_ptr<sage::rhi::RenderTarget> m_visible;   // 1x1: доля видимого солнца
};

} // namespace sage::render
