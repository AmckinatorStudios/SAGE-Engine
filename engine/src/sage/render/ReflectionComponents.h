// Зонд отражений: снимает окружение из своей точки в кубическую карту, и всё,
// что попадает в его коробку влияния, отражает СЦЕНУ, а не только небо.
//
// Компонент, а не настройка сцены, ровно потому, что зондов нужно несколько:
// в трюме отражается трюм, на палубе — палуба и небо, и снять это одной картой
// из одной точки нельзя. Какой зонд действует, решается по положению камеры
// (см. sage::render::PickReflectionProbe).
//
// Карта живёт в рантайме и НЕ сериализуется: она пересобирается из той же
// геометрии и того же неба, а хранить в проекте шесть картинок на зонд, которые
// устаревают от любой правки уровня, — худший из вариантов.
struct ReflectionProbeComponent {
    // Сторона грани куба. 128 хватает почти всегда: отражение либо размыто
    // шероховатостью, либо его перекрывает плоское отражение, которое подробнее.
    int Resolution = 128;
    // Полуразмеры коробки влияния (в мировых единицах, от позиции сущности).
    glm::vec3 BoxHalfExtents{8.0f, 4.0f, 8.0f};
    float Intensity = 1.0f;
    // Параллакс-коррекция по коробке. Без неё отражение «плывёт» при движении
    // камеры, будто окружение приклеено к предмету; с ней оно ведёт себя как
    // отражение комнаты, у которой есть стены.
    bool BoxParallax = true;
    // Дальняя плоскость съёмки. Меньше — резче глубина у ближних граней.
    float FarClip = 60.0f;
    // Пересниматься ли каждый кадр. По умолчанию НЕТ: съёмка — это шесть
    // проходов сцены, и включать её постоянно можно только зная зачем
    // (движущееся зеркало, вращающаяся дверь).
    bool Realtime = false;

    // --- рантайм (не сериализуется) ---
    bool Dirty = true;                  // нужно снять (после загрузки/правки)
    std::shared_ptr<void> Runtime;      // sage::render::EnvironmentMap; void — чтобы
                                        // Components.h не тянул за собой рендер
};
