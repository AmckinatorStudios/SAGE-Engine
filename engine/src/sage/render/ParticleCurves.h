#pragma once
#include <vector>

#include <glm/glm.hpp>

// ---------------------------------------------------------------------------
// Кривые, градиенты и разбросы — язык, на котором частица меняется со временем.
//
// ЗАЧЕМ. Прежняя частица знала ровно две точки: «в начале» и «в конце», и между
// ними шла прямая. Дым так не живёт: он быстро набирает размер и медленно
// растворяется; искра вспыхивает и гаснет; пламя из белого становится жёлтым,
// оранжевым, красным и только потом прозрачным. Две точки этого не выражают,
// и поэтому в движке и были «пресеты» — зашитые в код рецепты, заменявшие
// недостающую выразительность. Кривая и градиент возвращают её в данные.
//
// Всё здесь — чистые значения без графики: их проверяют модульные тесты и
// сериализует сцена.
// ---------------------------------------------------------------------------
namespace sage::fx {

// Кривая на отрезке времени жизни t ∈ [0, 1]. Ключи — (t, значение), линейная
// интерполяция между ними; за крайними ключами значение держится. Пустая
// кривая — единица: «модуль ничего не меняет», а не «всё схлопнулось в ноль».
struct Curve {
    std::vector<glm::vec2> Keys;

    float Evaluate(float t) const;
    // Ключи по возрастанию t (редактор двигает точки как угодно).
    void Sort();

    static Curve Constant(float v) { return Curve{{{0.0f, v}}}; }
    static Curve Linear(float from, float to) { return Curve{{{0.0f, from}, {1.0f, to}}}; }
};

// Градиент цвета и прозрачности по времени жизни. Цвет и альфа — РАЗНЫЕ
// наборы ключей: «пламя меняет цвет четыре раза, а гаснет один» — обычный
// случай, и держать их одним списком значило бы дублировать альфу в каждом
// цветовом ключе.
struct Gradient {
    struct ColorKey { float T; glm::vec3 Color; };
    struct AlphaKey { float T; float Alpha; };
    std::vector<ColorKey> Colors;
    std::vector<AlphaKey> Alphas;

    glm::vec4 Evaluate(float t) const;
    void Sort();

    static Gradient Solid(const glm::vec4& c) {
        return Gradient{{{0.0f, glm::vec3(c)}}, {{0.0f, c.a}}};
    }
    static Gradient Fade(const glm::vec4& from, const glm::vec4& to) {
        return Gradient{{{0.0f, glm::vec3(from)}, {1.0f, glm::vec3(to)}},
                        {{0.0f, from.a}, {1.0f, to.a}}};
    }
};

// Разброс «от — до»: каждая частица берёт своё значение случайно. Без разброса
// эффект выглядит механически — сотня одинаковых клонов.
struct Range {
    float Min = 0.0f;
    float Max = 0.0f;
    float Lerp(float u) const { return Min + (Max - Min) * u; }
};

} // namespace sage::fx
