#pragma once
#include <memory>

#include <glm/glm.hpp>

class Skybox;
class SkyRenderer;
struct LightingEnvironment;

// ---------------------------------------------------------------------------
// «Нарисовать небо сцены» — ОДИН раз на весь движок.
//
// Выбор режима (процедурный градиент / каталог с гранями / шесть отдельных
// файлов), запасной путь при неудачной загрузке и цвета с учётом времени суток
// — всё это лежало КОПИЯМИ у каждого потребителя: вьюпорт редактора, панель
// Game, съёмка отражений редактора, кадр игры, съёмка отражений игры. Копии
// начинали расходиться при первой же правке: режим «по кусочкам», добавленный в
// одном месте, в остальных четырёх просто не существовал бы, и небо в
// отражениях отличалось бы от неба в кадре — дефект, который ищут глазами.
//
// Здесь последовательность записана один раз, и все пять потребителей зовут
// одну строку.
// ---------------------------------------------------------------------------
namespace sage::render {

// Кубическая карта неба сцены или nullptr, если небо процедурное (или файлы не
// читаются). Нужна отражениям: они обязаны отражать ТО ЖЕ небо, что видно в
// кадре, иначе вода показывает одно, а горизонт другое.
std::shared_ptr<Skybox> SceneSkyCubemap(const LightingEnvironment& env);

// ЧЕМ ЗАЛИВАТЬ КАДР ДО ОТРИСОВКИ СЦЕНЫ.
//
// Небо включено — цвет неба (приглушённый): его всё равно закроет сама
// отрисовка неба, и заливка нужна лишь чтобы в кадре не мелькнул чужой цвет.
//
// Небо ВЫКЛЮЧЕНО — ЧЁРНЫЙ. Раньше и здесь стоял SkyColor: человек выключал
// небо, а кадр оставался голубым — то есть небо никуда не девалось, просто
// становилось плоским. Выключенное небо должно выглядеть как его отсутствие, а
// это чернота — та же, что за краем мира.
//
// Правило одно на всех: вьюпорт редактора, панель Game и кадр игры. Три копии
// этой строчки уже разошлись однажды.
glm::vec3 SceneClearColor(const LightingEnvironment& env);

// Рисует небо сцены в текущий буфер. fallback — процедурное небо движка, оно
// используется и как запасной путь, когда текстурное не загрузилось: падать на
// отсутствующем файле нельзя, а чёрный фон вместо неба выглядит как поломка
// рендера, а не как отсутствующий ассет.
//
// Ничего не делает, если небо у сцены выключено.
void DrawSceneSky(SkyRenderer& fallback, const LightingEnvironment& env, const glm::mat4& view,
                  const glm::mat4& proj);

} // namespace sage::render
