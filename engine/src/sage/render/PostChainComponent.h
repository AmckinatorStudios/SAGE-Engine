#pragma once
#include <entt/entt.hpp>

#include "sage/core/Config.h"
#include "sage/render/PostEffect.h"

// Сцена движка живёт в ГЛОБАЛЬНОМ пространстве имён (см. SystemScheduler.h):
// объявляем её здесь так же, иначе получили бы другой тип.
class Scene;

// ---------------------------------------------------------------------------
// Тракт пост-обработки, принадлежащий КАМЕРЕ.
//
// ПОЧЕМУ КОМПОНЕНТ, А НЕ НАСТРОЙКА ПРОЕКТА. У сцены бывает несколько камер с
// разным назначением: вид от первого лица, орто-вид сверху для схемы, камера,
// рисующая в текстуру для портала или мини-карты. «Красота» у них разная, а
// настройка была одна на проект — то есть у всех сразу. Плюс к этому настройка
// жила в `sage.cfg`, то есть в ФАЙЛЕ ПРОЕКТА: её нельзя было ни сохранить в
// сцену, ни положить в префаб, ни скопировать на другую камеру.
//
// ЧТО ЭТО МЕНЯЕТ НА ПРАКТИКЕ. Проекту с одной камерой настраивать по-прежнему
// нечего: камера без компонента берёт тракт проекта (см. ResolvePostChain), и
// старое поведение сохраняется целиком.
// ---------------------------------------------------------------------------
namespace sage::render {

struct PostChainComponent {
    PostChain Chain;

    // Взять тракт ПРОЕКТА, а не свой.
    //
    // Поле нужно затем, чтобы «как в проекте» было ВИДИМЫМ решением, а не
    // отсутствием компонента: без него нельзя отличить «камеру ещё не
    // настроили» от «камеру намеренно не настраивали», и первая же правка
    // тракта проекта молча меняла бы вид такой камеры. А с ним человек,
    // скопировавший камеру, получает копию ЕЁ тракта, а не сюрприз.
    bool UseProjectDefault = false;
};

// Тракт для камеры: её компонент, если он есть и не просит умолчание, иначе —
// тракт проекта из конфига.
//
// ЕДИНСТВЕННОЕ место, где это решается. Редактор и рантайм обязаны смотреть на
// камеру одинаково: «в редакторе одна картинка, в игре другая» начинается
// ровно с того, что правило выбора тракта записано в двух местах.
PostChain ResolvePostChain(Scene& scene, entt::entity camera, const sage::EngineConfig& cfg);

} // namespace sage::render
