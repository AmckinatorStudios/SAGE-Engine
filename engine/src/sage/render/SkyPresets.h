#pragma once
#include <string>

struct SkyboxSettings;

// ---------------------------------------------------------------------------
// Готовые виды процедурного неба.
//
// Полей у неба три десятка (см. SkyboxSettings), и собрать из них узнаваемое
// небо с нуля — работа на полчаса с подбором цветов. Пресет — отправная точка:
// выбрал «Пасмурно», дальше крути то, что хочется поменять.
//
// Пресет меняет только ВИД процедурного неба. Выбранные файлы текстурного неба,
// яркость, поворот и смена суток остаются как были: это решения автора сцены,
// а не часть «вида», и терять их при смене пресета нельзя.
// ---------------------------------------------------------------------------
namespace sage::render {

enum class SkyPreset {
    Default = 0,   // небо движка по умолчанию (как до появления пресетов)
    Overcast,      // пасмурно: серое небо, сплошные мягкие облака, без солнца
    Count
};

// Имя для файлов и скриптов ("default", "overcast") и для
// интерфейса (английское, переводится через T()).
const char* SkyPresetId(SkyPreset p);
const char* SkyPresetLabel(SkyPreset p);
bool ParseSkyPreset(const std::string& id, SkyPreset& out);

void ApplySkyPreset(SkyboxSettings& sky, SkyPreset p);

} // namespace sage::render
