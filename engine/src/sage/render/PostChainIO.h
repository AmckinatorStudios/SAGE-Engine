#pragma once
#include <nlohmann/json.hpp>

#include "sage/render/PostEffect.h"

// ---------------------------------------------------------------------------
// Тракт пост-обработки на диске.
//
// Формат ОДИН на всех, кто его хранит: сцена (компонент на камере) и конфиг
// проекта (`sage.cfg`, тракт по умолчанию). Пока конвертеров было бы два, они
// разъехались бы на первой же правке — ровно так в этом движке и разъезжались
// копии прохода теней, пока их не свели в один ScenePasses.
//
// ЗНАЧЕНИЯ ПАРАМЕТРОВ ПИШУТСЯ ПО ИМЕНИ, а не позиционно. Список параметров звена
// принадлежит ДВИЖКУ и в следующей версии может подрасти или переставиться:
// добавили настройку — добавили параметр. Позиционная запись в таком случае
// сдвинула бы значения всех последующих параметров, и старая сцена молча
// открылась бы с чужими настройками. Именная переживает и добавление, и
// перестановку: чего в файле нет — берётся из умолчаний вида, чего в виде нет —
// пропускается.
// ---------------------------------------------------------------------------
namespace sage::render {

// Тракт в JSON: { "effects": [ { "kind", "enabled", "params" }, ... ] }
nlohmann::json PostChainToJson(const PostChain& chain);

// Обратно. НИКОГДА НЕ БРОСАЕТ и не падает на битом тексте: значения приходят из
// файла, который правят руками, и строка там, где ждали число, — обычное дело.
// Непонятное значение не применяется, параметр остаётся на умолчании вида, звено
// неизвестного вида доезжает до тракта (о нём скажет компилятор).
PostChain PostChainFromJson(const nlohmann::json& json);

} // namespace sage::render
