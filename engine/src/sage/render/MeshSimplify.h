#pragma once
#include <vector>

#include "sage/render/Mesh.h"

// ---------------------------------------------------------------------------
// Упрощение меша — построение грубых уровней детализации (LOD) из подробного.
//
// ЗАЧЕМ ЭТО В ДВИЖКЕ, А НЕ В БЛЕНДЕРЕ. Уровни детализации, которые надо делать
// руками, не делает никто. Пока LOD требует отдельной работы художника на
// каждую модель, механизм выбора уровня стоит в движке мёртвым грузом. Здесь
// уровни строятся сами при загрузке — не идеально, но бесплатно для человека.
//
// КАКОЙ АЛГОРИТМ И ПОЧЕМУ ИМЕННО ОН. Кластеризация вершин по сетке: габарит
// модели делится на ячейки, все вершины внутри ячейки схлопываются в одну,
// треугольники, у которых после этого совпали углы, выбрасываются.
//
// Это НЕ лучший из существующих алгоритмов. Схлопывание рёбер по квадрикам
// (Garland–Heckbert) даёт заметно более аккуратный силуэт при той же экономии.
// Выбрана кластеризация, потому что:
//   • она устойчива на любой геометрии, включая незамкнутую и «грязную» — с
//     дырами, T-стыками, вывернутыми нормалями. Схлопывание рёбер на такой
//     геометрии либо ломается, либо требует много кода на исключения;
//   • она линейна по числу вершин и работает мгновенно на загрузке;
//   • грубые уровни смотрят издалека, и разница между «аккуратно» и
//     «приемлемо» там не видна — а вот разница между «есть LOD» и «нет LOD»
//     видна сразу, в кадрах в секунду.
//
// ЧЕСТНО О ГРАНИЦАХ. На ближних уровнях (сокращение меньше чем вдвое)
// кластеризация не годится: она гуляет по силуэту заметнее, чем экономит.
// Её место — дальние уровни, где модель занимает десятки пикселей.
// ---------------------------------------------------------------------------
namespace sage::render {

struct SimplifyResult {
    std::vector<Vertex> Vertices;
    std::vector<unsigned int> Indices;
    int SourceTriangles = 0;
    int Triangles = 0;
    // Фактическая доля оставшихся треугольников. Может заметно отличаться от
    // запрошенной: сетка кластеров — грубый рычаг, и точное попадание в цель
    // ей недоступно (см. SimplifyToRatio).
    float Ratio = 1.0f;
};

// Кластеризация с сеткой gridSize ячеек по длинной стороне габарита.
// Меньше gridSize — грубее результат.
SimplifyResult SimplifyByClustering(const std::vector<Vertex>& vertices,
                                    const std::vector<unsigned int>& indices, int gridSize);

// Подбирает сетку так, чтобы получить примерно targetRatio треугольников от
// исходного (0..1). Подбор — двоичным поиском по размеру сетки за несколько
// проб: прямой формулы «сетка → число треугольников» нет, она зависит от того,
// как геометрия распределена в пространстве.
SimplifyResult SimplifyToRatio(const std::vector<Vertex>& vertices,
                               const std::vector<unsigned int>& indices, float targetRatio);

} // namespace sage::render
