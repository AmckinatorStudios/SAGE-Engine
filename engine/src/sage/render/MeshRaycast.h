#pragma once
#include <vector>

#include <glm/glm.hpp>

#include "sage/render/Mesh.h"   // Vertex

namespace sage::render {

// ---------------------------------------------------------------------------
// Пересечение луча с мешем — «по какому объекту я щёлкнул».
//
// ЗАЧЕМ ОТДЕЛЬНО. Выбор объекта мышью в редакторе делался по кубу со стороной
// РАДИУСА ОГРАНИЧИВАЮЩЕЙ СФЕРЫ. Сфера считается для отсечения по фрустуму, где
// она и уместна: инвариантна к повороту, проверка дешёвая, а ошибка в большую
// сторону безобидна — лишний объект просто нарисуется. Для попадания мышью та
// же ошибка становится главной: у куба такая коробка больше него на 73% по
// каждой оси, у пола 20x20 — это куб 28x28x28, внутри которого оказывается вся
// сцена вместе с камерой. Пол выигрывал у всего остального просто потому, что
// его коробка начиналась ближе, и клик «мимо на полметра» засчитывался как
// попадание.
//
// ДВА УРОВНЯ ТОЧНОСТИ. Сначала настоящий AABB меша — он всегда есть и уже этого
// достаточно, чтобы промахи перестали засчитываться. Если у меша сохранена
// копия геометрии на стороне процессора, дальше идёт перебор треугольников
// (Мёллер—Трумбор): тогда клик в дырку между спицами колеса не выбирает колесо.
// Копия есть не у всех мешей — держать её ради выбора мышью в ИГРЕ было бы
// расточительством, — поэтому точность честно деградирует до коробки, а не
// отказывает.
//
// Луч задаётся В ЛОКАЛЬНЫХ КООРДИНАТАХ МЕША (вызывающий умножает на обратную
// мировую матрицу). Направление НЕ обязано быть единичным: так возвращённое t
// остаётся в тех же единицах, в которых задан луч, и результаты для объектов с
// разным масштабом можно сравнивать напрямую.
// ---------------------------------------------------------------------------

struct RayHit {
    bool Hit = false;
    float Distance = 0.0f;  // t вдоль луча: точка = origin + dir * t
    bool Exact = false;     // true — попадание по треугольнику, false — по коробке
};

// Луч против коробки [lo, hi]. t входа; 0, если начало луча внутри коробки.
// Hit=false, если пересечения нет или оно позади начала.
RayHit RayAabb(const glm::vec3& origin, const glm::vec3& dir, const glm::vec3& lo,
               const glm::vec3& hi);

// Луч против геометрии: AABB, затем — если треугольники переданы — точный тест.
// verts/idx могут быть nullptr: тогда точность остаётся на уровне коробки.
//
// Отдельно от версии для Mesh, потому что Mesh — это ресурс ВИДЕОКАРТЫ: он не
// создаётся без графического контекста, а значит и проверить на нём эту чистую
// математику было бы негде. Здесь же на входе только числа.
RayHit RayGeometry(const glm::vec3& origin, const glm::vec3& dir, const glm::vec3& lo,
                   const glm::vec3& hi, const std::vector<Vertex>* verts,
                   const std::vector<unsigned int>* idx);

// Луч против меша: AABB, затем — при наличии копии геометрии — треугольники.
RayHit RayMesh(const Mesh& mesh, const glm::vec3& origin, const glm::vec3& dir);

} // namespace sage::render
