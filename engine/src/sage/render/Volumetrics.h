// ---------------------------------------------------------------------------
// Объёмный свет и объёмные облака.
//
// Даёт две вещи, которых нельзя получить ни тенями, ни туманом по глубине:
//   • ЛУЧИ. Свет, пробившийся между досками надстройки, виден в воздухе, а не
//     только пятном на палубе. Считается маршем по лучу взгляда с выборкой
//     карты теней солнца: там, где отрезок луча освещён, воздух светится.
//   • ОБЛАКА. Настоящий объём, а не картинка на куполе: у них есть низ и верх,
//     они самозатеняются, светятся по краю на просвет и плывут по ветру.
//
// ЦЕНА И КАЧЕСТВО: ЧЕМ ЗДЕСЬ ПЛАТЯТ ЗА ЧТО.
//
// Марш по лучу — это интеграл, взятый КОНЕЧНЫМ числом шагов, и все артефакты
// объёма родом отсюда. Наивный проход выглядит одинаково плохо у всех: полосы
// поперёк лучей (мало шагов), зернистая рябь (шаги сдвинуты шумом, чтобы полос
// не было), мыло и лесенка на силуэтах (проход идёт в уменьшенном буфере).
// Здесь против каждого стоит свой приём, и убрать любой из них — вернуть свой
// артефакт:
//
//   1. НАКОПЛЕНИЕ ПО КАДРАМ (temporal). Сдвиг начала марша меняется КАЖДЫЙ
//      кадр, а результат смешивается с предыдущим кадром, перепроецированным в
//      текущий. Шум усредняется по времени: тридцать шагов дают картинку,
//      которой иначе потребовалось бы несколько сотен. Ореолов не появляется,
//      потому что история ограничивается окрестностью текущего кадра
//      (neighborhood clamp) — при резком повороте она просто отбрасывается.
//   2. СОБСТВЕННЫЙ БУФЕР ГЛУБИНЫ прохода. Марш и подъём читают ОДНУ И ТУ ЖЕ
//      уменьшенную глубину (ближайшую в блоке), поэтому вес совпадает с тем,
//      что марш реально видел. Пока подъём сравнивал полноразмерную глубину
//      сам с собой, «билатеральный» фильтр был обычным размытием 3x3 — отсюда
//      и мыло.
//   3. ПОДЪЁМ ПО ЧЕТЫРЁМ БЛИЖАЙШИМ с билинейными весами, домноженными на
//      близость глубины. На ровной поверхности это точная билинейная выборка
//      (ничего не размывается), на силуэте — выбор совпавших выборок (нет
//      светящейся каймы вокруг тонких предметов).
//   4. ПОЛНОЕ РАЗРЕШЕНИЕ ПО УМОЛЧАНИЮ (Scale = 1). Тогда подъём вырождается в
//      копию, и не остаётся ни лесенки, ни мыла вовсе. Половина стороны —
//      по-прежнему один ползунок, но теперь это выбор «быстрее», а не
//      единственный режим.
//   5. МЯГКАЯ ТЕНЬ В МАРШЕ (4 выборки карты теней вместо одной). Бинарная
//      выборка давала лучам рубленый край в пиксель толщиной, который не
//      лечился ни шагами, ни накоплением.
//   6. РАСТУЩИЙ ШАГ. Первые метры перед камерой важнее последних: шаг растёт
//      вдоль луча, поэтому плотная дымка у земли не полосит, а дальний конец
//      не стоит лишних выборок.
//
// ИСТОРИЯ ПРИНАДЛЕЖИТ ВИДУ. Один и тот же объект обслуживает несколько окон
// (вьюпорт редактора, его раскладку, панель Game), и накопленный кадр одного
// окна не имеет отношения к другому — ровно как ответы проверки перекрытия в
// RenderBatch. Поэтому история хранится по номеру вида, а не одна на всех.
// ---------------------------------------------------------------------------
namespace sage::render {

struct VolumetricSettings {
    bool Enabled = false;

    // --- Объёмный свет в воздухе -------------------------------------------
    bool LightShafts = true;
    float Density = 0.02f;        // плотность среды у земли, 1/м
    float Anisotropy = 0.76f;     // вытянутость рассеяния вперёд (0 — равномерно)
    float MaxDistance = 160.0f;   // дальше не маршируем
    int Steps = 32;
    float Intensity = 1.0f;
    // Убывание плотности с высотой: без него дымка одинакова и у воды, и в
    // небе, отчего сцена выглядит затянутой молоком.
    float HeightFalloff = 0.06f;
    float BaseHeight = 0.0f;

    // --- Облака --------------------------------------------------------------
    bool Clouds = true;
    float CloudBottom = 180.0f;
    float CloudTop = 520.0f;
    float Coverage = 0.56f;       // 0 — ясно, 1 — сплошная облачность
    float CloudDensity = 1.3f;
    float CloudScale = 0.0022f;   // размер клубов (меньше — крупнее)
    glm::vec2 Wind{7.0f, 2.5f};
    glm::vec3 Tint{1.0f, 1.0f, 1.0f};
    int CloudSteps = 48;
    int CloudLightSteps = 6;

    // Доля разрешения для прохода: 1 — полное, 0.5 — половина стороны.
    float Scale = 1.0f;

    // Накопление по кадрам. Выключается только для сравнения «до/после» и для
    // эталонных кадров, где нужен ОДИН воспроизводимый кадр без истории.
    bool Temporal = true;
    // Доля истории в смеси: 0.9 — быстрое накопление, 0.98 — очень гладко, но
    // заметно тянется за движением.
    float TemporalBlend = 0.9f;

    // Показать поле видимости солнца вместо результата (отладка теней в марше).
    bool Debug = false;
};

VolumetricSettings VolumetricsFromConfig(const sage::EngineConfig& cfg);

class Volumetrics {
public:
    Volumetrics() = default;
    Volumetrics(const Volumetrics&) = delete;
    Volumetrics& operator=(const Volumetrics&) = delete;

    // Считает объём в своём буфере и КОМПОЗИТИТ его в target. Вызывать после
    // отрисовки геометрии и до пост-обработки: свечение лучей должно попасть в
    // bloom, иначе солнце светит, а его лучи — нет.
    //
    // target — буфер сцены, в который композитится результат. Передаётся явно,
    // а не берётся «текущим»: марш идёт в свои буферы, и вернуться после него
    // надо туда, откуда пришли, а не в экран.
    //
    // viewId — какое окно рисуется. Накопленный кадр принадлежит виду: у
    // вьюпорта редактора и панели Game разные камеры, и смешивать их истории
    // значило бы получить призрак чужого кадра (см. заголовок).
    void Render(Framebuffer& target, sage::rhi::TextureHandle sceneDepth, int w, int h,
                const glm::mat4& proj, const glm::mat4& view, const glm::vec3& camPos,
                const LightingEnvironment& env, const ShadowBinding& shadows,
                const VolumetricSettings& s, float time, int viewId = 0);

    // Забыть накопленное (смена сцены, телепорт камеры, выход из Play). История
    // после такого события описывает другой мир, и смешивать её с новым кадром
    // — это призрак предыдущего.
    void ResetHistory();

private:
    // Всё, что принадлежит ОДНОМУ виду: два буфера накопления (пинг-понг) и
    // матрица его прошлого кадра.
    struct ViewHistory {
        std::unique_ptr<sage::rhi::RenderTarget> Accum[2];
        glm::mat4 PrevViewProj{1.0f};
        int Width = 0, Height = 0;
        bool Valid = false;   // есть ли что перепроецировать
        int Current = 0;      // в какой из двух писать
    };

    void EnsureShared(int w, int h);
    ViewHistory& HistoryFor(int viewId, int w, int h);

    std::unique_ptr<sage::rhi::Geometry> m_fsTri;
    std::unique_ptr<sage::rhi::RenderTarget> m_march;    // сырой результат марша
    std::unique_ptr<sage::rhi::RenderTarget> m_depthLow; // R — расстояние, G — небо
    int m_w = 0, m_h = 0;   // размер уменьшенного буфера
    unsigned m_frame = 0;   // номер кадра — сдвиг шума накопления

    std::unordered_map<int, ViewHistory> m_history;
};

} // namespace sage::render
