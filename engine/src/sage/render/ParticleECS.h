#pragma once
#include <cstdint>

#include <entt/entt.hpp>

class Scene;
class ParticleSystem;

// ---------------------------------------------------------------------------
// Связка ECS ↔ система частиц. Каждая сущность с ParticleEmitterComponent —
// свой эмиттер в ParticleSystem (своя текстура, смешивание, отрисовка); общая
// система принадлежит слою (редактор/рантайм/игра), он же её и рисует.
// ---------------------------------------------------------------------------
namespace sage::fx {

// Постоянный ключ эмиттера объекта: сцена + сущность. Сцена — часть ключа,
// потому что одна система частиц обслуживает и игру, и предпросмотры редактора.
uint64_t EmitterKey(const Scene& scene, entt::entity e);

// Переносит эмиттеры сцены в систему (эффект, положение, команды скриптов) и
// шагает все эмиттеры на dt.
void UpdateEmitters(Scene& scene, ParticleSystem& sys, float dt);

} // namespace sage::fx
