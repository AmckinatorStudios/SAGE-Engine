#pragma once
#include <string>
#include <vector>

// ---------------------------------------------------------------------------
// Набор соответствия RHI: исполняемый контракт бэкенда.
//
// ЗАЧЕМ. Абстракция с одной реализацией — это гипотеза, а не абстракция. Пока
// бэкенд один, «интерфейс» и «то, что делает OpenGL» — одно и то же, и
// отличить обязательство от привычки невозможно: любое поведение выглядит
// правильным, потому что сравнивать не с чем.
//
// Отсюда — контракт, вынесенный из комментариев в КОД. Комментарий «начало
// отсчёта — левый нижний угол» ничего не гарантирует: второй бэкенд напишут
// через год, и никто не станет перечитывать заголовок. Проверка, которую он
// обязан пройти, гарантирует.
//
// ЧЕГО ЭТОТ НАБОР НЕ ДЕЛАЕТ, И ЭТО НАДО СКАЗАТЬ ПРЯМО. Он не превращает
// GL-подобный интерфейс в переносимый. Vulkan-бэкенду нужны командные буферы,
// проходы и дескрипторы, а их в этом интерфейсе нет — см. честную оценку в
// GraphicsDevice.h. Набор сужает гипотезу, а не снимает её: он ловит
// расхождения в том, о чём интерфейс УЖЕ договорился, и делает это до того, как
// они превратятся в перевёрнутую картинку, которую ищут неделю.
//
// ДВА УРОВНЯ. Структурный обязаны проходить ВСЕ бэкенды, включая Null: он про
// хендлы, дескрипторы, времена жизни и безопасность вызовов с невалидным
// аргументом. Пиксельный — только те, кто действительно растеризует: он про
// соглашения о системе координат, а проверить их можно, лишь что-то нарисовав.
// Null не растеризует и честно пропускается, а не подделывает результат.
// ---------------------------------------------------------------------------
namespace sage::rhi {

class GraphicsDevice;

struct ConformanceOptions {
    // Бэкенд действительно рисует и умеет читать пиксели обратно. Для Null —
    // false: заставлять пустышку «пройти» пиксельный уровень значило бы
    // получить зелёный результат, который ничего не значит.
    bool Rasterizes = false;
};

struct ConformanceResult {
    // Названия проваленных проверок с объяснением. Пусто — бэкенд соответствует.
    std::vector<std::string> Failures;
    int Checked = 0;   // сколько проверок выполнено
    int Skipped = 0;   // сколько пропущено по возможностям бэкенда

    bool Ok() const { return Failures.empty(); }
};

// Гоняет набор по УЖЕ инициализированному устройству. Требует живого контекста,
// если бэкенд его использует: вызывающий отвечает за то, чтобы устройство было
// готово к работе.
ConformanceResult RunConformance(GraphicsDevice& device, const ConformanceOptions& options);

} // namespace sage::rhi
