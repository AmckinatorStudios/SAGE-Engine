#pragma once
#include <cstdint>
#include <string>

// ---------------------------------------------------------------------------
// Учёт GPU-объектов: сколько их СОЗДАНО за время работы и сколько ЖИВО сейчас.
//
// ЗАЧЕМ. Жалоба «рендер сначала работает, а потом без причины деградирует» не
// проверяется ни одним тестом на картинку: кадр номер один правильный, и
// кадр номер тысяча тоже правильный — если только к тысячному не кончилась
// видеопамять. Утечка GPU-объектов не роняет программу и ничего не пишет в
// лог: драйвер молча отдаёт всё новые текстуры, пока не откажет, — и отказ
// приходит через полчаса работы, в произвольном месте, на чужой машине.
//
// Здесь ведётся простой счёт: каждый ресурс RHI считает себя сам, в базовом
// классе (Resources.h), поэтому счётчик не зависит ни от бэкенда, ни от того,
// вспомнил ли автор нового ресурса про учёт. Проверка «после N циклов
// Play/Stop живых объектов столько же, сколько до» превращается в одно
// сравнение чисел, а не в разглядывание диспетчера задач.
//
// ЧЕГО ЭТОТ УЧЁТ НЕ ДЕЛАЕТ. Он считает ОБЪЕКТЫ, а не байты видеопамяти: узнать
// у OpenGL 3.3 занятую память переносимо нельзя (расширения есть только у
// NVIDIA и AMD, и они врут по-разному). Растущее число объектов — надёжный
// признак утечки; постоянное число при растущей памяти означало бы, что кто-то
// перевыделяет хранилище живого объекта, и это видно другими средствами
// (Resize у рендер-таргетов).
// ---------------------------------------------------------------------------
namespace sage::rhi {

// Виды GPU-объектов, за которыми имеет смысл следить по отдельности: у каждого
// своя цена и свой характерный сценарий утечки.
enum class ResourceKind {
    Shader = 0,      // программы
    Geometry,        // вершинные/индексные буферы
    Texture,         // 2D/3D/куб — всё, что занимает память под пиксели
    RenderTarget,    // кадровые буферы вместе с их вложениями
    Query,           // запросы перекрытия и метки времени
    Count
};

struct ResourceCounts {
    long long Live[(int)ResourceKind::Count] = {0, 0, 0, 0, 0};
    long long Created[(int)ResourceKind::Count] = {0, 0, 0, 0, 0};

    long long LiveTotal() const;
    long long CreatedTotal() const;
    // Одна строка для лога и панели: «шейдеры 12, геометрия 40, ...».
    std::string ToString() const;
    // Разница по живым объектам (this - baseline) одной строкой; пусто, если
    // разницы нет. Ровно то, что нужно печатать в тесте на утечку.
    std::string DiffFrom(const ResourceCounts& baseline) const;
};

class ResourceLedger {
public:
    // Считают сами ресурсы; звать это из кода движка не нужно.
    static void Acquired(ResourceKind kind);
    static void Released(ResourceKind kind);

    // Снимок счётчиков. Потокобезопасен: ресурсы создаются и в загрузочных
    // потоках тоже.
    static ResourceCounts Snapshot();

    // Сколько живых объектов данного вида.
    static long long Live(ResourceKind kind);
};

} // namespace sage::rhi
