#include <cstdint>
#include <filesystem>
#include <string>
#include <unordered_map>
#include <vector>

#include "sage/project/Project.h"

// ---------------------------------------------------------------------------
// Слежение за файлами проекта: кто-то изменил их МИМО нас.
//
// ЗАЧЕМ. Редактор и код (SDK) работают с ОДНИМ каталогом проекта — это и есть
// смысл того, что проект живёт в движке, а не в редакторе. Значит нормальный
// рабочий день выглядит так: сцена открыта в редакторе, рядом в терминале
// скрипт правит ту же сцену, генератор уровней дописывает третью. Без слежения
// редактор об этом не знает — и первым же «Сохранить» затирает чужую работу
// молча.
//
// ЧТО ЭТО ДАЁТ И ЧЕГО НЕ ДАЁТ. Даёт: «вот эти файлы изменились снаружи».
// Не даёт: слияния правок и решения, чья версия важнее. Решать обязан человек,
// потому что только он знает, что именно он делал последние десять минут.
// Автоматическая перезагрузка без спроса — тот же молчаливый затир, только
// в другую сторону.
//
// ПОЧЕМУ ОПРОС, А НЕ inotify/ReadDirectoryChangesW. Событийные API у каждой
// системы свои, и это три реализации вместо одной — ровно то, чего движок
// избегает. Опрос по времени последней записи переносим дословно, стоит один
// обход каталога в секунду и ошибается только в одну сторону: может заметить
// изменение чуть позже, но не может сообщить о несуществующем. Для правки
// файла человеком или скриптом секунда — незаметная задержка.
// ---------------------------------------------------------------------------
namespace sage::project {

// Что именно случилось с файлом.
enum class ChangeKind : uint8_t {
    Added,     // файл появился
    Modified,  // изменился (другое время записи или размер)
    Removed,   // исчез
};

struct Change {
    ChangeKind Kind = ChangeKind::Modified;
    // Путь относительно корня проекта, через '/' — в том же виде, в каком
    // ссылки лежат в сценах и материалах.
    std::string Path;
};

class ProjectWatcher {
public:
    // Начать следить за проектом. Первый снимок берётся сразу и изменениями НЕ
    // считается: иначе открытие проекта немедленно сообщало бы о сотне
    // «новых» файлов.
    void Watch(const Project& project);
    void Stop();
    bool Watching() const { return m_watching; }

    // Файлы, которые СЛЕДИТ считает своими. По умолчанию — сцены, скрипты,
    // материалы и файл проекта: то, что правят снаружи осмысленно. Текстуры и
    // модели сюда не входят намеренно — их перезагрузкой занимается кэш
    // ресурсов, а не редактор сцен.
    void SetExtensions(std::vector<std::string> extensions);

    // Опросить каталог, если пришло время. Зовётся каждый кадр; сам решает,
    // прошёл ли интервал, — потребителю не надо заводить свой таймер.
    // Возвращает изменения с прошлого опроса (пусто — ничего не менялось).
    std::vector<Change> Poll(double nowSeconds);

    // Интервал опроса в секундах. Меньше — быстрее заметит, дороже обход.
    void SetInterval(double seconds) { m_interval = seconds; }

    // Забыть об изменениях конкретного файла: мы сами его только что записали,
    // и сообщать себе о собственной записи незачем. Без этого каждое
    // «Сохранить» в редакторе возвращалось бы вопросом «файл изменён снаружи,
    // перезагрузить?» — и человек перестал бы читать этот вопрос вообще.
    void MarkOwnWrite(const std::filesystem::path& path);

private:
    struct Stamp {
        int64_t WriteTime = 0;
        uintmax_t Size = 0;
    };

    void Snapshot(std::unordered_map<std::string, Stamp>& out) const;
    bool Interesting(const std::filesystem::path& path) const;
    std::string RelPath(const std::filesystem::path& path) const;

    bool m_watching = false;
    std::filesystem::path m_root;
    std::unordered_map<std::string, Stamp> m_known;
    std::vector<std::string> m_extensions;
    double m_interval = 1.0;
    double m_lastPoll = 0.0;
};

} // namespace sage::project
