#pragma once
#include <filesystem>
#include <string>
#include <vector>

// ---------------------------------------------------------------------------
// Проект игры — ПОНЯТИЕ ДВИЖКА, а не редактора.
//
// Проект это папка с файлом project.sageproj и стандартными подпапками:
//
//   <dir>/project.sageproj   имя, версия формата, стартовая сцена
//   <dir>/scenes/            сцены .sage
//   <dir>/assets/            модели, текстуры, звук, скрипты
//
// ПОЧЕМУ ЭТО ЖИВЁТ В ДВИЖКЕ. Раньше жило в редакторе — класс editor/Project с
// комментарием «проект это сущность редактора, движку о нём знать не нужно».
// Из этого следовали ровно те две беды, которых архитектура движка не должна
// допускать:
//
//   • ВТОРАЯ РЕАЛИЗАЦИЯ. Плеер (SagePlayer) проектов открывать умеет, но класса
//     редактора у него нет — и он разбирал project.sageproj своим кодом, своим
//     json-парсером, со своим правилом поиска главной сцены. Две реализации
//     одного понятия расходятся не «если», а «когда»: достаточно добавить поле
//     в файл проекта, и редактор будет его писать, а плеер — не замечать;
//   • НЕДОСТУПНОСТЬ ИЗ КОДА. Игра, написанная на движке без редактора,
//     проектом воспользоваться не могла вовсе: ни создать, ни открыть, ни
//     спросить, где лежат сцены. То есть один и тот же движок давал два разных
//     набора возможностей в зависимости от того, запущен редактор или нет.
//
// Теперь реализация одна, и все трое пользуются ей: редактор — чтобы открыть
// проект по File > Open, плеер — чтобы запустить готовую игру, код игры и
// инструмент `sage` — чтобы создать проект и работать с ним программно. Проект,
// созданный из командной строки, открывается редактором без конвертации,
// потому что это буквально один и тот же код и один и тот же файл.
//
// ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. Смены рабочего каталога, монтирования пакета и
// создания окна. Это политика КОНКРЕТНОГО потребителя: плеер делает chdir в
// папку игры, редактор — принципиально нет (у него открыто несколько окон и
// свой рабочий каталог). Проект отвечает на вопрос «что и где лежит», а не
// «как этим распорядиться».
// ---------------------------------------------------------------------------
namespace sage::project {

// Имена, из которых состоит раскладка проекта. Собраны в одном месте: строка
// "scenes", записанная в пяти файлах, однажды разъедется — и разъедется молча.
namespace layout {
inline constexpr const char* kProjectFile = "project.sageproj";
inline constexpr const char* kScenesDir = "scenes";
inline constexpr const char* kAssetsDir = "assets";
inline constexpr const char* kScriptsDir = "assets/scripts";
inline constexpr const char* kSceneExt = ".sage";
// Имя сцены, которая считается главной, если в project.sageproj не сказано
// иное. Соглашение, а не требование: проект без main.sage запускается по
// первой сцене (см. StartScenePath).
inline constexpr const char* kDefaultScene = "main.sage";
} // namespace layout

// Содержимое project.sageproj. Отдельной структурой, потому что её пишет и
// читает не только редактор: инструмент командной строки создаёт проект с
// теми же полями, а плеер читает те же.
struct Info {
    std::string Name;
    int FormatVersion = 1;
    // Какую сцену запускать. Пусто — политика по умолчанию (см. StartScenePath).
    //
    // Появилось потому, что правило «main.sage, иначе первая по алфавиту» было
    // ЗАШИТО в плеер и нигде больше не существовало: ни редактор, ни автор игры
    // повлиять на него не могли, а узнать — только из исходников плеера.
    std::string StartScene;
    // Версия движка, которым проект создан. Не используется для проверок —
    // нужна человеку, который через год откроет чужой проект и захочет знать,
    // на чём он писался.
    std::string EngineVersion;
};

class Project {
public:
    // --- Жизненный цикл ------------------------------------------------------

    // Создаёт <baseDir>/<name>/ с project.sageproj, scenes/ и assets/ и делает
    // проект текущим. false + error, если папка занята непустой или запись не
    // удалась.
    bool Create(const std::filesystem::path& baseDir, const std::string& name,
                std::string& error);

    // Открывает существующий проект: путь к project.sageproj или к папке с ним.
    bool Open(const std::filesystem::path& fileOrDir, std::string& error);

    // Записывает project.sageproj по текущим Info. Нужен и редактору
    // (изменили стартовую сцену), и коду игры (создали проект программно).
    bool Save(std::string& error) const;

    void Close();
    bool Loaded() const { return m_loaded; }

    // --- Где что лежит -------------------------------------------------------

    const std::string& Name() const { return m_info.Name; }
    const std::filesystem::path& Dir() const { return m_dir; }
    std::filesystem::path ProjectFile() const { return m_dir / layout::kProjectFile; }
    std::filesystem::path ScenesDir() const { return m_dir / layout::kScenesDir; }
    std::filesystem::path AssetsDir() const { return m_dir / layout::kAssetsDir; }
    std::filesystem::path ScriptsDir() const { return m_dir / layout::kScriptsDir; }

    const Info& GetInfo() const { return m_info; }
    Info& MutableInfo() { return m_info; }

    // --- Сцены ---------------------------------------------------------------

    // Имена файлов сцен («main.sage», «level2.sage»), отсортированы.
    //
    // Смотрит и в пакет, и на диск: у СОБРАННОЙ игры каталога scenes/ на диске
    // нет вовсе — всё лежит в game.sagepak, и обход каталога вернул бы пустоту.
    // Это ровно тот случай, ради которого правило поиска сцены нельзя оставлять
    // отдельной реализации у каждого потребителя.
    std::vector<std::string> SceneNames() const;

    // Есть ли в проекте хоть одна сцена — на диске или в пакете.
    bool HasScenes() const { return !SceneNames().empty(); }

    // Полный путь к сцене по имени (с расширением или без).
    std::filesystem::path ScenePath(const std::string& name) const;

    // Ссылка на сцену в том виде, в каком её понимают И файлы проекта, И пакет
    // игры: «scenes/main.sage», относительно корня проекта, через прямой слэш.
    //
    // Отдельно от ScenePath, потому что это РАЗНЫЕ ответы для разных мест.
    // Редактору и коду нужен полный путь на диске; собранной игре — ссылка
    // внутрь пакета, где никакого диска нет вовсе. Раньше эту разницу каждый
    // потребитель держал в голове, и плеер составлял «scenes/…» руками.
    std::string SceneRef(const std::string& name) const;

    // Имя файла стартовой сцены («main.sage»). Пусто — сцен нет.
    // Порядок: Info::StartScene, если задана и существует; иначе main.sage;
    // иначе первая по алфавиту.
    std::string StartSceneName() const;

    // Стартовая сцена полным путём (редактор, код) и ссылкой (собранная игра).
    std::filesystem::path StartScenePath() const;
    std::string StartSceneRef() const;

    // --- Ассеты --------------------------------------------------------------

    // Путь ассета в том виде, в каком его надо ЗАПИСАТЬ в сцену, материал или
    // компонент: относительно корня проекта, через '/'.
    //
    // ЗАЧЕМ. Панель Assets и файловые диалоги отдают АБСОЛЮТНЫЙ путь
    // («/home/вася/Проекты/Игра/assets/models/герой.obj»), и до сих пор он в
    // таком виде и уезжал в сцену. В редакторе на этой машине всё работало —
    // и ровно там заканчивалось. Собранная игра делает chdir в свою папку и
    // ищет «assets/models/герой.obj»; абсолютного пути с чужой машины у неё
    // нет, поэтому модель молча не грузилась, а сцена показывала пустоту.
    // Тот же результат давали перенос проекта в другую папку, второй
    // компьютер и любой архив, отданный товарищу.
    //
    // Путь ВНЕ проекта возвращается как есть: сослаться на файл в чужой папке
    // — законное временное состояние (человек только что выбрал модель в
    // «Загрузках»), и подменять его выдуманным относительным было бы враньём.
    std::string AssetRef(const std::filesystem::path& path) const;

    // Принять каталог как проект БЕЗ файла описания: имя берётся из имени папки.
    //
    // Нужно ровно одному случаю — собранной игре, которая везёт содержимое
    // проекта одним пакетом, а на диске рядом с exe файла описания может не
    // быть. Отдельным методом, а не тихим послаблением в Open: «файла проекта
    // нет» в подавляющем большинстве случаев означает «это вообще не папка
    // игры», и проглатывать это молча — значит вместо понятного отказа выдать
    // человеку пустой чёрный экран.
    void AdoptDirectory(const std::filesystem::path& dir, const std::string& name);

    // Сделать этот проект ДЕЙСТВУЮЩИМ для подсистем движка: создать подпапки,
    // пересканировать базу ассетов, назначить имя для сохранений, сбросить кэш
    // префабов. Зовётся из Create и Open; публичен, потому что нужен ещё и там,
    // где файлы появляются в папке ПОСЛЕ создания (проект из шаблона).
    void Adopt();

    // --- Поиск ---------------------------------------------------------------

    // Ищет project.sageproj в указанном каталоге и выше по дереву. Пустой путь
    // — не нашли. Нужен инструменту командной строки («я где-то внутри
    // проекта») и плееру, запущенному из подпапки.
    static std::filesystem::path Find(const std::filesystem::path& start);

    // Похоже ли, что по этому пути лежит проект. Дешёвая проверка без чтения:
    // ею отличают «это не папка игры» от «папка игры, но пустая», а это разные
    // беды с разными решениями.
    static bool LooksLikeProject(const std::filesystem::path& fileOrDir);

private:
    bool m_loaded = false;
    std::filesystem::path m_dir;
    Info m_info;
};

} // namespace sage::project
