// ---------------------------------------------------------------------------
// Система наклеек: строит их геометрию по сцене.
//
// Наклейка (DecalComponent) — коробка-проектор. Система находит геометрию,
// попавшую внутрь коробки, проецирует её (sage/render/DecalProjection.h) и
// кладёт получившийся меш в MeshRendererComponent той же сущности. Дальше
// наклейка — обычный объект сцены, и ничего специального рендер о ней не знает.
//
// Пересборка идёт только по флагу Dirty: наклейки статичны по своей природе, и
// платить за обход геометрии каждый кадр не за что.
// ---------------------------------------------------------------------------
namespace sage::ecs {

// Геометрия приёмника на CPU. Примитивы берутся у генераторов движка (та же
// геометрия, что уходит на видеокарту), модели — из копии, если её просили
// сохранить. Пустой результат — приёмник, о котором мы ничего не знаем: он
// просто не участвует.
sage::render::MeshData ReceiverGeometry(const MeshRendererComponent& mr);

struct DecalBuildStats {
    int Rebuilt = 0;    // сколько наклеек пересобрано в этом вызове
    int Triangles = 0;  // сколько треугольников получилось суммарно
};

// Пересобирает наклейки со взведённым Dirty. Возвращает, что было сделано —
// это же и ответ на вопрос «почему наклейки не видно».
//
// makeMesh — как превратить готовую геометрию в GPU-меш. Отдельным параметром,
// потому что система обязана работать и БЕЗ графического контекста (тесты,
// инструменты, сервер): передайте nullptr, и посчитается только геометрия.
// Готовый способ превратить геометрию в GPU-меш — то, что передают BuildDecals
// потребители с графическим контекстом (игра, редактор). Требует контекста,
// поэтому и вынесен отдельно от самой системы.
std::shared_ptr<Mesh> MakeDecalMesh(const sage::render::MeshData& data);

DecalBuildStats BuildDecals(Scene& scene,
                            const std::function<std::shared_ptr<Mesh>(const sage::render::MeshData&)>&
                                makeMesh);

} // namespace sage::ecs
