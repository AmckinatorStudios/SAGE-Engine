#pragma once
#include <entt/entt.hpp>
#include <glm/glm.hpp>

class Scene;

// ---------------------------------------------------------------------------
// Единый способ получить кадр (view/proj) от ИГРОВОЙ камеры сцены — первой
// сущности с CameraComponent{Primary=true}. Позиция и ориентация берутся из
// МИРОВОЙ матрицы сущности (учёт иерархии родителей), поэтому предпросмотр в
// панели Game редактора и собранная игра (SagePlayer) ГАРАНТИРОВАННО видят
// сцену одинаково — раньше редактор считал через WorldMatrix, а рантайм через
// локальный Transform, и вид «в игре» мог отличаться от превью («фальшивость»).
// ---------------------------------------------------------------------------
namespace sage::ecs {

struct CameraFrame {
    glm::mat4 View{1.0f};
    glm::mat4 Proj{1.0f};
    glm::vec3 Position{0.0f};
    bool HasPrimary = false; // false — Primary-камеры в сцене нет
};

// Кадр от Primary-камеры (мировая матрица + Fov/Near/Far компонента).
// HasPrimary=false, если камеры нет — вызывающий решает, что показать (редактор
// рисует подсказку, рантайм — запасной вид с явным предупреждением в лог).
CameraFrame PrimaryCameraFrame(Scene& scene, float aspect);

// Сущность Primary-камеры — та, через которую смотрит игра. entt::null, если
// такой камеры в сцене нет.
//
// Отдельно от PrimaryCameraFrame, потому что кадру нужны МАТРИЦЫ, а тракту
// пост-обработки — САМА СУЩНОСТЬ: его компонент висит на камере. Оба ответа
// обязаны получаться из одного правила «первая Primary-камера», иначе кадр мог
// бы считаться по одной камере, а обработка — по другой.
entt::entity PrimaryCameraEntity(Scene& scene);

// Кадр от ЗАДАННОЙ камеры-сущности. Тот же расчёт, что у Primary: превью
// выбранной камеры в редакторе обязано показывать ровно то, что покажет игра,
// а два разных расчёта «куда смотрит камера» разошлись бы на первом же повороте
// родителя. HasPrimary=false, если у сущности нет CameraComponent.
CameraFrame CameraFrameFor(Scene& scene, entt::entity camera, float aspect);

} // namespace sage::ecs
