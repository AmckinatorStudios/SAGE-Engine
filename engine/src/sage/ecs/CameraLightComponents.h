// Игровая камера сцены. Позицию и ориентацию задаёт Transform сущности
// (Scale не влияет). Панель Game редактора — и игры, которым это удобно —
// рендерят изображение от ПЕРВОЙ сущности с Primary == true; так камера
// становится частью сцены (сериализуется), а не хардкодом кода игры.
struct CameraComponent {
    // Тип проекции. Перспектива — обычная игровая камера; орто нужна там, где
    // размер объекта не должен зависеть от расстояния: 2.5D-игры, изометрия,
    // техническая анимация, схемы и чертежи.
    enum class Projection { Perspective, Orthographic };

    Projection Mode = Projection::Perspective;
    float Fov = 60.0f;          // вертикальный угол обзора, градусы (перспектива)
    float OrthoHeight = 10.0f;  // видимая ВЫСОТА кадра в метрах (орто)
    float NearClip = 0.1f;
    float FarClip = 200.0f;
    bool Primary = true;        // первая Primary-камера сцены — «главная»

    // Матрица проекции — ЕДИНСТВЕННОЕ место, где она собирается из компонента.
    // Иначе про орто пришлось бы помнить в каждом вызывающем, и однажды кто-то
    // забыл бы: превью показывало бы одно, рендер — другое.
    //
    // Ширина орто-кадра выводится из высоты и соотношения сторон, а не задаётся
    // отдельно: так смена размера окна не меняет КОМПОЗИЦИЮ по вертикали —
    // ровно то же поведение, что у Fov в перспективе.
    glm::mat4 ProjectionMatrix(float aspect) const {
        const float a = aspect > 0.0001f ? aspect : 0.0001f;
        if (Mode == Projection::Orthographic) {
            const float halfH = (OrthoHeight > 0.0001f ? OrthoHeight : 0.0001f) * 0.5f;
            const float halfW = halfH * a;
            return glm::ortho(-halfW, halfW, -halfH, halfH, NearClip, FarClip);
        }
        return glm::perspective(glm::radians(Fov), a, NearClip, FarClip);
    }
};

// Свет на сущности: позиция берётся из Transform (двигается гизмо,
// анимируется скриптами — как любой объект). Тип задаёт форму источника:
//   • Point       — точечный, светит во все стороны (лампа, факел);
//   • Spot        — прожектор, светит конусом вдоль «вперёд» сущности
//                   (-Z её поворота): фонарик, лампа-спот, сценический свет;
//   • Directional — «солнце»: светит из бесконечности в одну сторону (тот же
//                   -Z поворота), не затухает с расстоянием.
// Затухание с расстоянием — из Range (см. Point/SpotLight в Light.h); у Spot
// дополнительно InnerCone/OuterCone задают жёсткость края конуса. Directional
// не использует ни Range, ни углы конуса: у света из бесконечности нет ни
// расстояния, ни края.
//
// ПОЧЕМУ СОЛНЦЕ ЗДЕСЬ, А НЕ В НАСТРОЙКАХ СЦЕНЫ. Раньше направленный свет жил
// ТОЛЬКО в Scene::Lighting.Sun — то есть был настройкой окружения, а не
// объектом. Это противоречило ECS ровно в тех местах, где противоречие
// чувствуется руками:
//
//   • солнце нельзя было выбрать в иерархии, повернуть гизмо и увидеть, куда
//     оно светит, — направление задавалось тремя числами в панели, и подобрать
//     по ним закат означало крутить их вслепую;
//   • его нельзя было ни анимировать, ни привязать к родителю, ни включить в
//     префаб — всё, что движок умеет делать с сущностями, солнца не касалось;
//   • в сцене не могло быть двух направленных светов (луна вдобавок к солнцу,
//     свет «сверху» плюс подсветка сзади) — поле было одно;
//   • скрипт менял его через отдельный API (GetLighting().Sun), а не через тот
//     же компонент, что и все прочие света.
//
// Теперь солнце — обычная сущность с LightComponent{Directional}. Настройка
// окружения (Scene::Lighting.Sun) осталась ОСНОВАНИЕМ кадра: она нужна коду,
// который собирает сцену без редактора (игры, превью ассетов, тесты), и её
// перекрывает направленный свет-сущность, если он в сцене есть. Старые сцены
// переносятся миграцией (см. MigrateV4toV5 в SceneSerializer).
//
// Рендер собирает итоговое освещение кадра через sage::ecs::CollectLighting:
// окружение сцены + света-сущности.
struct LightComponent {
    enum class Type { Point, Spot, Directional };

    Type Kind = Type::Point;
    glm::vec3 Color{1.0f, 0.9f, 0.7f};
    float Intensity = 1.5f;
    float Range = 12.0f;         // дистанция затухания, единицы мира
    float InnerConeDeg = 20.0f;  // Spot: полная яркость внутри этого полуугла
    float OuterConeDeg = 30.0f;  // Spot: край конуса (яркость -> 0)

    // Отбрасывает ли свет тени. Раньше этого поля не было, потому что тени
    // умело только солнце: у точечных и прожекторов свет проходил СКВОЗЬ
    // стены, и единственным способом это скрыть было не ставить их там, где
    // видно. Теперь тень считают все три типа (см. render/ShadowAtlas.h), и
    // выключатель нужен: карта локального света стоит целого прохода геометрии,
    // а у точечного — шести, и декоративной лампе в углу они не нужны.
    bool CastShadows = true;
};
