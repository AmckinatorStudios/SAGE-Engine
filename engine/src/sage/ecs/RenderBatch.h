#include <unordered_map>
#include <vector>

#include <glm/glm.hpp>
#include <entt/entt.hpp>

#include "sage/render/Mesh.h"
#include "sage/render/LodGroup.h"
#include "sage/render/ShadowMap.h"

class Scene;
struct LightingEnvironment;
struct Material;
namespace sage::gi { struct GIState; }

// ---------------------------------------------------------------------------
// RenderBatch — масштабируемый проход статических мешей: отсечение по фрустуму
// + инстансный батчинг. Вместо «один draw call на сущность» собирает видимые
// сущности, группирует по мешу и рисует каждую группу ОДНИМ инстансным вызовом
// (per-instance поток — модельная матрица + цвет). Так число draw call'ов
// зависит от числа РАЗНЫХ мешей, а не от числа сущностей, а стоимость — от
// видимых, а не от всех. Освещение идентично статическому lit.frag.
//
// Владелец (слой редактора/рантайма/игры) держит один экземпляр; шейдеры —
// внутренние (встроенные), создаются лениво.
// ---------------------------------------------------------------------------
namespace sage::ecs {

struct RenderStats {
    int Total = 0;      // всего рендерящихся сущностей
    int Drawn = 0;      // прошли отсечение (реально нарисованы)
    int Culled = 0;     // отсечены фрустумом
    int CulledTiny = 0; // отсечены по размеру на экране (мельче порога LOD)
    int Batches = 0;    // инстанс-групп = draw call'ов геометрии
    // Треугольников отправлено на отрисовку и сколько было бы без уровней
    // детализации. Пара чисел, а не одно: экономия — это разница, и показывать
    // её надо рядом с тем, от чего считали.
    long long Triangles = 0;
    long long TrianglesAtLod0 = 0;
};

class RenderBatch {
public:
    // Цветной проход: отсечение по камере + инстансная отрисовка с полным
    // освещением. shadingMode: 0 lit / 1 unlit / 2 normals. Возвращает статистику.
    RenderStats RenderColor(Scene& scene, const glm::mat4& view, const glm::mat4& proj,
                            const glm::vec3& viewPos, const LightingEnvironment& env,
                            const ShadowBinding& shadows, int shadingMode);

    // Depth-проход для карты теней: отсечение по фрустуму СВЕТА + инстансная
    // отрисовка только глубины (без освещения).
    void RenderDepth(Scene& scene, const glm::mat4& lightMatrix);

    // ------------------------------------------------------------------------
    // Проход СКОРОСТЕЙ: экранное смещение каждого пикселя между прошлым кадром
    // и этим, в текущий render-target (RG в долях экрана, .xy).
    //
    // Зачем отдельный проход. Смаз движения можно приблизить, восстановив
    // мировую точку из глубины и спроецировав её матрицей прошлого кадра, — но
    // так получается смаз ТОЛЬКО от камеры: мир при этом считается неподвижным,
    // и пролетающий мимо объект при неподвижной камере остаётся резким. Здесь
    // же у каждой сущности берётся ЕЁ СОБСТВЕННАЯ матрица прошлого кадра,
    // поэтому движение объектов и движение камеры складываются естественно.
    //
    // Зовётся ПОСЛЕ RenderColor того же кадра: используется уже собранный
    // список видимого (m_cull), повторное отсечение не делается.
    //
    // prevViewProj — матрица камеры на ПРОШЛОМ шаге времени. Она своя у каждого
    // потока кадров, поэтому передаётся снаружи, а не хранится здесь: вьюпорт,
    // Render View и экспорт смотрят разными камерами и с разным ритмом.
    //
    // Сущность, которой на прошлом шаге не было (только что создана, вошла в
    // кадр), получает нулевую скорость — иначе она размазалась бы через весь
    // экран из точки, где никогда не была.
    void RenderVelocity(const glm::mat4& viewProj, const glm::mat4& prevViewProj);

    // Запоминает положение мира как «прошлое». Зовётся РОВНО ОДИН РАЗ на шаг
    // времени сцены — после того как отрисованы все виды этого шага.
    //
    // Отдельно от RenderVelocity намеренно. Положение объектов от камеры не
    // зависит, а видов за один шаг рисуется несколько; если бы историю двигал
    // сам проход скоростей, второй вид сравнивал бы мир сам с собой и получал
    // нули.
    void AdvanceVelocityHistory();

    // Рвёт непрерывность движения: следующий шаг посчитает нулевые скорости.
    // Нужно при скачке во времени, смене сцены и загрузке проекта — иначе
    // первый кадр после скачка смазался бы по всей длине прыжка.
    void ResetVelocityHistory();

    const RenderStats& LastStats() const { return m_stats; }

private:
    // Одна видимая текстурная сущность (с albedo/normal-картами) — рисуется
    // индивидуально текстурным PBR-шейдером (нельзя инстансить с текстурами).
    // LmPage >= 0 — сущность лайтмапнута (страница атласа GI).
    struct TexturedItem { Mesh* Mesh_; glm::mat4 Model; const Material* Mat; int LmPage; };

    // Кандидат кадра: заполняется ПОСЛЕДОВАТЕЛЬНЫМ проходом по реестру (чтение
    // ECS не потокобезопасно на структурные правки), затем ПАРАЛЛЕЛЬНО
    // проверяется на видимость (frustum) — каждый поток пишет только свой
    // Visible, читая общий frustum/bounds меша только на чтение. Слияние в
    // бакеты — снова последовательно, в исходном порядке (детерминизм).
    struct CullItem {
        Mesh* Mesh_;
        glm::mat4 Model;
        const Material* Mat;
        glm::vec3 Color;
        int LmPage;     // страница лайтмапы (-1 — не запечена)
        bool Textured;
        bool Visible;
        // Нужна проходу скоростей: по ней ищется матрица ПРОШЛОГО кадра этой же
        // сущности. Больше нигде не используется — отсечению и отрисовке
        // достаточно меша с матрицей.
        entt::entity Entity;
        // Уровни детализации сущности (nullptr — их нет) и её ИСХОДНЫЙ меш.
        // Исходный нужен отдельно, потому что Mesh_ по ходу отсечения
        // подменяется на меш выбранного уровня, а статистика «сколько было бы
        // без LOD» считается от исходного.
        const sage::render::LodComponent* LodInfo;
        Mesh* BaseMesh;
        int Lod = 0;
    };

    // Инстанс-группа одного меша. У запечённой статики меш уникален для
    // сущности (свои лайтмап-UV), так что LmPage один на группу.
    struct Group {
        std::vector<MeshInstance> Instances;
        int LmPage = -1;
    };

    // Сбор видимых сущностей: flat (без карт) — в m_groups по мешу (инстансинг),
    // текстурные (с картами) — в m_textured. cullMatrix — фрустум камеры/света.
    void CollectVisible(Scene& scene, const glm::mat4& cullMatrix);

    std::unordered_map<Mesh*, Group> m_groups; // flat-инстансы по мешу
    std::vector<TexturedItem> m_textured;                          // текстурные (индивидуально)
    std::vector<CullItem> m_cull;                                  // кандидаты кадра (переиспользуется)
    // Мировые матрицы кадра (Scene::ComputeWorldMatrices) — один O(n)-проход
    // на сбор вместо рекурсивного WorldMatrix на каждую сущность (см. Scene.h).
    // Переиспользуется между кадрами, чтобы не переаллоцировать хэш-таблицу.
    std::unordered_map<entt::entity, glm::mat4> m_worldCache;
    // Мировые матрицы ПРОШЛОГО кадра — источник скоростей объектов. Держим
    // отдельной таблицей, а не полем сущности: скорость нужна только рендеру,
    // и складывать её в ECS значило бы платить за неё во всех сценах, включая
    // те, где смаза нет вовсе.
    std::unordered_map<entt::entity, glm::mat4> m_prevWorld;
    bool m_hasPrevFrame = false;
    RenderStats m_stats;
};

} // namespace sage::ecs
