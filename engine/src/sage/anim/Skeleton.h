#pragma once
#include <string>
#include <vector>

#include <glm/glm.hpp>
#include <glm/gtc/quaternion.hpp>

// ---------------------------------------------------------------------------
// Скелет и анимационные клипы — данные скелетной анимации, независимые от GPU
// и графического API (как sage/physics независим от бэкенда физики). Загружаются
// из glTF (см. SkinnedModel) или строятся процедурно; проигрываются классом
// Animator, который выдаёт палитру матриц костей для скиннинг-шейдера.
// ---------------------------------------------------------------------------
namespace sage::anim {

// Максимум костей в палитре — совпадает с размером uBones[] в скиннинг-шейдере.
constexpr int kMaxBones = 128;

// Кость (сустав) скелета. Локальный дефолт хранится как TRS, чтобы каналы
// анимации могли независимо переопределять перенос/поворот/масштаб, а поворот
// корректно интерполировался сферически (slerp).
struct Joint {
    std::string Name;
    int Parent = -1;                       // индекс родителя в Skeleton::Joints (-1 — корень)
    glm::vec3 Translation{0.0f};
    glm::quat Rotation{1.0f, 0.0f, 0.0f, 0.0f};
    glm::vec3 Scale{1.0f};
    glm::mat4 InverseBind{1.0f};           // mesh-space -> joint-space (из glTF inverseBindMatrices)

    glm::mat4 LocalMatrix() const;         // TRS дефолтной позы
};

struct Skeleton {
    std::vector<Joint> Joints;

    // Трансформ НАД корневой костью: всё, что стоит в файле выше скелета.
    //
    // ЗАЧЕМ. В glTF обратные bind-матрицы (InverseBind) заданы относительно
    // КОРНЯ СЦЕНЫ, а не корня скелета, и глобальная матрица кости по спецификации
    // тоже считается от корня сцены. Экспортёры почти всегда кладут над скелетом
    // пару узлов с поворотом (смена Z-up на Y-up у Blender, «Sketchfab_model» у
    // выгрузок оттуда). Пока эта цепочка отбрасывалась, каждая кость получала
    // множитель Root^-1 — модель целиком оказывалась повёрнутой (обычно на 180°
    // вокруг Y, то есть спиной к камере), и жёстко привязанные к костям детали
    // сходились с ней только потому, что ошибка была общей.
    //
    // Матрицей, а не TRS: над скелетом встречается зеркальный масштаб (-1 по
    // оси), а разложение такой матрицы в TRS неоднозначно. Анимация её не
    // трогает — она общая для всего скелета и в клипах не участвует.
    glm::mat4 Root{1.0f};

    int Count() const { return (int)Joints.size(); }
};

// Что анимирует канал у одной кости.
enum class AnimPath { Translation, Rotation, Scale };
// Как интерполировать между ключами.
//
// КУБИЧЕСКАЯ — ОТДЕЛЬНЫМ ВИДОМ, а не «как линейная». Формат её даёт (glTF
// CUBICSPLINE, экспорт Blender с кривыми Безье), и кривая там задана не только
// значениями, но и КАСАТЕЛЬНЫМИ на входе и выходе ключа. Пока её сводили к
// линейной, значения ключей читались не с того места: у CUBICSPLINE выход
// сэмплера — тройка «касательная на входе, значение, касательная на выходе»,
// и разбор брал первую из трёх. То есть поза бралась из касательной — числа,
// которое к позе отношения не имеет. Снаружи это и есть «анимация дёргается».
enum class AnimInterp { Linear, Step, CubicSpline };

// Один канал: последовательность ключей (время → значение) для одного свойства
// одной кости. Для Translation/Scale значимы xyz Values; для Rotation — кватернион
// (x,y,z,w) в Values.
struct AnimChannel {
    int Joint = -1;
    AnimPath Target = AnimPath::Translation;
    AnimInterp Interp = AnimInterp::Linear;
    std::vector<float> Times;      // возрастающие метки времени (сек)
    std::vector<glm::vec4> Values; // по одному значению на метку
    // Касательные кубической кривой — по одной паре на ключ. Заполняются ТОЛЬКО
    // при Interp == CubicSpline; у прочих видов пусты, и места не занимают.
    std::vector<glm::vec4> InTangents;
    std::vector<glm::vec4> OutTangents;

    // Сэмплирует канал в момент t: перенос/масштаб — в outVec3, поворот — в outQuat.
    // Используется только соответствующее поле (по Target).
    void Sample(float t, glm::vec3& outVec3, glm::quat& outQuat) const;
};

// Переопределение локальной позы ОДНОЙ кости — то, чем инструмент анимации
// правит позу поверх клипа (или вместо него, когда клипа нет).
//
// Переопределения хранятся в тех же локальных TRS, что и ключи клипа, и
// применяются ПОСЛЕ сэмплирования и смешивания клипов. Поэтому они складываются
// с клипом предсказуемо: переопределённое свойство берётся отсюда, остальные —
// из клипа. Флаги раздельные по T/R/S: анимировать поворот руки, оставив
// перенос от клипа, — обычная задача, и она не должна требовать ключей на всё.
struct JointPose {
    bool HasTranslation = false;
    bool HasRotation = false;
    bool HasScale = false;
    glm::vec3 Translation{0.0f};
    glm::quat Rotation{1.0f, 0.0f, 0.0f, 0.0f};
    glm::vec3 Scale{1.0f};

    bool Any() const { return HasTranslation || HasRotation || HasScale; }
    void Clear() { HasTranslation = HasRotation = HasScale = false; }
};

// Анимационный клип: набор каналов + длительность (макс. время ключей).
struct AnimationClip {
    std::string Name;
    float Duration = 0.0f;
    std::vector<AnimChannel> Channels;
};

} // namespace sage::anim
