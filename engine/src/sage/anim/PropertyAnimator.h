#pragma once
#include <memory>
#include <string>

#include <entt/entt.hpp>

#include "sage/anim/PropertyClip.h"

class Scene;

// ---------------------------------------------------------------------------
// ПРОИГРЫВАНИЕ КЛИПА ПО СВОЙСТВАМ — компонент и система.
//
// ГРАНИЦА, РАДИ КОТОРОЙ ЭТО РАЗДЕЛЕНО. Инструмент анимации правит ТОЛЬКО КЛИП:
// он не знает ни про сцену, в которой клип проиграют, ни про то, когда его
// запустят. Компонент отвечает на другой вопрос — какой клип играть на ЭТОЙ
// сущности, с какой скоростью и зациклен ли он. Пока это было бы одним целым,
// один и тот же «мигание» нельзя было бы повесить на десять кнопок: правка
// одной правила бы всех.
//
// АДРЕСАЦИЯ ЦЕЛЕЙ. Дорожка клипа указывает путь от ВЛАДЕЛЬЦА («Icon»,
// «Bar/Fill»), и разрешается он от сущности с компонентом. Поэтому один клип
// ложится на любое поддерево с такими же именами — ровно как скелетный клип
// ложится на любой скелет с такими же именами костей.
// ---------------------------------------------------------------------------
struct PropertyAnimatorComponent {
    // Файл клипа (.sageclip), путь относительно проекта. Пусто — играть нечего.
    std::string ClipPath;

    bool Playing = true;
    bool Loop = true;       // перебивает Loop самого клипа: одно движение может
                            // быть и петлёй фона, и разовым откликом на нажатие
    float Speed = 1.0f;
    float Time = 0.0f;      // текущее время внутри клипа, секунды

    // Загруженный клип — РАНТАЙМ, в файл не пишется: путь есть, а грузить его
    // дело системы. Общий указатель, потому что один клип висит на десятке
    // сущностей и копировать его на каждую значит платить памятью за то, что
    // никто не правит.
    std::shared_ptr<sage::anim::PropertyClip> Clip;
    bool Ready = false;     // попытка загрузки уже была (в том числе неудачная)
};

namespace sage::anim {

// Продвигает время и применяет позу всем сущностям с PropertyAnimatorComponent.
// Безопасно звать каждый кадр; dt <= 0 применяет позу, не двигая время, — это
// нужно редактору, который сам решает, где стоит бегунок.
void UpdatePropertyAnimators(Scene& scene, float dt);

// Применяет клип к сущности в заданный момент — БЕЗ компонента и без времени
// внутри него. Ровно этим редактор показывает позу под бегунком: инструмент
// правит клип, а увидеть его надо на настоящих объектах настоящей сцены.
void ApplyClipAt(Scene& scene, entt::entity owner, const PropertyClip& clip, float time);

// Сущность по пути от владельца («Bar/Fill»). entt::null — такой нет: клип
// пережил переименование объекта, и это не повод падать.
entt::entity ResolveTarget(Scene& scene, entt::entity owner, const std::string& path);

} // namespace sage::anim
