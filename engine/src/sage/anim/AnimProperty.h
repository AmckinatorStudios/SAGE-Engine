#pragma once
#include <string>
#include <string_view>
#include <vector>

#include <entt/entt.hpp>
#include <glm/glm.hpp>

// ---------------------------------------------------------------------------
// АНИМИРУЕМЫЕ СВОЙСТВА — РЕЕСТР, а не список в редакторе анимации.
//
// ЗАЧЕМ ЭТО ЗДЕСЬ, А НЕ В РЕДАКТОРЕ. Дорожка анимации адресует свойство именем
// («element.position», «fill.color»), и по этому имени его надо УМЕТЬ ЧИТАТЬ И
// ПИСАТЬ — и в редакторе, когда ставят ключ, и в собранной игре, когда клип
// проигрывается. Список «что можно анимировать», написанный в редакторе,
// означал бы игру, которая не умеет проиграть то, что редактор записал.
//
// ОТКУДА БЕРУТСЯ СВОЙСТВА. Из тех же таблиц, которыми часть описывает себя:
// у интерфейса это sage::ui::Parts() с их PartField, у объекта сцены —
// положение, поворот и масштаб. Числовые поля (Float, Vec2, Vec4, Color)
// анимируемы, остальные — нет: анимировать путь к файлу или список связей
// нечем, промежуточного значения у них не существует.
//
// Отсюда главное свойство: ЧАСТЬ, ПРИШЕДШАЯ ИЗ ИГРЫ, СТАНОВИТСЯ АНИМИРУЕМОЙ
// САМА. Ни строки правок ни в редакторе анимации, ни здесь.
//
// ЗНАЧЕНИЕ — ВСЕГДА vec4. Свойств одно-, двух-, трёх- и четырёхмерных поровну
// много, и четыре разных типа ключа означали бы четыре ветки в сэмплере, в
// файле и в рисовании кривой. Сколько компонент на самом деле значимо, говорит
// Components; остальные — нули и в файл идут нулями.
// ---------------------------------------------------------------------------
namespace sage::anim {

struct PropertyType {
    // Ключ в файле клипа: «element.position». Часть до точки — Id части (или
    // «object» для полей самой сущности), после — ключ поля.
    std::string Id;
    std::string Title;   // подпись в редакторе (английский ключ, переводится там)
    std::string Group;   // как называется ветка дорожек: «Layout», «Fill»
    int Components = 1;  // сколько чисел значимо: 1..4

    // СВОЙ доступ — для того, у чего таблицы полей нет: положение, поворот и
    // масштаб старше реестра частей и лежат в основании сцены. Пусто —
    // значит свойство принадлежит части, и доступ идёт через её таблицу
    // (см. ReadProperty ниже). Двух путей ровно два, и второй существует
    // только потому, что первый физически не к чему приложить.
    bool (*Has)(const entt::registry&, entt::entity) = nullptr;
    glm::vec4 (*Get)(const entt::registry&, entt::entity) = nullptr;
    void (*Set)(entt::registry&, entt::entity, const glm::vec4&) = nullptr;
};

// Зарегистрировать своё свойство. Повторная регистрация с тем же Id заменяет
// прежнюю — так игра подменяет встроенное поведение своим.
void RegisterProperty(const PropertyType& type);

// Все свойства. Первый вызов регистрирует встроенные (объект сцены + всё, что
// объявили части интерфейса).
const std::vector<PropertyType>& Properties();

// Свойство по ключу; nullptr — такого нет. Клип с неизвестным ключом не
// ошибка: он мог прийти из сборки игры с другими частями, и терять его дорожки
// при открытии сцены нельзя.
const PropertyType* FindProperty(std::string_view id);

// --- Доступ по свойству ------------------------------------------------------
//
// ОДИН вход и для редактора, и для проигрывания: «прочитать текущее значение»
// (ставя ключ) и «записать посчитанное» (проигрывая клип). Ветка «это часть
// интерфейса или поле объекта» живёт ровно здесь, и больше нигде.
//
// false — свойства у этой сущности сейчас нет (сняли компонент, клип пришёл от
// другой сборки игры). Не ошибка: дорожка остаётся в клипе, её просто некуда
// применить, и терять записанное движение из-за снятой галки нельзя.
bool ReadProperty(const PropertyType& p, const entt::registry& reg, entt::entity e,
                  glm::vec4& out);
bool WriteProperty(const PropertyType& p, entt::registry& reg, entt::entity e,
                   const glm::vec4& value);
bool HasProperty(const PropertyType& p, const entt::registry& reg, entt::entity e);

// Свойства, которые ИМЕЕТ СМЫСЛ анимировать у этой сущности: те, чья часть на
// ней есть. По ним редактор предлагает «добавить дорожку».
std::vector<const PropertyType*> PropertiesFor(const entt::registry& reg, entt::entity e);

} // namespace sage::anim
