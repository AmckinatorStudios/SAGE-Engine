namespace sage::render { class SkinnedModel; }

// Скелетно-анимированная модель на сущности. Path — файл .glb/.gltf со скином и
// анимациями; ПУСТОЙ Path означает встроенную процедурную демо-модель (щупалец
// с клипом «Wave»), удобную для примеров и тестов без ассетов. Позой управляет
// система анимации (sage/anim/AnimationSystem): при первом обновлении грузит
// модель, привязывает Animator к её скелету и запускает клип Clip; каждый кадр
// продвигает время и обновляет палитру костей, которой рисуется модель.
//
// Сериализуются только «описательные» поля (Path/DemoSegments/Clip/Speed/Loop/
// Playing); Model/Anim/Ready — рантайм-состояние, восстанавливается загрузкой.
struct AnimatedModelComponent {
    std::string Path;         // .glb/.gltf; пусто -> процедурный демо-щупалец
    int DemoSegments = 6;     // число костей процедурного демо (если Path пуст)
    int Clip = 0;             // индекс проигрываемого клипа (смена -> кросс-фейд)
    float Speed = 1.0f;
    bool Loop = true;
    bool Playing = true;
    float BlendTime = 0.25f;  // длительность кросс-фейда при смене Clip (0 — резко)
    // Корневое движение: перемещение, запечённое в клип, снимается с позы и
    // применяется к САМОЙ СУЩНОСТИ. Без этого меш уезжает от своего трансформа —
    // персонаж идёт, а его коллайдер и камера стоят.
    bool RootMotion = false;

    // Веса блендшейпов в порядке SkinnedModel::MorphNames(). Это ПОЗА ЛИЦА, и
    // живёт она рядом с позой скелета: у одной модели может быть много
    // экземпляров с разными выражениями. Пусто — форма как в файле.
    std::vector<float> MorphWeights;

    // Переопределения позы по костям — то, чем скрипт двигает скелет НАПРЯМУЮ.
    //
    // Нужны не для удобства: наборы персонажей сплошь и рядом приходят
    // оснащёнными, но БЕЗ единого клипа (анимации покупаются отдельно). Без
    // этого поля такой пакет — набор неподвижных статуй, и проверить скиннинг
    // на нём нечем. Применяются поверх клипа, поэтому «повернуть голову за
    // курсором» поверх ходьбы — это тоже они.
    std::vector<sage::anim::JointPose> PoseOverrides;

    std::shared_ptr<sage::render::SkinnedModel> Model; // рантайм (не сериализуется)
    sage::anim::Animator Anim;                          // рантайм-состояние проигрывания
    bool Ready = false;                                 // инициализирован ли (загрузка+rig)
};

// Одна цель обратной кинематики: «поставь ЭТУ кость СЮДА».
//
// Кость задаётся ИМЕНЕМ, а не индексом: индекс зависит от порядка костей в
// файле и молча меняется при переэкспорте, а «foot_l» переживает и то и другое.
// Индексы ищутся один раз при первой обработке и кэшируются рядом.
struct IKGoal {
    std::string Bone;            // конец цепочки: ступня, кисть, голова
    int ChainLength = 2;         // КОСТЕЙ в цепочке: 2 — двухзвенный, больше — FABRIK
    glm::vec3 Target{0.0f};      // куда, В МИРОВЫХ координатах
    bool UsePole = false;        // куда смотрит колено/локоть
    glm::vec3 Pole{0.0f};
    float Weight = 1.0f;         // 0 — цель выключена, 1 — держим точно
    bool Enabled = true;

    // Довернуть конец цепочки под нормаль поверхности (ступня ложится на склон,
    // а не втыкается носком). Ноль — не доворачивать.
    glm::vec3 AlignNormal{0.0f};

    // Взгляд: вместо позиционирования цепочки повернуть ОДНУ кость так, чтобы
    // её ось AimAxis смотрела на Target. Голова за курсором, ствол за целью.
    bool Aim = false;
    glm::vec3 AimAxis{0.0f, 0.0f, 1.0f};
    float AimMaxAngle = 80.0f;   // предел отклонения от текущего направления

    // Прилипание к земле. Пока стопа ниже PlantHeight (в координатах МОДЕЛИ),
    // её мировая точка запоминается и держится — это и есть лекарство от
    // «скольжения ног»: при переносе анимации с чужого скелета или при
    // несовпадении скорости шага с корневым движением стопа иначе едет по полу.
    bool Lock = false;
    float PlantHeight = 0.12f;
    float ReleaseTime = 0.12f;   // за сколько секунд замок отпускает ногу

    // --- рантайм (не сериализуется) ---
    int EndJoint = -1, MidJoint = -1, RootJoint = -1;
    bool Locked = false;         // сейчас прилипла
    glm::vec3 LockedAt{0.0f};    // мировая точка, где прилипла
    float LockBlend = 0.0f;      // 1 — держим, 0 — отпустили; между — сглаживание
    bool Resolved = false;       // индексы найдены
};

// Обратная кинематика сущности: набор целей поверх позы клипа.
//
// Живёт ОТДЕЛЬНО от AnimatedModelComponent намеренно: анимация — это «что
// проигрывать», IK — «что поправить в результате». Их правят разные люди в
// разное время, и половине анимированных сущностей IK не нужен вовсе.
struct IKComponent {
    std::vector<IKGoal> Goals;
    bool Enabled = true;

    // --- рантайм (не сериализуется) ---
    //
    // Что IK написал в позу в прошлом кадре и что стояло там ДО него. Перед
    // новым решением это возвращается на место, и каждый кадр IK считается от
    // чистой позы клипа.
    //
    // Без отката было бы две беды. Первая: доворот конца — величина
    // ОТНОСИТЕЛЬНАЯ, и, накладываясь сам на себя, он раскручивал бы ступню
    // кадр за кадром. Вторая: выключенная цель оставляла бы свой последний
    // поворот в позе навсегда — снять IK было бы нечем.
    std::vector<int> Touched;
    std::vector<sage::anim::JointPose> Saved;
};
