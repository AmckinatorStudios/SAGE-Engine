namespace sage::render { class SkinnedModel; }

// Проигрывание анимации на сущности. САМА МОДЕЛЬ ЗДЕСЬ НЕ ХРАНИТСЯ.
//
// ЧТО ИЗМЕНИЛОСЬ И ПОЧЕМУ. Раньше это был компонент «Animated Model»: он держал
// и путь к файлу, и состояние проигрывания, — то есть в сцене существовало ДВА
// РАЗНЫХ ВИДА ОБЪЕКТА, «модель» и «анимированная модель». Для человека,
// собирающего уровень, это ложное деление: анимация — характеристика предмета,
// а не отдельный сорт предмета. Практическая цена деления такая же ложная:
// одна и та же модель, положенная в сцену «как декорация» и «как персонаж»,
// требовала разных компонентов, разных полей и разного порядка действий, а
// материалы, слоты подмешей и настройки отрисовки были только у одного из них.
//
// Теперь ЧТО рисуем описывает Mesh (MeshRendererComponent), а Animation
// отвечает только на вопрос КАК ЭТО ДВИЖЕТСЯ: какой клип, с какой скоростью,
// зациклен ли. Скелет берётся из модели, на которую показывает Mesh; если у
// той скелета нет, анимировать нечего — и редактор говорит это прямо, вместо
// того чтобы молча ничего не делать.
//
// Сериализуются только «описательные» поля (Clip/Speed/Loop/Playing/BlendTime/
// RootMotion/веса); Model/Anim/Ready — рантайм, восстанавливается загрузкой.
// --- ПАРАМЕТРЫ АНИМАТОРА -----------------------------------------------------
//
// Именованные числа, флаги и «взведённые» события, которыми игра описывает
// состояние движения: Speed, IsGrounded, Jump. Это УНИВЕРСАЛЬНЫЙ словарь —
// движок не знает, что значит «Speed», он только хранит и отдаёт.
//
// Зачем они здесь, а не в скрипте. Состояние движения читают несколько
// потребителей сразу: сам скрипт, другой скрипт (оружие смотрит на «бежит
// ли»), а в дальнейшем — граф состояний аниматора. Пока оно лежит в локальной
// переменной скрипта, дотянуться до него нельзя никому.
//
// ГРАФА СОСТОЯНИЙ В SAGE ПОКА НЕТ, и это сказано прямо: параметры хранятся и
// читаются, но сами по себе клип не переключают — клип переключает Play(). Это
// честнее, чем не дать API вовсе: игра пишет свою логику на них сегодня и
// ничего не переписывает, когда граф появится.
struct AnimationParams {
    std::unordered_map<std::string, float> Floats;
    std::unordered_map<std::string, bool> Bools;
    // Взводится на один раз: прочитавший его — потребил. Иначе «прыгнул»
    // остаётся истиной навсегда, и первый же переход по нему срабатывает
    // вечно.
    std::unordered_map<std::string, bool> Triggers;
    // Вес слоя по ИМЕНИ (AnimationLayer::Name) — то, что пишет
    // `animator:SetLayerWeight("Wave", 0.5)`. Нет записи — вес из самого слоя.
    std::unordered_map<std::string, float> Layers;
};

// СЛОЙ АНИМАЦИИ: ещё один клип поверх основной позы (клипа компонента или
// графа), с весом и маской. Смешивается только то, что в клипе слоя есть, и
// только на костях маски (sage::anim::ApplyLayer).
struct AnimationLayer {
    std::string Name;               // по нему вес задают из скрипта (Params.Layers)
    std::string ClipPath;           // .sageanim — кости по именам
    float Weight = 1.0f;            // 0..1
    // МАСКА: кости скелета, каждая вместе со всеми потомками («от плеча» —
    // вся рука). Пусто — весь скелет. Имена проверяются по скелету модели:
    // ненайденные считаются (MissingMaskBones) и показываются, а не угадываются.
    std::vector<std::string> Mask;
};

// Рантайм слоя: привязанный к скелету клип, веса костей из маски, время.
struct AnimationLayerState {
    const sage::anim::Skeleton* BoundTo = nullptr;  // скелет, к которому привязан
    std::string ClipFrom;                           // путь, из которого собран клип
    std::vector<std::string> MaskFrom;              // маска, из которой собраны веса
    sage::anim::AnimationClip Clip;
    bool HasClip = false;
    std::vector<float> JointWeights;                // пусто — весь скелет
    float Time = 0.0f;
    int MissingBones = 0;                           // каналов клипа без кости
    int MissingMaskBones = 0;                       // имён маски без кости
};

struct AnimationComponent {
    // КЛИП — ФАЙЛ (.sageanim), а не номер внутри модели.
    //
    // Номер зависел от порядка клипов в файле модели и молча менялся при
    // переэкспорте: художник поменял местами «Idle» и «Walk» — персонаж в сцене
    // начал стоять вместо ходьбы, и ни ошибки, ни предупреждения. Файл
    // адресуется путём, лежит в проекте рядом с моделью и переживает
    // переэкспорт; кости внутри него адресованы именами (см. anim/ClipFile.h).
    //
    // Пусто — играем клип из самой модели по номеру ниже. Так открываются сцены,
    // сделанные до появления файлов клипов, и так же работает модель, клипы
    // которой ещё не вынуты.
    std::string ClipPath;

    // ГРАФ АНИМАЦИИ (.sageanimgraph). Параметры графа — Params.Floats
    // (SetFloat ниже, в Lua — animator:SetFloat): тот же словарь, что уже
    // читают скрипты.
    std::string GraphPath;

    // ИСТОЧНИК ПОЗЫ: играет ровно один из двух ресурсов выше, и выбирает его
    // ЭТО поле, а не то, какой путь заполнен. Раньше «граф задан — клип не
    // играет», и переключение режима стирало путь соседа: назначенный клип
    // пропадал от одного нажатия на «Graph». Теперь оба пути живут рядом и не
    // трогают друг друга; выбранный источник не подменяется другим: Graph без
    // рабочего графа не играет ничего (причина — GraphProblem), а не клип.
    enum class SourceKind { Clip, Graph };
    SourceKind Source = SourceKind::Clip;
    // Рантайм: почему выбранный граф не играет (пусто — играет или не выбран).
    std::string GraphProblem;
    // Рантайм: клип снят с проигрывания на время режима Graph; вернувшись к
    // Clip, система заново подключает его (иначе аниматор остался бы стоять).
    bool ClipSuspended = false;
    // Рантайм: GraphAsset положил редактор (предпросмотр правок до сохранения),
    // система его не читает из файла и не проверяет. Выставляется только на
    // копии объекта в Animation Stage, настоящему объекту сцены — никогда.
    bool GraphInMemory = false;

    int Clip = 0;             // запасной путь: номер клипа В МОДЕЛИ
    float Speed = 1.0f;
    bool Loop = true;
    bool Playing = true;
    float BlendTime = 0.25f;  // длительность кросс-фейда при смене Clip (0 — резко)
    // Корневое движение: перемещение, запечённое в клип, снимается с позы и
    // применяется к САМОЙ СУЩНОСТИ. Без этого меш уезжает от своего трансформа —
    // персонаж идёт, а его коллайдер и камера стоят.
    bool RootMotion = false;

    // Веса блендшейпов в порядке SkinnedModel::MorphNames(). Это ПОЗА ЛИЦА, и
    // живёт она рядом с позой скелета: у одной модели может быть много
    // экземпляров с разными выражениями. Пусто — форма как в файле.
    std::vector<float> MorphWeights;

    // Переопределения позы по костям — то, чем скрипт двигает скелет НАПРЯМУЮ.
    //
    // Нужны не для удобства: наборы персонажей сплошь и рядом приходят
    // оснащёнными, но БЕЗ единого клипа (анимации покупаются отдельно). Без
    // этого поля такой пакет — набор неподвижных статуй, и проверить скиннинг
    // на нём нечем. Применяются поверх клипа, поэтому «повернуть голову за
    // курсором» поверх ходьбы — это тоже они.
    std::vector<sage::anim::JointPose> PoseOverrides;

    std::shared_ptr<sage::render::SkinnedModel> Model; // рантайм (не сериализуется)
    // Клип, прочитанный из файла и привязанный к ЭТОМУ скелету. Живёт здесь, а
    // не в модели: один и тот же .sageanim может играть на разных персонажах, и
    // номера костей у каждого свои.
    std::vector<sage::anim::AnimationClip> OwnClips;    // рантайм
    // Из какого файла собран OwnClips — чтобы заметить смену клипа в инспекторе.
    std::string ClipResolvedFrom;
    // Сколько костей клипа не нашлось в скелете. Не ноль — клип от другого
    // персонажа, и часть движения не играет; редактор обязан это показать, а не
    // оставить человека гадать, почему двигается половина.
    int MissingBones = 0;
    sage::anim::Animator Anim;                          // рантайм-состояние проигрывания
    AnimationParams Params;                             // рантайм (см. выше)

    // Слои поверх основной позы — сохраняются со сценой.
    std::vector<AnimationLayer> Layers;
    std::vector<AnimationLayerState> LayerStates;              // рантайм
    std::vector<sage::anim::AnimLayerPose> LayerPoses;          // рантайм: указатели в LayerStates
    // Действующий вес слоя: из скрипта (Params.Layers), иначе свой.
    float LayerWeight(size_t i) const {
        if (i >= Layers.size()) return 0.0f;
        auto it = Params.Layers.find(Layers[i].Name);
        return it != Params.Layers.end() ? it->second : Layers[i].Weight;
    }

    // Параметр графа из C++ — та же запись, что делает Lua animator:SetFloat.
    void SetFloat(const std::string& name, float value) { Params.Floats[name] = value; }
    float GetFloat(const std::string& name) const {
        auto it = Params.Floats.find(name);
        return it != Params.Floats.end() ? it->second : Graph.GetFloat(name);
    }

    // Граф: ресурс (общий, неизменяемый) и состояние ЭТОГО объекта. Ресурс
    // читается из GraphPath; редактор кладёт сюда граф прямо из памяти для
    // предпросмотра, оставив GraphPath пустым.
    std::shared_ptr<const sage::anim::AnimGraph> GraphAsset;  // рантайм
    sage::anim::AnimGraphInstance Graph;                      // рантайм
    std::string GraphResolvedFrom;                            // рантайм
    uint64_t GraphRevision = 0;                               // рантайм (AnimGraphRevision)
    bool Ready = false;                                 // инициализирован ли (загрузка+rig)
    // Из какого файла собран Model. Нужен, чтобы заметить смену модели в Mesh:
    // человек меняет модель в инспекторе, и скелет обязан переехать за ней, а
    // не остаться от прежней — иначе клипы играют по костям, которых больше нет.
    std::string ResolvedFrom;
    // Поколение ресурсов на момент разбора (ResourceManager::AssetsGeneration).
    // Аниматор держит УКАЗАТЕЛИ внутрь модели — на скелет и на список клипов, —
    // и после перечитывания файла модели они ведут в прежнюю, уже никому не
    // нужную. Сменившееся поколение означает «разбери заново», и именно так
    // переэкспорт персонажа из 3D-редактора доезжает до сцены без перезапуска.
    uint64_t ResourceGen = 0;
};

// Одна цель обратной кинематики: «поставь ЭТУ кость СЮДА».
//
// Кость задаётся ИМЕНЕМ, а не индексом: индекс зависит от порядка костей в
// файле и молча меняется при переэкспорте, а «foot_l» переживает и то и другое.
// Индексы ищутся один раз при первой обработке и кэшируются рядом.
struct IKGoal {
    std::string Bone;            // конец цепочки: ступня, кисть, голова
    int ChainLength = 2;         // КОСТЕЙ в цепочке: 2 — двухзвенный, больше — FABRIK
    glm::vec3 Target{0.0f};      // куда, В МИРОВЫХ координатах
    bool UsePole = false;        // куда смотрит колено/локоть
    glm::vec3 Pole{0.0f};
    float Weight = 1.0f;         // 0 — цель выключена, 1 — держим точно
    bool Enabled = true;

    // Довернуть конец цепочки под нормаль поверхности (ступня ложится на склон,
    // а не втыкается носком). Ноль — не доворачивать.
    glm::vec3 AlignNormal{0.0f};

    // Взгляд: вместо позиционирования цепочки повернуть ОДНУ кость так, чтобы
    // её ось AimAxis смотрела на Target. Голова за курсором, ствол за целью.
    bool Aim = false;
    glm::vec3 AimAxis{0.0f, 0.0f, 1.0f};
    float AimMaxAngle = 80.0f;   // предел отклонения от текущего направления

    // Прилипание к земле. Пока стопа ниже PlantHeight (в координатах МОДЕЛИ),
    // её мировая точка запоминается и держится — это и есть лекарство от
    // «скольжения ног»: при переносе анимации с чужого скелета или при
    // несовпадении скорости шага с корневым движением стопа иначе едет по полу.
    bool Lock = false;
    float PlantHeight = 0.12f;
    float ReleaseTime = 0.12f;   // за сколько секунд замок отпускает ногу

    // --- рантайм (не сериализуется) ---
    int EndJoint = -1, MidJoint = -1, RootJoint = -1;
    bool Locked = false;         // сейчас прилипла
    glm::vec3 LockedAt{0.0f};    // мировая точка, где прилипла
    float LockBlend = 0.0f;      // 1 — держим, 0 — отпустили; между — сглаживание
    bool Resolved = false;       // индексы найдены
};

// Обратная кинематика сущности: набор целей поверх позы клипа.
//
// Живёт ОТДЕЛЬНО от AnimationComponent намеренно: анимация — это «что
// проигрывать», IK — «что поправить в результате». Их правят разные люди в
// разное время, и половине анимированных сущностей IK не нужен вовсе.
struct IKComponent {
    std::vector<IKGoal> Goals;
    bool Enabled = true;

    // --- рантайм (не сериализуется) ---
    //
    // Что IK написал в позу в прошлом кадре и что стояло там ДО него. Перед
    // новым решением это возвращается на место, и каждый кадр IK считается от
    // чистой позы клипа.
    //
    // Без отката было бы две беды. Первая: доворот конца — величина
    // ОТНОСИТЕЛЬНАЯ, и, накладываясь сам на себя, он раскручивал бы ступню
    // кадр за кадром. Вторая: выключенная цель оставляла бы свой последний
    // поворот в позе навсегда — снять IK было бы нечем.
    std::vector<int> Touched;
    std::vector<sage::anim::JointPose> Saved;
};
