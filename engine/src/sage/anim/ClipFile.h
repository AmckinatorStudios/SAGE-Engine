// ---------------------------------------------------------------------------
// АНИМАЦИОННЫЙ КЛИП КАК ОТДЕЛЬНЫЙ ФАЙЛ (.sageanim).
//
// ЗАЧЕМ. До сих пор клипы существовали только ВНУТРИ модели: компонент Animation
// хранил ИНДЕКС клипа в файле модели, и всё. Отсюда три беды, и все три —
// молчаливые.
//
//   • Индекс зависит от порядка клипов в файле. Художник переэкспортировал
//     модель, поменяв местами «Idle» и «Walk», — и персонаж в сцене начал
//     стоять вместо ходьбы. Ни ошибки, ни предупреждения: индекс 0 остался
//     валидным индексом 0.
//   • Клип нельзя ни переиспользовать, ни посмотреть, ни положить в проект
//     отдельно. Анимации сплошь и рядом покупаются отдельно от персонажа —
//     приложить их было НЕКУДА.
//   • Про содержимое модели нельзя было узнать ничего, не загрузив её целиком:
//     в панели ассетов .glb — непрозрачный ком.
//
// Теперь клипы ВЫНИМАЮТСЯ из модели в файлы рядом с ней, ровно как материалы
// вынимаются в .sagemat. Файл — обычный JSON, как и всё остальное в движке:
// сцена, материал, настройки импорта. Его видно в панели ассетов, на него можно
// сослаться, его можно положить в папку и отдать другому персонажу.
//
// КОСТИ АДРЕСУЮТСЯ ИМЕНАМИ, А НЕ НОМЕРАМИ. Это то же решение, что у целей
// обратной кинематики, и по той же причине: номер кости зависит от порядка в
// файле модели и молча меняется при переэкспорте, а «mixamorig:LeftFoot»
// переживает и переэкспорт, и перенос клипа на другой скелет с такими же
// именами. Номера ищутся один раз при привязке клипа к скелету (Bind).
//
// ЧЕГО ЗДЕСЬ НЕТ. Скелета: клип описывает ДВИЖЕНИЕ, а кости живут в модели.
// Класть скелет в каждый клип значило бы получить двадцать копий одного
// скелета в одной папке и вопрос «какая из них правильная» при первом же
// расхождении.
// ---------------------------------------------------------------------------
namespace sage::anim {

// Клип, каким он лежит на диске: каналы адресуют кости ИМЕНАМИ.
struct ClipAsset {
    std::string Name;       // имя клипа («Walk»), а не имя файла
    float Duration = 0.0f;

    struct Channel {
        std::string Joint;          // имя кости
        AnimPath Target = AnimPath::Translation;
        AnimInterp Interp = AnimInterp::Linear;
        std::vector<float> Times;
        std::vector<glm::vec4> Values;
    };
    std::vector<Channel> Channels;

    bool Empty() const { return Channels.empty(); }
};

// --- Файл -------------------------------------------------------------------

// Пишет .sageanim. Бросает std::runtime_error, если файл не открывается.
void SaveClip(const ClipAsset& clip, const std::string& path);

// Читает .sageanim. Бросает std::runtime_error на нечитаемом или непонятном
// файле — вызывающий решает, чем ответить (редактор показывает причину,
// ResourceManager логирует и отдаёт пусто).
ClipAsset LoadClip(const std::string& path);

// --- Перенос между «в модели» и «в файле» -----------------------------------

// Клип модели -> клип файла: номера костей заменяются их именами по скелету.
ClipAsset ToAsset(const AnimationClip& clip, const Skeleton& skeleton);

// Клип файла -> клип модели: имена костей ищутся в скелете. Каналы, для которых
// кости с таким именем нет, ОТБРАСЫВАЮТСЯ, а их число возвращается в
// outMissing — молча терять половину движения нельзя, об этом надо сказать.
AnimationClip Bind(const ClipAsset& asset, const Skeleton& skeleton, int* outMissing = nullptr);

// Имя файла для клипа рядом с моделью: <модель>.<клип>.sageanim. Имя клипа
// чистится от того, что не годится в имя файла, — клипы из чужих пакетов
// зовутся и «Armature|Walk», и «walk 01».
std::string ClipFileName(const std::string& modelFileStem, const std::string& clipName);

} // namespace sage::anim
