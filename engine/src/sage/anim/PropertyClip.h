#pragma once
#include <string>
#include <vector>

#include <glm/glm.hpp>

// ---------------------------------------------------------------------------
// КЛИП ПО СВОЙСТВАМ (.sageclip) — то, что делает инструмент анимации.
//
// ЧЕМ ОН ОТЛИЧАЕТСЯ ОТ .sageanim. Тот описывает движение СКЕЛЕТА: каналы
// адресуют кости, значения — это позиция, поворот и масштаб сустава, и приходит
// он из GLB/FBX вместе с моделью. Этот описывает движение ЧЕГО УГОДНО, что
// объявлено анимируемым (sage/anim/AnimProperty.h): положение элемента
// интерфейса, цвет подложки, прозрачность, масштаб объекта сцены. Смешивать их
// в одном формате нельзя: у скелетного клипа нет понятия «свойство части», а у
// этого — понятия «кость», и объединение дало бы файл, половина которого всегда
// пустая.
//
// ЧТО ТАКОЕ ДОРОЖКА. Одно свойство одного объекта во времени. Объект адресуется
// ПУТЁМ ОТ ВЛАДЕЛЬЦА КЛИПА («HP Bar/Icon»), а не номером: номер сущности живёт
// один запуск, а клип лежит в проекте годами. Пустой путь — сам владелец.
//
// ИНТЕРПОЛЯЦИЯ ЖИВЁТ У КЛЮЧА, а не у дорожки: в одной дорожке ступенька до
// середины и плавный разгон после — обычное дело (мигание, потом уезд), и
// заставлять ради этого заводить вторую дорожку значит заставлять держать
// синхронными два списка ключей.
//
// ПРОВЕРЯЕМОСТЬ. Здесь нет ни сцены, ни ECS, ни ImGui — только числа и время.
// «Ключ в 0.5 с безье даёт вот такое значение» — утверждение о числах, и
// проверять его надо числами (tests/test_propertyclip.cpp), а не глазами по
// экрану, на котором что-то шевелится.
// ---------------------------------------------------------------------------
namespace sage::anim {

// Как значение идёт ОТ этого ключа К следующему.
enum class Interp {
    // Держать до следующего ключа и переключиться скачком. Мигание, смена
    // кадра спрайта, включение-выключение — всё, у чего промежуточного
    // состояния не бывает.
    Constant,
    // Прямая. Честный ответ по умолчанию: предсказуемо и видно, что задано.
    Linear,
    // Кубическая Безье по касательным. Разгон и торможение — то, чем движение
    // отличается от «переезда из точки в точку».
    Bezier,
};

struct Key {
    float Time = 0.0f;
    glm::vec4 Value{0.0f};
    Interp Out = Interp::Linear;

    // Касательные В ДОЛЯХ ОТРЕЗКА между этим ключом и соседним: x — доля
    // времени, y — доля разности значений. Не в секундах и не в пикселях
    // намеренно: ключ можно двигать по времени и менять его значение, а форма
    // разгона остаётся той же — иначе каждый сдвиг ключа ломал бы настроенную
    // кривую, и настраивать её было бы бессмысленно.
    //
    // Это ровно те же четыре числа, что у «cubic-bezier» в вебе, и записаны
    // они так же: управляющая точка = ключ + касательная. Значения по
    // умолчанию (треть отрезка по обеим осям) дают ПРЯМУЮ — ключ, только что
    // переключённый в безье, не меняет движения, пока его не потянут.
    //
    // Одна пара чисел на все четыре компоненты намеренно: кривая описывает
    // ХАРАКТЕР движения («резко стартует, мягко тормозит»), и разные характеры
    // у x и y одного положения — это не анимация, а два разных движения,
    // которым место в двух дорожках.
    glm::vec2 InTangent{-1.0f / 3.0f, -1.0f / 3.0f};
    glm::vec2 OutTangent{1.0f / 3.0f, 1.0f / 3.0f};
};

struct Track {
    std::string Target;    // путь к объекту от владельца клипа; пусто — он сам
    std::string Property;  // ключ свойства (sage::anim::Properties())
    std::vector<Key> Keys; // отсортированы по времени
};

// Метка на линейке времени: «удар», «выстрел», «конец замаха». Сама по себе
// ничего не делает — по ней ставят ключи и её читает игра, когда ей надо
// поймать момент внутри движения, а не его конец.
struct Marker {
    float Time = 0.0f;
    std::string Name;
};

struct PropertyClip {
    std::string Name;
    float Duration = 1.0f;
    bool Loop = true;
    std::vector<Track> Tracks;
    std::vector<Marker> Markers;

    // ПРИШЁЛ ИЗ МОДЕЛИ — ЗНАЧИТ ТОЛЬКО ДЛЯ ЧТЕНИЯ.
    //
    // Клип, вынутый из GLB/FBX, — это копия чужих данных: он пересоздаётся при
    // каждом переимпорте модели, и правка в нём живёт до первого переимпорта.
    // Молча потерять работу хуже, чем не дать её начать, поэтому импортированный
    // клип редактор показывает, даёт проиграть и скопировать, но не даёт
    // править. Свой клип («Custom») правится как угодно.
    bool Imported = false;

    bool Empty() const { return Tracks.empty(); }
};

// --- Счёт --------------------------------------------------------------------

// Значение дорожки в момент t. Пустая дорожка — нули; время до первого ключа
// даёт первый ключ, после последнего — последний (клип не обязан начинаться в
// нуле и кончаться в Duration).
glm::vec4 Sample(const Track& track, float time);

// Куда попадает время по зацикленному клипу. Отдельной функцией, потому что
// «остаток от деления» неверен на границе: в конце незацикленного клипа надо
// остаться в конце, а не прыгнуть в начало.
float WrapTime(float time, float duration, bool loop);

// Ставит (или заменяет) ключ в дорожке и держит её отсортированной. Возвращает
// номер ключа. Два ключа в одно время — это не «оба», а «последний победил»:
// иначе порядок между ними зависел бы от того, в каком порядке их создавали.
int SetKey(Track& track, float time, const glm::vec4& value, Interp interp = Interp::Linear);

// Убирает ключ по номеру. Ложь — номера нет.
bool RemoveKey(Track& track, int index);

// --- Файл --------------------------------------------------------------------
//
// JSON, как всё остальное в движке. Отдельным файлом, а не внутри сцены: клип
// переиспользуют — один «мигание» на десяток кнопок, — и копия внутри каждой
// сцены означала бы десяток разъехавшихся копий.
std::string ToJsonString(const PropertyClip& clip);
bool FromJsonString(const std::string& text, PropertyClip& out, std::string& err);
bool SaveClipFile(const PropertyClip& clip, const std::string& path, std::string& err);
bool LoadClipFile(const std::string& path, PropertyClip& out, std::string& err);

} // namespace sage::anim
