#pragma once
#include <string>
#include <vector>

#include "sage/anim/Skeleton.h"

// ---------------------------------------------------------------------------
// Ретаргет — перенос анимации с одного скелета на другой.
//
// Зачем: библиотеки движений и анимации, купленные или снятые мокапом, сделаны
// НЕ под ваш скелет. Без ретаргета каждая анимация привязана к своей модели, и
// «дать этому персонажу ту ходьбу» означает переделать ходьбу.
//
// Как это работает здесь.
//
//   1. СООТВЕТСТВИЕ КОСТЕЙ строится по именам, приведённым к общему виду:
//      снимается префикс экспортёра ("mixamorig:Hips" -> "hips"), убираются
//      разделители и регистр. Совпадение по именам — не эвристика ради
//      эвристики: экспортёры сохраняют имена, и это единственное, что переживает
//      смену программы. Соответствие можно и задать руками.
//
//   2. ПОВОРОТЫ переносятся ОТНОСИТЕЛЬНО БИНД-ПОЗЫ, а не напрямую. Прямой
//      перенос локального поворота верен только если у скелетов совпадает
//      ориентация суставов, а она не совпадает почти никогда: у одного «вперёд»
//      это +Z кости, у другого +Y. Поэтому берётся отклонение от бинд-позы
//      источника и прикладывается к бинд-позе цели:
//
//          R_target = B_target * (B_source⁻¹ * R_source)
//
//      Разница бинд-поз таким образом сокращается, и «согнуть локоть на 40°»
//      остаётся «согнуть локоть на 40°» независимо от того, как экспортёр
//      сориентировал кость.
//
//   3. ДЛИНЫ КОСТЕЙ НЕ ПЕРЕНОСЯТСЯ. Перенос кости — это, по сути, длина кости,
//      и она принадлежит ЦЕЛЕВОМУ скелету: иначе персонаж превратился бы в
//      того, с кого сняли движение. Исключение — корень: он несёт перемещение
//      персонажа в пространстве, и его перенос масштабируется отношением роста
//      скелетов, иначе низкий персонаж шагал бы шагами высокого.
//
// ЧЕСТНОЕ ОГРАНИЧЕНИЕ. Это ретаргет на уровне поз, а не полноценная система с
// IK: если у скелетов сильно разные пропорции, ступни могут проскальзывать по
// полу, а руки — не сходиться в точке. Лечится IK-доводкой поверх результата
// (см. ROADMAP), которой в движке пока нет.
// ---------------------------------------------------------------------------
namespace sage::anim {

// Соответствие костей: индекс кости источника -> индекс кости цели (-1 — нет пары).
struct BoneMap {
    std::vector<int> SourceToTarget;

    int Mapped() const {
        int n = 0;
        for (int t : SourceToTarget) {
            if (t >= 0) ++n;
        }
        return n;
    }
    bool Empty() const { return Mapped() == 0; }
};

// Приведение имени кости к сравнимому виду: нижний регистр, без префикса
// экспортёра до ':' или '|', без разделителей ('_', '-', пробелов, точек).
// Открыто наружу, потому что этим же правилом пользуются инструменты, когда
// показывают пользователю, почему кость не нашла пары.
std::string NormalizeBoneName(const std::string& name);

// Каноническое имя кости: нормализованное имя, у которого известные СИНОНИМЫ
// разных соглашений сведены к одному слову — clavicle/shoulder, thigh/upperleg/
// upleg, calf/lowerleg/leg, hips/pelvis/root.
//
// Зачем. Библиотеки анимаций и модели персонажей делают разные люди и по разным
// соглашениям: Unreal зовёт бедро thigh_l, Blender — UpperLeg.L, Mixamo —
// LeftUpLeg. Совпадение по буквам находит только руки, кисти и голову, и
// перенесённая анимация выходит без ног — что выглядит как «ретаргет сломан», а
// на деле просто никто не договаривался об именах. Таблица синонимов покрывает
// три самых ходовых соглашения; за её пределами по-прежнему нужен ручной BoneMap.
std::string CanonicalBoneName(const std::string& normalized);

// Строит соответствие по именам: сначала точное совпадение нормализованных
// имён, затем — по каноническим (синонимы). Точное имеет приоритет: если в
// целевом скелете есть кость ровно с тем же именем, синоним не должен её
// перебивать.
BoneMap MapByName(const Skeleton& source, const Skeleton& target);

// Переносит клип на целевой скелет. Каналы костей без пары отбрасываются —
// применять их некуда. Имя клипа сохраняется.
AnimationClip Retarget(const AnimationClip& clip, const Skeleton& source,
                       const Skeleton& target, const BoneMap& map);

// То же, но соответствие строится по именам автоматически.
AnimationClip Retarget(const AnimationClip& clip, const Skeleton& source, const Skeleton& target);

} // namespace sage::anim
