#pragma once
#include <string>
#include <vector>

#include <glm/glm.hpp>

#include "sage/anim/Skeleton.h"

// ---------------------------------------------------------------------------
// Обратная кинематика (IK) — «поставь кисть СЮДА», а движок сам считает,
// как для этого повернуть плечо и локоть.
//
// Прямая кинематика (то, что уже есть) идёт от корня к концу: повернул плечо —
// поехала вся рука. Для позы это неудобно ровно там, где важен КОНЕЦ цепочки:
// ступня должна стоять на полу, кисть — лежать на предмете, а не «примерно
// там». Без IK каждый такой ключ — это ручной подбор трёх углов, и при любом
// сдвиге персонажа его приходится подбирать заново.
//
// Здесь два солвера, потому что задачи разные:
//
//   • ДВУХЗВЕННЫЙ (SolveTwoBone) — рука и нога, то есть 95% случаев. Считается
//     аналитически, по теореме косинусов: угол в локте однозначно определяется
//     расстоянием до цели. Ни итераций, ни дрожания, ни зависимости от прошлого
//     кадра — при одном и том же входе всегда один и тот же ответ. Это важно
//     для анимации: при перемотке кадр обязан выглядеть одинаково, куда бы
//     головку ни привели.
//
//   • FABRIK (SolveChain) — цепочка любой длины: хвост, щупальце, позвоночник,
//     верёвка. Работает итерациями «протянуть к цели — вернуть к корню»,
//     сохраняя длины звеньев. Аналитического решения для длинной цепи нет.
//
// Оба солвера НЕ трогают скелет и не рисуют: они принимают текущие глобальные
// матрицы костей и возвращают локальные повороты. Их результат кладётся в тот
// же слой JointPose, что и ручная поза (Animator::SetPoseOverride), поэтому IK
// складывается с клипом и с ручной правкой по тем же правилам.
// ---------------------------------------------------------------------------
namespace sage::anim {

// Цепочка костей для двухзвенного солвера: плечо -> локоть -> кисть.
// Индексы — в скелете; кости должны идти по родительской цепочке подряд.
struct TwoBoneChain {
    int Root = -1;   // плечо / бедро
    int Middle = -1; // локоть / колено
    int End = -1;    // кисть / ступня

    bool Valid() const { return Root >= 0 && Middle >= 0 && End >= 0; }
};

// Результат работы солвера: локальные повороты, которые надо положить в позу.
// Возвращаются именно ЛОКАЛЬНЫЕ повороты, а не глобальные матрицы: движок
// хранит позу в локальных TRS, и перевод обратно — часть работы солвера, а не
// вызывающего.
struct IKResult {
    bool Solved = false;
    std::vector<int> Joints;         // каких костей касается
    std::vector<glm::quat> Rotations; // и какой локальный поворот им ставить

    // Дотянулись ли до цели. false — цель дальше вытянутой цепочки: поза
    // максимально вытянута в её сторону, но кончик до неё не достаёт. Это НЕ
    // ошибка, а нормальный ответ, который вызывающий может показать аниматору.
    bool Reached = false;
};

// Двухзвенный солвер.
//
//   globals    — текущие глобальные матрицы костей (Animator::GlobalMatrices),
//                в пространстве МОДЕЛИ;
//   target     — куда поставить конец цепочки, в пространстве модели;
//   poleTarget — куда «смотрит» колено/локоть. Без него у задачи бесконечно
//                много решений (цепочка может вращаться вокруг оси корень-цель),
//                и колено выгибалось бы в произвольную сторону. Если задан
//                nullptr, плоскость сохраняется от ТЕКУЩЕЙ позы — обычно это
//                и есть то, чего ждёт аниматор.
IKResult SolveTwoBone(const Skeleton& skeleton, const std::vector<glm::mat4>& globals,
                      const TwoBoneChain& chain, const glm::vec3& target,
                      const glm::vec3* poleTarget = nullptr);

// FABRIK для цепочки произвольной длины (от корня к концу, кости идут подряд
// по родительской связи). iterations — сколько проходов «туда-обратно»;
// tolerance — на каком расстоянии до цели считать задачу решённой.
IKResult SolveChain(const Skeleton& skeleton, const std::vector<glm::mat4>& globals,
                    const std::vector<int>& chain, const glm::vec3& target,
                    int iterations = 10, float tolerance = 1e-3f);

// Кладёт результат солвера в набор переопределений позы (см. JointPose).
// Отдельная функция, а не часть солвера: результат бывает нужно посмотреть,
// смешать с весом или отбросить, не трогая позу.
void ApplyIK(const IKResult& result, std::vector<JointPose>& pose, int skeletonSize,
             float weight = 1.0f);

// Собирает цепочку от кости end вверх по родителям на length костей.
// Пустой вектор — цепочка не набралась (кость слишком близко к корню).
std::vector<int> ChainFromEnd(const Skeleton& skeleton, int end, int length);

} // namespace sage::anim
