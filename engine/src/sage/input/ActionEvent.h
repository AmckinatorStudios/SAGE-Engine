#pragma once
#include <string>

#include <glm/glm.hpp>

#include "sage/input/Action.h"

// ---------------------------------------------------------------------------
// СОБЫТИЕ ДЕЙСТВИЯ (§11 ТЗ) — то, что игра слышит вместо «нажали пробел».
//
//     пробел нажат  ->  раскладка  ->  действие «Прыжок»  ->  ActionEvent
//
// Это верхняя ступень лестницы ввода и единственная, до которой должна
// доходить игровая логика. Сообщение содержит ИМЯ действия и его значение —
// ни клавиши, ни устройства в нём нет, поэтому обработчик прыжка одинаково
// работает от клавиатуры, геймпада и заново назначенной игроком кнопки.
//
// Отдельный тип, а не строка на именной шине, потому что подписчику нужны
// фаза и значение: «Движение» шлёт вектор, «Прыжок» — факт, и разбирать это
// из строки каждому подписчику заново было бы работой без причины. Для тех,
// кто говорит данными (Lua, связи в инспекторе), InputSystem ДОПОЛНИТЕЛЬНО
// шлёт именное событие "input.<Действие>" — см. InputSystem::SetEventBus.
// ---------------------------------------------------------------------------
namespace sage::input {

struct ActionEvent {
    std::string Action;
    std::string Context;  // из какого контекста пришло (§8): «Игра», «Меню»...
    Phase State = Phase::Released;
    // Сработало по выбранному режиму (Press/Release/Hold/Tap). Отдельно от
    // фазы: у действия «удержать E» фаза всё время Held, а сработать оно
    // обязано ровно один раз.
    bool Triggered = false;
    float Value = 0.0f;
    glm::vec2 Vector{0.0f};
};

} // namespace sage::input
