#pragma once
#include <glm/glm.hpp>

// ---------------------------------------------------------------------------
// ОТНОСИТЕЛЬНОЕ ДВИЖЕНИЕ МЫШИ ИЗ ПОЛОЖЕНИЙ КУРСОРА.
//
// Оконная система сообщает ПОЛОЖЕНИЕ курсора, а обзору нужно СМЕЩЕНИЕ. В
// захвате (GLFW_CURSOR_DISABLED) положение виртуальное и без границ, так что
// смещение — просто разница двух соседних положений. Ломается это ровно в тех
// местах, где разница соседних положений движением не является: курсор только
// что захватили или отпустили (система прячет его и переносит), окно получило
// или потеряло фокус, курсор вошёл в окно с другого края. Там отсчёт
// начинается заново — и ТОЛЬКО там.
//
// Почему отдельно и с SetCaptured, а не «Rebase при каждом вызове захвата»:
// захват просят каждый кадр (редактор в Play, скрипт игры в Update). Раньше
// каждый такой вызов начинал отсчёт заново, и первое движение мыши каждого
// кадра выбрасывалось — обзор «недокручивался» и дёргался ровно на быстрых
// поворотах. Смена состояния — событие, повтор того же состояния — нет.
// Проверяется без окна (tests/test_input.cpp).
// ---------------------------------------------------------------------------
namespace sage::input {

class CursorMotion {
public:
    // Новое положение (координаты окна, Y вниз) -> смещение в конвенции движка
    // (Y вверх). Первое положение после сброса — только точка отсчёта.
    glm::vec2 Feed(const glm::vec2& pos) {
        glm::vec2 delta(0.0f);
        if (!m_fresh) delta = glm::vec2(pos.x - m_last.x, m_last.y - pos.y);
        m_fresh = false;
        m_last = pos;
        return delta;
    }
    // Разница со следующим положением — не движение (вход в окно, фокус).
    void Rebase() { m_fresh = true; }
    // Захват включён или выключен. Отсчёт заново только при СМЕНЕ.
    void SetCaptured(bool captured) {
        if (captured == m_captured) return;
        m_captured = captured;
        m_fresh = true;
    }
    const glm::vec2& Last() const { return m_last; }

private:
    glm::vec2 m_last{0.0f};
    bool m_fresh = true;
    bool m_captured = false;
};

} // namespace sage::input
