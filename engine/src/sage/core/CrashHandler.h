#pragma once
#include <functional>
#include <string>

// ---------------------------------------------------------------------------
// Обработчик аварийного завершения.
//
// ЗАЧЕМ. До этого падение выглядело так: окно исчезло. Ни файла, ни строки, ни
// намёка, что вообще произошло, — а вместе с окном исчезала и несохранённая
// сцена. Для редактора это худший из отказов: пользователь теряет работу и не
// может даже сообщить, на чём именно всё сломалось.
//
// Что делает обработчик, когда процесс уже падает:
//   1. пишет отчёт (что за сигнал, стек вызовов, версия, открытый проект и
//      последние строки лога) в файл рядом с проектом;
//   2. зовёт аварийное сохранение — редактор сбрасывает сцену на диск;
//   3. отдаёт управление системе, чтобы падение осталось падением и его увидел
//      отладчик и системный сборщик отчётов.
//
// ЧТО МОЖНО ДЕЛАТЬ В ЭТОТ МОМЕНТ. Почти ничего. Обработчик сигнала работает в
// сломанном процессе: куча могла быть повреждена, блокировки — захвачены, и
// любой malloc способен повиснуть навсегда вместо того, чтобы упасть.
// Поэтому:
//   • буфер отчёта выделен ЗАРАНЕЕ и заполняется без выделений памяти;
//   • последние строки лога копятся в кольцевом буфере фиксированного размера;
//   • запись идёт низкоуровневым write(), а не потоками ввода-вывода;
//   • аварийное сохранение — единственное, что делает выделения, и оно
//     осознанный риск: потерять сцену хуже, чем не дописать отчёт.
//
// Второй сигнал во время обработки первого не приведёт к бесконечной рекурсии:
// обработчик снимает себя первой же строкой.
// ---------------------------------------------------------------------------
namespace sage {

class CrashHandler {
public:
    // Куда писать отчёты и что делать перед смертью. saveHandler зовётся уже
    // после записи отчёта; пустой — ничего не сохранять.
    struct Config {
        std::string ReportDir = ".";        // каталог для sage-crash-*.txt
        std::string AppName = "SAGE";
        std::string Version;
        // Аварийное сохранение. Возвращает путь сохранённого файла (или пусто).
        // Держать коротким: процесс уже сломан, времени на всё нет.
        std::function<std::string()> EmergencySave;
        // Дополнительный контекст в отчёт (открытый проект, сцена, видеокарта).
        std::function<std::string()> Context;
    };

    static void Install(const Config& config);
    // Снять обработчики (тесты, выгрузка плагина). Идемпотентно.
    static void Uninstall();
    static bool Installed();

    // Кольцевой буфер последних сообщений — то, что попадёт в отчёт. Заполняется
    // из Log; отдельно от самого лога потому, что лог может писать в файл,
    // который в момент падения уже недоступен.
    static void Note(const std::string& line);

    // Собрать текст отчёта, как если бы упали сейчас. Нужно тестам: проверять
    // обработчик настоящим падением нельзя, а проверять содержимое — можно.
    static std::string BuildReport(const std::string& reason);

    // Путь последнего записанного отчёта (пусто, если не падали).
    static const std::string& LastReportPath();
};

} // namespace sage
