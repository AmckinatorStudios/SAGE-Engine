#include <vector>

// ---------------------------------------------------------------------------
// Профилировщик кадра: сколько времени занял каждый проход на CPU и на GPU.
//
// ЗАЧЕМ. Без него оптимизировать нечего: «стало медленно» не отвечает на
// вопрос «где». Хуже того, интуиция здесь систематически ошибается — тяжёлым
// кажется то, что заметно в коде, а стоит обычно то, что незаметно (лишний
// проход по сцене, пересборка буфера, ожидание видеокарты).
//
// ДВЕ ШКАЛЫ, И ИХ НЕЛЬЗЯ ПУТАТЬ. Время CPU — сколько мы потратили, СОБИРАЯ
// команды. Время GPU — сколько видеокарта их выполняла. Они идут параллельно:
// CPU уже строит следующий кадр, пока GPU рисует предыдущий. Поэтому сумма
// частей не обязана равняться времени кадра, а узкое место — это МАКСИМУМ из
// двух, а не сумма.
//
// ПОЧЕМУ РЕЗУЛЬТАТ ЗАПАЗДЫВАЕТ. Метки времени GPU читаются через несколько
// кадров. Спросить их сразу — значит дождаться, пока видеокарта закончит, то
// есть своим измерением создать ту самую задержку, которую измеряешь. Поэтому
// цифры GPU относятся к кадру двух-трёхлетней давности по меркам кадра; для
// поиска узкого места этого достаточно, для «мгновенного отклика» — нет, и
// притворяться иначе было бы враньём.
//
// Использование:
//     void RenderFrame() {
//         sage::profile::BeginFrame();
//         { SAGE_PROFILE("Тени");  DrawShadows(); }
//         { SAGE_PROFILE("Сцена"); DrawScene(); }
//         sage::profile::EndFrame();
//     }
// ---------------------------------------------------------------------------
namespace sage::profile {

struct Entry {
    std::string Name;
    int Depth = 0;       // вложенность: проход внутри прохода
    double CpuMs = 0.0;
    double GpuMs = 0.0;  // 0, если бэкенд не умеет таймеров
    int Calls = 0;
};

// Профилирование выключено по умолчанию: метки времени GPU не бесплатны, и
// платить за них в игре у игрока незачем.
void SetEnabled(bool enabled);
bool Enabled();

void BeginFrame();
void EndFrame();

// Открыть/закрыть именованный участок. Обычно через SAGE_PROFILE.
void Push(const char* name);
void Pop();

// Результаты последнего кадра, у которого созрели метки GPU. Порядок — тот,
// в котором участки открывались; Depth задаёт вложенность.
const std::vector<Entry>& Frame();
// Сглаженные по последним кадрам значения — по ним и смотрят, потому что
// покадровые скачут на десятки процентов от планировщика ОС.
const std::vector<Entry>& Average();

double FrameCpuMs();
double FrameGpuMs();
bool GpuTimersAvailable();

// Строка для отладочного оверлея/строки состояния.
std::string Summary();

class Scope {
public:
    explicit Scope(const char* name) { Push(name); }
    ~Scope() { Pop(); }
    Scope(const Scope&) = delete;
    Scope& operator=(const Scope&) = delete;
};

} // namespace sage::profile

#define SAGE_PROFILE_CONCAT_(a, b) a##b
#define SAGE_PROFILE_CONCAT(a, b) SAGE_PROFILE_CONCAT_(a, b)
#define SAGE_PROFILE(name) sage::profile::Scope SAGE_PROFILE_CONCAT(_sageProfile, __LINE__)(name)
