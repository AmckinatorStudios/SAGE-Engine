#pragma once
#include <array>
#include <cstddef>

// ---------------------------------------------------------------------------
// СКЛЕЙКА ДЛИННЫХ ЛИТЕРАЛОВ ПРИ КОМПИЛЯЦИИ.
//
// Длинный встроенный текст (общий GLSL-блок PBR, прелюдия SAGE Lua) удобнее
// держать частями по смыслу, в разных файлах, — но наружу он обязан выходить
// ОДНОЙ строкой, ровно той же, что была одним литералом. Склейка здесь
// происходит при компиляции: готовая строка существует до любого
// статического инициализатора, и разбиение текста на части ничего не меняет
// в поведении.
// ---------------------------------------------------------------------------
namespace sage::text {

template <size_t A, size_t B>
constexpr std::array<char, A + B - 1> Concat(const char (&a)[A], const char (&b)[B]) {
    std::array<char, A + B - 1> out{};
    for (size_t i = 0; i + 1 < A; ++i) out[i] = a[i];
    for (size_t i = 0; i < B; ++i) out[A - 1 + i] = b[i];
    return out;
}

} // namespace sage::text
