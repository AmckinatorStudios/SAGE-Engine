// ---------------------------------------------------------------------------
// БЕЗОПАСНАЯ ЗАПИСЬ ФАЙЛА: сначала во временный рядом, затем подмена.
//
// Оборвавшаяся запись (нет места, упал редактор) оставляет ПРЕЖНИЙ файл целым,
// а не наполовину записанный JSON, который потом не откроется вовсе. Путь —
// UTF-8 (кириллические папки Windows).
//
// Временный файл — уникальное имя рядом с целью (тот же том, иначе подмена не
// атомарна), данные сбрасываются на диск до подмены. Подмена: rename(2) на
// POSIX, MoveFileExW(REPLACE_EXISTING | WRITE_THROUGH) на Windows; прежний файл
// до успешной подмены не удаляется. При любой ошибке — false, причина в err,
// временный файл убран, цель не тронута.
// ---------------------------------------------------------------------------
namespace sage {

bool WriteFileAtomic(const std::string& utf8Path, const std::string& bytes, std::string& err);

} // namespace sage
