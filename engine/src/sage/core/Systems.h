#pragma once
#include <string>
#include <vector>

// ---------------------------------------------------------------------------
// Версии подсистем движка. Отдельно от версии движка ЦЕЛИКОМ (файл VERSION /
// sage/core/Version.h): движок как продукт релизится своим темпом, а каждая
// подсистема несёт СВОЮ мажорную версию — контракт её API/поведения. Пока все
// подсистемы на v1 (первая стабильная ревизия); когда контракт конкретной
// подсистемы сломается несовместимо, её Major поднимут независимо от прочих.
//
// Список — единый источник правды: логируется на старте движка и показывается
// в редакторе (Help > About SAGE). Добавил подсистему — добавь строку сюда.
// ---------------------------------------------------------------------------
namespace sage {

struct SystemVersion {
    const char* Name;     // человекочитаемое имя подсистемы
    int Major;            // мажорная версия подсистемы (ломающие изменения)
    const char* Summary;  // что делает подсистема (одной строкой)

    std::string Tag() const { return "v" + std::to_string(Major); } // "v1"
};

// Полный список подсистем движка с версиями (детерминированный порядок).
const std::vector<SystemVersion>& EngineSystems();

// Пишет в лог сводку: версия движка + все подсистемы с их версиями. Зовётся
// один раз при старте (Application), чтобы состав/версии были в логах любой сборки.
void LogEngineSystems();

} // namespace sage
