#pragma once
#include <filesystem>
#include <string>
#include <string_view>
#include <vector>

// ---------------------------------------------------------------------------
// Где лежит сама программа и как найти рядом с ней ресурсы движка.
//
// Нужно это ровно из-за одной ошибки, которая ломала SAGE Player: шейдеры
// рантайма грузились по ОТНОСИТЕЛЬНОМУ пути ("assets/shaders/lit.vert"), то
// есть от ТЕКУЩЕЙ ПАПКИ. Пока плеер запускали из его собственной папки, это
// работало; стоило запустить его откуда-то ещё —
//
//     cd ~/MyGame && /opt/sage/SagePlayer .
//
// — как он падал с «Фатальная ошибка: не удалось открыть файл шейдера», хотя
// шейдеры были на месте, рядом с бинарником. Текущая папка — это то, откуда
// человек ЗАПУСКАЕТ, а не то, куда программа УСТАНОВЛЕНА, и путать одно с
// другим нельзя: игру нормально запускают ярлыком, из другой папки, из
// скрипта. Тем более что плеер сам меняет CWD на папку проекта — после этого
// любой относительный путь к его собственным ресурсам заведомо мимо.
// ---------------------------------------------------------------------------
namespace sage {

// Папка, в которой лежит запущенный бинарник. Пустой путь — если ОС не дала
// ответа (тогда вызывающий откатывается к прежнему поведению «от CWD»).
std::filesystem::path ExecutableDir();

// ---------------------------------------------------------------------------
// КОДИРОВКА ПУТЕЙ. Почему без этих трёх функций редактор не запускался.
//
// Внутри программы путь — это std::string в UTF-8: так его отдаёт
// std::filesystem::path::string(), так он лежит в сценах и настройках, так его
// рисует ImGui. Но СИСТЕМА на Windows разговаривает с программой не в UTF-8:
// getenv, argv и прочие «узкие» API отдают байты в ANSI-кодировке (на русской
// системе — CP1251). Для «C:\Users\Владимир» это байты, которые не являются
// корректным UTF-8 вообще.
//
// А std::filesystem::path на mingw именно UTF-8 из узкой строки и ждёт: увидев
// такие байты, конструктор БРОСАЕТ filesystem_error «Cannot convert character
// sequence: Illegal byte sequence». Не вернёт пустой путь, не испортит имя —
// свалит программу. Ровно это и происходило: редактор на русской Windows
// умирал на строке
//
//     if (const char* appdata = std::getenv("APPDATA")) base = appdata;
//
// ещё до создания окна, то есть у всех, у кого имя пользователя написано
// кириллицей. Один getenv — и программа не запускается.
//
// Поэтому: у системы спрашиваем ШИРОКУЮ строку (_wgetenv), а узкую не трогаем
// вовсе; а там, где строка уже пришла откуда-то ещё, преобразуем её сами и
// НИКОГДА не бросаем. Путь, записанный со странностями, — это повод показать
// его криво, но не повод не запуститься.
// ---------------------------------------------------------------------------

// Значение переменной окружения как путь. Пустой путь — переменной нет или она
// пуста. На Windows читается через _wgetenv, минуя ANSI: имя пользователя
// кириллицей больше не ломает ничего.
std::filesystem::path EnvPath(const char* name);

// Значение переменной окружения как строка UTF-8 (пусто, если переменной нет).
// Для случаев, где значение — не путь, но может содержать не-ASCII.
std::string EnvString(const char* name);

// Путь -> UTF-8. Не бросает никогда: при беде отдаёт что смог.
std::string PathToUtf8(const std::filesystem::path& p);

// UTF-8 -> путь. Не бросает никогда: если байты не UTF-8, пробует ANSI, а затем
// подставляет замену вместо неразбираемого символа.
std::filesystem::path PathFromUtf8(std::string_view utf8);

// Байты, пришедшие от системного «узкого» API (ANSI на Windows) -> UTF-8.
std::string SystemToUtf8(const char* bytes);

// Ресурс движка, поставляемый рядом с программой: <папка exe>/<relative>.
// Если такого файла там нет, возвращается relative как есть — чтобы сборки,
// разложенные иначе (и запуск из папки сборки), продолжали работать.
std::string EngineAssetPath(const std::string& relative);

// ---------------------------------------------------------------------------
// Папки пользователя: «Документы», «Загрузки», «Рабочий стол» и прочее.
//
// В движке потому, что Файловый диалог редактора свой, на ImGui (системный тянет
// по реализации на платформу и не открывается в headless-прогоне), и «быстрый
// доступ» ему приходится собирать самому. Собирать его в редакторе значило бы
// написать разбор XDG и переменных Windows в панели интерфейса — не то место.
//
// ГДЕ ЭТИ ПАПКИ НА САМОМ ДЕЛЕ. Ни на одной системе они не «домашняя папка плюс
// английское имя». На Linux их имена локализованы и лежат в
// ~/.config/user-dirs.dirs (XDG_DOWNLOAD_DIR="$HOME/Загрузки"), на Windows их
// можно перенести на другой диск. Поэтому: сначала спрашиваем систему, и только
// если она не ответила — берём привычное имя, и то лишь если такая папка
// действительно существует. Выдуманный путь хуже отсутствующей кнопки: по нему
// диалог открывает пустоту.
// ---------------------------------------------------------------------------
struct UserFolder {
    const char* Label;                 // подпись для интерфейса
    std::filesystem::path Path;
};

// Домашняя папка пользователя. Пусто, если система не сказала.
std::filesystem::path HomeDir();

// Существующие папки пользователя в порядке, удобном для списка: дом, рабочий
// стол, документы, загрузки, изображения, музыка, видео. Несуществующие
// пропускаются — кнопка, ведущая в никуда, бесполезна.
std::vector<UserFolder> UserFolders();

// Куда по умолчанию класть НОВЫЕ проекты: <Документы>/SAGE Projects, а если
// документов нет — <дом>/SAGE Projects, а если и дома нет — текущая папка.
//
// Не рядом с бинарником: редактор запускают из папки со сборкой, из ярлыка, из
// распакованного архива — и проект, созданный «здесь», оказывается внутри
// установки движка, где его никто потом не найдёт и где его снесёт следующая
// распаковка.
std::filesystem::path DefaultProjectsDir();

} // namespace sage
