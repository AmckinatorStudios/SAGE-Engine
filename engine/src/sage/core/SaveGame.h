#pragma once
#include <cstdint>
#include <string>
#include <vector>

// ---------------------------------------------------------------------------
// Сохранения игры — ПРОГРЕСС ИГРОКА, а не сцена.
//
// ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ SceneSerializer. Сцена — редакторный формат: что за
// объекты в уровне, где они стоят, какие у них компоненты. Это ИСХОДНИК, он
// лежит рядом с игрой и одинаков у всех игроков. Прогресс — противоположное:
// он принадлежит одному человеку, меняется каждую минуту игры и не имеет
// ничего общего с расстановкой объектов в редакторе. Сохранять прогресс
// сериализацией сцены — значит записывать в файл игрока всю геометрию уровня и
// при загрузке подменять ему уровень на тот, что был при сохранении: любая
// правка игры перестаёт доходить до тех, кто уже начал играть.
//
// ГДЕ ЛЕЖИТ. В пользовательском каталоге данных, а НЕ рядом с игрой. Папка
// установки бывает доступна только на чтение (Program Files, /usr, каталог
// Steam), и запись туда либо молча не проходит, либо требует прав, которых у
// игры нет. Linux: $XDG_DATA_HOME или ~/.local/share; Windows: %APPDATA%.
//
// КАК ПИШЕТСЯ. Во временный файл, fsync, затем переименование поверх старого.
// Переименование в пределах одного тома атомарно, и это единственный способ
// пережить падение или выключение питания посреди записи: иначе игрок теряет
// не текущее сохранение, а ВСЁ — файл остаётся обрезанным на середине, и
// прошлого уже нет. Самый обидный вид потери данных из всех.
//
// ВЕРСИЯ. У каждого сохранения свой номер формата — та же дисциплина, что у
// сцен. Игра меняет структуру прогресса чаще, чем формат уровней, и без номера
// первое же изменение молча испортило бы чужие сохранения.
//
// ---------------------------------------------------------------------------
//  ФОРМАТ ФАЙЛА: ЗАГОЛОВОК ОТДЕЛЬНО ОТ ПРОГРЕССА
// ---------------------------------------------------------------------------
//
// Раньше слот был одним JSON-объектом: {"sage_save_version", "savedAt", "data"}.
// Читалось это ровно один раз — целиком, — и три беды из этого следовали сразу.
//
// 1. МЕНЮ «ПРОДОЛЖИТЬ» РАЗБИРАЛО ВСЕ СОХРАНЕНИЯ ЦЕЛИКОМ. Чтобы показать строчку
//    «Слот 3, вчера», Slots() парсил весь файл — включая мегабайты инвентаря и
//    карты мира, — и выбрасывал результат. Восемь слотов по пять мегабайт
//    означали сорок мегабайт разбора на открытие меню, каждый раз.
// 2. ФАЙЛ БЫЛ ВТРОЕ БОЛЬШЕ НУЖНОГО. Текст писался с отступами (dump(2)), а
//    прогресс — это тысячи коротких чисел и повторяющихся ключей, то есть
//    ровно то, что deflate жмёт в пять-десять раз.
// 3. ПРЕДЫДУЩЕЕ СОХРАНЕНИЕ ИСЧЕЗАЛО. Переименование поверх атомарно, но старое
//    оно всё равно стирает: игра, сохранившаяся в сломанное состояние, уносила
//    с собой единственную рабочую копию.
//
// Формат теперь такой:
//
//   "SAGESAVE" u32:формат u32:флаги u32:длина заголовка u64:контрольная сумма
//   [заголовок — JSON: версия игры, время, МЕТКА слота]
//   [прогресс — JSON, сжатый deflate или как есть]
//
// Заголовок лежит ПЕРВЫМ и читается отдельно: меню открывается, прочитав по
// сотне байт на слот вместо мегабайтов. Метка слота (глава, время игры, имя
// героя, путь к скриншоту) кладётся туда же — её показывают, не трогая сам
// прогресс. Контрольная сумма ловит испорченный файл до разбора: «сохранение
// повреждено» честнее, чем прогресс с половиной значений.
//
// Старый формат (голый JSON) читается по-прежнему: у игроков уже есть такие
// файлы, и первое же обновление игры не имеет права их потерять.
// ---------------------------------------------------------------------------
namespace sage::save {

// Что известно о слоте, не читая прогресс. Список сохранений в меню строится по
// этому — и теперь буквально: заголовок отделён от данных, и Slots() читает
// только его.
struct SlotInfo {
    std::string Name;           // имя слота (оно же имя файла без расширения)
    long long SavedAtUnix = 0;  // когда записан
    int Version = 0;            // версия формата, которую записала игра
    size_t Bytes = 0;           // размер файла на диске
    bool Compressed = false;
    // Метка слота, как её записала игра: JSON-объект строкой ("{}" — пусто).
    // Глава, время игры, имя героя, путь к скриншоту — всё, что показывают в
    // меню. Здесь, а не в прогрессе: меню не должно грузить прогресс.
    std::string Meta = "{}";
    // Файл есть, но прочитать его не вышло. Такой слот всё равно показывают:
    // игрок должен видеть, что он есть, и иметь возможность его удалить.
    bool Broken = false;
};

// Что кладём при записи сверх самого прогресса.
struct WriteOptions {
    int Version = 1;
    // Метка слота — JSON-объект строкой. Пусто означает «метки нет».
    std::string MetaJson;
    // Сжимать прогресс. Включено: сохранение — это тысячи коротких чисел и
    // повторяющихся ключей, и deflate жмёт их в разы. Выключают его при
    // отладке, когда файл хотят открыть глазами.
    bool Compress = true;
    // Держать предыдущее сохранение как <слот>.bak. Игра, сохранившаяся в
    // сломанное состояние, иначе уносит с собой единственную рабочую копию.
    bool KeepBackup = true;
};

// Имя игры определяет папку сохранений. Задаётся один раз при старте (рантайм
// берёт его из имени проекта). Пустое имя означает «sage-game» — работать
// будет, но соседние игры на движке сложат прогресс в одну папку.
void SetGameName(const std::string& name);
const std::string& GameName();

// Каталог сохранений (создаётся при первой записи).
std::string Directory();

// Пишет слот. Содержимое — готовый JSON-текст прогресса; движок добавляет к
// нему свой заголовок. false — не удалось (нет прав, нет места, прогресс не
// является корректным JSON); причина уходит в лог.
bool Write(const std::string& slot, const std::string& payloadJson, const WriteOptions& options);
// Короткая форма для тех, кому хватает версии.
bool Write(const std::string& slot, const std::string& payloadJson, int version = 1);

// Читает слот. Возвращает false, если слота нет или он битый; outVersion —
// версия, которую записала игра (ей решать, что с ней делать).
bool Read(const std::string& slot, std::string& outPayloadJson, int* outVersion = nullptr);

// Заголовок слота БЕЗ чтения прогресса. Ради строчки в меню читается сотня
// байт, а не весь файл.
bool ReadInfo(const std::string& slot, SlotInfo& out);

// Откатиться на резервную копию, которую оставила прошлая запись (см.
// WriteOptions::KeepBackup). false — копии нет. Нужен ровно в том случае, ради
// которого копия и заводилась: игра сохранилась в состояние, из которого не
// выбраться.
bool RestoreBackup(const std::string& slot);
bool HasBackup(const std::string& slot);

bool Exists(const std::string& slot);
bool Delete(const std::string& slot);

// Все слоты, новые первыми — ровно в том порядке, в каком их показывают в меню.
std::vector<SlotInfo> Slots();

} // namespace sage::save
