#pragma once
#include <glm/glm.hpp>

// ---------------------------------------------------------------------------
// RawInputSource — «сырой» ввод, который НЕ укладывается в именованные действия
// (см. InputMap): смещение мыши за кадр, колесо, положение курсора и сам захват
// курсора.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ИНТЕРФЕЙС. Действия (Jump/Break) — дискретные: нажато или нет,
// их ремапят, их читают через InputMap. Обзор от первого лица — не действие: это
// непрерывная величина, которой нужна дельта и захваченный курсор. Раньше эта
// половина ввода существовала только внутри InputSystem и до скриптов не
// доходила — из Lua нельзя было написать ни одного вида от первого лица.
//
// Интерфейс, а не прямая ссылка на InputSystem, потому что источников два и они
// разные: в собранной игре это GLFW-окно (InputSystem), а в Play-режиме
// редактора — панель Game под ImGui, где «захват» означает своё. ScriptEngine
// одинаково работает с обоими (см. ScriptEngine::BindRawInput).
// ---------------------------------------------------------------------------
namespace sage {

class RawInputSource {
public:
    virtual ~RawInputSource() = default;

    // Смещение мыши за текущий кадр, в пикселях. X — вправо, Y — ВВЕРХ
    // (конвенция движка, см. InputSystem::OnMouseMove): мир, а не экран.
    virtual glm::vec2 MouseDelta() const = 0;

    // Положение курсора в окне/панели, в пикселях от левого верхнего угла.
    virtual glm::vec2 MousePosition() const = 0;

    // Сдвиг колеса за кадр: отрицательный — «вверх/к началу списка»
    // (та же конвенция, что у ScrollUp/ScrollDown в InputBinding).
    virtual int ScrollDelta() const = 0;

    // Захват курсора для обзора от первого лица (спрятать и «приклеить»).
    virtual void SetMouseCaptured(bool captured) = 0;
    virtual bool MouseCaptured() const = 0;
};

} // namespace sage
