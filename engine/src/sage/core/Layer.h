#pragma once
#include <string>

namespace sage {

// ---------------------------------------------------------------------------
// Layer — единица логики, которую движок «водит» в главном цикле. Игра, оверлей
// отладки, панели редактора — всё это слои поверх одного и того же цикла
// Application. Движок не знает, ЧТО делает слой; он лишь вызывает его хуки в
// правильном порядке каждый кадр. Так достигается чёткое разделение: движок
// владеет окном/циклом/таймингом, а конкретное поведение живёт в слоях.
//
//   OnAttach  — один раз при добавлении слоя (GL-контекст уже готов): грузим
//               ресурсы, строим сцену, привязываем ввод.
//   OnDetach  — один раз при остановке (GL-контекст ещё жив): освобождаем
//               GPU-ресурсы, пока это безопасно.
//   OnUpdate  — каждый кадр: ввод, симуляция, игровая логика. dt в секундах.
//   OnRender  — каждый кадр после всех OnUpdate: проходы отрисовки.
//   OnImGui   — каждый кадр внутри ImGui-фрейма (если он активен): панели/оверлеи.
// ---------------------------------------------------------------------------
class Layer {
public:
    explicit Layer(std::string name = "Layer") : m_name(std::move(name)) {}
    virtual ~Layer() = default;

    virtual void OnAttach() {}
    virtual void OnDetach() {}
    virtual void OnUpdate(float /*dt*/) {}
    virtual void OnRender() {}
    virtual void OnImGui() {}

    const std::string& Name() const { return m_name; }

private:
    std::string m_name;
};

} // namespace sage
