#pragma once
#include <functional>
#include <string>
#include <vector>

#include <nlohmann/json.hpp>

// ---------------------------------------------------------------------------
// ВЕРСИЯ ФОРМАТА ФАЙЛА — ОДНО ПРАВИЛО НА ВСЕ ФАЙЛЫ ДВИЖКА.
//
// Версию писали почти все форматы, а ЧИТАЛИ — единицы: раскладка управления,
// клипы свойств, скелетные клипы, оглавление ассетов ставили «version: 1» и
// больше на неё не смотрели, у материала её не было вовсе. Это хуже, чем
// ничего: номер создаёт видимость, что о совместимости позаботились, а
// первое же ломающее изменение тихо испортило бы старые файлы, и файл из
// более новой версии движка читался бы наполовину, с потерей полей.
//
// Сцена прошла это первой (SceneMigrations.h); здесь её правила — для всех:
//   • нет номера — версия 1 (файлы до появления проверки обязаны читаться);
//   • файл НОВЕЕ движка — отказ с понятной причиной, а не половинчатое чтение;
//   • миграции — по шагу «из N в N+1» над JSON, а не над готовым объектом:
//     правка на уровне JSON не устаревает вместе со структурами кода;
//   • после чтения номер — текущий: повторный прогон ничего не меняет.
//
// Как добавить ломающее изменение формата: увеличить Current и дописать шаг
// {From = старая версия, Apply = как переложить JSON}. Удалять шаги нельзя —
// файл двухлетней давности обязан открыться.
// ---------------------------------------------------------------------------
namespace sage::format {

struct Step {
    int From = 1;   // шаг переводит From -> From + 1
    std::function<void(nlohmann::json&)> Apply;
};

struct Spec {
    const char* Key = "version";   // где в файле лежит номер
    int Current = 1;
    const char* What = "файл";       // для сообщений: «материал», «раскладка управления»
    std::vector<Step> Steps;
};

// Номер файла (нет номера — 1; не число — 0).
int VersionOf(const nlohmann::json& doc, const Spec& spec);

// Приводит документ к текущей версии. false + err — файл новее движка, номер
// испорчен или нет нужного шага миграции; документ тогда не тронут.
bool Upgrade(nlohmann::json& doc, const Spec& spec, std::string& err);

// Записать текущий номер (при сохранении).
void Stamp(nlohmann::json& doc, const Spec& spec);

} // namespace sage::format
