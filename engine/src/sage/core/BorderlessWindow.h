struct GLFWwindow;

// ---------------------------------------------------------------------------
// БЕЗРАМОЧНОЕ ОКНО ВО ВЕСЬ МОНИТОР — так, чтобы его можно было записывать.
//
// Окно, привязанное к монитору (glfwSetWindowMonitor с монитором), драйвер
// OpenGL на Windows считает ЭКСКЛЮЗИВНЫМ полноэкранным: пока оно в фокусе,
// кадр идёт на экран мимо композитора рабочего стола. «Захват окна» OBS,
// Discord и запись Windows в этот момент видят последний кадр до фокуса —
// запись замирает, стоит щёлкнуть по игре. Ровно монитор размером окно без
// рамки драйвер тоже повышает до эксклюзивного («оптимизация полноэкранного
// режима»).
//
// Поэтому безрамочный режим — ОБЫЧНОЕ окно без рамки, на строку выше монитора:
// размер не совпадает с экраном, и драйвер оставляет кадр композитору.
// Лишняя строка уходит за нижний край — её не видно. Панель задач Windows
// прячется сама (окно накрывает монитор целиком), а для верности окно
// помечается полноэкранным для неё (ITaskbarList2::MarkFullscreenWindow).
// ---------------------------------------------------------------------------
namespace sage::display {

struct WindowRect {
    int X = 0, Y = 0, Width = 0, Height = 0;
};

// Где и какого размера безрамочное окно для монитора (x, y, w, h).
WindowRect BorderlessRect(int monitorX, int monitorY, int monitorW, int monitorH);

// Сказать панели задач, что окно — полноэкранное (true) или обычное. Вне
// Windows ничего не делает.
void MarkFullscreenWindow(GLFWwindow* window, bool fullscreen);

} // namespace sage::display
