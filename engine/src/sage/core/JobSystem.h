#pragma once
#include <cstddef>
#include <functional>
#include <memory>
#include <vector>

namespace sage {

// ---------------------------------------------------------------------------
// JobSystem — многопоточный пул задач движка (единственный на процесс).
//
// Постоянный набор фоновых воркеров + вызывающий поток разбирают работу.
// Базовый примитив — ParallelFor: диапазон [0, count) режется на непересекающиеся
// подотрезки, каждый исполняется на своём потоке, вызов блокируется до конца.
// Тело обязано трогать ТОЛЬКО свой подотрезок [begin, end) — тогда гонок нет
// (разные потоки пишут в разные элементы; общие данные читаются только для
// чтения). Это то, чем безопасно распараллеливается «горячая» работа кадра:
// отсечение по фрустуму / подготовка батчей рендера (GL-вызовы при этом
// остаются на главном потоке — контекст один).
//
// Что СОЗНАТЕЛЬНО не идёт сюда: игровые Lua-скрипты (одна sol::state + они
// делают структурные правки ECS — spawn/destroy — из тела апдейта; параллельный
// заход в один lua_State и одновременные структурные изменения реестра — UB) и
// сама выдача GL-команд (контекст один). Физика Jolt распараллелена собственным
// пулом. Подробности — README, раздел «Модель многопоточности».
//
// Если пул не инициализирован явно (Application делает это на старте из
// EngineConfig), ParallelFor поднимает его лениво с авто-числом воркеров.
// При одном ядре / отключённом MT — честный последовательный фолбэк, поведение
// идентично однопоточному (детерминизм сохраняется: слияние результатов идёт
// в исходном порядке у вызывающего).
// ---------------------------------------------------------------------------
class JobSystem {
public:
    static JobSystem& Get();

    // workerThreads: 0 — авто (аппаратные потоки − 1, т.к. главный тоже считает);
    // >0 — точное число фоновых воркеров; отрицательное трактуется как 0.
    // Идемпотентно: повторный вызов с тем же числом — no-op; с другим —
    // корректно останавливает старые воркеры и поднимает новые.
    void Initialize(int workerThreads = 0);
    void Shutdown();

    // Рантайм-переключатель распараллеливания (EngineConfig.MultithreadedRender).
    // Выключенный — ParallelFor исполняется последовательно на вызывающем потоке.
    void SetEnabled(bool enabled) { m_enabled = enabled; }
    bool Enabled() const { return m_enabled; }

    int WorkerCount() const;              // фоновых воркеров (0 — только главный)
    int ThreadCount() const { return WorkerCount() + 1; } // эффективный параллелизм

    // Параллельный проход по [0, count). body(begin, end) вызывается для каждого
    // непересекающегося подотрезка. Блокирует до завершения всех. minPerThread —
    // минимум элементов на поток (мелкие диапазоны не дробятся: накладные расходы
    // синхронизации превысили бы выигрыш). Исключение из любого подотрезка
    // пробрасывается вызывающему после дожидания всех потоков (без утечек/
    // висячих ссылок на body).
    void ParallelFor(std::size_t count,
                     const std::function<void(std::size_t begin, std::size_t end)>& body,
                     std::size_t minPerThread = 256);

    // Разнородные независимые задачи: все запускаются на пуле (+ вызывающий),
    // вызов ждёт завершения всех. Для параллельных секций «одно И другое».
    void Dispatch(const std::vector<std::function<void()>>& tasks);

private:
    JobSystem() = default;
    ~JobSystem();
    JobSystem(const JobSystem&) = delete;
    JobSystem& operator=(const JobSystem&) = delete;

    struct Impl;
    std::unique_ptr<Impl> m_impl; // пул спрятан в .cpp (не тащим <thread> в заголовки)
    bool m_enabled = true;
};

} // namespace sage
