#pragma once
#include <cstdint>
#include <string>

// ---------------------------------------------------------------------------
// Звук как СВОЙСТВО ОБЪЕКТА СЦЕНЫ.
//
// ЗАЧЕМ ЭТОТ КОМПОНЕНТ ВООБЩЕ ПОЯВИЛСЯ. Звуковая подсистема в движке была
// полной: 2D и 3D, лупы, музыка, категории громкости, честный немой режим на
// машине без звуковой карты. Дотянуться до неё можно было ровно одним способом
// — из скрипта, вызовом с путём к файлу и координатами. То есть чтобы у двери
// был скрип, дверь обязана была обзавестись программистом.
//
// Между тем звук — такая же характеристика предмета, как его меш и его
// коллайдер: у водопада шум, у факела треск, у ящика стук при падении. Ставить
// это мышью в сцене и слышать при первом же Play — не удобство, а условие
// того, чтобы звуком вообще занимались: пока для каждого шороха нужен файл
// скрипта, звука в игре не будет.
//
// ЧТО ХРАНИТ КОМПОНЕНТ. Только состояние и ссылку на ресурс — ровно как
// договорено про компоненты. Никакого проигрывания здесь нет: им занимается
// система (sage/audio/AudioSystem.h), потому что проигрывание — это работа со
// звуковым устройством, общим на всю сцену.
//
// ПОЧЕМУ ОДИН КОМПОНЕНТ, А НЕ «ЗВУК ОТКРЫТИЯ» И «ЗВУК ЗАКРЫТИЯ». Компонент
// описывает ОДИН источник звука на объекте — то, что у него звучит само
// (шум водопада, гул лампы) или по команде. Набор реплик под разные события —
// это уже данные игры, и живут они в скрипте, который зовёт Play с нужным
// файлом. Заводить компонент на каждый звук значило бы, что у двери их три, у
// оружия семь, а у персонажа тридцать.
// ---------------------------------------------------------------------------

// Что делать системе с этим источником на ближайшем кадре. Команда, а не
// вызов: компонент не имеет доступа к звуковому устройству, а скрипт и
// редактор не должны знать, в каком порядке идут системы кадра.
enum class AudioRequest : int {
    None = 0,
    Play,     // начать заново (если уже играет — перезапустить)
    Stop,
};

// Микс-группа: раздельная громкость в настройках игрока. Значения совпадают с
// AudioEngine::Category — перечисление своё, чтобы компонент не тянул за собой
// заголовок звукового движка (его включают только система и рантайм).
enum class AudioCategory : int {
    Sfx = 0,
    Music = 1,
    Ambient = 2,
};

struct AudioSourceComponent {
    // --- Что звучит --------------------------------------------------------
    // Путь к файлу ОТНОСИТЕЛЬНО ПРОЕКТА (assets/audio/...): абсолютный путь
    // пережил бы ровно до первого переноса проекта на другую машину.
    // Форматы — те же, что понимает звуковой движок: WAV, MP3, FLAC.
    std::string Clip;

    // --- Как звучит --------------------------------------------------------
    float Volume = 1.0f;   // 0..1 внутри своей категории
    float Pitch = 1.0f;    // 1 — как в файле; меняет и высоту, и скорость
    bool Loop = false;     // зациклить (шум водопада) или сыграть один раз
    // Играть, как только сцена ожила (Play в редакторе, запуск игры). Для
    // постоянных звуков окружения это единственный разумный вариант; для
    // реплик по событию — выключается, и звук запускает скрипт.
    bool AutoPlay = true;

    // --- Где звучит --------------------------------------------------------
    // Позиционный звук идёт из точки объекта и затухает с расстоянием.
    // Выключенный слышен одинаково отовсюду — это музыка, голос за кадром,
    // звуки интерфейса.
    bool Spatial = true;
    float MinDistance = 1.0f;   // ближе — громкость уже не растёт
    float MaxDistance = 40.0f;  // дальше — не слышно
    float Rolloff = 1.0f;       // крутизна спада между ними
    AudioCategory Category = AudioCategory::Sfx;

    // --- Рантайм (НЕ сериализуется) ----------------------------------------
    // Дескриптор звучащего экземпляра у звукового движка. Ноль — не звучит.
    std::uint32_t Handle = 0;
    // Звучит ли ПРЯМО СЕЙЧАС. Отдельно от Handle, потому что одноразовый звук
    // доигрывает сам: дескриптор ещё жив, а звука уже нет.
    bool Playing = false;
    // Команда на ближайший кадр (см. AudioRequest).
    AudioRequest Request = AudioRequest::None;

    // Короткие помощники для скриптов и редактора: они ставят КОМАНДУ, а не
    // трогают устройство, поэтому их можно звать откуда угодно и когда угодно.
    void Play() { Request = AudioRequest::Play; }
    void Stop() { Request = AudioRequest::Stop; }
};
