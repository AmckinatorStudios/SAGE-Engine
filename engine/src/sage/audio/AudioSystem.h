// ---------------------------------------------------------------------------
// Система звуковых источников: связывает компоненты сцены (AudioSourceComponent)
// со звуковым устройством (AudioEngine).
//
// РАЗДЕЛЕНИЕ ТАКОЕ ЖЕ, КАК У ОСТАЛЬНЫХ СИСТЕМ: компонент хранит «что и как
// звучит», система знает «как это сделать» — где взять устройство, куда
// перенести источник за уехавшим объектом, когда освободить доигравший звук.
// Иначе компонент пришлось бы дать доступ к устройству, и первый же объект,
// созданный без сцены (превью ассета, тест), падал бы на его отсутствии.
//
// Порядок за кадр:
//   1. StartScene   — один раз, когда сцена ожила: запускает всё с AutoPlay;
//   2. Update       — каждый кадр: выполняет команды, тянет 3D-позиции за
//                     объектами, освобождает доигравшее;
//   3. StopScene    — один раз при остановке: глушит всё и отпускает ресурсы.
//
// БЕЗ ЗВУКОВОЙ КАРТЫ (сервер, CI, машина без устройства) всё это работает и
// ничего не ломает: движок в немом режиме отдаёт невалидные дескрипторы, а
// система честно оставляет Playing = false. Проверять «есть ли звук» перед
// каждой правкой сцены не нужно — иначе половина кода игры обросла бы такими
// проверками.
// ---------------------------------------------------------------------------

class Scene;
class AudioEngine;

namespace sage::audio {

// Запускает источники с AutoPlay. Зовётся на старте игры и на Play в редакторе.
// Повторный вызов ничего не портит: уже звучащий источник не перезапускается.
int StartScene(Scene& scene, AudioEngine& engine);

// Кадровое обслуживание: команды Play/Stop, перенос позиций, освобождение
// доигравших одноразовых звуков. Возвращает, сколько источников звучит.
int Update(Scene& scene, AudioEngine& engine);

// Глушит все источники сцены и отпускает дескрипторы. Зовётся при Stop в
// редакторе, смене сцены и выходе — иначе звук пережил бы объект, который его
// издавал, и остался бы играть в пустоте.
void StopScene(Scene& scene, AudioEngine& engine);

} // namespace sage::audio
