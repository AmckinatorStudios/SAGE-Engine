#pragma once
#include <string>
#include <vector>

class Scene;

// ---------------------------------------------------------------------------
// ГОТОВЫЕ ЭКРАНЫ ИНТЕРФЕЙСА — то, что человек собирается сделать первым делом.
//
// ЗАЧЕМ ОНИ В ДВИЖКЕ. Заготовки (UI.h) отвечают на вопрос «что такое кнопка».
// Оставшийся вопрос — «как из кнопок собирают ЭКРАН»: чем главное меню
// отличается от набора кнопок, положенных друг под другом, где живёт холст, что
// делает группа и зачем у списка маска. На него отвечает не документация, а
// работающий экран, который можно поставить в сцену и разобрать в инспекторе.
//
// Не файлы-сцены: Демо на диске устаревает молча: поля переименовали
// — сцена читается, но выглядит не так, и заметит это только тот, кто её
// откроет. Собранное кодом демо ломается на сборке движка и проверяется
// тестами: каждое из них ниже проверено без окна и без GL.
//
// ЧТО КАЖДОЕ ПОКАЗЫВАЕТ:
//   menu     — холст с опорным разрешением, вертикальная раскладка, кнопки с
//              ИМЕНАМИ ДЕЙСТВИЙ (игра спрашивает «нажали play», а не «нажали
//              сущность 37»), группа для плавного появления;
//   hud      — шкала со сглаживанием и значком, счётчик с авто-шириной,
//              растяжение по ширине экрана, порядок холстов (худ под меню);
//   settings — строки настроек: ползунок с шагом, галка, поле ввода, — и
//              раскладка, которая расставляет их сама.
// ---------------------------------------------------------------------------
namespace sage::ui {

// Имена демо-экранов: «menu», «hud», «settings». Имена, а не номера: их пишут
// в скриптах и в меню редактора.
const std::vector<std::string>& DemoNames();

// Ставит демо-экран в сцену и возвращает id его корня (-1 — имени нет).
//
// Корень — обычная сущность-контейнер: удалить экран целиком можно удалением
// одной сущности, а поставить два демо рядом — двумя вызовами.
int BuildDemo(Scene& scene, const std::string& name);

} // namespace sage::ui
