#pragma once
#include <memory>
#include <string>
#include <vector>

#include <entt/entt.hpp>

#include "sage/events/Events.h"
#include "sage/ui/UIFramework.h"
#include "sage/ui/render/UIEngineResources.h"

class Scene;
class Framebuffer;

// ---------------------------------------------------------------------------
// ИНТЕРФЕЙС В СЦЕНЕ.
//
// Документ интерфейса — самостоятельный ресурс (.uidoc), а не набор сущностей.
// Но игре надо как-то сказать «на этом уровне показывается вот этот интерфейс»,
// и место для такого высказывания — сцена.
//
// ПОЧЕМУ НЕ КАК РАНЬШЕ. Прежде интерфейс БЫЛ сущностями сцены: каждая надпись —
// объект в иерархии, рядом с камерой и светом. Из этого следовало всё плохое
// сразу: один и тот же худ нельзя было переиспользовать на двух уровнях, не
// скопировав его целиком; правка в одном месте не доезжала до второго; а
// «интерфейс» и «мир» жили в одном дереве, хотя это разные вещи с разными
// правилами.
//
// Теперь в сцене лежит ССЫЛКА: один компонент с путём к документу. Документ
// живёт своей жизнью, редактируется своим редактором и переиспользуется
// сколько угодно раз.
// ---------------------------------------------------------------------------
namespace sage::ui {

// «Здесь показывается вот этот документ интерфейса».
struct UIDocumentComponent {
    std::string Path;      // путь к .uidoc
    int SortOrder = 0;     // порядок между документами одной сцены
    bool Interactive = true; // false — документ виден, но не ловит мышь
    bool Visible = true;

    // ЧТО ЗНАЧАТ КОМАНДЫ ДОКУМЕНТА.
    //
    // Узел интерфейса умеет ровно одно: сообщить строку-команду ("menu.play").
    // Что она означает — не его дело и никогда им не будет (§103: игровой
    // логики в ядре интерфейса нет). Но и заставлять игру каждый кадр
    // опрашивать список команд — значит требовать скрипт-опросчик ради каждой
    // кнопки.
    //
    // Место, где интерфейс встречается с игрой, — вот здесь, в СЦЕНЕ: Trigger
    // связи — имя команды, остальное — обычная связь событий движка. Кнопка
    // по-прежнему ничего не знает про дверь, а дверь открывается сама.
    sage::events::Bindings Commands;
};

// ---------------------------------------------------------------------------
// РЕЕСТР ОТКРЫТЫХ ДОКУМЕНТОВ — по одному рантайму на ПУТЬ.
//
// Именно на путь, а не на сущность: два объекта, ссылающиеся на один документ,
// — это один интерфейс, показанный дважды, и состояние у него общее. И скрипт,
// и сцена, и редактор обращаются к одному и тому же — иначе игра меняла бы
// значение в своей копии, а на экране была бы чужая.
//
// Такой же именованный кэш, как у рендер-текстур движка (см.
// render/RenderTexture.h): имя документа — общий язык между сценой, скриптом и
// редактором, и двух разных «hud.uidoc» быть не должно.
// ---------------------------------------------------------------------------
class UIDocuments {
public:
    static UIDocuments& Instance();

    // Открыть документ (или отдать уже открытый). nullptr не возвращает
    // никогда: документа может не быть на диске, но интерфейс обязан
    // продолжать работать — вернётся пустой рантайм и запись в лог.
    UIRuntime& GetOrLoad(const std::string& path);
    UIRuntime* Find(const std::string& path);
    bool Loaded(const std::string& path) const;

    // Перечитать с диска (редактор сохранил файл).
    bool Reload(const std::string& path);
    void Remove(const std::string& path);
    void Clear();

    // Перевод строк — общий для всех документов.
    void SetLocalizer(std::function<std::string(const std::string&)> fn);

    std::vector<std::string> OpenPaths() const;

private:
    UIDocuments() = default;
    struct Entry {
        std::string Path;
        std::unique_ptr<UIRuntime> Runtime;
        bool Loaded = false;
    };
    std::vector<std::unique_ptr<Entry>> m_docs;
    std::unique_ptr<UIEngineResources> m_resources;
    std::function<std::string(const std::string&)> m_localize;
};

// ---------------------------------------------------------------------------
// РАНТАЙМ ИНТЕРФЕЙСА СЦЕНЫ — склейка «сцена → документы → кадр».
//
// Держит по одному UIRuntime на каждый ПУТЬ (а не на каждую сущность): два
// объекта, ссылающиеся на один документ, — это один интерфейс, показанный
// дважды, и состояние у него общее.
//
// Ничего не знает ни об игре, ни о том, что означают команды: собирает их и
// отдаёт наружу.
// ---------------------------------------------------------------------------
class UISceneRuntime {
public:
    UISceneRuntime();

    // Есть ли в сцене хоть один документ (и стоит ли вообще что-то делать).
    bool Any(Scene& scene) const;

    // Посчитать все документы сцены под размер кадра.
    void Update(Scene& scene, glm::vec2 screenPixels, float dt);
    // Раздать ввод. Возвращает СВОДНЫЙ отчёт: игре важно «взял ли интерфейс
    // щелчок себе», а не какой именно документ его взял.
    UIInputReport HandleInput(Scene& scene, const UIInputFrame& input, glm::vec2 screenPixels);
    // Нарисовать. root — цель, в которую идёт кадр (нужна композиции эффектов);
    // nullptr — буфер по умолчанию.
    void Render(Scene& scene, UIRenderer& renderer, glm::vec2 screenPixels,
                Framebuffer* root = nullptr);

    // Сводная стоимость всех документов кадра.
    const UIProfile& Profile() const { return m_profile; }

private:
    // Документы сцены в порядке SortOrder. Собирается каждый кадр: сцена
    // меняется, и держать «актуальный» список между кадрами — значит однажды
    // нарисовать документ удалённого объекта.
    //
    // Вместе с объектом-владельцем: он решает, ловит ли документ мышь, и он же
    // — отправитель событий, на которые кнопка переводится (Commands).
    struct Open {
        entt::entity Entity = entt::null;
        UIRuntime* Runtime = nullptr;
        bool Interactive = true;
    };
    std::vector<Open> Collect(Scene& scene);
    // Команды документа -> события сцены по связям владельца.
    void Dispatch(Scene& scene, entt::entity owner, const std::vector<std::string>& commands);

    UIProfile m_profile;
};

} // namespace sage::ui
