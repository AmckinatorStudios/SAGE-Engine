#pragma once
#include <nlohmann/json.hpp>

#include <entt/entt.hpp>

// ---------------------------------------------------------------------------
// ЭЛЕМЕНТ ИНТЕРФЕЙСА <-> JSON. Одна запись и одно чтение на весь движок.
//
// ПОЧЕМУ ОТДЕЛЬНО ОТ СЕРИАЛИЗАТОРА СЦЕН. Элемент теперь живёт в ДВУХ местах:
// в сцене (когда интерфейс собран прямо в ней) и в отдельном ресурсе .sageui
// (см. sage/ui/Interface.h). Если бы каждый писал его сам, у одного формата
// оказалось бы два описания — и разошлись бы они не сразу, а на третьем
// добавленном компоненте, причём молча: интерфейс, сохранённый как ресурс,
// открывался бы в сцене без половины настроек.
//
// КОМПОНЕНТЫ ПИШУТСЯ ПО РЕЕСТРУ (sage/ui/UIPart.h), а не списком полей. Это и
// есть расширяемость: свой компонент игры получает запись, чтение и инспектор
// одной регистрацией, без единой правки здесь.
// ---------------------------------------------------------------------------
namespace sage::ui {

struct Image;

// Элемент и все его компоненты в JSON-объект вида {"element": {...}, "fill": {...}}.
// Возвращает false, если у сущности нет Element — записывать нечего.
bool SaveElement(nlohmann::json& out, const entt::registry& reg, entt::entity e);

// Обратно. Ключ, которого реестр не знает (компонент из другой сборки игры),
// пропускается молча и остаётся в файле нетронутым: терять чужие данные при
// открытии нельзя.
void LoadElement(const nlohmann::json& in, entt::registry& reg, entt::entity e);

// Догружает текстуру картинки (рантайм-поле, в файл не пишется). Публичная,
// потому что её зовёт и разбор старого формата сцен: текстуру надо поднять
// одинаково, каким бы путём элемент ни пришёл.
void ResolveImageTexture(Image& image);

// ЗАГРУЗИТЬ, ЕСЛИ ЗАГРУЖЕНО НЕ ТО. Зовётся отрисовкой каждый кадр и обычно
// ничего не делает: сравнивает путь с тем, из которого сделан текущий
// указатель.
//
// Зачем это отрисовке. Раньше текстура читалась ТОЛЬКО при чтении сцены, и
// путь, назначенный в редакторе, до неё не доходил: человек клал картинку в
// слот и не видел ничего — до тех пор, пока не запускал и не останавливал
// игру (Play/Stop перечитывает сцену). Правок путей много — инспектор,
// перетаскивание, отмена, скрипт, префаб, — и вешать перезагрузку на каждую
// значит однажды забыть одну. Отрисовка же одна.
void EnsureImageTexture(Image& image);

// НУЖНА ЛИ ПЕРЕЗАГРУЗКА — чистый вопрос о числах и строках, без GL и без
// файлов. Отдельно от EnsureImageTexture именно поэтому: решение проверяется
// тестом, а загрузка требует контекста отрисовки и диска.
bool ImageTextureStale(const Image& image);

} // namespace sage::ui
