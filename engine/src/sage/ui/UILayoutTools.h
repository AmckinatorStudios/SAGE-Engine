#pragma once
#include <vector>

#include <glm/glm.hpp>

#include "sage/ui/UIAnchor.h"

// ---------------------------------------------------------------------------
// ИНСТРУМЕНТЫ ВЁРСТКИ: привязка, выравнивание, распределение.
//
// ЗАЧЕМ ЭТО В ДВИЖКЕ, А НЕ В РЕДАКТОРЕ. Здесь нет ни ImGui, ни сцены, ни ECS —
// только прямоугольники и числа. Это сделано намеренно, и вот почему:
//
//   • Проверяемость. «Элемент притянулся к краю соседа» — утверждение о числах,
//     и проверять его надо числами, а не глазами по скриншоту. Пока эта
//     математика жила бы внутри обработчика мыши, единственным способом её
//     проверить было бы возить мышью.
//   • Одно правило на всех. Притяжка нужна не только мыши: те же расчёты
//     хочет клавиатурный сдвиг, хочет вставка элемента «рядом с этим», захочет
//     скрипт, расставляющий кнопки. Формула, спрятанная в UICanvas.cpp,
//     доступна ровно одному вызывающему.
//   • Отделение «что» от «как». Редактор отвечает за то, ЧТО тянут мышью;
//     здесь — КУДА это должно встать.
//
// СИСТЕМА КООРДИНАТ. Всё в пикселях кадра интерфейса (тех же, в которых
// работает раскладка), ось Y — вниз. Прямоугольники — UIRect (левый верхний
// угол, ширина, высота).
// ---------------------------------------------------------------------------
namespace sage::ui {

// --- Привязка ---------------------------------------------------------------

// Линия, к которой притянулись. Её ПОКАЗЫВАЮТ, пока идёт перетаскивание:
// без линии человек видит, что элемент дёрнулся, но не видит, ПОЧЕМУ и к чему,
// и воспринимает притяжку как «редактор не даёт поставить куда надо».
struct SnapGuide {
    enum class Axis {
        X, // вертикальная линия: притяжка по горизонтали
        Y, // горизонтальная линия: притяжка по вертикали
    };
    // Откуда линия взялась — от этого зависит и цвет, и приоритет.
    enum class Source {
        Grid,     // узел сетки
        Parent,   // край или центр родителя
        Sibling,  // край или центр соседнего элемента
    };

    Axis Along = Axis::X;
    Source From = Source::Grid;
    float Position = 0.0f;          // координата линии по своей оси
    float Begin = 0.0f, End = 0.0f; // отрезок вдоль ДРУГОЙ оси (что с чем совпало)
};

// Настройки притяжки. Живут в редакторе (человек их крутит), сюда приходят
// значением: математике незачем знать, где они хранятся.
struct SnapSettings {
    bool ToGrid = true;
    float GridStep = 8.0f;
    // К краям и центрам родителя и соседей. Именно это и есть «умные
    // направляющие»: сетка ставит на круглые числа, а края — в один ряд с тем,
    // что уже стоит.
    bool ToEdges = true;
    // Радиус притяжения в пикселях кадра. Больше — «липнет» издалека и мешает
    // поставить рядом, но не вплотную; меньше — в него не попасть мышью.
    float Threshold = 6.0f;
};

// Какие рёбра прямоугольника ведёт мышь. Перемещение — все четыре сразу;
// растягивание за ручку — одно или два.
//
// Без этого различия привязка при растягивании неизбежно врёт: тянут правый
// край, а притягивается ближайшим оказывается левый, и элемент прыгает целиком.
struct SnapEdges {
    bool Left = false, Right = false, Top = false, Bottom = false;

    static SnapEdges Whole() { return SnapEdges{true, true, true, true}; }
    bool MovesWhole() const { return Left && Right && Top && Bottom; }
    bool MovesX() const { return Left || Right; }
    bool MovesY() const { return Top || Bottom; }
};

struct SnapResult {
    // Поправка к тому положению, куда прямоугольник встал бы без привязки.
    // Для перемещения прибавляется ко всему прямоугольнику, для растягивания —
    // к тому ребру, которое ведут.
    glm::vec2 Delta{0.0f, 0.0f};
    std::vector<SnapGuide> Guides;
};

// Считает поправку. `moving` — прямоугольник БЕЗ привязки (там, где его держит
// мышь), `siblings` — прочие элементы того же экрана (в них не должно быть
// самого движимого: он притянулся бы к себе).
//
// Оси считаются НЕЗАВИСИМО: по горизонтали можно встать в ряд с соседом, а по
// вертикали — на узел сетки. Требовать, чтобы обе оси взялись из одного
// источника, значит терять половину привязок.
SnapResult Snap(const UIRect& moving, const SnapEdges& edges, const UIRect& parent,
                const std::vector<UIRect>& siblings, const SnapSettings& settings);

// --- Выравнивание -----------------------------------------------------------

// По какому краю равняем. Шесть значений вместо двух перечислений (ось + край)
// потому, что кнопок в панели ровно шесть и каждая означает ровно одно.
enum class AlignEdge {
    Left, CenterX, Right,
    Top, CenterY, Bottom,
};

// Горизонтальное ли это выравнивание (двигает по X).
bool AlignIsHorizontal(AlignEdge edge);

// Смещение, которое поставит `r` по краю `target`. Вторая координата всегда 0:
// выравнивание по левому краю не имеет права двигать элемент по вертикали.
glm::vec2 AlignDelta(const UIRect& r, const UIRect& target, AlignEdge edge);

// --- Распределение ----------------------------------------------------------

// Равные ПРОМЕЖУТКИ между соседями: крайние остаются на месте, остальные
// раздвигаются так, чтобы зазоры совпали. Для ряда кнопок разной ширины это
// единственный правильный смысл слова «поровну».
//
// Возвращает смещение вдоль оси для КАЖДОГО входного прямоугольника, в том же
// порядке, в каком их подали (сортировка по положению — внутри). Меньше трёх
// прямоугольников — все нули: распределять нечего.
std::vector<float> DistributeGapDeltas(const std::vector<UIRect>& rects, bool horizontal);

// Равные ЦЕНТРЫ: одинаковый шаг между серединами. Для одинаковых по размеру
// элементов совпадает с предыдущим, для разных — нет, и разница как раз в том,
// что нужно для сетки иконок: там равняют шаг, а не зазор.
std::vector<float> DistributeCenterDeltas(const std::vector<UIRect>& rects, bool horizontal);

// --- Прочее -----------------------------------------------------------------

// Объединяющий прямоугольник. Нужен и привязке (набор тянут как одно целое), и
// выравниванию (к чему равнять, когда «главного» элемента нет).
UIRect Union(const std::vector<UIRect>& rects);

} // namespace sage::ui
