#pragma once
#include <string>
#include <vector>

#include <entt/entt.hpp>
#include <nlohmann/json.hpp>

class Scene;

// ---------------------------------------------------------------------------
// INTERFACE — СТРУКТУРА ИНТЕРФЕЙСА ОТДЕЛЬНЫМ РЕСУРСОМ (.sageui).
//
// ЗАЧЕМ. Интерфейс собирался прямо в сцене и жил только в ней. Отсюда всё
// остальное: меню паузы, окно инвентаря и HUD существовали внутри конкретного
// уровня; перенести их во второй уровень можно было только копированием
// поддерева, после чего копий становилось две и правки в них расходились.
// Открыть интерфейс, не открывая уровень, было нельзя вовсе — а верстают его
// отдельно и подолгу.
//
// Теперь это РЕСУРС, как сцена, материал или клип анимации: лежит в проекте,
// виден в панели ассетов, ссылается на него кто угодно и сколько угодно раз.
//
// ЧТО ВНУТРИ. Дерево узлов. Узел — это имя, сам элемент (раскладка, порядок,
// видимость) и его компоненты; компоненты пишутся ПО РЕЕСТРУ
// (sage/ui/UIPart.h), тем же кодом, что и в сцене (sage/ui/UISerialize.h).
// Одна запись на оба места — иначе у одного формата оказалось бы два описания,
// и разошлись бы они на третьем добавленном компоненте, причём молча.
//
// ЧЕГО ЗДЕСЬ НЕТ. Логики игры. Интерфейс не знает ни про инвентарь, ни про
// здоровье, ни про меню паузы: он описывает, ЧТО нарисовано и как оно
// расположено. Связь с игрой — через события и скрипты, как у всего остального
// в движке.
// ---------------------------------------------------------------------------
namespace sage::ui {

// Узел дерева. Имя лежит здесь, а не в Element, по той же причине, по какой его
// нет в Element: в сцене имя принадлежит сущности (NameComponent), и второй
// копии внутри элемента быть не должно. В файле же сущностей нет — есть узлы.
struct InterfaceNode {
    std::string Name = "Element";
    // Элемент и его компоненты ровно в том виде, в каком они лежат в сцене
    // (см. UISerialize.h): {"element": {...}, "fill": {...}, ...}.
    nlohmann::json Data = nlohmann::json::object();
    std::vector<InterfaceNode> Children;
};

struct Interface {
    // Имя ресурса — то, что видно в панели ассетов и в заголовке редактора.
    // Не имя файла: файл можно переименовать, не трогая содержимого.
    std::string Name = "Interface";
    // Корней может быть НЕСКОЛЬКО: HUD и меню паузы — два независимых дерева
    // одного интерфейса, и заворачивать их в общий пустой узел только ради
    // одного корня значит добавить в дерево строку, которая ничего не значит.
    std::vector<InterfaceNode> Roots;

    // --- Файл ---------------------------------------------------------------
    std::string ToJsonString() const;
    static bool FromJsonString(const std::string& text, Interface& out, std::string& err);
    bool SaveFile(const std::string& path, std::string& err) const;
    static bool LoadFile(const std::string& path, Interface& out, std::string& err);
};

// --- Сцена <-> ресурс --------------------------------------------------------

// Создаёт в сцене сущности по дереву ресурса. parent — куда положить корни
// (невалидная — в корень сцены). Возвращает созданные корневые сущности.
//
// Не «загружает интерфейс», а РАЗВОРАЧИВАЕТ его: тот же ресурс можно
// развернуть дважды (два окна инвентаря рядом), и копии не будут знать друг о
// друге.
std::vector<entt::entity> Instantiate(Scene& scene, const Interface& ui,
                                      entt::entity parent = entt::null);

// Обратно: снимает поддерево сцены в ресурс. Берутся только сущности с Element
// — 3D-объект, случайно попавший в поддерево интерфейса, в ресурс не поедет.
Interface Capture(const Scene& scene, const std::vector<entt::entity>& roots);

} // namespace sage::ui
