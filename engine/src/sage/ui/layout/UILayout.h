#include "sage/ui/core/UITypes.h"

// ---------------------------------------------------------------------------
// КОНТЕЙНЕР РАСКЛАДКИ (§12–14 ТЗ).
//
// Раскладка — ОТДЕЛЬНАЯ подсистема, а не набор особых правил внутри кнопки или
// списка. Узел, у которого есть этот компонент, сам расставляет своих детей;
// узел без него не расставляет никого, и дети стоят по своим якорям.
//
// ПОЧЕМУ ЭТО ВАЖНО. Меню из пяти кнопок, инвентарь, панель настроек, строка
// вкладок — всё это раньше расставлялось вручную: каждому ребёнку свой отступ,
// посчитанный на бумаге. Шестая кнопка означала пересчёт пяти чужих отступов.
// Здесь родитель расставляет детей сам, а размеры и зазоры заданы один раз.
//
// ЧЕГО ЗДЕСЬ НЕТ. Нет рисования: контейнер не «панель со списком», у него может
// не быть вообще никакого оформления. Нет знания о том, ЧТО внутри: строка
// вкладок и полка предметов — один и тот же горизонтальный контейнер.
// ---------------------------------------------------------------------------
namespace sage::ui {

// Куда прижимать содержимое вдоль оси.
enum class UIAlign {
    Start,
    Center,
    End,
    Stretch,      // растянуть по поперечной оси
    SpaceBetween, // зазоры между детьми, края прижаты
    SpaceAround,  // равные поля вокруг каждого
    SpaceEvenly,  // равные промежутки, включая края
};

struct UILayout : UIComponentOf<UILayout> {
    static const UIComponentType& StaticType();

    // Виды раскладки (§12). Список открыт: свой вид добавляется своим
    // компонентом со своим решателем — ядро об этом знать не обязано.
    enum class Mode {
        None,       // дети по своим якорям
        Horizontal, // ряд
        Vertical,   // столбец
        Grid,       // сетка с фиксированным числом столбцов
        Wrap,       // ряд с переносом на следующую строку
        Overlay,    // все дети занимают весь контейнер (слои)
        Center,     // все дети по центру, размеры свои
        Stack,      // как Overlay, но со сдвигом каждого следующего
        Aspect,     // один ребёнок, вписанный по соотношению сторон
    };

    Mode Kind = Mode::Vertical;

    UIEdges Padding{8.0f, 8.0f, 8.0f, 8.0f};
    glm::vec2 Gap{8.0f, 8.0f}; // зазор вдоль основной и поперечной осей

    UIAlign Main = UIAlign::Start;  // вдоль основной оси
    UIAlign Cross = UIAlign::Start; // поперёк

    int Columns = 3;             // для Grid
    glm::vec2 CellSize{0.0f, 0.0f}; // для Grid: 0 — из размера контейнера
    glm::vec2 StackOffset{12.0f, 12.0f}; // для Stack

    // Подгонка собственного размера под содержимое (§14). Работает вместе с
    // UISizeMode::Content у соответствующей оси Transform: флаг здесь —
    // «контейнер умеет посчитать своё содержимое», режим там — «этой осью
    // пользуйся».
    bool FitWidth = false;
    bool FitHeight = false;

    // Обратный порядок детей — для нижних панелей и списков «снизу вверх»
    // (чат, лог). Без него приходится хранить детей в обратном порядке, и
    // дерево в редакторе перестаёт совпадать с тем, что видно.
    bool Reverse = false;
};

const char* const* UIAlignNames();
int UIAlignCount();

} // namespace sage::ui
