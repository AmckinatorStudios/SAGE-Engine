#pragma once
#include <glm/glm.hpp>
#include <string>
#include <vector>

class UIRenderer;

// ---------------------------------------------------------------------------
// Векторная иконография интерфейса.
//
// ИКОНКИ РИСУЮТСЯ, А НЕ ЗАГРУЖАЮТСЯ. Ни одного PNG, ни атласа, ни импорта:
// каждая иконка — десяток кругов, четырёхугольников и колец из UIRenderer.
// Причины ровно три, и все практические:
//
//   • Интерфейсу движка нужны иконки СРАЗУ. Игра, у которой ещё нет художника,
//     иначе остаётся с текстовым HUD — а «нет иконок» и есть первое, за что
//     цепляется глаз.
//   • Векторная форма не мылится: одна и та же иконка одинаково резка и в 16,
//     и в 64 пикселя, тогда как атлас надо печь под каждый размер.
//   • Цвет — параметр вызова, а не свойство файла: та же иконка сердца красная
//     в полоске здоровья и серая в неактивном слоте.
//
// ЧТО ДВИЖОК ДЕРЖИТ У СЕБЯ, А ЧТО НЕТ.
//
// Здесь лежит только НЕЙТРАЛЬНЫЙ набор: управление (play/pause/gear/save/exit),
// разметка (plus/minus/check/cross/warn), состояние (heart/drop/flame/clock) —
// то, что осмысленно в любой игре любого жанра.
//
// Раньше рядом с ним жил инвентарь одной конкретной игры: доска, бревно, ящик,
// бочка, верёвка, ткань, рыба, удочка, парус, якорь, водоочиститель и прочее —
// двадцать четыре предмета ЧУЖОГО мира в движке, который эту игру не содержит.
// Любая другая игра таскала их в каждой сборке и не могла добавить свои, не
// правя движок: таблица была зашита в .cpp.
//
// Теперь предметный набор приносит игра — RegisterIcon (пример:
// games/testgame/src/GameIcons.cpp, откуда эти двадцать четыре и переехали).
// Движок даёт механизм, содержимое даёт игра.
//
// Иконка всегда вписана в КВАДРАТ (x, y, size) и рисуется целиком внутри него,
// поэтому вёрстка не зависит от того, какую именно нарисовали.
//
//   sage::ui::DrawIcon(ui, "heart", 16, 16, 24, {0.9f, 0.3f, 0.3f});
//
// Неизвестное имя — не ошибка: рисуется «нет иконки» (пустой квадрат с
// диагональю), и вызов возвращает false. Интерфейс не должен рассыпаться из-за
// опечатки в имени.
// ---------------------------------------------------------------------------
namespace sage::ui {

// Перо иконки: НОРМАЛИЗОВАННЫЕ координаты 0..1 внутри своего квадрата,
// перевод в экранные — здесь. Так форма описывается один раз и одинаково
// выглядит в любом размере, а правка не превращается в перенабор пиксельных
// координат.
//
// Публичное, потому что рисовать иконки должна уметь и игра (RegisterIcon), а
// не только движок. Методы определены в .cpp: заголовку иконок незачем тянуть
// за собой весь UIRenderer.
struct IconPen {
    UIRenderer& Ui;
    float X, Y, Size;
    glm::vec3 Color;
    float Alpha;

    glm::vec2 P(float u, float v) const;      // точка в долях стороны -> экран
    float L(float k) const;                   // длина в долях стороны -> пиксели
    void Dot(float u, float v, float r) const;
    void Ring(float u, float v, float r, float t) const;
    // Прямоугольник по левому-верхнему углу и размеру (всё в долях стороны).
    void Box(float u, float v, float w, float h, float round = 0.0f) const;
    void Tri(float u0, float v0, float u1, float v1, float u2, float v2) const;
    void Quad4(float u0, float v0, float u1, float v1, float u2, float v2, float u3,
               float v3) const;
    // Отрезок заданной толщины — четырёхугольник вдоль направления.
    void Line(float u0, float v0, float u1, float v1, float t) const;
};

using IconDrawFn = void (*)(const IconPen&);

// Добавляет иконку в набор. Имя занято — старая заменяется (игра вправе
// переопределить и движковую: её «сердце» может быть не таким, как здесь).
// Звать до первой отрисовки — обычно при старте игры.
void RegisterIcon(const std::string& name, IconDrawFn draw);

// Рисует иконку name, вписанную в квадрат (x, y, size). false — имя незнакомо
// (нарисована заглушка). Звать между UIRenderer::Begin и End.
bool DrawIcon(UIRenderer& ui, const std::string& name, float x, float y, float size,
              glm::vec3 color, float alpha = 1.0f);

// Есть ли такая иконка (без отрисовки) — для валидации в редакторе.
bool HasIcon(const std::string& name);

// Все известные имена, отсортированные. Редактор показывает их списком в
// инспекторе, чтобы имя иконки не приходилось угадывать. Список пересобирается
// после RegisterIcon: иконки игры обязаны быть в нём видны.
const std::vector<std::string>& IconNames();

} // namespace sage::ui
