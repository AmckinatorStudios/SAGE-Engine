#pragma once

class Scene;

namespace sage::ui {

// ---------------------------------------------------------------------------
// UIShowcase — БОЕВОЙ сложный интерфейс из UIElementComponent: инвентарь (сетка
// слотов с иконками/счётчиками, выделение, полоса веса, обрезка маской) и дерево
// навыков (узлы, соединённые «проводами», состояния locked/unlocked, счётчик
// очков). Не демо на паре панелей, а плотный реальный экран — стресс-тест
// тулкита (вёрстка якорями во вложенных контейнерах, слои, клип-маски, десятки
// элементов). Строится из ECS-сущностей, поэтому рендерится и в редакторе
// (панель Game), и в собранной игре (SagePlayer) системой DrawSceneUI.
//
// Возвращает id корневой сущности-оверлея (её удаление убирает весь интерфейс).
// Отдельные части — под именами "Inventory"/"SkillTree" (FindByName).
// ---------------------------------------------------------------------------
int BuildShowcase(Scene& scene);

} // namespace sage::ui
