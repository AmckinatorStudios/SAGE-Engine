// ---------------------------------------------------------------------------
// ПЕРЕЕЗД СО СТАРОЙ СИСТЕМЫ ИНТЕРФЕЙСА.
//
// Старый интерфейс был СУЩНОСТЯМИ СЦЕНЫ: каждая надпись — объект в иерархии
// рядом с камерой и светом, а её свойства лежали в блоке "ui" файла .sage.
// Самой системы в движке больше нет; переезд остался, и работает он не с живыми
// компонентами, а с ФАЙЛОМ.
//
// Так и должно быть: инструмент переезда обязан пережить систему, из которой
// переезжают. Иначе он умирает вместе с ней ровно тогда, когда становится
// нужен, — а старые сцены у людей на диске остаются.
//
// Читаются оба старых формата: плоский элемент с ключом "kind" (сорок полей на
// каждый элемент, включая бессмысленные) и поздний покомпонентный.
//
// ЧЕГО ПЕРЕЕЗД НЕ ДЕЛАЕТ: не тащит в новую систему старые ограничения. Девять
// якорей становятся долями, флаг обрезки — полноценной маской, тень двумя
// полями — эффектом в стеке. Обратного перевода нет и не планируется.
// ---------------------------------------------------------------------------
namespace sage::ui {

struct UIMigrationReport {
    bool Ok = false;
    int Nodes = 0;
    int Components = 0;
    std::vector<std::string> Warnings; // что не перенеслось и почему
    std::string Error;
};

// Собрать документ из блоков "ui" сцены .sage. Документ очищается.
UIMigrationReport UIMigrateSceneFile(const std::string& scenePath, UIDocument& doc);
// То же из уже прочитанного текста сцены — для тестов и инструментов.
UIMigrationReport UIMigrateSceneText(const std::string& sceneJson, UIDocument& doc);

} // namespace sage::ui
