#pragma once
#include <string>

#include "sage/ui/core/UIComponent.h"
#include "sage/ui/core/UITypes.h"

// ---------------------------------------------------------------------------
// ВЕКТОРНЫЙ ЗНАЧОК ДВИЖКА.
//
// Значки движка (sage/ui/UIIcons.h) не загружаются, а РИСУЮТСЯ: десяток кругов,
// четырёхугольников и колец на каждый. Из-за этого они не выражаются ни
// картинкой, ни процедурной формой — и остались бы недоступны новой системе,
// если бы у неё не было собственного компонента.
//
// Как он попадает на экран: эмиттер выдаёт команду с ПОЛЬЗОВАТЕЛЬСКИМ
// МАТЕРИАЛОМ (§44) с именем "icon" и именем значка. Ядро интерфейса при этом не
// знает, что такое значок и как он устроен, — ровно как и с любым другим
// материалом. Знает только бэкенд, у которого есть чем его нарисовать.
// ---------------------------------------------------------------------------
namespace sage::ui {

struct UIIcon : UIComponentOf<UIIcon> {
    static const UIComponentType& StaticType();

    std::string Name;
    UIColor Color{1.0f, 1.0f, 1.0f, 1.0f};
    // 0 — вписать в меньшую сторону узла. Значок всегда квадратный, поэтому
    // «размер» у него один, а не два.
    float Size = 0.0f;
};

} // namespace sage::ui
