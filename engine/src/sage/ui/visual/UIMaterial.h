#pragma once
#include <string>

#include "sage/ui/core/UIComponent.h"
#include "sage/ui/core/UITypes.h"

// ---------------------------------------------------------------------------
// ПОЛЬЗОВАТЕЛЬСКИЙ МАТЕРИАЛ (§44, §45 ТЗ).
//
// Визуальный элемент не обязан быть жёстко связан с одним шейдером. Узел с этим
// компонентом рисуется тем, что назовёт разработчик, — и ядро интерфейса не
// знает и не должно знать, что там внутри.
//
// Что шейдер получает от системы (§45, §46): прямоугольник узла в экранных
// пикселях, локальную и нормализованную позицию, UV, размер, цвет, итоговую
// прозрачность, состояние маски и время. Всё это уже есть в команде отрисовки —
// материалу остаётся добавить свои текстуры и числа.
//
// ПОЧЕМУ ЭТО КОМПОНЕНТ, А НЕ ПОЛЕ У ЗАЛИВКИ. Свой материал бывает нужен и
// вместо заливки, и вместо картинки, и сам по себе (шум, помехи, индикатор,
// процедурный фон). Поле у одного из них означало бы, что все остальные случаи
// выразить нечем.
// ---------------------------------------------------------------------------
namespace sage::ui {

struct UIMaterial : UIComponentOf<UIMaterial> {
    static const UIComponentType& StaticType();

    // Имя шейдера в понятиях бэкенда. Что оно значит, решает бэкенд.
    std::string Shader;
    // Что именно рисуем этим шейдером (имя набора, вариант, ключ).
    std::string Name;

    std::string Texture0, Texture1, Texture2, Texture3;
    glm::vec4 Param0{0.0f}, Param1{0.0f}, Param2{0.0f}, Param3{0.0f};

    UIColor Color{1.0f, 1.0f, 1.0f, 1.0f};
    UIBlendMode Blend = UIBlendMode::Normal;
};

} // namespace sage::ui
