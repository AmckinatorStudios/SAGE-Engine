#pragma once
#include "sage/ui/core/UIComponent.h"
#include "sage/ui/visual/UIGradient.h"

// ---------------------------------------------------------------------------
// РАМКА (§22 ТЗ) — самостоятельный визуальный компонент.
//
// Раньше рамка была двумя полями внутри заливки, и из этого следовало: рамка
// без заливки невозможна, рамка своего цвета поверх картинки невозможна, рамка
// с собственным скруглением невозможна. Отдельный компонент снимает все три
// ограничения сразу и ничего не стоит там, где его нет (§130).
// ---------------------------------------------------------------------------
namespace sage::ui {

struct UIBorder : UIComponentOf<UIBorder> {
    static const UIComponentType& StaticType();

    // Толщина по сторонам. Одинаковая — обычный случай; разная нужна вкладкам,
    // разделителям и «подчёркнутому» полю ввода.
    UIEdges Thickness{1.0f, 1.0f, 1.0f, 1.0f};
    UIColor Color{0.85f, 0.80f, 0.65f, 0.9f};
    UIGradient Gradient;
    // Радиусы рамки. Отрицательное значение — «взять у заливки»: чаще всего
    // рамка обводит именно её, и дублировать числа руками — верный способ
    // получить рассинхрон.
    UICorners Radius{-1.0f, -1.0f, -1.0f, -1.0f};
    // Смещение рамки наружу от края узла (обводка «вокруг», а не «внутри»).
    float Inset = 0.0f;
};

} // namespace sage::ui
