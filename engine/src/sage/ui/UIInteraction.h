#pragma once
#include <string>
#include <glm/glm.hpp>

// ---------------------------------------------------------------------
// Ввод для интерфейса сцены: то, что рантайм собирает за кадр и отдаёт
// sage::ui::UpdateSceneUI (см. UISceneSystem.h).
//
// ЗАЧЕМ ОТДЕЛЬНАЯ СТРУКТУРА, А НЕ ОПРОС УСТРОЙСТВ ВНУТРИ UI. Интерфейс живёт и
// в игре, и в панели Game редактора, и в тестах без окна вовсе. Опрашивай он
// устройства сам — он был бы намертво привязан к GLFW, а редактор не смог бы
// отдать ему координаты, пересчитанные в свою панель (там мышь смещена и
// отмасштабирована). Здесь UI получает уже готовые числа и остаётся чистой
// функцией от них — его можно прогнать в юнит-тесте без единого окна.
//
// ТЕКСТ ПРИХОДИТ СИМВОЛАМИ, А НЕ КЛАВИШАМИ. Клавиша и символ — разные вещи:
// раскладка, Shift, мёртвые клавиши и композиция превращают нажатия в символы
// по правилам системы. Повторять эти правила в движке нельзя (получится ввод,
// работающий только на английской раскладке), поэтому TypedText — уже готовая
// строка UTF-8 от оконной системы.
// ---------------------------------------------------------------------
namespace sage::ui {

struct UIInputState {
    glm::vec2 Mouse{-1.0f, -1.0f}; // экранные пиксели; за пределами — ничего не под курсором
    bool MouseDown = false;        // левая кнопка удерживается СЕЙЧАС
    bool MousePressed = false;     // нажата именно в этом кадре
    bool MouseReleased = false;    // отпущена именно в этом кадре

    std::string TypedText;         // символы, набранные за кадр (UTF-8)

    // Клавиши редактирования: у них нет символа, но есть автоповтор.
    bool Backspace = false;
    bool Delete = false;
    bool Left = false;
    bool Right = false;
    bool Home = false;
    bool End = false;
    bool Enter = false;   // подтвердить ввод (снимает фокус)
    bool Escape = false;  // отменить/снять фокус
    bool Tab = false;     // перейти к следующему полю

    float DeltaTime = 0.0f; // для мигания курсора
};

// Что интерфейс СЪЕЛ в этом кадре. Игра обязана это уважать: щелчок по кнопке
// меню не должен одновременно стрелять из ружья, а буква, набранная в поле
// имени, — двигать персонажа.
struct UIInputResult {
    bool WantsMouse = false;    // курсор над интерактивным элементом или тащит ползунок
    bool WantsKeyboard = false; // есть поле ввода в фокусе
    int ClickedId = -1;         // id сущности, по которой кликнули (-1 — ни по кому)
};

// Дописывает codepoint в строку UTF-8. Оконная система отдаёт символ числом, а
// поле ввода хранит текст байтами — перевод нужен ровно один и в одном месте.
inline void AppendUtf8(std::string& out, unsigned int cp) {
    if (cp < 0x80) {
        out += (char)cp;
    } else if (cp < 0x800) {
        out += (char)(0xC0 | (cp >> 6));
        out += (char)(0x80 | (cp & 0x3F));
    } else if (cp < 0x10000) {
        out += (char)(0xE0 | (cp >> 12));
        out += (char)(0x80 | ((cp >> 6) & 0x3F));
        out += (char)(0x80 | (cp & 0x3F));
    } else {
        out += (char)(0xF0 | (cp >> 18));
        out += (char)(0x80 | ((cp >> 12) & 0x3F));
        out += (char)(0x80 | ((cp >> 6) & 0x3F));
        out += (char)(0x80 | (cp & 0x3F));
    }
}

} // namespace sage::ui
