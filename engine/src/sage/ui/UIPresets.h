// Заготовки элементов интерфейса — В ДВИЖКЕ, а не в редакторе.
//
// ЗАЧЕМ. «Кнопка» — это не вид элемента, а НАБОР ЗНАЧЕНИЙ: панель, у которой
// включено Interactive, есть надпись, рамка в один пиксель и размер, в который
// эта надпись помещается. Ровно это и есть та «странность компонентов», на
// которую жалуются: компонент один на восемь видов элементов, и чтобы получить
// кнопку, надо знать, какие семь полей у панели поменять. Кто не знает —
// получает прямоугольник, который не нажимается.
//
// Знание это жило в ОДНОМ месте — в функции редактора, создающей элемент по
// пункту меню. Значит, кнопку можно было получить только мышью в редакторе:
// скрипт, собирающий интерфейс на лету (диалог, инвентарь, меню паузы), обязан
// был повторить те же семь присваиваний у себя, а игра, собранная без
// редактора, не имела к ним доступа вовсе. Заготовка переехала в движок:
// редактор, скрипты и рантайм получают ОДНУ и ту же кнопку.
//
// Здесь только ДАННЫЕ по умолчанию. Никакой логики: заготовка применяется к
// уже существующему компоненту и дальше правится как обычно.
// ---------------------------------------------------------------------------
namespace sage::ui {

// Имена заготовок берутся у новой системы интерфейса (sage/ui/UI.h) —
// PresetNames() объявлена там.

// Применяет заготовку к компоненту. Возвращает false, если имени нет в списке —
// молча оставить элемент пустым значило бы «кнопка не создалась и не сказала».
bool ApplyPreset(UIElementComponent& element, const std::string& preset);

} // namespace sage::ui
