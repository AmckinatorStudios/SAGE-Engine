#pragma once
#include <string>
#include <vector>

#include <entt/entt.hpp>

class Scene;

// ---------------------------------------------------------------------------
// Заготовки элементов интерфейса — В ДВИЖКЕ, а не в редакторе.
//
// ЗАЧЕМ. «Кнопка» — это не вид элемента, а НАБОР ЧАСТЕЙ: прямоугольник,
// подложка, надпись и реакция на мышь. Знание это жило в ОДНОМ месте — в
// функции редактора, создающей элемент по пункту меню. Значит, кнопку можно
// было получить только мышью в редакторе: скрипт, собирающий интерфейс на лету
// (диалог, инвентарь, меню паузы), обязан был повторить те же присваивания у
// себя, а игра, собранная без редактора, не имела к ним доступа вовсе.
//
// Сама таблица заготовок живёт в UI.h (Preset, PresetNames, FindPreset) — это
// ДАННЫЕ. Здесь единственное действие над ними: собрать из заготовки элемент на
// сущности.
// ---------------------------------------------------------------------------
namespace sage::ui {

// Собирает элемент из заготовки НА СУЩНОСТИ: ставит ровно те компоненты, из
// которых заготовка состоит, и снимает те, которых в ней нет.
//
// Снимает намеренно. «Сделать из кнопки надпись» — обычное действие в
// редакторе, и если старые части остаются, надпись продолжает ловить мышь и
// рисовать подложку, а причина этого не видна нигде: в инспекторе компонент
// есть, в заготовке его нет. Заготовка обязана давать ровно то, что обещает.
//
// Возвращает false, если имени нет в списке — молча оставить элемент пустым
// значило бы «кнопка не создалась и не сказала».
bool ApplyPreset(entt::registry& reg, entt::entity e, const std::string& preset);

// То же, но СО СЦЕНОЙ — и потому с детьми.
//
// Заготовка кнопки это подложка ПЛЮС объект-надпись внутри неё (см. Preset::
// Children): надпись видна в дереве, её можно двигать, красить и убирать, а не
// «выключать текст у подложки». Создать объект и назначить ему родителя умеет
// только сцена, поэтому у сборки с детьми свой вход.
//
// Существующие дети-элементы заменяются: применить заготовку — значит получить
// ровно её, а не её поверх прошлой.
bool ApplyPreset(Scene& scene, entt::entity e, const std::string& preset);

} // namespace sage::ui
