#include <cstddef>
#include <string>
#include <vector>

#include <glm/glm.hpp>

#include "sage/ui/core/UITypes.h"

// ---------------------------------------------------------------------------
// ОПИСАНИЕ СВОЙСТВА — единственный источник правды о том, из чего компонент
// интерфейса состоит.
//
// По одной таблице свойств работают ЧЕТЫРЕ подсистемы:
//   • запись документа в файл;
//   • чтение документа из файла (включая переезд со старой версии);
//   • инспектор редактора (какие поля показать и каким виджетом);
//   • анимация и связывание данных (адресация «узел/компонент.свойство»).
//
// Раньше эти четыре списка писались руками по отдельности и неизбежно
// расходились: свойство, добавленное в компонент и забытое в сериализаторе,
// молча терялось при сохранении сцены, а забытое в инспекторе не существовало
// для человека вовсе. Здесь забыть нельзя: свойство либо есть в таблице — и
// тогда оно есть везде, — либо его нет нигде.
// ---------------------------------------------------------------------------
namespace sage::ui {

// СТРОКА ДЛЯ ЧЕЛОВЕКА, которую покажет РЕДАКТОР. В движке это обычный литерал:
// движок ничего не переводит. Пометка нужна сборщику переводов
// (scripts/check_localization.py) — иначе названия свойств оказались бы
// единственными строками редактора, которых не сторожит ни один список.
#ifndef SAGE_UI_TEXT
#define SAGE_UI_TEXT(s) s
#endif

// Смещение поля внутри компонента.
//
// Не offsetof: компоненты — полиморфные типы (у них есть таблица виртуальных
// функций), а offsetof для таких типов формально не разрешён, и GCC честно
// ругается -Winvalid-offsetof на каждую строку каждой таблицы свойств. Разность
// адресов даёт то же число без предупреждений и работает на всех компиляторах,
// которыми собирается движок.
#define SAGE_UI_OFFSET(Type, Field)                                             \
    ((size_t)((const char*)&(reinterpret_cast<const Type*>(1024)->Field)) - 1024u)

struct UIProperty {
    // Тип значения. Определяет и то, как свойство пишется в файл, и то, каким
    // виджетом его правят по умолчанию.
    enum class Kind {
        Bool,
        Int,
        Float,
        String,
        Color,    // UIColor (vec4 RGBA)
        Vec2,
        Vec4,
        Enum,     // int с именами значений
        Edges,    // UIEdges — четыре стороны
        Corners,  // UICorners — четыре радиуса
        Gradient, // UIGradient — список остановок (пишется своим кодом)
        Custom,   // компонент сериализует поле сам (списки, вложенные объекты)
    };

    // Чем свойство правят, когда обычного виджета по типу мало. Декларативно
    // здесь, а не списком исключений в редакторе: «это путь к картинке» —
    // свойство самого поля.
    enum class Widget {
        Auto,
        Texture,   // строка — путь к изображению: слот с обложкой и приёмом броска
        Font,      // строка — путь к шрифту
        IconName,  // строка — имя векторного значка движка
        Multiline, // строка в несколько строк
        Slider,    // число — ползунок в границах Min..Max
        Angle,     // число — градусы
        Anchor,    // vec2 0..1 — сетка якорей 3x3 плюс произвольная точка
    };

    const char* Key = nullptr;   // ключ в файле — не меняется никогда
    const char* Label = nullptr; // подпись в редакторе (через SAGE_UI_TEXT)
    Kind Type = Kind::Float;
    size_t Offset = 0;           // смещение поля внутри компонента (offsetof)
    float Min = 0.0f;
    float Max = 0.0f;            // Max <= Min — границы не заданы
    const char* Tooltip = nullptr;
    const char* const* EnumNames = nullptr;
    int EnumCount = 0;
    Widget Editor = Widget::Auto;
    // Подгруппа внутри инспектора компонента: «Границы», «Тень», «Перенос».
    // Компонент из двадцати полей без подгрупп нечитаем, а разбивать его на
    // пять компонентов ради вида — врать про модель данных.
    const char* Group = nullptr;

    bool HasRange() const { return Max > Min; }
};

// Доступ к полю по таблице. Отдельными помощниками, потому что читают их трое
// (запись, чтение, редактор) и приведение типов должно быть записано ОДИН раз.
template <class T> T& UIFieldAs(void* data, const UIProperty& p) {
    return *reinterpret_cast<T*>(static_cast<char*>(data) + p.Offset);
}
template <class T> const T& UIFieldAs(const void* data, const UIProperty& p) {
    return *reinterpret_cast<const T*>(static_cast<const char*>(data) + p.Offset);
}

// --- Числовой доступ для анимации и связывания данных ------------------------
//
// Анимации и внешним источникам данных (§47, §48) не нужен полный доступ к
// компоненту: им нужно «положить число в свойство» и «прочитать число из
// свойства». Отдельная пара функций, потому что иначе каждая анимация писала бы
// свой switch по типам — то есть ещё один список, который разъедется.
//
// component — какая по счёту компонента у vec2/vec4/цвета (0..3), для Float и
// Int игнорируется.
bool UIPropertyGetFloat(const void* data, const UIProperty& p, int component, float& out);
bool UIPropertySetFloat(void* data, const UIProperty& p, int component, float value);

// Сколько числовых компонент у свойства (Float/Int — 1, Vec2 — 2, Vec4/Color —
// 4, Edges/Corners — 4). 0 — свойство не числовое и анимировать его нельзя.
int UIPropertyFloatCount(const UIProperty& p);

} // namespace sage::ui
