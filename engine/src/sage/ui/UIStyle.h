#pragma once
#include <string>

#include <entt/entt.hpp>
#include <nlohmann/json.hpp>

class Scene;

// ---------------------------------------------------------------------------
// СТИЛЬ ЭЛЕМЕНТА — ФАЙЛ (.sageuistyle), а не копия настроек в каждом элементе.
//
// Двадцать кнопок меню, раскрашенных по одной, — это двадцать мест, где цвет
// надо поменять при каждой правке, и одна обязательно останется старой.
// Стиль хранит ВИД типа — подложку и её виды состояний, картинки, девятину,
// шрифт, цвета, — и элемент ссылается на него путём (Element::Style). Правка
// файла меняет все элементы, которые на него ссылаются, прямо в открытой
// сцене.
//
// СОДЕРЖИМОЕ В СТИЛЬ НЕ ПОПАДАЕТ: текст надписи, значение ползунка, действие
// кнопки, связи событий помечены в таблице полей как Content (UIPart.h), и
// применение стиля их не трогает. Иначе «стиль кнопки» переписал бы подписи
// всем кнопкам меню.
//
// Формат: {"sage_ui_style": 1, "type": "Button", "parts": {"fill": {...}, ...}}
// — те же ключи частей и полей, что в сцене.
// ---------------------------------------------------------------------------
namespace sage::ui {

constexpr const char* kStyleExtension = ".sageuistyle";

// Вид элемента в JSON стиля: все части элемента, без полей-содержимого.
nlohmann::json CaptureStyle(const entt::registry& reg, entt::entity e);

// Применить стиль к элементу. Трогает только ТЕ части, что у элемента уже
// есть (стиль кнопки на надписи не добавит ей подложку), и только поля вида.
void ApplyStyle(const nlohmann::json& style, entt::registry& reg, entt::entity e);

bool SaveStyleFile(const std::string& path, const nlohmann::json& style, std::string* err = nullptr);
bool LoadStyleFile(const std::string& path, nlohmann::json& out, std::string* err = nullptr);

// Раз в кадр: стили, чей файл изменился (или ещё не применялся к элементу),
// ложатся на свои элементы. Файл перечитывается не чаще раза в полсекунды —
// спрашивать диск на каждом кадре о каждом стиле незачем.
void ApplyStyles(Scene& scene);

// Забыть прочитанное (смена проекта): тот же путь в другом проекте — другой файл.
void ClearStyleCache();

} // namespace sage::ui
