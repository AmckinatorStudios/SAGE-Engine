#include "sage/ui/components/Layout.h"

// ---------------------------------------------------------------------------
// ИНТЕРФЕЙС — КОНТЕКСТ, А НЕ ЭЛЕМЕНТ.
//
// ЧТО БЫЛО НЕ ТАК. Элементы интерфейса жили в сцене россыпью: корнем считался
// любой прямоугольник, у которого нет родителя-прямоугольника. Пока интерфейс
// в сцене был один, это работало. Как только их становилось два — меню паузы и
// HUD, — они оказывались В ОДНОМ дереве редактора: элементы обоих вперемешку,
// без границы между ними. Верстать один, не задевая другой, можно было только
// пряча чужие объекты глазом в иерархии, то есть правя СЦЕНУ ради того, чтобы
// посмотреть на один экран.
//
// Причина не в панели, а в том, что у интерфейса не было СОБСТВЕННОГО узла:
// «интерфейс» существовал только как наблюдение «эти элементы лежат рядом».
//
// ЧТО ТЕПЕРЬ. Интерфейс — объект сцены с этим компонентом. Он ничего не рисует
// сам: он ГРАНИЦА. Элементы принадлежат тому интерфейсу, внутри которого лежат
// (ближайший предок с этим компонентом, см. InterfaceOf), и никакому другому.
// Из этого следует всё остальное:
//
//   • в сцене их может быть сколько угодно, и они не знают друг о друге;
//   • редактор вёрстки работает с ОДНИМ выбранным — дерево, холст и правки
//     относятся только к нему;
//   • опорное разрешение и порядок показа — свойства ИНТЕРФЕЙСА, а не первого
//     попавшегося его элемента;
//   • спрятать интерфейс целиком — одно поле, а не обход всех его элементов.
//
// В обычном пространстве сцены это рядовой объект: его видно в иерархии, он
// двигается, копируется и ложится в префаб, как всё остальное.
// ---------------------------------------------------------------------------
namespace sage::ui {

struct InterfaceComponent {
    // Рисуется ли интерфейс. Выключенный не показывается и не ловит мышь —
    // целиком, со всеми своими элементами.
    bool Visible = true;

    // Порядок МЕЖДУ интерфейсами: HUD под меню паузы, меню под диалогом.
    // Раньше это число жило в Canvas корневого элемента — то есть у элемента, а
    // не у интерфейса, и два корня одного интерфейса могли спорить о нём.
    int SortOrder = 0;

    // Ловит ли интерфейс мышь. Нужен там, где интерфейс показывают, но им не
    // пользуются: заставка, титры, подсказка поверх игры.
    bool ReceivesInput = true;

    // Опорное разрешение и способ пересчёта — свойство ВСЕГО интерфейса:
    // верстают под один размер экрана весь экран, а не каждый его корень
    // по-своему.
    sage::ui::Canvas Canvas;
};

} // namespace sage::ui
