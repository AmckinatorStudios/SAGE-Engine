#pragma once
#include "sage/ui/UIAnchor.h"
#include "sage/ui/UIInteraction.h"
#include <entt/entt.hpp>
#include <vector>

class Scene;
class UIRenderer;

// ---------------------------------------------------------------------
// Система интерфейса сцены: рисует сущности с компонентами интерфейса (см.
// scene/Components.h) поверх кадра и отвечает на «что под точкой?».
//
//   • Вёрстка: якорь + отступ внутри РОДИТЕЛЯ (HierarchyComponent) — вложенные
//     панели ведут себя как контейнеры; корневые элементы якорятся к экрану.
//   • Порядок: корни и группы детей сортируются по Layer (стабильно, при
//     равенстве — по Id), дети рисуются поверх родителя.
//   • Маски: ClipChildren обрезает всё поддерево прямоугольником элемента
//     (аппаратные ножницы, вложенные маски пересекаются).
//
// Использование (рантайм/редактор):
//   ui.Begin(w, h);
//   sage::ui::DrawSceneUI(scene, ui, w, h);
//   ui.End();
// ---------------------------------------------------------------------
namespace sage::ui {

// Есть ли у сущности интерфейсная часть.
//
// Обязательная часть ровно одна — прямоугольник (sage::ui::Element): без него
// элемент негде рисовать, а всё остальное (подложка, надпись, картинка)
// необязательно и добавляется по надобности. Отдельная функция, а не
// all_of<Element> по месту, потому что «что считается элементом» — это
// правило, и оно должно быть записано один раз.
bool IsElement(const entt::registry& reg, entt::entity e);

// --- ЧЕЙ ЭТО ЭЛЕМЕНТ --------------------------------------------------------
//
// Интерфейс — объект с InterfaceComponent (sage/ui/components/InterfaceComponent.h);
// элемент принадлежит ближайшему такому предку. Правило записано ОДИН раз и
// здесь: по нему работают и отрисовка, и редактор, и «сколько их в сцене».
entt::entity InterfaceOf(Scene& scene, entt::entity element);

// Все интерфейсы сцены В ПОРЯДКЕ ПОКАЗА (SortOrder, при равенстве — по id).
std::vector<entt::entity> SortedInterfaces(Scene& scene);

// Корневые элементы интерфейса: те, у кого нет родителя-ЭЛЕМЕНТА внутри него.
// interfaceEntity == entt::null — элементы, не лежащие ни в одном интерфейсе
// (их собирают кодом и скриптом; в редакторе они показываются отдельной
// строкой списка, а не подмешиваются к чужому интерфейсу).
std::vector<entt::entity> InterfaceRoots(Scene& scene, entt::entity interfaceEntity);

// ПЕРЕНЕСТИ ЭЛЕМЕНТ под другого родителя ВНУТРИ его интерфейса.
//
// newParent — элемент или entt::null («в корень»). КОРЕНЬ — это САМ
// ИНТЕРФЕЙС, а не корень сцены: перенос «в корень» раньше отвязывал элемент
// от интерфейса целиком, и он пропадал из дерева вёрстки — со стороны это
// выглядело как «перетащил, и элемент исчез».
//
// Отказ (false, ничего не меняется): родитель — сам элемент или его потомок
// (элемент стал бы родителем самого себя), родитель — не элемент, родитель из
// ЧУЖОГО интерфейса.
bool CanReparent(Scene& scene, entt::entity element, entt::entity newParent);
bool ReparentElement(Scene& scene, entt::entity element, entt::entity newParent);

// ОБЛАСТЬ РАБОТЫ: весь интерфейс сцены или ровно один из них.
//
// Нужна редактору вёрстки: он показывает и правит ОДИН интерфейс, а игра
// рисует все. Один и тот же расчёт на оба случая — иначе редактор считал бы
// раскладку своей копией формул и отставал от движка (ровно это и было с
// масштабом холста).
struct UIScope {
    bool Limited = false;                  // false — всё, что есть в сцене
    entt::entity Interface = entt::null;   // какой именно (null — «без интерфейса»)

    static UIScope All() { return {}; }
    static UIScope Only(entt::entity interfaceEntity) { return {true, interfaceEntity}; }
    bool Accepts(entt::entity owner) const { return !Limited || owner == Interface; }
};

// Прямоугольник элемента внутри родителя считает sage::ui::Resolve (UI.h) —
// чистая математика по его Element, без ECS и без GL.

// Рисует весь UI сцены. Вызывать между ui.Begin() и ui.End().
void DrawSceneUI(Scene& scene, UIRenderer& ui, int screenW, int screenH,
                 const UIScope& scope = UIScope::All());

// Один шаг интерактива: подсветка под курсором, нажатие, фокус, набор текста,
// перетаскивание ползунков. Вызывать РАНЬШЕ игровой логики кадра — по
// результату (UIInputResult) игра решает, доставать ли ей тот же щелчок.
//
// Отдельно от DrawSceneUI намеренно: рисовать интерфейс может и тот, кто не
// даёт ему ввод (превью в редакторе, скриншот), а обрабатывать ввод надо ровно
// один раз за кадр, даже если панелей с картинкой две.
UIInputResult UpdateSceneUI(Scene& scene, const UIInputState& input, int screenW, int screenH,
                            const UIScope& scope = UIScope::All());

// Прямоугольник элемента В ЭКРАННЫХ ПИКСЕЛЯХ — ровно тот, в котором его
// рисуют.
//
// НУЖЕН РЕДАКТОРУ, И ВОТ ПОЧЕМУ ИМЕННО ОТСЮДА. Редактор вёрстки рисует рамки
// поверх кадра и ловит по ним мышь; считать их своей копией формул нельзя —
// копия неизбежно отстаёт. Так и вышло: раскладка научилась переводить
// опорные единицы холста в пиксели экрана, а редактор продолжал считать по
// старому, и рамки разъехались с нарисованным интерфейсом тем сильнее, чем
// дальше масштаб холста от единицы. Один расчёт на отрисовку, попадание и
// редактор — единственный способ, чтобы они не расходились.
struct ElementRect {
    entt::entity Entity = entt::null;
    UIRect Rect{};          // в пикселях экрана (масштаб холста уже применён)
    UIRect Parent{};        // прямоугольник родителя, тоже в пикселях экрана
    // Масштаб холста этого элемента. Правки записываются в ОПОРНЫХ единицах
    // (Offset/Size хранятся в них), поэтому обратный ход — деление на него.
    float Scale = 1.0f;
    bool Visible = true;    // сам по себе, без учёта родителей
    bool InLayout = false;  // родитель раскладывает детей сам: тащить бесполезно
};

// Раскладка всей сцены в экранных пикселях. includeHidden — включать
// выключенные элементы (нужно редактору: иначе выключенный элемент нельзя
// найти и включить обратно).
std::vector<ElementRect> SolveSceneRects(Scene& scene, int screenW, int screenH,
                                         bool includeHidden,
                                         const UIScope& scope = UIScope::All());

// Верхний видимый элемент под экранной точкой (x, y): id сущности или -1.
// Учитывает Layer/порядок отрисовки (возвращается тот, кто нарисован поверх)
// и маски (точка вне маски не попадает в её поддерево). Для кнопок: игра
// сама решает, что делать по клику (см. Lua-биндинг GetUIElementAt).
int HitTest(Scene& scene, float x, float y, int screenW, int screenH,
            const UIScope& scope = UIScope::All());

} // namespace sage::ui
