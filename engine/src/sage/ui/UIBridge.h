#pragma once
#include <entt/entt.hpp>

#include "sage/ui/UI.h"

struct UIElementComponent;

// ---------------------------------------------------------------------------
// Мост между НАБОРОМ компонентов интерфейса и плоским описанием для отрисовки.
//
// ЗАЧЕМ ОН НУЖЕН. Данные интерфейса разделены на компоненты (Transform, Fill,
// Label, Image, Bar, Icon, Interactable...), и это правильно для сцены,
// инспектора, скриптов и запросов вида «все элементы с картинкой». Но САМОЙ
// ОТРИСОВКЕ нужно ровно обратное: один проход, где под рукой сразу и цвет
// подложки, и текст, и состояние нажатия — иначе на каждый примитив
// приходилось бы лезть в реестр за пятью компонентами.
//
// Поэтому плоская структура осталась — но как ВНУТРЕННЕЕ ОПИСАНИЕ КАДРА, а не
// как модель данных: её никто не хранит, не сохраняет в сцену и не правит в
// инспекторе. Compose собирает её на лету из компонентов, Decompose делает
// обратное — им пользуются миграция старых сцен и загрузка старых префабов.
//
// Заодно это защита от визуальных регрессий: отрисовка не переписывалась
// вместе с моделью данных, она получает те же поля, что и раньше.
// ---------------------------------------------------------------------------
namespace sage::ui {

// Собрать плоское описание элемента из его компонентов.
UIElementComponent Compose(const entt::registry& reg, entt::entity e);

// Разложить старый компонент на новые. Существующие компоненты перезаписываются.
void Decompose(const UIElementComponent& flat, entt::registry& reg, entt::entity e);

// Есть ли у сущности интерфейсная часть (обязательный Transform).
bool IsElement(const entt::registry& reg, entt::entity e);

} // namespace sage::ui
