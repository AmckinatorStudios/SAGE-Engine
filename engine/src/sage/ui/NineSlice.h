#pragma once
#include <string>
#include <vector>

#include <glm/glm.hpp>

// ---------------------------------------------------------------------------
// ДЕВЯТИНА («9-slice») — КАК РАСТЯГИВАТЬ КАРТИНКУ-РАМКУ.
//
// Панель из набора интерфейса нарисована как 48x48 с уголками по 8 пикселей.
// Растянуть её на 300x120 обычным квадом нельзя: углы размажутся вместе с
// серединой, и от рисунка ничего не останется. Девятина режет картинку на
// девять кусков: углы не тянутся вовсе, края тянутся по одной оси, середина —
// по обеим.
//
// ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ТИП, А НЕ ЧЕТЫРЕ ЧИСЛА В КОМПОНЕНТЕ.
//
// 1. ОПИСАНИЕ ОДНО, А ПОЛЬЗОВАТЕЛЕЙ МНОГО. Рамку «панель из набора Kenney»
//    используют десяток элементов интерфейса. Пока это четыре числа в каждом,
//    поправить нарезку значит найти и поправить десять мест — и одно
//    обязательно останется старым. `.sage9` рядом с картинкой описывает нарезку
//    ОДИН раз, элементы на неё ссылаются.
// 2. РАСТЯГИВАНИЕ — НЕ ЕДИНСТВЕННЫЙ СПОСОБ. У пиксель-арта растянутый край
//    превращается в мыло: правильный ответ — ПОВТОРИТЬ кусок, а не растянуть.
//    Это свойство картинки, а не элемента, который её показывает.
// 3. ГЕОМЕТРИЮ МОЖНО ПРОВЕРИТЬ. Раскладка девяти кусков — чистый счёт, и здесь
//    она отделена от рисования: `Solve` не знает ни про текстуры, ни про GL, и
//    проверяется обычным модульным тестом (tests/test_nineslice.cpp). Пока она
//    жила внутри функции отрисовки, единственным способом заметить ошибку был
//    взгляд на экран.
// ---------------------------------------------------------------------------
namespace sage::ui {

// Как заполняется кусок, который тянется.
enum class SliceFill {
    // Растянуть. Годится для гладких рамок и градиентов.
    Stretch,
    // Повторить куском исходного размера. Единственный правильный ответ для
    // пиксель-арта и любого узора: растянутый на 300 пикселей орнамент из 16
    // превращается в мыло, повторённый — остаётся орнаментом.
    Tile,
};

// --- Описание нарезки --------------------------------------------------------
//
// Хранится в пикселях ИСХОДНИКА, а не в долях: в наборе спрайтов уголок описан
// как «8 пикселей», и переводить это в 0.1666 должен движок, а не человек.
struct NineSlice {
    // Неподвижные поля: слева, сверху, справа, снизу.
    float Left = 0.0f, Top = 0.0f, Right = 0.0f, Bottom = 0.0f;

    SliceFill CenterFill = SliceFill::Stretch;
    SliceFill EdgeFill = SliceFill::Stretch;

    // Рисовать ли середину. У рамки-обводки середины нет: сквозь неё видно то,
    // что под элементом, и залитый центр закрыл бы это. Отдельный флаг, а не
    // «нулевая середина»: размер середины считается из полей, и обнулить его,
    // не сломав края, нельзя.
    bool DrawCenter = true;

    bool Empty() const { return Left <= 0.0f && Top <= 0.0f && Right <= 0.0f && Bottom <= 0.0f; }

    glm::vec4 Border() const { return {Left, Top, Right, Bottom}; }
    void SetBorder(const glm::vec4& b) { Left = b.x; Top = b.y; Right = b.z; Bottom = b.w; }

    // --- Файл описания (.sage9 рядом с картинкой) ---------------------------
    //
    // JSON, как все текстовые форматы движка. Отсутствие файла — не ошибка:
    // картинка без нарезки рисуется целиком, и это нормальный случай.
    std::string ToJsonString() const;
    static bool FromJsonString(const std::string& text, NineSlice& out, std::string& err);
    bool SaveFile(const std::string& path, std::string& err) const;
    static bool LoadFile(const std::string& path, NineSlice& out, std::string& err);
    // Путь описания для картинки: "panel.png" -> "panel.png.sage9". Сайдкаром,
    // а не заменой расширения: рядом могут лежать panel.png и panel.jpg, и
    // одно описание на двоих было бы неверным для обоих.
    static std::string SidecarPath(const std::string& imagePath);
};

// --- Раскладка ---------------------------------------------------------------

// Один кусок: откуда в исходнике и куда на экране. Оба прямоугольника — в
// пикселях (исходника и экрана соответственно).
struct SliceQuad {
    float DstX = 0.0f, DstY = 0.0f, DstW = 0.0f, DstH = 0.0f;
    float SrcX = 0.0f, SrcY = 0.0f, SrcW = 0.0f, SrcH = 0.0f;
};

// Что нужно знать, чтобы разложить куски.
struct SliceRequest {
    // Кусок исходника, который режем (весь файл — просто его размеры).
    float SrcX = 0.0f, SrcY = 0.0f, SrcW = 0.0f, SrcH = 0.0f;
    // Прямоугольник на экране, в который вписываем.
    float DstX = 0.0f, DstY = 0.0f, DstW = 0.0f, DstH = 0.0f;
    // Во сколько раз пиксель исходника крупнее экранного. Поля умножаются на
    // него: рамка в 8 пикселей на удвоенном масштабе занимает 16 экранных.
    float Scale = 1.0f;
};

// Считает куски. Возвращает от 0 до 9 штук: вырожденные (нулевой ширины или
// высоты) и выключенная середина не попадают в список вовсе — рисовать их
// нечем, а пустой квад в буфере стоит столько же, сколько настоящий.
//
// Если поля не влезают в запрошенный размер (элемент уже собственных углов),
// они ужимаются ПРОПОРЦИОНАЛЬНО: иначе куски наложились бы друг на друга и
// рамка вывернулась бы наизнанку.
std::vector<SliceQuad> Solve(const NineSlice& slice, const SliceRequest& req);

// Минимальный размер, в котором рамка ещё не ужимается: сумма полей по каждой
// оси с учётом масштаба. Редактору он нужен, чтобы не дать утащить ползунок
// предпросмотра в размер, где рамка перестаёт быть собой.
glm::vec2 MinimumSize(const NineSlice& slice, float scale);

// Догадка о нарезке по самой картинке: ищет по краям полосы, которые НЕ меняются
// вдоль своей оси, — ровно то, что человек и назвал бы уголком. Пиксели
// передаются RGBA восемью битами на канал.
//
// Догадка, а не ответ: рамку с градиентом угадать нельзя, и редактор показывает
// результат как ПРЕДЛОЖЕНИЕ, которое видно и можно поправить. Но для честного
// набора спрайтов она попадает точно, и это избавляет от самого муторного —
// считать пиксели по увеличенной картинке.
bool GuessBorder(const unsigned char* rgba, int width, int height, NineSlice& out);

// То же по ФАЙЛУ картинки. Здесь, а не в редакторе: разбор картинки —
// единственное, что редактору пришлось бы для догадки завести у себя, и завёл
// бы он второй декодер рядом с движковым.
bool GuessBorderFromFile(const std::string& imagePath, NineSlice& out);

} // namespace sage::ui
