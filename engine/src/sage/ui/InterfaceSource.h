#pragma once
#include <string>

#include <entt/entt.hpp>

class Scene;

// ---------------------------------------------------------------------------
// ИНТЕРФЕЙС ИЗ ФАЙЛА В СЦЕНЕ.
//
// В сцене интерфейс — ОДИН объект (InterfaceComponent с путём Source), а его
// элементы живут в файле .sageui и правятся в пространстве «Интерфейс». Чтобы
// их рисовала, раскладывала и нажимала та же система, что и всё остальное,
// содержимое файла РАЗВОРАЧИВАЕТСЯ под объектом — сущностями с меткой
// InterfaceInstanceTag:
//
//   • в файл сцены они не пишутся (SceneSerializer их пропускает): описание
//     экрана одно — в его файле;
//   • в иерархии сцены не показываются: интерфейс — одна строка без стрелки;
//   • правка файла (сохранение в пространстве «Интерфейс») доходит до каждой
//     сцены сама: версия файла сменилась — копия разворачивается заново.
//
// Скрипт во время игры работает с развёрнутыми элементами как с обычными
// объектами: находит по имени, меняет текст и значения.
// ---------------------------------------------------------------------------
namespace sage::ui {

// Метка: сущность — часть развёрнутого из файла интерфейса, а не объект сцены.
struct InterfaceInstanceTag {};

// Привести развёрнутые интерфейсы сцены в соответствие их файлам: развернуть
// новые, развернуть заново изменившиеся, убрать копии у тех, чей Source стал
// пустым. Дёшево, если ничего не менялось (файл проверяется не чаще двух раз
// в секунду). Зовётся перед отрисовкой и вводом интерфейса и после чтения
// сцены.
void SyncInterfaceSources(Scene& scene);

// Часть ли развёрнутого интерфейса (сама или кто-то из предков).
bool IsInstancePart(const Scene& scene, entt::entity e);

// Забыть прочитанные файлы: следующая синхронизация прочитает их заново.
// Нужна тестам и смене проекта (тот же путь — другой файл).
void ClearInterfaceSourceCache();

// Расширение файла интерфейса.
constexpr const char* kInterfaceExtension = ".sageui";

} // namespace sage::ui
