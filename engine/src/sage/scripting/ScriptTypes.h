#pragma once
#include <string>
#include <vector>

#include "sage/vars/Table.h"

// ---------------------------------------------------------------------------
// СЛОВАРЬ СКРИПТИНГА, НЕ ЗНАЮЩИЙ НИ ОДНОГО ЯЗЫКА.
//
// Здесь описано то, о чём движок разговаривает со ЛЮБЫМ скриптом: какие бывают
// события жизненного цикла, как выглядит ошибка выполнения, что такое
// экземпляр скрипта и его публичные поля. Ни Lua, ни sol2, ни какого-либо
// другого рантайма в этом заголовке нет и быть не должно — иначе «добавить C#»
// означало бы переписать ECS, компоненты и инспектор, которые включают его
// транзитивно.
//
// Публичные поля НЕ заводят своего типа: это те же sage::vars::Value/Table, на
// которых уже держатся инспектор, сериализация сцены и связи событий. Второй
// тип значения означал бы второй инспектор и второй формат файла, которые
// однажды разойдутся молча.
// ---------------------------------------------------------------------------
namespace sage::scripting {

// Событие жизненного цикла. Порядок — порядок кадра: Start, затем Update,
// FixedUpdate идёт своим постоянным шагом, LateUpdate — после всех Update.
enum class Hook {
    Start = 0,
    Update,
    FixedUpdate,
    LateUpdate,
    OnEnable,
    OnDisable,
    OnDestroy,
    OnCollisionEnter,
    OnCollisionExit,
    OnTriggerEnter,
    OnTriggerExit,
    OnAnimationEvent,
    // Каждый шаг, пока гость в зоне (кроме шага входа — тот уже OnTriggerEnter).
    // В конце списка: номера хуков старше него не сдвигаются.
    OnTriggerStay,
    Count
};

// Имя хука ровно в том написании, в котором его объявляет скрипт. Одно место:
// разъехавшиеся написания дают хук, который никогда не зовётся, — и молча.
const char* HookName(Hook hook);

// --- Ошибка выполнения -------------------------------------------------------
//
// Файл и СТРОКА отдельными полями, а не одной строкой текста: консоль редактора
// обязана открыть файл на нужной строке, а не показать человеку текст, из
// которого он сам выковыривает номер глазами.
struct ScriptError {
    std::string File;       // путь к файлу скрипта, как его видит проект
    int Line = 0;           // строка; 0 — неизвестна
    std::string Message;    // «attempt to call nil value 'Move'»
    std::string Traceback;  // стек вызовов языка, если рантайм его дал

    bool Empty() const { return Message.empty(); }
    void Clear() { File.clear(); Line = 0; Message.clear(); Traceback.clear(); }

    // Человеческий вид: "player.lua:42: attempt to call nil value 'Move'".
    std::string Format() const;
};

// Дескриптор живого экземпляра скрипта внутри бэкенда. Номер, а не указатель:
// бэкенд волен хранить экземпляры как угодно (таблица Lua, объект CLR), и
// отдавать наружу сырую память чужого рантайма — прямой путь к падению после
// сборки мусора.
using InstanceId = int;
inline constexpr InstanceId kInvalidInstance = 0;

// Исходник скрипта, прочитанный ХОЗЯИНОМ (через vfs — диск или .sagepak).
// Бэкенд файлов не читает: в собранной игре файлов на диске нет, и каждый
// язык, читающий диск сам, сломался бы на сборке по-своему.
struct ScriptSource {
    std::string Path;   // как записано в сцене: "assets/scripts/player.lua"
    std::string Text;   // содержимое
    long long Stamp = 0; // время правки файла; 0 — файла на диске нет (пакет)
};

// --- Часы кадра --------------------------------------------------------------
//
// То, что скрипт видит как Time.deltaTime/fixedDeltaTime/time/timeScale. Живёт
// у системы скриптинга, а не внутри языка: две реализации времени (одна в Lua,
// другая в C#) разошлись бы на первой же паузе, и игра на двух языках шла бы с
// двумя разными «сейчас».
struct ScriptClock {
    float Delta = 0.0f;       // длительность прошлого кадра, УЖЕ с масштабом
    float FixedDelta = 1.0f / 60.0f; // постоянный шаг FixedUpdate
    float Time = 0.0f;        // сколько идёт игра (масштабированное время)
    float Unscaled = 0.0f;    // то же без масштаба — интерфейсу и отладке
    float Scale = 1.0f;       // замедление/ускорение; 0 — пауза
};

} // namespace sage::scripting
