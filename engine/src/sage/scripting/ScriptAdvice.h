// ---------------------------------------------------------------------------
// ОБЪЯСНЕНИЕ ОШИБКИ СКРИПТА: что случилось, почему, как исправить, пример.
//
// Lua говорит «attempt to index a nil value (field 'target')» — и это всё.
// Новичок не знает, что такое «index» и почему «nil»; опытный — знает, но
// тратит минуту, чтобы найти, какое из трёх «target» в строке пустое. Здесь
// сообщение языка разбирается на части и переводится в человеческое:
//
//   Поле «target» пустое (nil), а у него берут значение.
//   Как исправить: проверьте, что target задан, прежде чем к нему обращаться.
//   Пример:  if self.target then self.target.position = p end
//
// По возможности пример — это ВАША строка, исправленная (дописанный then,
// исправленная опечатка в имени), а не абстрактный шаблон из справочника.
// «Возможно, имелось в виду» ищется среди имён самого файла и хуков движка:
// опечатка почти всегда — в имени, которое рядом уже написано правильно.
// ---------------------------------------------------------------------------
namespace sage::scripting {

struct Advice {
    std::string Detail;               // почему — понятным языком
    std::vector<std::string> Hints;   // как исправить
    std::string Example;              // исправленная строка или образец
};

// Разобрать ошибку (сообщение Lua или диагностику SAGE Lua). source —
// текст файла, в котором ошибка (может быть пустым: тогда без своей строки).
Advice Explain(const ScriptError& err, const std::string& source);

// Ближайшее по написанию имя среди имён файла и хуков движка (расстояние
// правки не больше 2). Пусто — похожего нет.
std::string ClosestName(const std::string& wrong, const std::string& source);

// Проблема для реестра (Problems.h) — со строками кода вокруг ошибки.
sage::Problem ToProblem(const ScriptError& err, const std::string& source);

} // namespace sage::scripting
