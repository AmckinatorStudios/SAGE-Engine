-- =============================================================================
--  04_force_thruster.lua — реактивный ранец: пока зажат Space, тянет тело
--  вверх ПОСТОЯННОЙ СИЛОЙ.
--
--  ЧТО ПРОВЕРЯЕТ: AddForce действует ВЕСЬ следующий шаг физики, а её импульс
--  делится по внутренним подшагам, поэтому разгон одинаковый на любой частоте
--  кадров. Смените лимит кадров редактора (или просто сравните разгон на
--  быстром и медленном компьютере) — высота набора за одну и ту же секунду
--  должна совпадать.
--
--  ЧТО НУЖНО, ЧТОБЫ ЗАРАБОТАЛО: объект с RigidBody (Dynamic, масса 1-3 кг) +
--  Collider — через меню Object -> Physics Cube. Можно поставить на пол или
--  подвесить в воздухе.
--
--  УПРАВЛЕНИЕ: держать Space — тяга вверх; отпустить — свободное падение.
-- =============================================================================

thrust = 14.0   -- ньютонов

function OnStart(entity)
    Debug.Log("[04_force_thruster] " .. entity.Name .. ": держите Space для тяги вверх.")
end

function OnUpdate(entity, dt)
    if Input.IsKeyDown("Space") then
        AddForce(entity, Vec3(0.0, thrust, 0.0))
    end
end
