#pragma once
#include <cstddef>
#include <functional>
#include <string>

// ---------------------------------------------------------------------------
// EditorRecovery — ЧТО ОСТАЛОСЬ ОТ ПРОШЛОГО ЗАПУСКА и как не потерять этот.
//
// Три вещи, у которых один повод: редактор может умереть посреди работы.
//   • АВТОСОХРАНЕНИЕ пишет копию сцены раз в минуту — В ОТДЕЛЬНЫЙ ФАЙЛ, а не
//     поверх сцены: страховка, затирающая оригинал, страховкой не является.
//   • ФАЙЛ ВОССТАНОВЛЕНИЯ, найденный при запуске, — единственный след прошлого
//     запуска: спрашивать некого, тот процесс уже мёртв.
//   • ОТЧЁТ О ПАДЕНИИ рядом с редактором говорит, ЧЕМ прошлый запуск кончился.
//
// ПОЧЕМУ ОТДЕЛЬНО. Десяток полей этого сюжета лежал в EditorLayer вперемешку с
// проектом, панелями, Play-режимом и плагинами, а связь между ними — «сначала
// показать отчёт, потом предложить восстановление», «отказ удаляет файл, иначе
// редактор будет спрашивать до конца времён», «неудача автосохранения выключает
// его, чтобы не долбить диск каждую минуту» — держалась комментариями в трёх
// разных файлах. Здесь весь сюжет читается целиком.
//
// Рисование окон осталось у слоя: модалки — это ImGui и переводы, а этот класс
// про состояние и файлы.
// ---------------------------------------------------------------------------
class EditorRecovery {
public:
    // Ищет при запуске: отчёт о падении и файл восстановления. Зовётся один
    // раз, сразу после установки обработчика падений — если прошлый запуск
    // умер, человек должен узнать об этом первым делом, а не после того, как
    // заново соберёт сцену.
    void ScanOnStartup();

    // --- Автосохранение -----------------------------------------------------
    //
    // save возвращает false, если записать не вышло: тогда автосохранение
    // ВЫКЛЮЧАЕТСЯ до конца сеанса. Молчащее автосохранение хуже отсутствующего
    // — на него рассчитывают, — но и долбить диск каждую минуту без надежды не
    // за чем.
    //
    // Зовётся каждый кадр; active — идёт ли сейчас Play (тогда не сохраняем:
    // сцена живёт по игровым правилам, и записывать середину игры вместо
    // уровня незачем), dirty — есть ли несохранённые правки.
    void Tick(float dt, bool dirty, bool inPlayMode,
              const std::function<bool(const std::string& path)>& save);

    bool AutosaveEnabled() const { return m_interval > 0.0f; }
    const std::string& LastAutosave() const { return m_last; }
    // Выключить автосохранение (самопроверка, прогон без человека).
    void DisableAutosave() { m_interval = 0.0f; }

    // --- Файл восстановления ------------------------------------------------
    bool HasRecoveryFile() const { return m_recoveryPrompt; }
    const std::string& RecoveryFile() const { return m_recoveryFile; }
    // Предложение показывается ОДИН раз — каким бы ни был ответ.
    void DismissRecovery() { m_recoveryPrompt = false; }
    // Отказ удаляет файл, иначе редактор спрашивал бы про него до конца времён.
    void DeleteRecoveryFile();

    // --- Отчёт о прошлом падении -------------------------------------------
    bool HasCrashReport() const { return m_crashPrompt; }
    const std::string& CrashReportPath() const { return m_crashPath; }
    // Текст неконстантной ссылкой: ImGui показывает его полем ввода только для
    // чтения, а оно требует изменяемый буфер.
    std::string& CrashReportText() { return m_crashText; }
    size_t CrashReportCount() const { return m_crashCount; }
    void DismissCrashReport() { m_crashPrompt = false; }
    void DeleteCrashReport();

    // Имя файла, в который пишется автосохранение. Одно на весь редактор: его
    // ищет ScanOnStartup следующего запуска, и разойтись этим двум местам
    // значило бы никогда не предложить восстановление.
    static constexpr const char* kAutosaveFile = "sage-autosave.sage";
    // Аварийное сохранение пишет обработчик падений.
    static constexpr const char* kEmergencyFile = "sage-recovered.sage";

private:
    float m_interval = 60.0f;  // 0 — выключено
    float m_timer = 0.0f;
    std::string m_last;

    std::string m_recoveryFile;
    bool m_recoveryPrompt = false;

    std::string m_crashPath;
    std::string m_crashText;
    size_t m_crashCount = 0;
    bool m_crashPrompt = false;
};
