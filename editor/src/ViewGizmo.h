#pragma once
#include <imgui.h>

#include <glm/glm.hpp>

class Camera;

// ---------------------------------------------------------------------------
// ГИЗМО ОСЕЙ в углу вьюпорта: три цветных шарика X/Y/Z и три тёмных напротив.
//
// ЗАЧЕМ. В перспективе, покрутив камеру десяток секунд, перестаёшь понимать,
// где север: «спереди» у сцены не написано, а пол симметричен. Узнать, куда
// смотришь, можно было только по памяти — или подвигав камеру и посмотрев, что
// поехало. Шарики отвечают на это постоянно и без действий: красный вправо —
// значит +X справа.
//
// И ЭТО ЖЕ ОРГАН УПРАВЛЕНИЯ. Щелчок по шарику ставит камеру НА эту ось — вид
// строго спереди, сверху, сбоку, — а перетаскивание крутит её вокруг той же
// точки, вокруг которой смотрели. Это то, чем поворачивают вид везде: в
// Blender, в Unity, в CAD. Без него единственным способом встать ровно было
// «крутить правой кнопкой, пока не станет похоже», а строго ровно так не
// встаёшь никогда.
//
// ТОЧКА ВРАЩЕНИЯ — НЕ КАМЕРА, А ТО, НА ЧТО СМОТРЯТ. Поворот вокруг самой камеры
// («оглядеться») на гизмо осей смотрелся бы правильно и делал бы не то: предмет
// уезжал бы из кадра. Поэтому pivot передаётся снаружи — вьюпорт знает, что
// сейчас в центре внимания.
// ---------------------------------------------------------------------------
namespace sage::editor::viewgizmo {

struct State {
    bool Dragging = false;   // крутят гизмо прямо сейчас
    // Переход к выбранной оси — ПЛАВНЫЙ. Мгновенный скачок читается как «вид
    // подменили»: человек теряет связь между тем, что было, и тем, что стало,
    // и заново ищет глазами свой объект. Четверти секунды хватает, чтобы глаз
    // проследил поворот.
    bool Animating = false;
    float FromYaw = 0.0f, FromPitch = 0.0f;
    float ToYaw = 0.0f, ToPitch = 0.0f;
    float Time = 0.0f;       // 0..1
    glm::vec3 Pivot{0.0f};   // вокруг чего крутим на время перехода
};

// Рисует гизмо в правом верхнем углу прямоугольника вида и правит камеру.
// pivot — точка, вокруг которой крутить (обычно центр внимания вьюпорта).
// Возвращает true, если мышь занята гизмо: тогда вьюпорт не должен ни выбирать
// объекты, ни начинать рамку выделения.
//
// dl — список отрисовки ТОГО ОКНА, в котором лежит картинка сцены. Не «список
// текущего окна»: картинка вьюпорта живёт в дочернем окне ImGui, а дочерние
// окна выводятся ПОСЛЕ родительского. Гизмо, поданное в список родителя,
// рисовалось под кадром сцены — то есть не было видно вовсе.
bool Draw(ImDrawList* dl, State& state, Camera& camera, const ImVec2& viewMin,
          const ImVec2& viewMax, const glm::vec3& pivot, float dt);

} // namespace sage::editor::viewgizmo
