// ---------------------------------------------------------------------------
// ЦВЕТ С ЭКРАНА — ЗА ПРЕДЕЛАМИ ОКНА РЕДАКТОРА.
//
// Пипетка, которая видит только своё окно, отвечает не на тот вопрос: цвет
// берут с референса в браузере, со скриншота в просмотрщике, из чужой
// палитры. Кадр редактора этого не содержит — нужен экран целиком, а его
// отдаёт только система:
//   • Windows — GDI (GetDC(NULL) + GetPixel), клавиши — GetAsyncKeyState;
//   • Linux X11 — XGetImage корневого окна, кнопки — XQueryPointer. libX11
//     подгружается во время работы (dlopen), как это делает и сам GLFW:
//     редактор не получает новой зависимости при сборке и запускается там,
//     где X11 нет вовсе;
//   • Wayland запрещает читать чужие окна по замыслу — там глобальной
//     пипетки нет (GlobalAvailable() == false), работает только своё окно.
//
// Координаты — экранные, в пикселях. Цвет — sRGB 0..1, как его хранят поля
// цвета редактора и показывает hex.
// ---------------------------------------------------------------------------
namespace sage::editor::screencolor {

bool GlobalAvailable();
// Цвет под курсором мыши где угодно на экране. false — система не дала.
bool SampleAtCursor(float rgb[3], int* x = nullptr, int* y = nullptr);
// Кнопка мыши зажата где угодно, не только над окном (0 — левая, 1 — правая).
bool GlobalMouseDown(int button);
// Esc зажат (для отмены, когда фокус у чужого окна).
bool GlobalEscapeDown();

} // namespace sage::editor::screencolor
