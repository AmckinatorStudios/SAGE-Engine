#pragma once
#include <cstddef>
#include <functional>
#include <string>
#include <vector>

// ---------------------------------------------------------------------------
// EditorHistory — undo/redo редактора: стопка снимков сцены.
//
// Модель снимочная, а не покомандная: перед каждой мутацией сцена целиком
// сохраняется в строку, откат — загрузка строки обратно. Для редактора это
// оправдано: правок десятки видов (создание, удаление, перенос в иерархии,
// любое поле любого компонента), и обратную операцию для каждой пришлось бы
// писать и чинить отдельно.
//
// Со СЦЕНОЙ история не знакома — ей передают две функции: снять снимок и
// применить снимок. Это не украшение: так история проверяется модульным
// тестом без сцены, сериализатора и графики (tests/test_editorstate.cpp), а
// раньше добраться до неё можно было только запустив редактор целиком.
// Заодно исчезла причина держать стопки полями EditorLayer.
//
// В Play-режиме история ВЫКЛЮЧЕНА (Enabled(false)): правки там эфемерны, Stop
// откатит их и так, а попавший в стопку снимок игровой сцены означал бы откат
// в состояние, которого в редактируемой сцене никогда не было.
// ---------------------------------------------------------------------------
class EditorHistory {
public:
    // Глубина стопки. Снимок сцены — это её полный JSON, и без потолка
    // история крупного проекта съедала бы память тем быстрее, чем крупнее
    // сцена. Сотня шагов назад — больше, чем помнит человек.
    static constexpr size_t kMaxEntries = 100;

    using CaptureFn = std::function<std::string()>;
    using RestoreFn = std::function<bool(const std::string&)>;

    EditorHistory(CaptureFn capture, RestoreFn restore)
        : m_capture(std::move(capture)), m_restore(std::move(restore)) {}

    // Включена ли история. Выключенная молча игнорирует всё, кроме запросов
    // состояния, — так Play-режим не обязан обходить каждый вызов у себя.
    void SetEnabled(bool enabled) { m_enabled = enabled; }
    bool Enabled() const { return m_enabled; }

    bool CanUndo() const { return !m_undo.empty(); }
    bool CanRedo() const { return !m_redo.empty(); }

    // Снимок «до мутации». Зовётся ПЕРЕД правкой. true — снимок лёг в стопку.
    bool Push();

    // Одна запись на всё перетаскивание ползунка или набор текста: состояние
    // «до» запоминается на активации виджета (Capture), в стопку уходит на
    // завершении правки (Commit). Без этой пары каждый кадр перетаскивания
    // давал бы свою запись, и Ctrl+Z отматывал бы по пикселю.
    void CapturePending();
    bool CommitPending();

    bool Undo();
    bool Redo();

    // Сцену заменили целиком (новая, открытие, смена проекта) — история
    // прежней сцены к ней неприменима.
    void Clear();

private:
    // Кладёт снимок в стопку отмен, срезая самый старый при переполнении, и
    // обрывает ветку повторов: после новой правки «вперёд» идти некуда.
    void PushSnapshot(std::string snapshot);

    CaptureFn m_capture;
    RestoreFn m_restore;

    std::vector<std::string> m_undo;
    std::vector<std::string> m_redo;
    std::string m_pending;   // состояние на момент CapturePending
    bool m_enabled = true;
};
