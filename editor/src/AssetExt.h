#pragma once
#include <cctype>
#include <filesystem>
#include <string>

// ---------------------------------------------------------------------------
// Расширение файла в НИЖНЕМ РЕГИСТРЕ, с точкой.
//
// Отдельным заголовком, потому что по расширению узнают ассет сразу в
// нескольких местах редактора: перетаскивание файла в окно, бросок во вьюпорт,
// назначение материала, панель ассетов. Пока это была локальная функция одного
// файла, каждое новое место заводило свою — и они расходились в мелочах, из-за
// которых «.SAGE» и «.sage» оказывались разными форматами. Имена файлов
// приходят от человека и от файловой системы, и регистр в них ничего не значит.
// ---------------------------------------------------------------------------
namespace sage::editor {

inline std::string ToLowerExt(const std::filesystem::path& p) {
    std::string ext = p.extension().string();
    for (char& c : ext) c = (char)std::tolower((unsigned char)c);
    return ext;
}

} // namespace sage::editor
