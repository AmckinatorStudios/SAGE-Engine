#pragma once
#include <filesystem>
#include <string>
#include <vector>

// ---------------------------------------------------------------------------
// ШАБЛОНЫ ПРОЕКТА — с чего начинается новый проект.
//
// ЗАЧЕМ. Кнопка «Создать проект» всегда делала ОДНО И ТО ЖЕ: папку, пустую
// сцену и демо-контент — пять кубов, три примитива, свет и худ. Для первого
// запуска это хорошо: видно, что движок работает. Для второго и всех
// последующих — нет: человек, начинающий свою игру, первым делом удаляет
// девять чужих объектов, и делает это каждый раз. Выбора «пустой» не было
// вовсе, а «начать с готового меню» — тем более.
//
// ШАБЛОН — ЭТО ДАННЫЕ, А НЕ ВЕТКА В ДИАЛОГЕ. Список ниже читают и диалог
// «Новый проект», и стартовое окно, и самопроверка редактора. Пока выбор жил
// булевым параметром withDemoContent, добавить третий вариант можно было
// только правкой всех трёх мест сразу — и они бы разъехались, как разъехался
// импорт материалов.
//
// Чего шаблон НЕ делает: он не пишет файлы на диск и не создаёт папок. Его
// дело — сказать, что положить в первую сцену; всё остальное у проекта одно и
// то же, и разное поведение здесь означало бы разные проекты по структуре.
// ---------------------------------------------------------------------------

// Что кладём в стартовую сцену. Перечисление, а не функция обратного вызова:
// сборку делает EditorLayer (у него есть помощники для примитивов, света и
// камеры), а шаблон — это ВЫБОР, и он должен сохраняться, сравниваться и
// приходить из самопроверки строкой.
enum class ProjectTemplateKind {
    Empty,      // ничего: пустая сцена
    Demo,       // примитивы, свет, худ — витрина возможностей
    UIStarter,  // камера, свет, главное меню и худ из готовых экранов
    Copy,       // готовый проект целиком — копируется с диска (см. SourceDir)
};

// Встроен ли шаблон в редактор (собирается кодом) или установлен файлом.
// Различие видно человеку: встроенный нельзя удалить, установленный — можно.
inline bool ProjectTemplateIsBuiltIn(ProjectTemplateKind kind) {
    return kind != ProjectTemplateKind::Copy;
}

struct ProjectTemplate {
    // Идентификатор в коде и в аргументах самопроверки. Не переводится.
    std::string Id;
    ProjectTemplateKind Kind;
    // Подпись и одна строка пояснения. У встроенных — английский ключ, который
    // переводится при показе (T(...)); у установленных — текст из template.json
    // как есть: перевода для чужого шаблона у редактора взяться неоткуда.
    //
    // std::string, а не const char*: половина этих строк теперь приходит с
    // диска и живёт ровно столько, сколько живёт список.
    std::string Name;
    std::string Summary;
    // Что человеку сделать ПОСЛЕ создания, если само по себе видно не будет.
    //
    // Заведено ради витрины, и вот почему. Её мир собирают скрипты при запуске,
    // а в сцене на диске лежат два объекта — World и Player. Созданный проект
    // выглядит поэтому как пустой: белый вьюпорт и две строки в дереве. Со
    // стороны это неотличимо от «шаблон не работает», и именно так его и
    // читают. Одна строка в консоли и в диалоге снимает вопрос, а угадывать
    // это по числу объектов было бы гаданием: у пустого шаблона объектов тоже
    // ноль, и он ровно такой, каким обещан.
    std::string Note;

    // Для Kind == Copy: папка с готовым проектом ОТНОСИТЕЛЬНО каталога
    // редактора (templates/<имя>). Пусто у остальных.
    //
    // ПОЧЕМУ ОТДЕЛЬНЫЙ ВИД, А НЕ ЕЩЁ ОДНА ВЕТКА В NewScene. Шаблон, который
    // строит сцену кодом, ограничен тем, что умеет редактор: примитивы, свет,
    // камера. Готовый проект — это ещё и скрипты, модели, материалы и
    // настройки, то есть ровно то, чему на нём и учатся. Переписать такой
    // проект в C++ означало бы держать вторую его копию и обновлять обе.
    std::string SourceDir;
};

// Все шаблоны, в порядке показа: сначала встроенные (собираются кодом и потому
// ничего не весят), затем УСТАНОВЛЕННЫЕ — те, что найдены в templates/ рядом с
// редактором. Первый — тот, что предлагается по умолчанию.
//
// Список СОБИРАЕТСЯ, а не задан таблицей: шаблон теперь ставится и удаляется
// при работающем редакторе (см. TemplateStore.h), и таблица в коде значила бы,
// что установленный шаблон появляется в списке только после пересборки.
const std::vector<ProjectTemplate>& ProjectTemplates();

// Перечитать установленные шаблоны с диска. Зовётся после установки и удаления:
// список кэшируется, потому что его спрашивают каждый кадр при открытом окне
// создания проекта, а каталог на диске за кадр не меняется.
void RefreshProjectTemplates();

// Шаблон по идентификатору. nullptr — имени нет: молча подставить «пустой»
// значило бы создать не тот проект, о котором просили.
const ProjectTemplate* FindProjectTemplate(const std::string& id);

// Идентификатор по умолчанию — им пользуются диалоги при первом открытии.
const std::string& DefaultProjectTemplate();

// Где редактор ищет папки готовых проектов (templates/ рядом с бинарником).
// Отдельной функцией, потому что путь нужен и созданию проекта, и проверке
// «а есть ли этот шаблон на диске вообще».
std::filesystem::path ProjectTemplatesRoot();

// Готов ли шаблон к использованию: у Copy — лежит ли его папка на месте.
// Остальные готовы всегда.
bool ProjectTemplateAvailable(const ProjectTemplate& tpl);
