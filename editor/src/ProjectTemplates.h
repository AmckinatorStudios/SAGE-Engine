#pragma once
#include <string>
#include <vector>

// ---------------------------------------------------------------------------
// ШАБЛОНЫ ПРОЕКТА — с чего начинается новый проект.
//
// ЗАЧЕМ. Кнопка «Создать проект» всегда делала ОДНО И ТО ЖЕ: папку, пустую
// сцену и демо-контент — пять кубов, три примитива, свет и худ. Для первого
// запуска это хорошо: видно, что движок работает. Для второго и всех
// последующих — нет: человек, начинающий свою игру, первым делом удаляет
// девять чужих объектов, и делает это каждый раз. Выбора «пустой» не было
// вовсе, а «начать с готового меню» — тем более.
//
// ШАБЛОН — ЭТО ДАННЫЕ, А НЕ ВЕТКА В ДИАЛОГЕ. Список ниже читают и диалог
// «Новый проект», и стартовое окно, и самопроверка редактора. Пока выбор жил
// булевым параметром withDemoContent, добавить третий вариант можно было
// только правкой всех трёх мест сразу — и они бы разъехались, как разъехался
// импорт материалов.
//
// Чего шаблон НЕ делает: он не пишет файлы на диск и не создаёт папок. Его
// дело — сказать, что положить в первую сцену; всё остальное у проекта одно и
// то же, и разное поведение здесь означало бы разные проекты по структуре.
// ---------------------------------------------------------------------------

// Что кладём в стартовую сцену. Перечисление, а не функция обратного вызова:
// сборку делает EditorLayer (у него есть помощники для примитивов, света и
// камеры), а шаблон — это ВЫБОР, и он должен сохраняться, сравниваться и
// приходить из самопроверки строкой.
enum class ProjectTemplateKind {
    Empty,      // ничего: пустая сцена
    Demo,       // примитивы, свет, худ — витрина возможностей
    UIStarter,  // камера, свет, главное меню и худ из готовых экранов
};

struct ProjectTemplate {
    // Идентификатор в коде и в аргументах самопроверки. Не переводится.
    std::string Id;
    ProjectTemplateKind Kind;
    // Подпись и одна строка пояснения — переводятся при показе (T(...)).
    const char* Name;
    const char* Summary;
};

// Все шаблоны, в порядке показа. Первый — тот, что предлагается по умолчанию.
const std::vector<ProjectTemplate>& ProjectTemplates();

// Шаблон по идентификатору. nullptr — имени нет: молча подставить «пустой»
// значило бы создать не тот проект, о котором просили.
const ProjectTemplate* FindProjectTemplate(const std::string& id);

// Идентификатор по умолчанию — им пользуются диалоги при первом открытии.
const std::string& DefaultProjectTemplate();
