#pragma once
#include "imgui.h"

// ---------------------------------------------------------------------------
// ЗАХВАТ КУРСОРА В РЕДАКТОРЕ: окна панелей и смещение мыши.
//
// Редактор — не одно окно. Панель Game или вьюпорт, вытащенные из дока, живут
// в своих окнах системы, которые заводит бэкенд ImGui, а не Window. Отсюда
// две беды, которые этот модуль закрывает:
//   • события этих окон не доходили до ввода движка — игра в вытащенной
//     панели Game не получала ни клавиш, ни мыши;
//   • захват ставился главному окну — курсор прятался там, где его нет, а по
//     окну панели гулял свободно.
// ---------------------------------------------------------------------------
namespace cursorcapture {

// Один раз после ImGui_ImplGlfw_Init: события окон панелей идут и в ввод
// движка, а о закрытии окна панели узнаёт захват (иначе он держал бы
// уничтоженное окно).
void InstallViewportInput();
// До ImGui_ImplGlfw_NewFrame каждого кадра. Пока курсор захвачен, бэкенд
// ImGui не трогает вид курсора: он ставит обычный курсор всем окнам, кроме
// главного, — и сбрасывал захват окна панели каждый кадр.
void BeforeImGuiFrame();
// Забыть окно системы, которое уничтожают (зовёт перехват, проверка).
void ForgetPlatformWindow(void* handle);
// Последнее окно, о закрытии которого узнал захват (самопроверка).
void* LastForgottenWindow();

// Захватить (или отпустить) курсор для окна ImGui, которое рисуется сейчас:
// захват ставится окну системы, в котором оно живёт, — главному или своему.
void CaptureForCurrentWindow(bool captured);

// Смещение мыши за кадр для обзора (пиксели, Y вниз). В захвате мышь
// интерфейса стоит на месте, и io.MouseDelta — ноль; тогда смещение берётся
// из событий окна.
ImVec2 LookMouseDelta();

} // namespace cursorcapture

using cursorcapture::LookMouseDelta;
