#pragma once
#include <filesystem>
#include <string>
#include <vector>

// ---------------------------------------------------------------------------
// ХРАНИЛИЩЕ ШАБЛОНОВ: шаблон — это содержимое, а не часть программы.
//
// БЫЛО. Готовый проект-шаблон («Витрина») лежал ВНУТРИ сборки: CMake копировал
// games/showcase рядом с редактором, архив релиза тащил её с собой, и всякий,
// кто скачивал редактор, скачивал заодно чужую игру — нужна она ему или нет.
// Следствия по нарастающей:
//
//   • архив рос от содержимого, к движку отношения не имеющего, и рос бы
//     дальше с каждым новым шаблоном: два готовых проекта — два лишних
//     мегабайта у КАЖДОГО скачавшего;
//   • добавить свой шаблон было нельзя вовсе — только пересобрать редактор;
//   • шаблон нельзя было обновить отдельно от редактора и убрать, если он не
//     нужен: снести папку означало получить в списке вечное «не установлен».
//
// СТАЛО. Шаблоны живут отдельно от программы, в папке templates/ рядом с
// редактором, и попадают туда тремя путями: скачиванием из каталога, установкой
// файла .sagetemplate с диска и «сохранить текущий проект как шаблон».
// Программа при этом не знает заранее, какие шаблоны существуют, — она их
// НАХОДИТ. Встроенными остались только те, что не весят ничего, потому что
// собираются кодом: пустой проект, демо-сцена и заготовка интерфейса.
//
// ПОЧЕМУ .sagetemplate — ЭТО SAGEPAK, А НЕ ZIP. Пакет у движка уже есть
// (sage/assets/Pack.h), он умеет складывать каталог и разбирать обратно, и
// добавлять ради архива вторую библиотеку значило бы тащить в сборку zip ради
// того, что уже написано. Расширение своё, чтобы файл нельзя было спутать с
// собранной игрой.
// ---------------------------------------------------------------------------
namespace sage::editor::templates {

// Описание шаблона, как оно лежит в template.json внутри установленной папки
// и в каталоге для скачивания.
struct Manifest {
    std::string Id;          // папка в templates/ и имя в настройках
    std::string Name;        // подпись в списке
    std::string Summary;     // строка пояснения
    std::string Note;        // что сделать ПОСЛЕ создания (см. ProjectTemplates.h)
    std::string Version;     // произвольная строка; показывается как есть
    std::string Url;         // откуда скачать .sagetemplate (только в каталоге)
    uint64_t Bytes = 0;      // размер загрузки, чтобы обещать честно
    bool Installed = false;  // лежит ли уже в templates/
};

// Куда ставятся шаблоны: templates/ рядом с бинарником редактора.
std::filesystem::path Root();

// Что установлено сейчас. Читает диск, поэтому зовётся при открытии окна и
// после установки, а не каждый кадр.
std::vector<Manifest> Installed();

// --- установка -----------------------------------------------------------

// Поставить из файла .sagetemplate. err — почему нет.
bool InstallFromFile(const std::filesystem::path& file, std::string& err);

// Поставить из папки с готовым проектом (в ней обязан быть project.sageproj).
bool InstallFromFolder(const std::filesystem::path& dir, const Manifest& info, std::string& err);

// Снять установленный шаблон. Удаляет папку templates/<id> и только её.
bool Uninstall(const std::string& id, std::string& err);

// --- упаковка ------------------------------------------------------------

// Собрать .sagetemplate из папки проекта. Тем же файлом шаблон и ставится:
// «поделиться заготовкой» и «скачать чужую» — одно и то же действие с разных
// сторон, и разные форматы здесь означали бы два несовместимых пути.
bool Pack(const std::filesystem::path& projectDir, const Manifest& info,
          const std::filesystem::path& outFile, std::string& err);

// --- каталог -------------------------------------------------------------

// Адрес каталога по умолчанию (релиз этого же репозитория). Меняется в
// настройках редактора: каталог — это просто JSON по ссылке, и держать свой
// (внутри студии, в локальной сети) должно быть можно без правки кода.
std::string DefaultCatalogUrl();
std::string CatalogUrl();
void SetCatalogUrl(const std::string& url);

// Разобрать каталог из текста JSON. Отдельно от скачивания — чтобы разбор
// проверялся тестами без сети.
bool ParseCatalog(const std::string& json, std::vector<Manifest>& out, std::string& err);

// Скачать каталог и отметить в нём то, что уже установлено.
bool FetchCatalog(std::vector<Manifest>& out, std::string& err);

// Скачать и поставить шаблон из каталога.
bool Download(const Manifest& item, std::string& err);

// --- сеть ----------------------------------------------------------------
//
// Через внешний curl, а не через свою реализацию HTTP. Причина простая: свой
// HTTPS означает TLS-библиотеку в сборке, а curl есть и в Windows 10 (с 1803,
// в System32), и в любом Linux. Редактору незачем уметь то, что уже умеет
// система.
bool NetworkAvailable();              // нашёлся ли curl
bool HttpGet(const std::string& url, std::string& body, std::string& err);
bool HttpDownload(const std::string& url, const std::filesystem::path& to, std::string& err);

} // namespace sage::editor::templates
