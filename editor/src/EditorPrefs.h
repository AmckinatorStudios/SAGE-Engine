#pragma once
#include <string>

// ---------------------------------------------------------------------------
// Настройки САМОГО РЕДАКТОРА (не проекта и не сцены).
//
// Разница принципиальная. Настройки проекта едут в `sage.cfg` и достаются
// всем, кто его откроет; свойства сцены лежат в `.sage`. А то, что здесь, —
// привычки одного человека за одним компьютером: язык интерфейса, состав
// панели инструментов, недавние проекты. Навязывать их проекту нельзя: иначе
// коллега, открывший чужой проект, получил бы чужой набор кнопок.
//
// Файл — `~/.config/sage/editor_prefs.json` (на Windows — `%APPDATA%`), тот же,
// в котором уже жил язык. Чтение-правка-запись, а не перезапись целиком: в
// файле соседствуют настройки от разных мест редактора, и запись состава
// тулбара не имеет права стереть выбранный язык.
//
// Все функции безопасны при отсутствующем и при испорченном файле: настройки —
// не повод не запуститься, при любой беде возвращается значение по умолчанию.
// ---------------------------------------------------------------------------
namespace sage::editor::prefs {

// Путь к файлу настроек (создаётся при первой записи).
std::string Path();

bool GetBool(const std::string& key, bool fallback);
void SetBool(const std::string& key, bool value);
int GetInt(const std::string& key, int fallback);
void SetInt(const std::string& key, int value);
float GetFloat(const std::string& key, float fallback);
void SetFloat(const std::string& key, float value);
// Строка — для выбора из списка (тема оформления, язык): числом такой выбор
// хранить нельзя, порядок в списке меняется от сборки к сборке, а имя — нет.
std::string GetString(const std::string& key, const std::string& fallback);
void SetString(const std::string& key, const std::string& value);

} // namespace sage::editor::prefs
