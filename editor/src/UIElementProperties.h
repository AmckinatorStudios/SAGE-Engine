#pragma once
#include <string>

#include "sage/ui/UIAnchor.h"

class EditorHost;
class GameObject;
class AssetPreview;
class FileBrowser;

// ---------------------------------------------------------------------------
// Свойства ЭЛЕМЕНТА ИНТЕРФЕЙСА — один набор полей на весь редактор.
//
// Их правят из ДВУХ мест: из инспектора (выбрали элемент в иерархии) и из
// редактора интерфейса (выбрали его же на холсте). Пока это была приватная
// функция инспектора, у второго места было ровно два выхода: позвать инспектор
// целиком (то есть чужое окно со своим состоянием) или переписать те же
// тридцать полей заново. Второе — верный способ получить два редактора одного
// компонента, которые расходятся с первой же новой галкой.
//
// Поэтому функция общая, а всё, что ей нужно от вызывающего, приходит
// контекстом: обложки ассетов и файловый диалог — это состояние ПАНЕЛИ, и
// панель им и владеет.
// ---------------------------------------------------------------------------
namespace sage::editor {

struct UIPropsContext {
    // Обложки для слотов ассетов (картинка элемента). nullptr — без обложек.
    AssetPreview* Preview = nullptr;
    // Файловый диалог панели и её указатель «куда положить выбранный путь».
    // Диалог качает сама панель: он живёт дольше одного кадра.
    FileBrowser* Browser = nullptr;
    std::string** BrowseTarget = nullptr;
    // Показать секцию «Events» (связи сигналов). Инспектор объекта рисует её
    // сам — для любого объекта, — редактор интерфейса просит её здесь.
    bool ShowEvents = false;
};

// Сетка якоря 3x3 — тоже общая: её показывают и свойства элемента, и
// инструменты выравнивания.
bool DrawAnchorPicker(UIAnchor& anchor);

// Открыть интерфейс ЭТОГО объекта в пространстве «Интерфейс»: объект —
// сам интерфейс или элемент внутри него (интерфейс ищется вверх по дереву).
// Интерфейс старого вида (элементы прямо в сцене) сначала выносится в файл.
void OpenInInterfaceMode(EditorHost& host, GameObject obj);

// Все поля выбранного элемента: части, положение, вид, текст, поведение.
void DrawUIElementProperties(EditorHost& host, GameObject obj, const UIPropsContext& ctx);

// Свойства САМОГО ИНТЕРФЕЙСА (объекта-границы): видимость, порядок показа,
// приём ввода, опорное разрешение. Здесь НЕТ и не должно быть ни одного
// свойства элемента — ни цвета, ни отступов, ни текста: интерфейс не
// прямоугольник на экране, а контекст, которому эти прямоугольники
// принадлежат. Путаница между тем и другим — ровно то, из-за чего у объекта с
// интерфейсом в инспекторе оказывались поля кнопки.
//
// У интерфейса из файла (InterfaceComponent::Source) — только подключение:
// какой файл, показан ли, в каком порядке и кнопка «Открыть интерфейс».
// Содержимое и холст правятся в пространстве «Интерфейс».
void DrawInterfaceProperties(EditorHost& host, GameObject obj);

// Холст интерфейса: под какой экран верстают. Показывается в пространстве
// «Интерфейс» у главного контейнера — холст едет вместе с файлом.
void DrawInterfaceCanvas(EditorHost& host, GameObject interfaceObject);

} // namespace sage::editor
