#pragma once
#include <filesystem>
#include <string>
#include <utility>
#include <vector>

// ---------------------------------------------------------------------------
// ExternalGame — игра, запущенная НАСТОЯЩИМ SagePlayer в отдельном процессе и
// отдельном окне системы (режим «Window» панели Game).
//
// ПОЧЕМУ ПРОЦЕСС, А НЕ ВТОРОЕ ОКНО ВНУТРИ РЕДАКТОРА. Окно игры обязано жить по
// правилам игры: свои разрешение, режим, монитор и частота, свой цикл кадров,
// свой захват курсора. В процессе редактора это значило бы второй контекст
// GL и спор двух окон за один ввод. Плеер уже умеет всё это (он и есть
// собранная игра), поэтому редактор только запускает его и следит за ним.
// ---------------------------------------------------------------------------
class ExternalGame {
public:
    ~ExternalGame() { Stop(); }

    // Запустить плеер. env — дополнительные переменные окружения ТОЛЬКО для
    // дочернего процесса: окружение самого редактора не трогается.
    bool Start(const std::filesystem::path& player, const std::filesystem::path& projectDir,
               const std::vector<std::pair<std::string, std::string>>& env, std::string& err);

    // Процесс ещё жив. Заодно «собирает» завершившийся (без зомби).
    bool Running();

    // Завершить процесс и дождаться его: после возврата ни процесса, ни окна.
    void Stop();

private:
#ifdef _WIN32
    void* m_process = nullptr; // HANDLE
#else
    int m_pid = 0;
#endif
};
