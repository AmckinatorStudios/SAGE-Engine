// ---------------------------------------------------------------------------
// ОТЛАДЧИК SAGE AI — всё, что идёт в игре, и почему оно кончилось.
//
//   • СЛЕВА — дерево выполнений: каждая задача мира ИИ (граф, Lua, C++) под
//     той, что её запустила, с состоянием. Видно и то, что граф позвал
//     Lua-задачу, и то, на чём она упала.
//   • СПРАВА — выбранное: состояние, причина конца (ошибка, отмена), где
//     стоит пауза, значения его переменных (входы, выходы, локальные, память
//     экземпляра, общая область) — живыми, пока идёт Play.
//   • СНИЗУ — история: шаги узлов, события, запуски и концы задач, ошибки и
//     сообщения Log и решения графа (Decide), с фильтром по выполнению и виду.
//     Вместо истории — ПРОФИЛЬ: сколько стоит каждая задача (World::Stats).
//
// Данные — из sage::ai::GraphDebugger (пишется только в Play редактора) и
// из мира ИИ идущей игры.
// ---------------------------------------------------------------------------
class AiDebugPanel {
public:
    void Draw(EditorHost& host, bool* open, AiGraphPanel& graph);

private:
    int m_run = 0;
    bool m_onlyRun = false;
    int m_kind = 0;   // 0 — все, иначе индекс в списке видов
    bool m_follow = true;
    bool m_profile = false;

    void ProfileTable(sage::ai::World* world);
};
