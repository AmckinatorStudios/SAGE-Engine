#pragma once
#include "EditorTypes.h"
#include "UIToolSettings.h"

// ---------------------------------------------------------------------------
// EditorTools — состояние ИНСТРУМЕНТОВ редактора: гизмо, привязка, что видно
// во вьюпорте.
//
// Строка инструментов, вьюпорт, редактор интерфейса и горячие клавиши читают и
// пишут одно и то же: какой сейчас гизмо, включена ли привязка, в каких осях
// тянем, показывать ли сетку и габариты. Это единый набор настроек — и жил он
// дюжиной отдельных полей EditorLayer рядом с проектом, Play-режимом и
// плагинами, отдаваясь наружу дюжиной ссылочных методов EditorHost.
//
// Здесь он — один объект без сцены, ImGui и графики: класс, у которого нет
// зависимостей, читается целиком и проверяется модульным тестом.
// ---------------------------------------------------------------------------
struct EditorTools {
    int GizmoOp = 0;  // ImGuizmo::OPERATION; 0 — перенос

    // Оси по умолчанию — МИРОВЫЕ. В осях объекта стрелка «вправо» у повёрнутого
    // предмета ведёт вбок и вглубь одновременно, и человек, который об этом не
    // знает (а по умолчанию не знает никто), видит просто «гизмо тянет не
    // туда». Мир одинаков для всех объектов сцены, поэтому он и стоит первым;
    // локальные оси включаются осознанно — подписанным переключателем в строке
    // инструментов.
    EditorGizmoSpace GizmoSpace = EditorGizmoSpace::World;

    bool Snap = false;
    // Шаг привязки переноса — 1.0: движок строит примитивы размером в единицу,
    // и для постройки из блоков это единственный шаг, при котором блоки встают
    // вплотную без щелей и нахлёстов.
    float SnapMove = 1.0f;
    float SnapRotate = 15.0f;
    float SnapScale = 0.1f;

    bool ShowGrid = true;
    bool ShowBounds = false;
    EditorRenderMode RenderMode = EditorRenderMode::Shaded;

    UIToolSettings UI;          // сетка и привязки вёрстки (см. UIToolSettings.h)
    bool ColliderEdit = false;  // гизмо тянет коллайдер, а не объект

    // Шаг привязки для ТЕКУЩЕГО гизмо. Определён в .cpp: сверка GizmoOp с
    // ImGuizmo::OPERATION — единственное место, где это состояние вообще знает
    // про ImGuizmo, и тянуть его заголовок ко всем, кто читает настройки
    // инструментов, ради одной функции не за что.
    float SnapStepForCurrentOp() const;
};
