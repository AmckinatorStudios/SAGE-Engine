#pragma once
#include <string>
#include <vector>

#include <entt/entt.hpp>

class Scene;
class EditorHost;

// ---------------------------------------------------------------------------
// БУФЕР ОБМЕНА ЭЛЕМЕНТОВ ИНТЕРФЕЙСА.
//
// Копируется НЕ ссылка на сущность, а сам интерфейс — поддерево целиком, тем же
// ресурсом .sageui, каким интерфейс лежит в проекте (см. sage/ui/Interface.h).
// Отсюда всё остальное:
//
//   • вставить можно СКОЛЬКО УГОДНО РАЗ, и копии не знают друг о друге;
//   • вставить можно в ДРУГУЮ СЦЕНУ и в другой проект — буфер уходит в
//     системный, обычным текстом;
//   • скопированное переживает удаление оригинала: в буфере лежит описание, а
//     не указатель на то, чего уже нет.
//
// Ради последнего пункта буфер и сделан текстом, а не списком сущностей.
// Список сущностей — это буфер, который ломается ровно тогда, когда им
// собирались воспользоваться: скопировал панель, удалил, вставил — и вставлять
// нечего.
// ---------------------------------------------------------------------------
namespace sage::editor::uiclipboard {

// Кладёт поддеревья выделенных элементов в системный буфер обмена.
// Возвращает число скопированных корней (0 — копировать было нечего).
int Copy(const Scene& scene, const std::vector<entt::entity>& roots);

// Лежит ли в буфере интерфейс. Дешёвая проверка для «вставить» в меню: смотрит
// на признак формата, а не разбирает содержимое.
bool HasInterface();

// Вставляет содержимое буфера в сцену под указанного родителя (entt::null —
// в корень). Возвращает созданные корни; пусто — в буфере не интерфейс.
std::vector<entt::entity> Paste(Scene& scene, entt::entity parent);

} // namespace sage::editor::uiclipboard
