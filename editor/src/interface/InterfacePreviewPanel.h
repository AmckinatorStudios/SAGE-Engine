#pragma once
class EditorHost;

// ---------------------------------------------------------------------------
// ПРЕДПРОСМОТР — ТОТ ЖЕ КАДР, НО БЕЗ ЕДИНОГО ГИЗМО.
//
// Зачем он нужен рядом с холстом, на котором и так виден кадр: на холсте поверх
// интерфейса лежат рамки выделения, ручки, линии привязки, сетка и подписи
// расстояний. Они не мешают верстать — они мешают УВИДЕТЬ результат. Вопрос
// «как это выглядит на самом деле» задают каждые несколько минут, и до сих пор
// ответом было «выключить сетку, снять выделение, посмотреть, включить
// обратно».
//
// Здесь тот же игровой кадр (та же текстура, то же разрешение) — и ничего
// больше. Панель докуемая: её держат вкладкой рядом с холстом и переключаются
// одним щелчком, либо раскладывают обе рядом на широком экране.
// ---------------------------------------------------------------------------
class InterfacePreviewPanel {
public:
    void Draw(EditorHost& host, bool& open);
    void RequestFocus() { m_focusFrames = 3; }

private:
    int m_focusFrames = 0;
    // Во сколько раз показывать кадр. Ноль — вписать в панель: у предпросмотра
    // это и есть обычный случай, а крупный масштаб нужен, когда смотрят на
    // мелкий текст.
    float m_zoom = 0.0f;
};
