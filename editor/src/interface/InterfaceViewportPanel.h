#pragma once
#include "imgui.h"

#include "../UICanvas.h"

class EditorHost;

// ---------------------------------------------------------------------------
// ХОЛСТ ИНТЕРФЕЙСА — игровой кадр в ЕГО СОБСТВЕННОМ разрешении.
//
// Это главное отличие от прежнего «режима вёрстки»: там холстом был вьюпорт
// редактора, то есть чужой размер и чужое соотношение сторон. Вёрстка «на глаз»
// под чужой экран и есть причина, по которой собранная игра выглядела иначе,
// чем редактор.
//
// Панель ДОКУЕМАЯ: её можно растянуть на второй монитор, положить вкладкой
// рядом с игровым окном или оставить единственной на экране. Раньше это была
// колонка внутри одного окна, и ширину ей отмеряли соседи.
// ---------------------------------------------------------------------------
class InterfaceViewportPanel {
public:
    void Draw(EditorHost& host, bool& open);
    void RequestFocus() { m_focusFrames = 3; }
    // Вернуться к вписанному показу (кнопка «Вписать», смена пространства).
    void RequestFit() { m_autoFit = true; m_pan = ImVec2(0.0f, 0.0f); }

private:
    void DrawToolbar(EditorHost& host);
    void DrawCanvas(EditorHost& host);

    UICanvas m_canvas;

    // Показ холста. Масштаб и сдвиг — свойства ПОКАЗА, а не вёрстки: сам кадр
    // всегда рисуется в разрешении игры, меняется только то, как крупно его
    // видно. Иначе, отдалив холст, человек правил бы раскладку под другое
    // разрешение.
    float m_zoom = 1.0f;
    ImVec2 m_pan{0.0f, 0.0f};

    // ВПИСАННЫЙ ПОКАЗ — РЕЖИМ, А НЕ ОДНОРАЗОВОЕ ДЕЙСТВИЕ.
    //
    // Раньше масштаб вписывания считался ОДИН раз, флагом «впиши на следующем
    // кадре». Считался он при этом на кадре, когда панель ещё не получила свой
    // размер: раскладка дока устаканивается за несколько кадров, и первым из
    // них панель шириной во всё окно. Итог — масштаб под чужой размер: кадр
    // больше панели, видно его середину, а верхний левый угол (где обычно и
    // висит худ) обрезан. Выглядит это как «кадр уехал в сторону».
    //
    // Пока показ вписанный, масштаб считается КАЖДЫЙ кадр — панель можно
    // тянуть, перекладывать в доке и разворачивать, кадр останется целым.
    // Первое же ручное приближение (колесо, поле процентов, «1:1») режим
    // снимает: человек попросил конкретный масштаб, и подменять его своим
    // редактор не вправе.
    bool m_autoFit = true;
    int m_focusFrames = 0;

    // Подложка ЗАПОМИНАЕТСЯ МЕЖДУ ЗАПУСКАМИ. Это привычка одного человека
    // («я верстаю тёмный интерфейс на светлом фоне»), а не свойство проекта:
    // хранится в настройках редактора и не едет коллеге вместе с игрой.
    // Читается один раз при первом кадре: до него настроек ещё нет.
    bool m_backdropLoaded = false;
};
