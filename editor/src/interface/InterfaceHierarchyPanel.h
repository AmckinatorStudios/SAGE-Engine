#pragma once
#include <string>
#include <vector>

#include <entt/entt.hpp>

class EditorHost;
class Scene;

// ---------------------------------------------------------------------------
// ДЕРЕВО ЭЛЕМЕНТОВ ИНТЕРФЕЙСА — отдельная докуемая панель.
//
// Раньше это была колонка внутри окна редактора интерфейса: её нельзя было ни
// перетащить, ни отстыковать, ни положить на второй монитор, ни сделать шире
// холста. Внутри редактора с доккингом жил кусок без доккинга, и правила там
// были свои.
//
// ЧТО ЗДЕСЬ ЕСТЬ И ПОЧЕМУ ИМЕННО ТАК.
//
//   • ДЕЙСТВИЯ — В КОНТЕКСТНОМ МЕНЮ И НА ГОРЯЧИХ КЛАВИШАХ, а не кнопками под
//     списком. Кнопки «Удалить» и «Дублировать» занимали место постоянно, а
//     нужны раз в минуту; при этом переименования, копирования и вставки —
//     того, чем пользуются чаще всего, — не было вовсе.
//   • ПЕРЕИМЕНОВАНИЕ — ПО МЕСТУ (F2 или двойной щелчок). Имя правилось в
//     инспекторе, то есть в другом окне: чтобы назвать десять элементов, надо
//     было десять раз сходить туда и обратно.
//   • ПОИСК фильтрует дерево, СОХРАНЯЯ путь к найденному: показать одну
//     строку без её родителей значит показать, ЧТО нашлось, и спрятать, ГДЕ
//     это лежит.
//   • ГЛАЗОК и ЗАМОК — прямо в строке. Спрятать мешающую панель, чтобы
//     добраться до того, что под ней, и запереть разложенный фон, чтобы он
//     перестал ловить клики, — два самых частых действия вёрстки.
//   • ПЕРЕТАСКИВАНИЕ меняет родителя и порядок: бросок НА строку делает
//     элемент её ребёнком, бросок МЕЖДУ строками ставит рядом. Без второго
//     порядок среди соседей правился только числом Order, а «поставить выше
//     соседа» — самая частая правка порядка вообще.
// ---------------------------------------------------------------------------
class InterfaceHierarchyPanel {
public:
    void Draw(EditorHost& host, bool& open);

    // Вывести окно вперёд (после создания элемента из меню Create).
    void RequestFocus() { m_focusFrames = 3; }

private:
    // Одна строка дерева. Возвращает false, если строку рисовать не надо
    // (не прошла фильтр поиска и ни один её потомок тоже).
    bool DrawNode(EditorHost& host, Scene& scene, entt::entity e, int depth);
    void DrawToolbar(EditorHost& host);
    void DrawContextMenu(EditorHost& host, Scene& scene, entt::entity e);
    void HandleShortcuts(EditorHost& host);

    // Совпадает ли элемент или кто-то из его потомков с фильтром поиска.
    bool MatchesFilter(const Scene& scene, entt::entity e) const;

    // Полоса броска между строками: ставит перетаскиваемый элемент рядом с
    // этим, у того же родителя.
    void DropGap(EditorHost& host, Scene& scene, entt::entity before, entt::entity parent);

    // Выделить диапазон от последней выбранной до этой (Shift+щелчок) по
    // ПОКАЗАННОМУ порядку строк, а не по номерам сущностей.
    void SelectRangeTo(EditorHost& host, entt::entity e);

    std::string m_filter;
    // Строки в порядке показа этого кадра — по ним работает Shift+щелчок.
    std::vector<entt::entity> m_rows;
    entt::entity m_renaming = entt::null;
    char m_renameBuf[128] = {0};
    entt::entity m_lastClicked = entt::null;
    int m_focusFrames = 0;
};
