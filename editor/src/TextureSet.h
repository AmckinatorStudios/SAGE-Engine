#include <filesystem>
#include <string>
#include <vector>

// ---------------------------------------------------------------------------
// НАБОР КАРТ ИЗ ОДНОЙ ПАПКИ — материал целиком, а не одна картинка.
//
// ЧТО БЫЛО НЕ ТАК. Текстуры скачивают НАБОРАМИ: рядом лежат
// `brick-wall_albedo.png`, `_normal-ogl.png`, `_roughness.png`, `_metallic.png`,
// `_ao.png`, `_height.png`. Движок умеет их все, а редактор не умел взять ни
// одной: перетащить картинку на объект было нельзя вовсе («этот файл нельзя
// назначить объекту»), и единственным путём оставалось создать материал руками
// и назначить ПЯТЬ слотов по одному, зная, какой файл в какой слот. Понятно, до
// какого слота доходили на практике: до albedo. Отсюда и вывод, который и
// звучал, — «работает только albedo, остальные карты игнорируются».
//
// ЧТО ЗДЕСЬ. По ОДНОМУ файлу набора собирается весь набор: имена карт
// устроены одинаково почти во всех источниках (ambientCG, Poliigon, Quixel,
// Poly Haven, texture.ninja) — общий корень плюс суффикс с названием карты.
// Отсюда и правило: отбрасываем суффикс, ищем рядом файлы с тем же корнем и
// раскладываем их по назначению.
//
// РАЗБОР ИМЁН, А НЕ СОДЕРЖИМОГО: заглянуть внутрь и понять «это карта нормалей»
// нельзя надёжно — синеватой бывает и обычная картинка. Зато имя суффикса
// экспортёры пишут честно, и ошибиться здесь дешевле: человек видит, что
// подобралось, в слотах материала и может поправить.
// ---------------------------------------------------------------------------
namespace sage::editor {

struct TextureSet {
    std::string Base;        // общий корень имени («brick-wall»)
    std::string Albedo;      // пути как есть (абсолютные либо как пришли)
    std::string Normal;
    std::string Metallic;
    std::string Roughness;
    std::string AO;
    std::string Emissive;

    // Карты, которые в наборе есть, а движок их не применяет. Молчать о них
    // нельзя: человек видит файл `_height.png` и вправе ждать рельефа.
    std::vector<std::string> Unused;

    // Нормаль в формате DirectX (зелёный канал перевёрнут). Движок ждёт
    // OpenGL-формат, и подставленная DX-карта даёт рельеф «наизнанку» — это
    // видно глазами, но объяснить нечем, если об этом не сказать.
    bool NormalIsDirectX = false;

    int Found() const {
        return (int)(!Albedo.empty()) + (int)(!Normal.empty()) + (int)(!Metallic.empty()) +
               (int)(!Roughness.empty()) + (int)(!AO.empty()) + (int)(!Emissive.empty());
    }
    bool HasExtraMaps() const {
        return !Normal.empty() || !Metallic.empty() || !Roughness.empty() || !AO.empty() ||
               !Emissive.empty();
    }
};

// Собирает набор по ЛЮБОМУ его файлу: хоть по albedo, хоть по карте нормалей.
// Файл, у которого суффикса нет (просто `wall.png`), остаётся набором из одной
// карты — это честный ответ, а не отказ.
TextureSet FindTextureSet(const std::filesystem::path& anyMap);

} // namespace sage::editor
