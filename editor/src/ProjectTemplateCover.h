// ОБЛОЖКА ШАБЛОНА — картинка того, что получится.
//
// ЗАЧЕМ. Выбор шаблона был тремя радиокнопками с подписями «Demo scene»,
// «Empty project», «Menu and HUD». Что именно принесёт каждая — узнавали
// только создав проект: разница между «витриной движка» и «камерой со
// свободным экраном» словами не передаётся, а человек выбирает ПЕРВЫЙ в жизни
// проект и цены этих слов ещё не знает. Обложка отвечает на вопрос до нажатия.
//
// РИСУЕТСЯ, А НЕ ЗАГРУЖАЕТСЯ — ровно по тем же причинам, что иконки редактора
// (см. EditorIcons.h): картинка в репозитории означала бы бинарный файл на
// каждый шаблон, три размера под масштаб интерфейса и обязанность
// перерисовывать её вручную каждый раз, когда шаблон меняют. Здесь обложка —
// десяток примитивов в ImDrawList: резкая на любом масштабе, ничего не весит и
// правится там же, где правят сам шаблон.
//
// ЧЕСТНОСТЬ ОБЛОЖКИ. Рисунок повторяет то, что шаблон реально кладёт в сцену
// (EditorLayer::NewScene) — теми же цветами. Пустой шаблон поэтому изображён
// пустым: ни объекта, ни интерфейса, только рамка. Обложка, обещающая больше
// содержимого, чем шаблон даёт, хуже, чем отсутствие обложки.
// ---------------------------------------------------------------------------

// Рисунок в заданный прямоугольник ЭКРАНА (абсолютные координаты ImGui).
// Ничего не подаёт как элемент — это чистый рисунок, годится и внутри кнопки.
void DrawProjectTemplateCover(ProjectTemplateKind kind, float x, float y, float w, float h);

// Карточка «обложка + название», работающая как радиокнопка: возвращает true
// в кадре, когда её выбрали. Пояснение шаблона показывается подсказкой.
//
// Ширина задаётся вызывающим (в стартовом окне карточки узкие, в диалоге
// «Новый проект» шире), высота считается от неё — карточки в ряду обязаны быть
// одной высоты, иначе ряд «прыгает» при смене шрифта.
bool ProjectTemplateCard(const ProjectTemplate& tpl, bool selected, float width);

// Высота карточки при такой ширине — чтобы вызывающий мог отвести под ряд
// место заранее (дочернее окно, модалка с автоподбором размера).
float ProjectTemplateCardHeight(float width);
