#pragma once
#include <filesystem>
#include <string>
#include <vector>

// ---------------------------------------------------------------------------
// Файловая система для панелей редактора — с памятью.
//
// ЗАЧЕМ. Панель ассетов рисуется КАЖДЫЙ кадр, и каждый кадр она спрашивала
// диск: листинг текущей папки, время правки каждой плитки, листинг каждой
// папки дерева (есть ли подпапки, пустая ли она) и канонический путь каждой
// строки. На папке набора из магазина (сотни моделей и картинок) это тысячи
// системных вызовов за кадр — на Windows каждый ещё и дорогой, — и FPS
// редактора падал вдвое просто от открытой панели.
//
// Здесь те же ответы с памятью: листинг папки перечитывается, только когда
// сменилось время правки САМОЙ папки (а оно меняется при любом добавлении,
// удалении и переименовании внутри), остальное — не чаще раза в maxAge секунд.
// Правка содержимого файла (пересохранили материал) доходит до обложки не
// позже чем через секунду.
// ---------------------------------------------------------------------------
namespace sage::editor::fscache {

// Время правки файла (0 — файла нет). Спрашивает диск не чаще раза в maxAge с.
long long Stamp(const std::filesystem::path& path, double maxAge = 1.0);

struct Listing {
    std::vector<std::filesystem::path> Dirs;
    std::vector<std::filesystem::path> Files;   // без сайдкаров .meta
};
// Содержимое папки, отсортированное по имени. Перечитывается, когда меняется
// время правки папки (проверка — не чаще раза в maxAge с).
const Listing& List(const std::filesystem::path& dir, double maxAge = 0.2);

// weakly_canonical с памятью: сравнение «та ли это папка» идёт по нему на
// каждой строке дерева и в каждом кадре.
const std::filesystem::path& Canonical(const std::filesystem::path& path);

// Забыть всё (смена проекта; тесты).
void Clear();

} // namespace sage::editor::fscache
