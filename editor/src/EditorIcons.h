#pragma once
#include <glm/glm.hpp>

// ImGui — ради ImVec2/ImU32 в подписях ниже: значок и текст кладутся прямо в
// список отрисовки, а его типы описаны там.
#include <imgui.h>

struct ImDrawList;

// ---------------------------------------------------------------------------
// Иконки редактора — подмножество Tabler Icons.
//
// ПРАВИЛО. Интерфейс редактора рисует ImGui, а всё остальное в нём — движок:
// сцена, ресурсы, звук, физика идут теми же путями, что и в собранной игре, и
// второй реализации ради редактора не заводится. Движковый интерфейс
// (sage/ui) в редакторе встречается ровно там, где редактор РЕДАКТИРУЕТ
// интерфейс игры, — и нигде больше. Иконки берутся из Tabler Icons.
//
// ЧТО БЫЛО ДО ЭТОГО и почему поменялось. Иконки рисовались примерно
// полутысячей строк примитивов: прямоугольник, дуга, кривая, всё кратно 1/16.
// Довод был такой: ни бинарного файла в репозитории, ни чужой лицензии, ни
// магических констант в коде, и резкость на любом масштабе. Довод верный, а
// цена оказалась выше пользы: набор рос по одной иконке за раз, каждую надо
// было СРИСОВАТЬ руками, и в результате «шестерёнка» с «лампочкой» жили в
// разных весах штриха просто потому, что рисовались в разные месяцы. Стиль
// набора не выдерживается там, где каждую единицу набора рисуют отдельно.
//
// Tabler — тысячи иконок в одном весе штриха, нарисованных дизайнерами (MIT,
// текст лицензии в external/tabler-icons-LICENSE). В редактор попадают только
// нужные шесть десятков: scripts/gen_icon_font.py вырезает их в подмножество
// шрифта (22 КБ) и раскладывает в EditorIconFont.inl вместе с таблицей имён.
//
// Прежние возражения сняты, а не проигнорированы:
//   • бинарный файл — встроен МАССИВОМ, а не лежит рядом с exe: ещё один путь,
//     который может не найтись, редактору сейчас нужен меньше всего;
//   • магические константы — сгенерированы вместе со шрифтом и подписаны
//     именами («play», «material»), в коде их по-прежнему не пишут руками;
//   • лицензия — лежит в репозитории рядом с остальными сторонними.
//
// Имена иконок — про СМЫСЛ в редакторе («material», «prefab»), а не про
// рисунок: какой именно глиф Tabler за ними стоит, решает таблица в
// scripts/gen_icon_font.py, и поменять рисунок можно, не трогая ни одного
// места вызова.
//
// Все иконки вписаны в КВАДРАТ со стороной, равной высоте строки, поэтому
// вёрстка не зависит от того, какую именно нарисовали.
// ---------------------------------------------------------------------------
namespace EditorIcons {

// «Цвет — из темы». Значение по умолчанию у аргумента вычисляется в точке
// объявления, а тема к тому моменту ещё не выбрана, поэтому здесь стоит метка,
// а настоящий цвет берётся при отрисовке.
//
// Заведена не для красоты. Раньше по умолчанию стоял白 — glm::vec3(1.0f), — и
// на тёмном фоне это выглядело правильно. В светлой теме те же иконки
// оказались белыми на белом: панель инструментов вьюпорта превращалась в ряд
// пустых кружков. Цвет, прописанный числом, переживает смену темы — а вид нет.
inline constexpr glm::vec3 kThemeColor = glm::vec3(-1.0f);

// Собирает шрифт иконок в атлас ImGui. Зовётся один раз, сразу после текстового
// шрифта и до первого кадра (см. EditorTheme::LoadFont): атлас после сборки уже
// не пополняется.
void LoadFont();
// Собрался ли шрифт. Для самопроверки: молча нарисованные квадратики вместо
// иконок — это отказ, который человек замечает глазами, а тест не замечает.
bool FontReady();
// Есть ли у имени свой глиф. Имя без глифа рисуется заглушкой — то есть
// опечатка выглядит как поломка всего набора, а не как опечатка.
bool HasGlyph(const char* icon);

// ОТСТУП МЕЖДУ ЗНАЧКОМ И ПОДПИСЬЮ — ОДИН НА ВЕСЬ РЕДАКТОР.
//
// Его считал каждый, кто рисовал строку со значком, и считал по-своему: где-то
// это был FramePadding, где-то два пробела в формате, где-то «ширина значка на
// 1.15» или просто ноль. На экране это видно сразу: в одном меню подпись
// прилипла к рисунку, в соседнем стоит с зазором в полсимвола, и ни одна
// колонка не совпадает с другой. Один множитель от высоты строки держит все
// такие пары одинаковыми и при смене масштаба интерфейса.
float TextGap();

// Значок и подпись ОДНИМ блоком: значок вписан в квадрат line, подпись стоит за
// ним через TextGap и выровнена по середине той же высоты. Возвращает полную
// ширину блока — по ней его центрируют в кнопке или ячейке.
//
// Рисунком, а не элементами ImGui: так пара кладётся в любое место (в кнопку, в
// строку списка, в ячейку таблицы), не подавая собственного элемента и не сбивая
// «последний элемент», от которого работают подсказки и перетаскивание.
float DrawLabeled(ImDrawList* dl, ImVec2 pos, float line, const char* icon, ImU32 iconColor,
                  const char* text, ImU32 textColor);
// Ширина такой пары без отрисовки.
float LabeledWidth(float line, const char* text);

// Кнопка «иконка + подпись». tooltip показывается при наведении (nullptr — не
// показывать). Возвращает true при нажатии.
bool Button(const char* icon, const char* label, const char* tooltip = nullptr,
            bool active = false);

// Только иконка, размером с кнопку. Для тесных панелей (тулбар).
//
// hoverTint != nullptr — цвет значка ПОД КУРСОРОМ. Нужен там, где подложка
// кнопки под курсором заливается тем же цветом, что и значок: красная корзина
// на красной подложке пропадает целиком, и кнопка выглядит пустым квадратом —
// ровно в тот момент, когда на неё смотрят.
bool IconOnlyButton(const char* icon, const char* tooltip, bool active = false,
                    const glm::vec3& tint = kThemeColor, const glm::vec3* hoverTint = nullptr);

// ПУНКТ МЕНЮ СО ЗНАЧКОМ.
//
// ЗАЧЕМ. Контекстные меню разрослись: у файла в дереве проекта их восемь
// пунктов, у объекта в сцене — семь. Список из одинаковых серых строк читают
// ЦЕЛИКОМ, каждый раз, потому что зацепиться взгляду не за что; со значком
// нужный пункт находится по форме, до чтения. Те же значки стоят у этих же
// действий в панелях — «корзина» означает удаление везде.
//
// Значок рисуется ПОВЕРХ пункта, а не отдельным элементом: отдельный сделал бы
// «последним элементом» ImGui квадратик размером с букву, и меню перестало бы
// откликаться на клик (см. Overlay ниже).
bool MenuItem(const char* icon, const char* label, const char* shortcut = nullptr,
              bool enabled = true);

// Иконка внутри текстовой строки: занимает место одного символа и выравнена по
// базовой линии. Для списков (иерархия, консоль, ассеты).
void Inline(const char* icon, const glm::vec3& color = kThemeColor);

// Иконка ПОВЕРХ уже поданного элемента, в абсолютных экранных координатах.
//
// Отличие от Inline принципиальное, а не косметическое: Inline резервирует
// место через Dummy, то есть ПОДАЁТ СВОЙ ЭЛЕМЕНТ, и после него «последним
// элементом» для ImGui становится иконка. Всё, что читает последний элемент —
// IsItemClicked, BeginDragDropSource, BeginPopupContextItem, — начинает
// говорить про квадратик размером с букву вместо строки, к которой иконка
// нарисована. Overlay ничего не подаёт: это чистый рисунок в списке отрисовки,
// и строка остаётся строкой.
void Overlay(float x, float y, float size, const char* icon,
             const glm::vec3& color = kThemeColor);

// То же, но В ЗАДАННЫЙ список отрисовки.
//
// Нужна там, где рисуют ПОВЕРХ КАРТИНКИ СЦЕНЫ. Картинка вьюпорта лежит в
// дочернем окне ImGui, а дочерние окна выводятся ПОСЛЕ родительского: значок,
// поданный в список окна Viewport, честно рисуется — и целиком закрывается
// кадром сцены. Список нужного окна запоминается, пока оно открыто, и
// передаётся сюда.
void Overlay(ImDrawList* dl, float x, float y, float size, const char* icon,
             const glm::vec3& color = kThemeColor);

// Есть ли такая иконка. Неизвестное имя рисуется заглушкой (пустой квадрат с
// диагональю) — интерфейс не должен рассыпаться из-за опечатки.
bool Has(const char* icon);

// Перечисление всех имён: по нему проходит страница проверки и тесты.
int Count();
const char* NameAt(int index);

// Страница со всеми иконками на всех рабочих размерах (12–32 px).
//
// ЗАЧЕМ ОНА В ПРОГРАММЕ, А НЕ В ГОЛОВЕ. Иконка рисуется кодом, и увидеть её
// можно только там, где её вызвали: значок вьюпорта — открыв вьюпорт, значок
// консоли — доведя до ошибки. Половина рисунков так и не попадалась на глаза
// после правки, и «кривизна» жила месяцами. Здесь они лежат рядом и на всех
// размерах сразу — рассинхрон толщин и промахи мимо пиксельной сетки видно за
// секунду. Открывается через Window > Icon sheet (или SAGE_EDITOR_ICON_SHEET=1
// для скриншот-проверки).
void DrawSheet(bool* open);

} // namespace EditorIcons
