#pragma once
#include <string>

#include "ModelMaterialImport.h"

class Project;
class Scene;

// ---------------------------------------------------------------------------
// МОДЕЛЬ В СЦЕНУ — ИЕРАРХИЕЙ ОБЪЕКТОВ, как она устроена в файле.
//
// Раньше модель из нескольких частей (персонаж Blockbench: пояс, голова,
// руки, ноги со слоями) вставала ОДНИМ объектом: голову нельзя было
// повернуть, руку — спрятать, а скрипт не мог найти «Голову» по имени. Узлы
// файла при этом есть, с именами и своими трансформами, — они просто
// склеивались в один меш.
//
// Теперь каждый узел файла — свой объект: с именем узла, его местом
// относительно родителя и геометрией ТОЛЬКО этого узла (MeshRef::part);
// материалы назначаются по частям тем же импортом, что и у целой модели.
// Корень — пустой объект с именем модели: он несёт настройки импорта
// (масштаб, поворот, центрирование из .sageimport), и двигать модель
// целиком можно за него.
//
// Когда модель ставится ЦЕЛИКОМ, как раньше:
//   • в файле один узел с геометрией — иерархия из одного объекта ничего не
//     даёт;
//   • у модели есть скелет — её части двигают кости, и рисует её один
//     скелетный проход;
//   • в окне импорта снята галочка «Ставить иерархией объектов».
// ---------------------------------------------------------------------------
namespace sage::editor::modelhierarchy {

// Станет ли модель иерархией (без постановки — для подписи и проверок).
bool PlacesAsHierarchy(const std::string& modelRef);

// Ставит модель иерархией. Возвращает id корня или -1, если модель ставится
// целиком (см. выше) — тогда вызывающий ставит её как раньше. report — что
// сделал импорт материалов (сложено по всем частям).
int Place(const Project& project, Scene& scene, const std::string& modelRef,
          const std::string& rootName, ModelMaterialImportResult& report);

} // namespace sage::editor::modelhierarchy
