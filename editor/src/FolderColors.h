#pragma once
#include <filesystem>
#include <string>
#include <vector>

#include <glm/glm.hpp>

// ---------------------------------------------------------------------------
// ЦВЕТНЫЕ МЕТКИ ПАПОК — в дереве проекта и в списке сцены.
//
// ЗАЧЕМ. Папок в проекте быстро становится два десятка, и все они выглядят
// одинаково: один и тот же жёлтый значок, отличается только подпись. Найти
// среди них «текстуры персонажа» можно только чтением имён — по одному. Цвет
// находится боковым зрением, до чтения.
//
// ПОЧЕМУ ПАЛИТРА, А НЕ ПРОИЗВОЛЬНЫЙ ЦВЕТ. Метка обязана быть УЗНАВАЕМОЙ. Из
// круга оттенков человек выбирает восемь похожих болотных, и в списке они
// перестают различаться — то есть ради свободы выбора теряется ровно то, ради
// чего цвет и заводили. Восемь разнесённых тонов различаются всегда.
//
// ГДЕ ХРАНИТСЯ. Цвета папок ПРОЕКТА лежат в самом проекте
// (<проект>/folder_colors.json), а не в настройках редактора: раскладка папок —
// свойство проекта, и, открыв его на другой машине или отдав товарищу, человек
// ждёт ту же разметку. Цвет папки СЦЕНЫ живёт в самой сцене
// (FolderComponent::Color) по той же причине.
// ---------------------------------------------------------------------------
namespace sage::editor::foldercolors {

struct Tint {
    const char* Label;  // уже переведённая подпись
    glm::vec3 Color;
};

// Общая палитра: ею красят и папку проекта, и папку списка сцены. Одна на обе —
// иначе «зелёная папка» в дереве проекта и в сцене оказались бы разного зелёного.
//
// СОБИРАЕТСЯ ЗАНОВО НА КАЖДЫЙ ВЫЗОВ (как каталог объектов): подписи идут через
// T(), а язык редактора меняется на лету — замороженный в static список остался
// бы на языке, который был при первом открытии меню. Зовётся только когда меню
// раскрыто, так что цена — восемь указателей на кадр.
std::vector<Tint> Palette();

// Какой проект обслуживаем. Перечитывает файл цветов при СМЕНЕ пути; вызывать
// можно хоть каждый кадр.
void SetProject(const std::filesystem::path& projectDir);

// Цвет папки. false — цвет не назначен, рисовать как обычно.
bool Get(const std::filesystem::path& folder, glm::vec3& out);

// Назначить цвет и сразу записать файл: цвет, переживающий только текущий
// сеанс, — это цвет, который человек назначит второй раз и перестанет верить.
void Set(const std::filesystem::path& folder, const glm::vec3& color);

// Снять метку.
void Clear(const std::filesystem::path& folder);

// Папка переехала или переименована — метка едет с ней. Иначе раскладка
// рассыпалась бы от первого же переименования, причём молча.
void Rename(const std::filesystem::path& from, const std::filesystem::path& to);

} // namespace sage::editor::foldercolors
