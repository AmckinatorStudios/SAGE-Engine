#include <vector>

// ---------------------------------------------------------------------------
// КАТАЛОГ ОБЪЕКТОВ СЦЕНЫ: что предлагают «Объект > Создать» и правая кнопка в
// иерархии.
//
// ЗАЧЕМ. Раньше эти два меню были разными списками, написанными врозь. В меню
// «Объект» лежали примитивы, свет, наклейка, интерфейс и три штуки без общего
// признака — «Physics Cube», «Animated Object», «Particle Emitter»; по правой
// кнопке в иерархии не было ничего, кроме «пустой» и «куб». Человек, который
// один раз нашёл нужное в верхнем меню, второй раз искал его под правой
// кнопкой и не находил, а «Physics Cube» читался как отладочная кнопка автора
// движка, а не как предмет, который ставят в игру.
//
// Поэтому список ОДИН, живёт здесь и разложен по смыслу: формы, свет, камера,
// физика, эффекты, звук, логика, интерфейс. Оба меню рисуют его одной функцией
// и потому не могут разойтись.
//
// ПОЧЕМУ ЗДЕСЬ ТОЛЬКО ОГЛАВЛЕНИЕ. Создание объекта требует сцены, камеры и
// undo — всего того, что есть у EditorLayer. Каталог знает лишь ИМЯ действия
// (Item::Id) и отдаёт его хозяину редактора (EditorHost::CreateCatalogObject).
// Так список пунктов правится, не трогая код создания, и наоборот.
// ---------------------------------------------------------------------------
namespace sage::editor::objectcatalog {

struct Item {
    const char* Id;    // ключ действия: "shape.cube", "light.spot", ...
    const char* Label; // подпись (уже переведённая)
    const char* Hint;  // одна строка «что это» — подсказкой при наведении
};

struct Group {
    const char* Label;
    std::vector<Item> Items;
    std::vector<Group> Groups; // под-списки: «Эффекты > Частицы > Огонь»
};

// Корень каталога: Items — пункты верхнего уровня (пустой объект), Groups —
// категории.
//
// СОБИРАЕТСЯ ЗАНОВО НА КАЖДЫЙ ВЫЗОВ, а не кэшируется в static. Подписи идут
// через T(), а язык редактора меняется на лету: замороженный в static список
// остался бы на языке, который был при первом открытии меню. Вызывается он
// только когда меню РАСКРЫТО, так что цена — десяток указателей на кадр.
Group Catalog();

// Рисует каталог пунктами ImGui в уже открытом меню/всплывающем окне.
// Возвращает Id выбранного пункта или nullptr, если не выбрано ничего.
// Указатель живёт до конца работы программы (это литерал из таблицы выше).
const char* DrawMenu();

} // namespace sage::editor::objectcatalog
