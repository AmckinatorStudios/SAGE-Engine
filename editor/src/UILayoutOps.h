#pragma once
#include "sage/ui/UIAnchor.h"
#include "sage/ui/UILayoutTools.h"

class EditorHost;

// ---------------------------------------------------------------------------
// Операции вёрстки над ВЫДЕЛЕНИЕМ: выровнять, распределить, растянуть, сменить
// якорь.
//
// ПОЧЕМУ ОТДЕЛЬНО ОТ ПАНЕЛИ. Панель — это кнопки; операция — это «что при этом
// происходит со сценой». Их зовут двое: панель «Вёрстка» и (в будущем) меню и
// горячие клавиши. Спрятать операцию в обработчик кнопки значит согласиться,
// что повторить её можно только мышью по той же кнопке.
//
// ПОЧЕМУ НЕ В ДВИЖКЕ. Здесь есть выделение, undo и сцена редактора — то есть
// всё, чего в движке нет и быть не должно. Чистая математика (какие именно
// смещения) живёт в sage/ui/UILayoutTools.h и проверяется тестами; здесь —
// обход выделения и запись в компоненты.
//
// Каждая операция сама делает снимок для undo и сама молчит, когда делать
// нечего (пустое выделение, элементы без ui::Transform).
// ---------------------------------------------------------------------------
namespace uiops {

// Выровнять выделенные по краю. Целью служит ПЕРВИЧНЫЙ элемент (последний
// кликнутый), а если выделен ровно один — его РОДИТЕЛЬ.
//
// Второе важнее, чем кажется: «поставить надпись по центру панели» — самая
// частая операция вёрстки вообще, и выделять ради неё панель, чтобы стать
// целью, было бы лишним шагом. Выравнивание одного элемента относительно
// самого себя всё равно не значит ничего.
void Align(EditorHost& host, sage::ui::AlignEdge edge);

// Разложить выделенные поровну вдоль оси. byCenters — равнять шаг между
// центрами, иначе равные зазоры (см. UILayoutTools.h). Меньше трёх — молчит.
void Distribute(EditorHost& host, bool horizontal, bool byCenters);

// Растянуть выделенные на родителя с полями по краям (0 — вплотную).
void StretchToParent(EditorHost& host, float margin);

// Сменить якорь, ОСТАВИВ элемент на месте: пересчитывается Offset.
//
// Без пересчёта смена якоря в инспекторе телепортирует элемент в другой угол
// экрана — и выглядит это так, будто якорь «сломал» вёрстку. На деле якорь
// решает не где элемент сейчас, а куда он поедет при смене размера экрана, и
// менять его хочется именно у готового, уже поставленного элемента.
void SetAnchorKeepingPlace(EditorHost& host, UIAnchor anchor);

// Округлить положение и размер выделенных до шага сетки. Приводит в порядок
// экран, собранный до включения привязок, — иначе его пришлось бы перетаскивать
// заново поэлементно.
void SnapSelectionToGrid(EditorHost& host);

} // namespace uiops
