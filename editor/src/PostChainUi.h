#pragma once

#include "sage/render/PostEffect.h"

class EditorHost;

// ---------------------------------------------------------------------------
// Редактор тракта пост-обработки — ОДИН на два места.
//
// Тракт собирают в двух местах: в инспекторе камеры (её собственный тракт) и в
// окне настроек (тракт проекта, который уходит в собранную игру). Интерфейс у
// них один и тот же, и держать две копии нельзя: копии расходятся — сначала по
// мелочам, потом по составу кнопок, и «в настройках я могу, а в камере нет»
// объясняется уже ничем.
//
// Рисуется он ИЗ ОПИСАНИЙ звеньев, а не отдельным кодом на каждый эффект:
// поэтому новое звено каталога — в том числе принесённое игрой — появляется
// здесь само, без правки панелей.
// ---------------------------------------------------------------------------
namespace sage::editor {

// host == nullptr — правки НЕ пишутся в undo сцены. Так его зовёт окно
// настроек: тракт проекта живёт в `sage.cfg`, а не в сцене, и откатывать в нём
// нечего — файл сохраняют кнопкой.
//
// idScope разводит идентификаторы виджетов ImGui: один и тот же тракт может
// рисоваться в инспекторе и в настройках в одном кадре, и ImGui опознаёт
// виджеты по подписи — без разведения они бы «делили» состояние.
//
// Возвращает true, если тракт изменился: вызывающий сам решает, пометить сцену
// изменённой или записать конфиг.
bool DrawPostChainEditor(EditorHost* host, sage::render::PostChain& chain, const char* idScope);

} // namespace sage::editor
