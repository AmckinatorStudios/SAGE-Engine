#pragma once

#include "sage/render/PostEffect.h"

class EditorHost;

// ---------------------------------------------------------------------------
// Редактор пост-обработки камеры.
//
// РИСУЕТСЯ ПО ЭТАПАМ, А НЕ СПИСКОМ. Раньше здесь был список звеньев со
// стрелками «вверх/вниз»: порядок задавал человек, и он же мог его испортить.
// Свобода эта ничего не давала (осмысленный порядок обработки кадра ровно
// один) и стоила понимания: чтобы увидеть, что за чем идёт, надо было знать
// рендер.
//
// Теперь разделы идут в том порядке, в котором кадр проходит обработку
// (PostStage), и это ТОТ ЖЕ порядок, в котором звенья исполняются — исполнитель
// раскладывает их по этапам сам (PostChain::Ordered). Расходиться показанному и
// выполняемому стало негде.
//
// Каждый эффект — свой выключатель; выключенный показывает только заголовок.
// Список настроек, из которого не видно, что включено, — это и есть «десятки
// параметров сразу», от которых уходит этот экран.
//
// Сами разделы и параметры берутся ИЗ ОПИСАНИЙ звеньев (каталог), а не пишутся
// здесь по одному: поэтому эффект, принесённый игрой, появляется в инспекторе
// сам, в своём этапе и без правки панели.
// ---------------------------------------------------------------------------
namespace sage::editor {

// host == nullptr — правки НЕ пишутся в undo сцены.
//
// idScope разводит идентификаторы виджетов ImGui: один и тот же тракт может
// рисоваться в двух местах одного кадра, и ImGui опознаёт виджеты по подписи.
//
// Возвращает true, если тракт изменился.
bool DrawPostChainEditor(EditorHost* host, sage::render::PostChain& chain, const char* idScope);

} // namespace sage::editor
