#pragma once
#include "sage/ui/UILayoutTools.h"

// ---------------------------------------------------------------------------
// Настройки инструментов вёрстки — ОДНИ на редактор.
//
// Их читают двое: панель «Вёрстка» (человек их крутит) и холст во вьюпорте
// (он по ним притягивает и рисует сетку). Пока каждый держал бы своё, шаг
// сетки в панели и шаг, по которому притягивается мышь, разъехались бы при
// первой же правке — а выглядело бы это как «привязка не работает».
//
// Живут у EditorLayer и раздаются через EditorHost, как и остальное общее
// состояние редактора (режим гизмо, шаг привязки 3D, режим рендера).
// ---------------------------------------------------------------------------
struct UIToolSettings {
    // Сетку ПОКАЗЫВАТЬ и по сетке ПРИТЯГИВАТЬ — разные вещи, и разделены они
    // намеренно: сетка как линейка (видно, но не липнет) нужна не реже, чем
    // притяжка вслепую.
    bool ShowGrid = true;
    sage::ui::SnapSettings Snap;

    // Подписи расстояний до краёв родителя, пока элемент тянут. Верстают по
    // отступам («16 от края»), а не по абсолютным координатам, и без подписи
    // эти отступы приходится считать в уме по двум числам из инспектора.
    bool ShowDistances = true;

    // Показывать рамки НЕ выделенных элементов. Когда экран собран, полсотни
    // синих рамок мешают смотреть на сам интерфейс — тогда их выключают.
    bool ShowAllOutlines = true;

    // Размер кадра, в котором вёрстка считалась в ПОСЛЕДНИЙ раз. Пишет холст
    // (он один знает размер своего слота вьюпорта), читают операции панели.
    //
    // Не «настройка», а именно общее знание, и держать его здесь честнее, чем
    // заводить ради него ещё один путь: выравнивание считает прямоугольники
    // элементов, а те зависят от размера экрана — панель обязана считать их в
    // ТОМ ЖЕ кадре, что и видно во вьюпорте, иначе кнопка «по левому краю»
    // сдвинет элемент не туда, куда человек смотрит.
    glm::vec2 FrameSize{1920.0f, 1080.0f};
};
