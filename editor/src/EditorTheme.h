#pragma once
#include <string>
#include <vector>

#include "imgui.h"

// ---------------------------------------------------------------------------
// ОФОРМЛЕНИЕ РЕДАКТОРА: тема — это ДАННЫЕ, а не код.
//
// БЫЛО. Одна функция Apply() на сто строк, где цвета и метрики прописаны
// прямо в вызовах ImGui. Поменять вид редактора можно было единственным
// способом — правкой C++ и пересборкой; иметь два оформления сразу нельзя
// было вовсе; человек, которому не подходит тёмная тема, не мог сделать
// ничего. И при этом панели всё равно рисовали своими цветами мимо этой
// функции — красный «удалить», зелёный «включено», — поэтому даже правка
// Apply() меняла вид не целиком.
//
// СТАЛО. Тема — структура: палитра ролей плюс метрики. Их список открыт:
// встроенные темы лежат в коде, дополнительные — файлами `themes/*.json`
// рядом с редактором, и добавить своё оформление можно, ничего не собирая.
// Панели спрашивают цвет ПО РОЛИ (Role::Danger), а не по значению, поэтому
// новая тема перекрашивает и их тоже.
//
// ПОЧЕМУ РОЛИ, А НЕ ИМЕНА ЦВЕТОВ. «Красный» в светлой теме — другой красный,
// чем в тёмной: на белом фоне яркий #E5484D режет глаза и хуже читается. Роль
// («опасное действие») переживает смену темы, конкретный цвет — нет.
// ---------------------------------------------------------------------------
namespace EditorTheme {

// Роли цвета. Порядок важен: по нему темы читаются из JSON и по нему же
// расставляются цвета ImGui.
// СЛОИ ФОНА ИДУТ ЛЕСЕНКОЙ, и каждый чуть светлее предыдущего:
//
//     Bg          фон приложения, пустой док
//      -> Surface     поверхность панели
//         -> SurfaceAlt  приподнятое внутри панели (карточка, заголовок раздела)
//            -> Input       поле ввода, кнопка
//               -> Hover / Selected
//
// Одинаковый цвет у всех панелей — самый заметный признак «просто ImGui»:
// границы между областями видно только по рамкам, и экран читается как одно
// серое поле. Лесенка даёт глубину без единой тени.
enum class Role {
    Bg,            // самый дальний слой: фон приложения, пустой док
    Surface,       // поверхность окна/панели
    SurfaceAlt,    // приподнятое внутри панели: карточка, шапка раздела
    Elevated,      // ещё выше: всплывающая карточка, активная вкладка
    Input,         // поле ввода, кнопка, невыбранная вкладка
    Overlay,       // всплывающие окна и меню

    Line,          // разделители и рамки
    LineStrong,    // рамка, которую видно намеренно

    Text,          // основной текст
    TextDim,       // подписи, пояснения
    TextFaint,     // отключённое, водяные знаки
    TextOnAccent,  // текст поверх акцентной заливки

    Accent,        // фирменный жёлтый SAGE: выделение, активное состояние
    AccentHover,
    AccentActive,
    AccentMuted,   // акцент как подложка (выделенная строка) — не заливка

    Hover,         // наведение на строку/кнопку
    Selection,     // выбранная строка списка или дерева

    Ok,            // «сделано», «включено»
    Warn,          // «внимание»
    Danger,        // «удалить», «ошибка»
    Info,          // подсказка, ссылка

    _Count
};

// Метрики: сколько воздуха и насколько скруглены углы. Отдельно от цвета,
// потому что «современно» — это в первую очередь ОТСТУПЫ и радиусы, а не
// палитра: та же палитра в плотной раскладке выглядит как панель приборов, а
// в просторной — как современное приложение.
//
// БАЗОВЫЕ значения живут в Sage::UI::Style (ui/UIStyle.h) на сетке в 4 точки;
// здесь тема может их СДВИНУТЬ — например «классическая» делает плотнее и
// возвращает рамки. Тема задаёт характер, сетка — порядок.
struct Metrics {
    float FontSize = 16.0f;         // базовый кегль (масштаб интерфейса — отдельно)
    float Radius = 8.0f;            // окна, всплывающие
    float RadiusFrame = 6.0f;       // поля, кнопки, вкладки
    float RadiusSmall = 4.0f;       // грабы, полосы прокрутки
    ImVec2 WindowPadding{12, 10};
    ImVec2 FramePadding{10, 6};
    ImVec2 ItemSpacing{8, 7};
    ImVec2 ItemInnerSpacing{7, 5};
    ImVec2 CellPadding{8, 5};
    float ScrollbarSize = 12.0f;
    float GrabMinSize = 12.0f;
    float IndentSpacing = 18.0f;
    float BorderWindow = 0.0f;      // 0 — слои разделяет фон, а не линия
    float BorderFrame = 0.0f;
    float BorderPopup = 1.0f;
    float TabOverline = 3.0f;       // полоса акцента над активной вкладкой
    float SeparatorSize = 1.0f;
};

struct Theme {
    std::string Id;                 // в настройках и в аргументах самопроверки
    std::string Name;               // подпись в меню; НЕ переводится (см. язык)
    bool Dark = true;               // подсказка для мест, где нужен контраст
    ImVec4 Colors[(int)Role::_Count]{};
    Metrics Metric;
};

// Подготовить список тем и применить сохранённую. Зовётся один раз, ДО первого
// кадра и после ImGui::CreateContext.
void Init();

// Все темы в порядке показа: сначала встроенные, потом найденные в файлах.
const std::vector<Theme>& Themes();

// Текущая тема (после Init всегда существует).
const Theme& Current();
const std::string& CurrentId();

// Переключить тему по идентификатору и запомнить выбор. false — такой темы
// нет: молча оставить прежнюю честнее, чем показать не то, что просили.
bool SetTheme(const std::string& id);

// Масштаб интерфейса, 0.75…2.0. Отдельно от темы: это свойство ЭКРАНА и глаз,
// а не оформления, и переживает переключение тем.
float UiScale();
void SetUiScale(float scale);

// Цвет по роли — для панелей. Именно так, а не константой в файле панели:
// иначе новая тема перекрашивает всё, кроме той панели.
ImVec4 Color(Role role);
ImU32 Color32(Role role);
// Тот же цвет с другой прозрачностью — для подложек и подсветки строк.
ImVec4 ColorAlpha(Role role, float alpha);
ImU32 Color32Alpha(Role role, float alpha);

// --- готовые элементы, чтобы панели не красили себя сами -----------------
//
// Панель, рисующая свой цвет константой, выпадает из темы: сменил оформление —
// а «Удалить» осталось того же красного, что было подобрано под тёмный фон.
// Поэтому одинаковые по смыслу места собраны здесь.

// Заголовок раздела инспектора («Преобразование», «Отрисовка меша»).
//
// Отдельно от ImGui::CollapsingHeader ради вида: ImGui красит заголовок тем же
// цветом, что и ВЫДЕЛЕННУЮ строку списка (ImGuiCol_Header), и от этого каждый
// раздел инспектора выглядел выделенным — десяток синих полос сверху вниз.
// Здесь заголовок нейтральный, а акцент остаётся тому единственному месту, где
// он что-то значит: выбранному объекту в иерархии.
bool SectionHeader(const char* label, ImGuiTreeNodeFlags flags = ImGuiTreeNodeFlags_DefaultOpen);

// Кнопка в смысловом цвете: Role::Danger — «удалить», Role::Ok — «играть».
bool ColoredButton(const char* label, Role role, const ImVec2& size = ImVec2(0, 0));

// Применить текущую тему к ImGuiStyle. Вызывается из Init и при смене темы;
// отдельно наружу — для случая, когда стиль сбросили (мульти-вьюпорт).
void Apply();

// Шрифт с кириллицей (assets/fonts/editor.ttf либо системный DejaVu/SegoeUI);
// без него русский текст рисуется как '???'. Вызывать до создания атласа.
void LoadFont();

// Записать тему файлом JSON — чтобы взять текущую за основу своей. Ровно тот
// формат, который читается из themes/*.json.
bool ExportTheme(const Theme& theme, const std::string& path);

// Где редактор ищет дополнительные темы (themes/ рядом с бинарником).
std::string ThemesDir();

} // namespace EditorTheme
