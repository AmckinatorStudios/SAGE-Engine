#pragma once
#include <functional>
#include <string>
#include <unordered_map>

// ---------------------------------------------------------------------------
// Подтверждение опасного действия.
//
// ЗАЧЕМ. Удаление сущности, удаление файла ассета, замена несохранённой сцены —
// всё это делалось СРАЗУ по нажатию, без вопроса. Undo спасает не всегда: он не
// покрывает файлы на диске и обнуляется при смене сцены. Один промах мышью
// стоил часа работы.
//
// ПОЧЕМУ С ГАЛОЧКОЙ «БОЛЬШЕ НЕ СПРАШИВАТЬ». Диалог, который нельзя выключить,
// перестают читать: человек, удаляющий двадцать объектов подряд, жмёт «Да»
// вслепую — и подтверждение превращается в лишний клик, ничего не защищающий.
// Галочка возвращает вопросу смысл: он остаётся у тех действий, которые человек
// делает редко, и уходит там, где он делает их пачками. Решение запоминается
// ПО ВИДУ ДЕЙСТВИЯ, а не одно на всё: выключив вопрос про удаление объекта,
// человек не должен молча лишиться вопроса про удаление файла с диска.
//
// Ответ хранится в настройках редактора, то есть переживает перезапуск, и
// сбрасывается в Settings — иначе выключенный по ошибке вопрос вернуть было бы
// нечем.
// ---------------------------------------------------------------------------
class ConfirmDialog {
public:
    // Спрашивает подтверждение. Если для kind ответ «не спрашивать» уже дан,
    // действие выполняется немедленно.
    //
    // kind — устойчивый ключ вида "delete-entity": по нему запоминается ответ.
    void Ask(const char* kind, std::string title, std::string message,
             std::function<void()> onConfirm, const char* confirmLabel = "Удалить");

    // Рисует диалог (звать раз за кадр на уровне окна-хоста).
    void Draw();

    // --- Настройки ----------------------------------------------------------
    bool IsSuppressed(const char* kind) const;
    void SetSuppressed(const char* kind, bool suppressed);
    void ResetAll() { m_suppressed.clear(); }
    const std::unordered_map<std::string, bool>& Suppressed() const { return m_suppressed; }

private:
    std::unordered_map<std::string, bool> m_suppressed;

    bool m_open = false;
    bool m_needsOpen = false;
    bool m_dontAskAgain = false;
    std::string m_kind, m_title, m_message, m_confirmLabel;
    std::function<void()> m_action;
};
