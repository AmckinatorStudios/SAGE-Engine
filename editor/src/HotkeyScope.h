#pragma once

// ---------------------------------------------------------------------------
// КОМУ ПРИНАДЛЕЖИТ КЛАВИША В ЭТОМ КАДРЕ.
//
// ЗАЧЕМ. У редактора есть общие горячие клавиши: Delete удаляет выбранный
// объект, Ctrl+D его дублирует. Но у панелей есть СВОИ: в инструменте анимации
// Delete убирает выбранные ключи, в панели ассетов — файл, в списке элементов
// интерфейса Delete и Ctrl+D работают со своим выделением.
//
// ImGui::IsKeyPressed нажатие не «съедает», поэтому срабатывали ОБА. Человек
// правил анимацию — и вместе с ключом лишался объекта, который анимировал.
// Ctrl+D в списке элементов давал ДВЕ копии вместо одной: одну от панели,
// вторую от общего обработчика.
//
// Проверять в общем обработчике имя окна в фокусе нельзя: имена окон переведены
// и собираются из кусков (см. PanelWindowId.h), то есть список имён разошёлся бы
// с панелями на первой же правке перевода.
//
// Поэтому наоборот: панель, разобравшая клавишу, ГОВОРИТ ОБ ЭТОМ, а общий
// обработчик молчит, если её уже забрали.
// ---------------------------------------------------------------------------
namespace sage::editor::hotkeys {

// Клавиши, у которых есть и общий смысл, и свой у отдельных панелей.
enum class Key {
    Delete,     // удалить: объект сцены / ключ анимации / файл / элемент
    Duplicate,  // Ctrl+D
    Count,
};

// Начало кадра редактора: заявки прошлого кадра сдвигаются, новые обнуляются.
void NewFrame();

// «Эта клавиша в текущем кадре моя». Зовётся ПАНЕЛЬЮ, пока она в фокусе.
void Claim(Key key);

// Забрал ли кто-то клавишу. Учитывает и ПРОШЛЫЙ кадр — и это не небрежность:
// общий обработчик стоит в кадре РАНЬШЕ панелей (сначала рисуется окно-хост с
// меню и хоткеями, и только потом сами панели), так что спрашивать «забрали
// ли» до того, как панели успели забрать, бессмысленно. Соврать это не может:
// панель заявляет клавишу КАЖДЫЙ кадр, пока она в фокусе, а не в момент
// нажатия, — то есть «забирали в прошлом кадре» означает ровно «панель в
// фокусе и сейчас».
bool Claimed(Key key);

} // namespace sage::editor::hotkeys
