// КОМУ ПРИНАДЛЕЖИТ КЛАВИША В ЭТОМ КАДРЕ.
//
// ЗАЧЕМ. Delete у редактора значит «удалить выбранный объект», и разбирает его
// общий обработчик в конце кадра. Но у панелей есть СВОИ Delete: в инструменте
// анимации он убирает выбранные ключи, в панели ассетов — файл, в списке
// элементов интерфейса — элемент. ImGui::IsKeyPressed не «съедает» нажатие:
// панель убирала ключ, а следом тот же Delete доходил до общего обработчика и
// удалял из сцены ЦЕЛЫЙ ОБЪЕКТ. Человек правил анимацию — и лишался того, что
// анимировал, без единого вопроса.
//
// Проверять в общем обработчике имя окна в фокусе нельзя: имена окон
// переведены и собираются из кусков (см. PanelWindowId.h), то есть список имён
// разошёлся бы с панелями на первой же правке перевода.
//
// Поэтому наоборот: панель, разобравшая клавишу, ГОВОРИТ ОБ ЭТОМ. Общий
// обработчик стоит последним в кадре и молчит, если клавишу уже забрали.
// ---------------------------------------------------------------------------
namespace sage::editor::hotkeys {

// Начало кадра редактора: забытые заявки прошлого кадра сбрасываются.
void NewFrame();

// «Delete в этом кадре мой». Зовётся ПАНЕЛЬЮ, когда она его разобрала.
void ClaimDelete();

// Забрал ли кто-то Delete. Учитывает и прошлый кадр — см. HotkeyScope.cpp:
// общий обработчик стоит раньше панелей, и иначе он спрашивал бы до того, как
// панели успели ответить.
bool DeleteClaimed();

} // namespace sage::editor::hotkeys
