#pragma once
#include <filesystem>
#include <string>
#include <vector>

// ---------------------------------------------------------------------------
// ЧЕМ ОТКРЫВАТЬ КОД: выбор внешнего редактора или IDE.
//
// ЗАЧЕМ. Своего редактора кода в SAGE нет намеренно (см. EditorHost::
// OpenFileInSystemEditor): он соревновался бы с тем, где у человека настроены
// горячие клавиши, автодополнение, переход к определению и git, — и проигрывал
// бы. Но «открыть системной ассоциацией» — это не ответ целиком, и вот почему:
//
//   • Ассоциация для .lua у большинства не задана вовсе. На Windows двойной
//     клик по .lua в лучшем случае открывает «Блокнот», в худшем — окно «чем
//     открыть этот файл». На Linux xdg-open для .lua нередко молчит.
//   • Ассоциация одна на всю систему, а редакторов у человека обычно два:
//     тяжёлая IDE для работы и что-то лёгкое для «глянуть одну строчку».
//   • Ассоциация не умеет НОМЕР СТРОКИ. Ошибка в скрипте приходит как
//     «hero.lua:42», и открывать файл, чтобы потом искать строку руками, —
//     это ровно та работа, которую должен делать редактор.
//
// Поэтому здесь список известных редакторов, у каждого своя команда запуска и
// свой способ передать строку. Правило одно и жёсткое: показывается только то,
// что НА ЭТОЙ МАШИНЕ ДЕЙСТВИТЕЛЬНО ЕСТЬ. Пункт «Visual Studio Code» у человека
// без VS Code — это обещание, которое не выполнится: он выберет, нажмёт, и
// ничего не произойдёт.
//
// Выбор хранится в настройках РЕДАКТОРА (editor_prefs.json), а не в проекте:
// чем я открываю код — моя привычка на моей машине, а не свойство игры. Проект,
// навязывающий соавтору свою IDE, — не то, чего от проекта ждут.
// ---------------------------------------------------------------------------
namespace sage::editor::codeapp {

// Один известный редактор.
struct App {
    std::string Id;        // "vscode" — им выбор хранится в настройках
    std::string Name;      // «Visual Studio Code» — НЕ переводится: это имя программы
    std::string Command;   // чем запускать (исполняемый файл или полный путь)
    // Аргументы с подстановками {file} и {line}. Пусто — просто «команда файл».
    std::string ArgsWithLine;  // умеет открыть на строке
    std::string Args;          // без строки
};

// Все редакторы, которые НАЙДЕНЫ на этой машине. Считается один раз за сеанс:
// поиск программы — это обращение к диску по каждому кандидату, а список
// установленного за сеанс не меняется.
const std::vector<App>& Available();

// Заново поискать (пункт «Найти заново» в меню — человек поставил IDE, не
// перезапуская редактор).
void Rescan();

// Что выбрано. Пусто — «как откроет система», выбор по умолчанию.
std::string CurrentId();
void SetCurrent(const std::string& id);

// Имя выбранного для показа человеку. Пусто — системная ассоциация.
std::string CurrentName();

// Открыть файл выбранным редактором. line > 0 — попросить встать на строку;
// редактор, который так не умеет, откроет файл целиком.
//
// false — не открылось; причина уходит в лог. Вызывающий обязан это показать:
// молчащий отказ неотличим от сломанной кнопки.
bool Open(const std::filesystem::path& file, int line = 0);

// Разложить "{file}"/"{line}" в готовую строку аргументов. Отдельно — чтобы
// подстановку можно было проверить тестом, не запуская ничего.
std::string ExpandArgs(const std::string& pattern, const std::filesystem::path& file, int line);

} // namespace sage::editor::codeapp
