// ---------------------------------------------------------------------------
// Перечисления редактора, на которые ссылаются И контракт панелей (EditorHost),
// И состояние инструментов (EditorTools).
//
// Отдельным файлом, потому что иначе они замкнулись бы в кольцо: инструментам
// нужен режим показа и пространство гизмо, а контракту панелей — сами
// инструменты. Перечислениям при этом не нужно ничего: ни сцены, ни ImGui, ни
// заголовков движка.
// ---------------------------------------------------------------------------

// РАБОЧЕЕ ПРОСТРАНСТВО РЕДАКТОРА — набор панелей под одну задачу.
//
// Сцену расставляют и интерфейс верстают по-разному, и панели им нужны разные.
// Пока редактор интерфейса был ОДНИМ окном, внутри него жили собственные
// колонки: дерево слева, холст в центре, свойства справа — и ни одну из них
// нельзя было ни перетащить, ни отстыковать, ни положить на второй монитор.
// То есть внутри редактора с доккингом существовал кусок без доккинга, и
// правила там были свои.
//
// Пространство — это НЕ режим вьюпорта: переключение меняет состав панелей, а
// не поведение того, что уже открыто. У каждого пространства своё
// док-пространство, поэтому раскладки не мешают друг другу и сохраняются
// каждая своя.
enum class EditorWorkspace {
    Scene,      // расстановка объектов: Viewport, Game, Hierarchy, Inspector...
    Interface,  // вёрстка интерфейса: холст игрового кадра, дерево элементов...
    Count
};

// Состояние Play-режима редактора (см. EditorLayer): вынесено из класса,
// чтобы панели зависели от контракта EditorHost, а не от EditorLayer.
enum class EditorPlayState { Editing, Playing, Paused };

// Режим отображения сцены во вьюпорте (View > Render Mode / тулбар).
//   Shaded    — полное освещение (по умолчанию);
//   Wireframe — каркас (полигоны линиями), плоский цвет для читаемости;
//   дальше    — отладочные виды из sage/render/DebugView.h: вместо результата
//               освещения показывается одно его слагаемое.
//
// Порядок первых двух зафиксирован (на них завязан каркасный режим), остальные
// идут ровно как в DebugView и переводятся в него сдвигом — держать два разных
// порядка значило бы однажды показать шероховатость под именем нормалей.
enum class EditorRenderMode {
    Shaded,
    Wireframe,
    Unlit,
    Normals,
    Albedo,
    Roughness,
    Metallic,
    Emissive,
    AmbientOcclusion,
    Shadow,
    Depth,
    Cascades,
    WorldGrid,
    Count
};

// Панели редактора, у которых есть кнопка быстрого доступа в верхней панели и
// пункт в меню Window. Перечислением, а не строкой: опечатка в имени панели
// должна быть ошибкой компиляции, а не тихо не работающей кнопкой.
enum class EditorPanel {
    Hierarchy,
    Inspector,
    Environment,   // окно среды сцены (небо, воздух, окружающий свет)
    Assets,
    Console,
    Profiler,
    Game,
    Viewport,
    UIEditor,      // редактор интерфейса (холст игрового кадра + элементы)
    Settings,      // окно настроек движка (качество и цена кадра)
    Input,         // раскладка управления проекта (действия и привязки)
    // --- пространство «Интерфейс» ---
    InterfaceHierarchy, // дерево элементов интерфейса
    InterfaceViewport,  // холст: игровой кадр с гизмо и сеткой
    InterfaceInspector, // свойства элемента и его компонентов
    InterfacePreview,   // тот же кадр без единого гизмо — как увидит игрок
    // ИНСТРУМЕНТ АНИМАЦИИ — ОДИН НА ОБА ПРОСТРАНСТВА. Двигать кнопку
    // интерфейса и двигать предмет сцены — одно действие над разными
    // свойствами, и второй панели ради этого различия заводить незачем.
    Animation,
    Count
};

// Пространство манипулятора гизмо: Local — оси объекта, World — оси мира.
enum class EditorGizmoSpace { Local, World };
