#pragma once
#include <cstdint>
#include <filesystem>
#include <string>

// ---------------------------------------------------------------------------
// Обложки картинок — асинхронно, уменьшенными, с мипмапами.
//
// ЧТО БЫЛО. Обложкой картинки в редакторе служила САМА картинка: файловый
// диалог и панель ассетов звали ResourceManager::GetTexture и рисовали
// полученное в площадку 80x80. Три беды разом, и все три человек видит:
//
//   1. ЗАГРУЗКА ВСТАЁТ КОЛОМ. GetTexture — синхронный: он открывает файл,
//      декодирует его целиком и заливает в видеопамять ПРЯМО В КАДРЕ. Папка
//      «Изображения» с сотней фотографий по 4000x3000 — это сотня полных
//      декодирований в одном кадре и полтора гигабайта в видеопамяти ради
//      картинок размером с ноготь. Диалог замирал на секунды, и выглядело это
//      как зависание редактора.
//   2. КАЧЕСТВО. Текстура 4000 пикселей, нарисованная в 80, читается ОДНИМ
//      пикселем из каждых пятидесяти: половина деталей просто не попадает в
//      выборку, и обложка получается рваной и рябящей — то самое «пиксельное
//      качество». Лечится это не фильтром при отрисовке, а мипмапами: усреднить
//      2500 пикселей в один обязан тот, кто картинку готовит.
//   3. СООТНОШЕНИЕ СТОРОН. Картинка растягивалась на всю площадку, поэтому
//      панорама 3:1 выходила квадратом. Узнать по такой обложке свой файл
//      нельзя — а обложка ровно для этого и нужна.
//
// ЧТО ЗДЕСЬ. Отдельный кэш обложек: файл декодируется в ФОНОВОМ потоке и сразу
// уменьшается до нужной стороны усреднением (то есть с учётом всех пикселей, а
// не каждого пятидесятого), главный поток только заливает готовое в
// видеопамять — по нескольку штук за кадр, чтобы кадр не проседал. Размеры
// ИСХОДНОЙ картинки возвращаются вместе с обложкой: соотношение сторон считает
// тот, кто рисует, и растянуть картинку больше нечем.
//
// ПОЧЕМУ НЕ GetTextureAsync. Он тоже фоновый, но грузит картинку ЦЕЛИКОМ и
// кладёт её в общий кэш ресурсов — то есть беда №1 остаётся в полном объёме
// (видеопамять), а вместе с ней приходит новая: просмотр чужой папки засоряет
// кэш ресурсов проекта и вытесняет из него текстуры сцены.
// ---------------------------------------------------------------------------
namespace thumbs {

// Насколько крупная обложка нужна. Два размера, а не один: плиткам хватает
// маленькой (их полсотни на экране), а превью под курсором обязано показывать
// подробности — ради них его и открывают.
enum class Size {
    Tile,   // список и сетка: сторона не больше 256
    Large,  // превью при наведении: сторона не больше 1024
};

struct Thumb {
    uint64_t Id = 0;      // текстура для ImGui; 0 — рисовать нечего
    int W = 0, H = 0;     // размеры ИСХОДНОЙ картинки (соотношение сторон и подпись)
    bool Loading = false; // файл ещё читается фоновым потоком
    bool Failed = false;  // не открылась; почему — в Error
    std::string Error;    // готовая строка для человека (уже переведена)
};

// Есть ли смысл просить обложку у этого файла (картинка ли это по расширению).
bool IsImage(const std::filesystem::path& path);

// Обложка файла. Первый вызов ставит задачу фоновому потоку и возвращает
// Loading; готовая приезжает через несколько кадров.
Thumb Get(const std::filesystem::path& path, Size size = Size::Tile);

// Заливает в видеопамять то, что успел декодировать фоновый поток, и отпускает
// обложки, на которые давно не смотрели. ОБЯЗАН зваться на главном потоке раз в
// кадр (у него единственного контекст видеокарты). Возвращает число залитых.
int Pump();

// Отпустить всё (смена проекта, закрытие редактора).
void Clear();

} // namespace thumbs
