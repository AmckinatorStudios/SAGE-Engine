#pragma once
#include <filesystem>
#include <string>
#include <vector>

class EditorHost;
class AssetPreview;

// ---------------------------------------------------------------------------
// Слот ассета и перетаскивание — ОДИН виджет на весь редактор.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Слоты «меш», «материал», «текстура», «скрипт» были
// написаны по отдельности и вели себя по-разному: у меша поле ввода пути, у
// материала — превью и три кнопки, у текстур — свой вариант, у скрипта — свой.
// Разными были и приём перетаскивания (у одних есть, у других нет), и проверка
// типа (у одних по расширению, у других никакой), и поведение при промахе
// (молча ничего). Человек, научившийся назначать материал, приходил к мешу и
// начинал заново.
//
// Главное же: перетаскивание МОЛЧАЛО. Бросок файла не того типа не делал
// ничего — ни отказа, ни объяснения; со стороны это неотличимо от «редактор
// подвис» или «слот сломан». Слот обязан отвечать ещё ДО того, как отпустили
// кнопку: подсветиться зелёным, если возьмёт, и красным с объяснением, если
// нет. Здесь это делается один раз и достаётся всем слотам сразу.
//
// Ассет можно и ВЫТАЩИТЬ из слота: назначенный материал перетаскивается в слот
// другого объекта. Раньше источником перетаскивания была только панель Assets,
// то есть «скопировать материал с объекта на объект» означало вспомнить его имя
// и найти файл в дереве проекта.
// ---------------------------------------------------------------------------
namespace assetslot {

// Тип ассета, который слот готов принять. Any — принимает всё (панель Assets и
// вьюпорт решают по расширению, что значит «бросили сюда»).
enum class Kind { Any, Model, Material, Texture, Script, Prefab, Scene, Audio };

// Тип файла по расширению. Единственное место, где расширения превращаются в
// смысл: раньше эти списки были переписаны в семи местах и уже разошлись —
// .fbx умел импортироваться, но слот меша про него не знал.
Kind KindOf(const std::filesystem::path& path);

// Возьмёт ли слот такого типа этот файл.
bool Accepts(Kind slot, const std::filesystem::path& path);

// Название типа для человека («материал») — для отказа и подсказок.
const char* KindName(Kind kind);
// Значок типа (см. EditorIcons) — для пустого слота и для карточки перетаскивания.
const char* KindIcon(Kind kind);
// Расширения типа — для файлового диалога и для подсказки «поддерживаются…».
std::vector<std::string> Extensions(Kind kind);

// Тип полезной нагрузки перетаскивания. Один на весь редактор: путь строкой с
// завершающим нулём.
inline const char* kPayload = "SAGE_ASSET_PATH";

// Начать перетаскивание ассета (панель Assets, слоты, дерево проекта).
// Рисует под курсором обложку и имя — тащат обычно из десятка похожих файлов.
void BeginDrag(const std::filesystem::path& path, AssetPreview* preview);

// Что произошло со слотом за кадр.
struct Result {
    bool Changed = false;         // путь изменился (назначен или очищен)
    bool Cleared = false;         // нажали «убрать»
    bool BrowseRequested = false; // нажали «Обзор…» — диалог открывает вызывающий
    std::string Path;             // новый путь (при Changed)
};

// Слот: превью, имя, приём броска, «показать в Assets», очистка, «Обзор…».
//
// path передаётся ЗНАЧЕНИЕМ и не меняется на месте: вызывающий сам решает,
// когда записать новое значение, и делает это ПОСЛЕ PushUndoSnapshot —
// иначе отмена возвращала бы уже изменённое состояние.
Result Draw(EditorHost& host, const char* id, Kind kind, const std::string& path,
            AssetPreview* preview, const char* emptyHint = nullptr);

} // namespace assetslot
