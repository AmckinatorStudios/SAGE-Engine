// ИМЯ ОКНА ПАНЕЛИ В КОНКРЕТНОМ ПРОСТРАНСТВЕ.
//
// ЧТО БЫЛО НЕ ТАК. Ассеты, консоль и инструмент анимации нужны и в сцене, и в
// вёрстке, и до сих пор это было ОДНО окно ImGui на оба пространства. Окно
// может быть докнуто ровно в один узел, а узлов два — и всё остальное следовало
// отсюда:
//
//   • Раскладка второго пространства, построившись, ЗАБИРАЛА окно себе:
//     DockBuilderDockWindow переносит его из чужого узла в свой.
//   • Узел, из которого окно ушло последним, оставался пустым и удалялся —
//     возвращать панель становилось некуда, и в сцене она всплывала отдельным
//     окном посреди экрана.
//   • А иногда не всплывала вовсе: узла нет, окно докнуто в узел другого
//     пространства, которое сейчас не рисуется, — панель просто исчезала.
//
// Чинить это перекладыванием окна туда-обратно бессмысленно: пока окно одно,
// каждое переключение — это спор двух раскладок за него, и выигрывает та, что
// построилась последней.
//
// ЧТО ЗДЕСЬ. У каждого пространства СВОЁ окно панели: «Assets» в сцене и
// «AssetsUI» в вёрстке. Спорить больше не о чем — каждая раскладка владеет
// своими окнами и ничего не забирает у соседа.
//
// СОСТОЯНИЕ ПАНЕЛИ ПРИ ЭТОМ ОДНО: и там, и там рисует один и тот же объект
// (AssetsPanel, ConsolePanel), просто в окно с другим именем. Папка, в которую
// человек зашёл в сцене, остаётся открытой и в вёрстке — это одна панель, а не
// две; разное у них ровно одно — место в доке.
//
// ОДНО МЕСТО, ГДЕ ЭТО ПРАВИЛО ЗАПИСАНО. Имя нужно троим: самой панели (она
// открывает окно), строителю раскладки (он его докует) и меню «Отдельным
// окном». Три копии правила разошлись бы на первой же новой панели.
// ---------------------------------------------------------------------------
namespace sage::editor::panelid {

// Имя окна панели в этом пространстве. base — имя в пространстве сцены
// («Assets»); в вёрстке к нему добавляется «UI».
//
// Возвращает строку, а не указатель: имя собирается, а не выбирается из
// таблицы, и отдавать указатель на временную строку — верный способ получить
// окно со случайным именем.
inline std::string For(const char* base, EditorWorkspace workspace) {
    return workspace == EditorWorkspace::Interface ? (std::string(base) + "UI") : std::string(base);
}

// Заголовок окна: перевод плюс «###» с именем. ИМЯ ВСЕГДА ПОСЛЕ «###», потому
// что видимая часть переводится, а идентификатор окна обязан пережить смену
// языка (иначе раскладка теряется при переключении на английский).
inline std::string Title(const char* translated, const std::string& id) {
    return std::string(translated) + "###" + id;
}

} // namespace sage::editor::panelid
