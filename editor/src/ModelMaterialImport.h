#include <memory>
#include <string>
#include <vector>

#include <entt/entt.hpp>

#include "sage/scene/Components.h"

class Project;
class Mesh;

// ---------------------------------------------------------------------------
// Материалы модели -> .sagemat рядом с ней -> слоты сущности.
//
// ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Это делали ДВА места — инспектор (когда модель
// назначают его слотом) и слой редактора (когда её приносят перетаскиванием), —
// каждое своей копией кода. Копии успели разойтись: инспектор писал
// предупреждения в строку состояния, слой молчал; поправка в одном не доезжала
// до другого, и один и тот же ассет выглядел по-разному в зависимости от того,
// каким жестом его принесли. Теперь путь один.
//
// ЧТО ДЕЛАЕТСЯ. Из файла модели читаются ВСЕ материалы (ModelLoader::
// ExtractMaterials). Для каждого рядом с моделью появляется свой .sagemat, если
// его там ещё нет, и назначается в слот того подмеша, который этим материалом
// красится. Один материал — один слот; порядок слотов задаёт разметка меша.
//
// ЧЕГО НЕ ДЕЛАЕТСЯ. Существующий .sagemat не перезаписывается: материал после
// импорта правят руками, и повторное «загрузить модель» не повод стирать эту
// работу. Слот, в котором уже стоит выбранный человеком материал, не трогается
// — выбор человека главнее импорта.
// ---------------------------------------------------------------------------
struct ModelMaterialImportResult {
    int Created = 0;    // сколько .sagemat создано на этот раз
    int Assigned = 0;   // сколько слотов заполнено
    bool AnyMaps = false;
    // Первая причина, по которой что-то не доехало, — для строки состояния.
    // Полный список уходит в лог: строка состояния вмещает одну.
    std::string FirstWarning;
    // Что вообще было в файле и в разметке. Нужно панели, чтобы отличать «в
    // модели нет материалов» от «материалы есть, но не назначены» — снаружи оба
    // случая выглядят одинаково пустым слотом, а делать с ними надо разное.
    int FileMaterials = 0;
    int Parts = 0;

    // --- Скелет и анимация ---------------------------------------------------
    //
    // Модель с костями — это ПЕРСОНАЖ, а не декорация, и настроен он должен
    // быть как персонаж: с компонентом Animation и назначенным клипом. Поля
    // заполняет SetupModelAnimation (см. ниже), а редактор по ним говорит
    // человеку, что именно приехало вместе с моделью.
    bool Skeleton = false;      // в модели есть скин
    int Bones = 0;              // костей в скелете
    int Clips = 0;              // клипов в файле модели
    bool AnimationAdded = false;// компонент Animation появился этой правкой
    std::string Clip;           // какой клип назначен (ссылка проекта)
};

// mr.Ref.path должен указывать на модель; mr.MeshPtr — на её загруженный меш
// (по нему берётся разметка). Возвращает, что получилось.
ModelMaterialImportResult ImportModelMaterials(const Project& project, MeshRendererComponent& mr);

// --- МОДЕЛЬ СО СКЕЛЕТОМ НАСТРАИВАЕТСЯ САМА ----------------------------------
//
// ЧТО БЫЛО НЕ ТАК. Персонаж, положенный в сцену, приезжал СТАТУЕЙ. Движок
// честно разбирал скин (84 кости), вынимал все клипы в .sageanim — и клал
// сущности один Mesh. Компонента Animation не появлялось, клип не назначался,
// скелет не поднимался: в кадре стояла модель в позе привязки, а в логе
// красовалось «клипов 18». Со стороны человека это читается ровно так, как он
// и сказал: «загружается без костей, анимации нет».
//
// Чтобы это исправить руками, надо было ЗНАТЬ три вещи: что анимация — это
// отдельный компонент; что клип адресуется файлом, а не номером; и что файлы
// клипов уже лежат рядом с моделью. Ни одна из них из интерфейса не следует.
//
// ЧТО ЗДЕСЬ. Модель со скином — это персонаж, и настраивается он как персонаж:
// сущность получает Animation, а Animation — клип (предпочитая «idle»: это
// поза покоя, с которой персонажа и ставят в сцену). Клипы вынимаются тем же
// ImportModelClips, что и раньше, — новое здесь то, что результат доезжает до
// сущности, а не остаётся файлами на диске.
//
// Существующий выбор НЕ ПЕРЕБИВАЕТСЯ: если на сущности уже есть Animation с
// выбранным клипом, повторная установка модели его не трогает — иначе смена
// модели у настроенного персонажа молча сбрасывала бы его анимацию.
ModelMaterialImportResult& SetupModelAnimation(const Project& project, entt::registry& registry,
                                               entt::entity entity, const std::string& modelRef,
                                               ModelMaterialImportResult& result);

// Ставит сущности другой меш — и СБРАСЫВАЕТ слоты материалов, если модель
// сменилась.
//
// ЗАЧЕМ ОТДЕЛЬНАЯ ФУНКЦИЯ. Слот адресуется номером части, а части — это части
// КОНКРЕТНОЙ модели. Оставить слоты при смене модели значит покрасить голову
// нового персонажа ботинком старого, причём молча: номера-то есть, и они
// совпадут. Присвоений меша в редакторе четыре (слот инспектора, бросок на
// объект, бросок в список, бросок во вьюпорт), и правило должно быть одним на
// все — иначе оно снова разойдётся, как разошёлся импорт материалов.
//
// Тот же самый ref (переимпорт модели после правки .sageimport) слоты
// СОХРАНЯЕТ: модель та же, части те же, и стирать назначенные материалы не за
// что.
//
// МАТЕРИАЛЫ НАЗНАЧАЮТСЯ ЗДЕСЬ ЖЕ, а не у каждого, кто ставит меш. Это уже
// дважды расходилось: сперва импорт звали три пути из четырёх, потом четыре из
// пяти, и каждый раз модель приезжала белой ровно у того жеста, про который
// забыли. Правило «поставил меш — не забудь импортировать материалы» не
// удержалось ни разу, поэтому его больше нет: импорт делает сама функция,
// ставящая меш, и забыть его нельзя.
//
// Импорт идёт, только когда меш УЖЕ загружен (по нему берётся разметка частей).
// Инспектор ставит модель с mesh == nullptr и грузит её следующим шагом — там
// импорт случится вместе с загрузкой.
// СУЩНОСТЬ ЦЕЛИКОМ, а не только её MeshRenderer: поставить модель — это не
// только «чем рисовать». У модели со скелетом отсюда же появляется Animation
// (см. SetupModelAnimation), и без доступа к сущности этот шаг пришлось бы
// звать отдельно каждому из пяти мест, ставящих меш. Ровно это правило
// («поставил меш — не забудь ещё вот это») здесь уже дважды не удержалось.
ModelMaterialImportResult SetEntityMesh(const Project& project, entt::registry& registry,
                                        entt::entity entity, MeshRef::Type type,
                                        const std::string& path, std::shared_ptr<Mesh> mesh);

// --- КЛИПЫ АНИМАЦИИ В ОТДЕЛЬНЫЕ ФАЙЛЫ ---------------------------------------
//
// Вынимает из модели ВСЕ клипы в .sageanim рядом с ней — ровно так же, как
// материалы вынимаются в .sagemat, и по той же причине. Клип, живущий только
// внутри .glb, нельзя ни посмотреть в панели ассетов, ни назначить другому
// персонажу, ни сослаться на него из сцены иначе как номером — а номер молча
// меняется при переэкспорте модели.
//
// Существующий файл НЕ перезаписывается: клип после импорта могли поправить, и
// повторный импорт модели не повод стирать эту работу.
struct ClipImportResult {
    int Found = 0;      // сколько клипов в модели
    int Created = 0;    // сколько файлов записано на этот раз
    std::vector<std::string> Refs;   // ссылки проекта на файлы клипов, по порядку
    std::string FirstWarning;
};

// modelRef — ссылка проекта на модель (.glb/.gltf/.fbx). Скелетная модель
// грузится через кэш; у модели без скелета клипов нет, и это не ошибка.
ClipImportResult ImportModelClips(const Project& project, const std::string& modelRef);
