#pragma once
#include <string>
#include <vector>

class Project;
struct MeshRendererComponent;

// ---------------------------------------------------------------------------
// Материалы модели -> .sagemat рядом с ней -> слоты сущности.
//
// ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Это делали ДВА места — инспектор (когда модель
// назначают его слотом) и слой редактора (когда её приносят перетаскиванием), —
// каждое своей копией кода. Копии успели разойтись: инспектор писал
// предупреждения в строку состояния, слой молчал; поправка в одном не доезжала
// до другого, и один и тот же ассет выглядел по-разному в зависимости от того,
// каким жестом его принесли. Теперь путь один.
//
// ЧТО ДЕЛАЕТСЯ. Из файла модели читаются ВСЕ материалы (ModelLoader::
// ExtractMaterials). Для каждого рядом с моделью появляется свой .sagemat, если
// его там ещё нет, и назначается в слот того подмеша, который этим материалом
// красится. Один материал — один слот; порядок слотов задаёт разметка меша.
//
// ЧЕГО НЕ ДЕЛАЕТСЯ. Существующий .sagemat не перезаписывается: материал после
// импорта правят руками, и повторное «загрузить модель» не повод стирать эту
// работу. Слот, в котором уже стоит выбранный человеком материал, не трогается
// — выбор человека главнее импорта.
// ---------------------------------------------------------------------------
struct ModelMaterialImportResult {
    int Created = 0;    // сколько .sagemat создано на этот раз
    int Assigned = 0;   // сколько слотов заполнено
    bool AnyMaps = false;
    // Первая причина, по которой что-то не доехало, — для строки состояния.
    // Полный список уходит в лог: строка состояния вмещает одну.
    std::string FirstWarning;
};

// mr.Ref.path должен указывать на модель; mr.MeshPtr — на её загруженный меш
// (по нему берётся разметка). Возвращает, что получилось.
ModelMaterialImportResult ImportModelMaterials(const Project& project, MeshRendererComponent& mr);
