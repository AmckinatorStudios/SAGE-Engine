#pragma once
#include <string>
#include <vector>

// ---------------------------------------------------------------------------
// Локализация редактора.
//
// ЗАЧЕМ. До этого язык интерфейса был не решением, а следствием того, кто и
// когда писал панель: меню и заголовки окон по-английски, подсказки и половина
// инспектора по-русски, а часть строк — вперемешку в одной панели. Пользователю
// это читается как недоделанность, а разработчику мешает иначе: строку нельзя
// поменять централизованно, потому что «строки» как сущности не существует —
// есть литерал в месте вызова.
//
// КЛЮЧ — АНГЛИЙСКИЙ ТЕКСТ, а не идентификатор вроде inspector.light.type.
// Причина практическая: у идентификаторов есть ровно одно достоинство (они не
// меняются при правке текста) и два недостатка, которые здесь важнее. Первый:
// в исходнике перестаёт быть видно, что написано на экране, — читать код
// панели становится нельзя без второго файла. Второй: забытый перевод даёт на
// экране «inspector.light.type» вместо текста, то есть отсутствие перевода
// ломает интерфейс, а не ухудшает его. С английским ключом непереведённая
// строка показывает английский — ровно то состояние, в котором редактор и был.
//
// ЧТО СЧИТАЕТСЯ ПЕРЕВОДОМ. Только видимая часть. ImGui опознаёт виджеты по
// подписи, и у многих подпись содержит скрытый идентификатор после «##»
// («Position##t»). Переводить его нельзя: смена языка меняла бы идентификатор
// виджета, а с ним — раскладку окон в imgui.ini и состояние раскрытых секций.
// Поэтому T() переводит часть ДО «##» и приклеивает остаток как есть.
//
// ГДЕ ЖИВУТ ПЕРЕВОДЫ. Русский каталог встроен в исполняемый файл
// (lang_ru.inl): редактор обязан запускаться из любой папки и без ассетов.
// Сверх того при старте читается assets/lang/<код>.json, если он есть, — им
// можно поправить отдельные строки или добавить язык целиком, не пересобирая
// редактор.
// ---------------------------------------------------------------------------
namespace sage::editor {

struct LanguageInfo {
    std::string Code; // "en", "ru"
    std::string Name; // как язык называет себя сам: "English", "Русский"
};

// Читает встроенные каталоги и внешние из assets/lang/. Язык берётся из
// настроек редактора (~/.config/sage/editor_prefs.json), а если их нет — из
// переменной окружения SAGE_EDITOR_LANG, а если нет и её — английский.
void InitLocalization();

const std::vector<LanguageInfo>& AvailableLanguages();
const std::string& CurrentLanguageCode();
// Возвращает false, если такого языка нет. Смена языка мгновенная: следующий
// кадр интерфейса собирается уже на новом.
bool SetLanguage(const std::string& code);

// Перевод строки интерфейса. Возвращает сам ключ, если перевода нет.
//
// Указатель живёт до конца работы программы (переводы и склейки кэшируются и
// не удаляются) — на него можно опираться в пределах кадра и дольше. Это не
// щедрость, а требование: ImGui берёт подписи как const char* и обязан получить
// живую память, а кэш, который чистился бы при смене языка, оставлял бы
// висячие указатели у всех, кто сохранил строку в static.
const char* T(const char* key);

// Та же T() для std::string. Нужна с тех пор, как подписи шаблонов приходят с
// диска (template.json установленного шаблона), а не только литералами из
// таблицы: у чужого шаблона перевода нет, и T() отдаёт его текст как есть.
inline const char* T(const std::string& key) { return T(key.c_str()); }

// Ключи, для которых перевода не нашлось. Нужны, чтобы каталог не отставал от
// интерфейса: без такого списка новая панель молча выходит по-английски, и
// узнаётся об этом от пользователя. SAGE_EDITOR_L10N_MISSING=<файл> выгружает
// их при выходе.
const std::vector<std::string>& MissingKeys();
void DumpMissingKeys(const std::string& path);

} // namespace sage::editor

// Короткое имя в области видимости редактора: T("Open project"). Панели зовут
// его сотни раз, и sage::editor::T() на каждой подписи читался бы хуже, чем
// сама подпись.
using sage::editor::T;
