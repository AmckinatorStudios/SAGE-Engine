#pragma once
#include <memory>
#include <optional>

#include "imgui.h"

#include "sage/render/Framebuffer.h"
#include "sage/ui/UIRenderer.h"
#include "sage/ui/sageui/SageUI.h"

// ---------------------------------------------------------------------------
// ОСТРОВ SAGE UI ВНУТРИ ОКНА IMGUI — ПЕРЕХОДНАЯ ОБВЯЗКА, И ТОЛЬКО.
//
// ЗАЧЕМ ОНА НУЖНА. Оболочка редактора — меню, доки, окна — пока на ImGui, а
// панели переезжают на SAGE UI по одной. Между «первая панель переехала» и
// «переехала последняя» обе системы обязаны работать одновременно и в одном
// окне: иначе переезд превращается в один гигантский коммит, после которого
// редактор либо работает целиком, либо не работает вовсе.
//
// КАК ЭТО УСТРОЕНО. Панель на SAGE UI считается и рисуется в СВОЙ буфер, а
// окно ImGui показывает этот буфер картинкой и передаёт острову мышь,
// клавиатуру и колесо, переведённые в его координаты. Ровно тот же приём, каким
// панель Game уже показывает кадр игры, — новых понятий не заводится.
//
// ЧЕГО ОСТРОВ НЕ УМЕЕТ И НЕ ДОЛЖЕН. Всплывающее меню и подсказка не могут выйти
// за границы своего окна: они рисуются в буфер, а буфер и есть окно. Это
// осознанное ограничение переходного периода, а не недостаток фреймворка —
// когда оболочка переедет на SAGE UI, острова исчезнут вместе с ограничением, и
// меню будет жить в общем слое Popup.
//
// ЭТОТ ФАЙЛ ОБЯЗАН БЫТЬ УДАЛЁН вместе с последним вызовом ImGui в редакторе.
// Если он переживёт переезд — значит, переезд не закончен.
// ---------------------------------------------------------------------------
class SageUIIsland {
public:
    SageUIIsland();
    ~SageUIIsland();

    sage::ui::sui::UIContext& Ui() { return m_ui; }

    // Один шаг внутри уже открытого окна ImGui: занять оставшееся место,
    // посчитать, раздать ввод, нарисовать и показать картинкой.
    //
    // dt приходит снаружи: у острова нет своих часов, и заводить их значит
    // однажды получить анимацию, идущую не в такт с остальным редактором.
    void DrawInWindow(float dt);

    // Есть ли фокус клавиатуры внутри острова. Редактор спрашивает это, чтобы
    // не перехватывать те же клавиши: пока человек печатает в поле поиска
    // панели, Delete не должен удалять объект сцены.
    bool KeyboardCaptured() const { return m_report.KeyboardCaptured; }
    const sage::ui::UIInputReport& Report() const { return m_report; }

private:
    void FeedInput(const ImVec2& origin, const ImVec2& size, bool hovered, bool focused);

    sage::ui::sui::UIContext m_ui;
    std::optional<Framebuffer> m_fbo;
    std::unique_ptr<UIRenderer> m_renderer;
    sage::ui::UIInputFrame m_input;
    sage::ui::UIInputReport m_report;
    int m_width = 0, m_height = 0;
};
