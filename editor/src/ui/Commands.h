#pragma once
#include <functional>
#include <string>
#include <vector>

// ---------------------------------------------------------------------------
// КОМАНДЫ РЕДАКТОРА: одно действие — одна запись, а не три копии.
//
// ЗАЧЕМ. «Сохранить сцену» до сих пор существовало в трёх местах сразу: пункт
// меню, кнопка тулбара и обработчик Ctrl+S. Три вызова одного и того же — и
// три возможности разойтись: у пункта меню появилось подтверждение, у кнопки
// нет; горячая клавиша перестала проверять, открыт ли проект, а меню
// проверяло. Такие расхождения не ловятся тестом и находятся жалобой.
//
// Теперь действие описывается ОДИН раз: имя, к чему относится, горячая
// клавиша, доступно ли сейчас и что делать. Меню, тулбар, палитра команд и
// обработчик клавиш читают этот же список.
//
// ЧЕГО ЗДЕСЬ НЕТ. Отмены (Undo). Она требует, чтобы каждое действие умело
// откатываться, а это переделка всех правок редактора разом — отдельная
// работа. Реестр к ней готов: команда уже единственная точка, через которую
// проходит действие.
// ---------------------------------------------------------------------------
namespace Sage::UI {

struct Command {
    std::string Id;        // "scene.save" — по нему ищут и запоминают
    std::string Title;     // подпись; переводится при показе
    std::string Category;  // раздел в палитре: «Сцена», «Объект», «Окно»
    std::string Shortcut;  // "Ctrl+S" — только для показа, разбирается отдельно
    std::string Icon;      // имя иконки или пусто

    // Доступна ли команда сейчас. Пусто — всегда доступна. Недоступная НЕ
    // прячется, а показывается серой: исчезающие пункты меню заставляют искать
    // то, что «только что здесь было».
    std::function<bool()> Enabled;
    std::function<void()> Run;
};

// Реестр. Один на редактор.
class CommandRegistry {
public:
    void Add(Command cmd);
    const std::vector<Command>& All() const { return m_commands; }
    const Command* Find(const std::string& id) const;

    // Выполнить по идентификатору. false — команды нет или она недоступна.
    bool Run(const std::string& id);

    // Поиск по палитре: подстрока без учёта регистра, по подписи и разделу.
    // Возвращает индексы в All(), лучшие сверху.
    std::vector<int> Search(const std::string& query) const;

private:
    std::vector<Command> m_commands;
};

} // namespace Sage::UI
