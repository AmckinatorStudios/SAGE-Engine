#pragma once
#include <string>

#include "imgui.h"

// ---------------------------------------------------------------------------
// ТОКЕНЫ ИНТЕРФЕЙСА: размеры, отступы и типографика — в одном месте.
//
// ЗАЧЕМ. Отступы в редакторе назначались на глаз и по месту: где-то 7 точек,
// где-то 13, высота кнопки в тулбаре одна, в инспекторе другая, у одинаковых по
// смыслу полей разные радиусы. Заметно это не по одному элементу, а по экрану
// целиком: интерфейс выглядит собранным из кусков, потому что он и есть
// собранный из кусков.
//
// ЕДИНАЯ СЕТКА. Все размеры кратны 4 точкам: 4, 8, 12, 16, 20, 24, 32. Это не
// эстетическое правило, а способ не думать: любое «сколько тут отступ» имеет
// ровно один правильный ответ, и два человека (или один в разные дни) дадут
// одинаковый.
//
// МАСШТАБ. Каждый размер отдаётся УЖЕ УМНОЖЕННЫМ на масштаб интерфейса, потому
// что забыть умножить легко, а увидеть последствия — только на чужом экране с
// другим DPI. Целые числа: половина точки на границе элемента даёт мыло, и
// именно она делает интерфейс «кривым» при 125%.
// ---------------------------------------------------------------------------
namespace Sage::UI {

// Шаг сетки. Всё остальное — производные от него.
inline constexpr float kGrid = 4.0f;

struct Style {
    // --- отступы (кратны сетке) ---
    float SpacingXS;    // 4  — между иконкой и её подписью
    float SpacingSM;    // 8  — между элементами одной строки
    float SpacingMD;    // 12 — между строками одной группы
    float SpacingLG;    // 16 — между группами
    float SpacingXL;    // 24 — между разделами

    // --- внутренние поля ---
    float PaddingPanel;    // поле панели от края окна
    float PaddingControl;  // поле внутри поля ввода/кнопки по горизонтали
    float PaddingControlY; // то же по вертикали

    // --- формы ---
    float CornerRadius;      // поля, кнопки, вкладки
    float CornerRadiusLarge; // окна, всплывающие
    float CornerRadiusSmall; // грабы, значки
    float BorderWidth;

    // --- высоты (одинаковые у всего, что стоит в один ряд) ---
    float ControlHeight;  // кнопка, поле ввода, выпадающий список
    float ToolbarHeight;
    float HeaderHeight;
    float RowHeight;      // строка списка/дерева
    float StatusBarHeight;

    // --- иконки ---
    float IconSize;       // рядом с текстом
    float IconSizeLarge;  // кнопка-иконка в тулбаре

    // --- инспектор ---
    float LabelColumn;    // ширина колонки подписей в сетке свойств
    float ScrollbarSize;
    float IndentSpacing;

    // --- типографика: КЕГЛИ, а не «какой шрифт» ---
    //
    // Пять размеров, и этого достаточно. Каждый новый кегль — ещё одна
    // возможность поставить не тот, и ещё один способ сломать выравнивание.
    float FontDisplay;    // крупная надпись на пустом экране
    float FontTitle;      // заголовок окна
    float FontSection;    // заголовок раздела (Transform, Mesh Renderer)
    float FontBody;       // основной текст
    float FontCaption;    // подписи, единицы, статус-бар
};

// Текущие токены. Пересчитываются при смене масштаба интерфейса.
const Style& Get();

// Пересчитать под масштаб. Зовётся из EditorTheme::Apply().
void Rebuild(float scale);

// Масштаб, с которым посчитаны токены (для мест, где нужен сам множитель).
float Scale();

} // namespace Sage::UI
