#pragma once
#include <string>
#include <vector>

// ---------------------------------------------------------------------------
// ПОЛЕ «НАПИСАТЬ ИЛИ ВЫБРАТЬ».
//
//     [ start_game          ][▾]
//
// Имя события или метода бывает двух видов: известное заранее (сигналы
// кнопки, методы скрипта) и такое, которого редактор не знает (своё событие,
// метод в скрипте, который ещё не написан). Чистый список запрещал второе, а
// чистое поле ввода заставляло помнить первое и набирать его по буквам. Здесь
// и то и другое: пишут вручную, а стрелка открывает список известных — сначала
// те, что похожи на набранное.
// ---------------------------------------------------------------------------
namespace sage::editor::suggest {

struct Item {
    std::string Value;   // что подставится в поле
    std::string Label;   // как показать в списке (пусто — Value)
    std::string Group;   // заголовок раздела списка (пусто — без раздела)
    std::string Tip;     // подсказка при наведении
};

// Порядок показа для набранного текста: точное совпадение, начало, вхождение
// (без учёта регистра), затем остальные — список не прячет ничего, а только
// поднимает похожее наверх. Внутри разряда — исходный порядок.
std::vector<int> Rank(const std::vector<Item>& items, const std::string& typed);

// Есть ли значение среди известных.
bool Known(const std::vector<Item>& items, const std::string& value);

// Поле с ручным вводом и списком. true — значение принято: Enter, уход из поля
// после правки или выбор из списка; value тогда уже новое. Ширина — как у
// обычного поля: SetNextItemWidth перед вызовом.
bool Field(const char* id, std::string& value, const std::vector<Item>& items, const char* hint);

} // namespace sage::editor::suggest
