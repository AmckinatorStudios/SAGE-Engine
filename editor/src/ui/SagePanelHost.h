#pragma once
#include <memory>
#include <string>
#include <unordered_map>

#include "ui/EditorPanel.h"
#include "ui/SageUIIsland.h"

// ---------------------------------------------------------------------------
// ХОЗЯИН ПАНЕЛЕЙ НА SAGE UI — ВТОРАЯ ПОЛОВИНА ПЕРЕХОДНОЙ ОБВЯЗКИ.
//
// Держит по одному острову на панель и показывает панель внутри окна ImGui:
// открыть окно, отдать острову оставшееся место, посчитать, нарисовать,
// закрыть окно. Панель при этом про ImGui не знает ничего.
//
// ПО ОСТРОВУ НА ПАНЕЛЬ, А НЕ ОДИН ОБЩИЙ. Каждая панель — своя сцена интерфейса:
// свой фокус, своя каретка, свой захват мыши. Общий контекст на все панели
// означал бы, что фокус в поле поиска консоли теряется при щелчке в инспекторе,
// — а это ровно то, чего человек не ждёт.
//
// Как и SageUIIsland, этот файл обязан исчезнуть вместе с последним вызовом
// ImGui в редакторе: тогда панели переедут в настоящий DockSpace, и посредник
// станет не нужен.
// ---------------------------------------------------------------------------
class SagePanelHost {
public:
    // Показать панель в своём окне ImGui. open — та же переменная видимости,
    // что и у остальных панелей редактора.
    // defaultSize — размер окна при ПЕРВОМ показе. Без него плавающее окно
    // открывается схлопнутым в полоску: у острова внутри нет своего размера, он
    // занимает то, что дали, а ImGui без подсказки даёт минимум.
    void Draw(EditorPanel& panel, const char* windowTitle, bool* open, float dt,
              ImVec2 defaultSize = ImVec2(560.0f, 360.0f));

    // Показать панель вперёд соседей по вкладке. Нужно и «Окну > Консоль», и
    // скриншот-проверкам: панель, спрятанная за чужой вкладкой, ничем не
    // отличается от невидимой.
    void RequestFocus(EditorPanel& panel) { m_focus = &panel; }

    // Посчитать и обновить панель, даже если её окно закрыто. Нужно тем, кто
    // копит данные (консоль): панель, не получающая Sync, пропускает сообщения
    // и показывает при открытии дырявый лог.
    void SyncHidden(EditorPanel& panel, float dt);

    // Забрал ли кто-то из панелей клавиатуру. Редактор спрашивает это, чтобы не
    // перехватывать те же клавиши: пока человек печатает в поле поиска, Delete
    // не должен удалять объект сцены.
    bool KeyboardCaptured() const { return m_keyboard; }
    void BeginFrame() { m_keyboard = false; }

private:
    SageUIIsland& IslandFor(EditorPanel& panel);

    std::unordered_map<EditorPanel*, std::unique_ptr<SageUIIsland>> m_islands;
    EditorPanel* m_focus = nullptr;
    bool m_keyboard = false;
};
