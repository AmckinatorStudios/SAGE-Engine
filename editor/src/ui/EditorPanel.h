#pragma once
#include <string>

#include "sage/ui/sageui/SageUI.h"

// ---------------------------------------------------------------------------
// ПАНЕЛЬ РЕДАКТОРА НА SAGE UI (§28–29 ТЗ).
//
// ГЛАВНОЕ ОТЛИЧИЕ ОТ ПРЕЖНЕГО Draw(). Панель больше не «рисует себя каждый
// кадр». Она СОБИРАЕТСЯ ОДИН РАЗ (Build) и потом только обновляет значения
// (Sync). Это не стилистическая разница, а причина, по которой всё остальное
// вообще возможно:
//
//   • у элементов есть постоянная личность, значит у них есть состояние —
//     прокрутка, выделение, фокус, каретка в поле ввода. В immediate-mode всё
//     это приходится хранить сбоку и вручную связывать с «тем самым» виджетом
//     по идентификатору;
//   • дерево панели — обычный документ интерфейса, значит его можно сохранить,
//     показать в инспекторе, оформить темой и подсветить в отладке;
//   • кадр стоит ровно столько, сколько изменилось: неизменившаяся панель не
//     пересобирает ни одного узла.
//
// ЧТО ПАНЕЛЬ НЕ ДЕЛАЕТ. Не рисует (это делает ядро), не считает раскладку, не
// знает про ImGui и про то, в каком окне она показана. Ровно это и позволит
// перенести её из острова внутри ImGui в настоящий док без единой правки.
// ---------------------------------------------------------------------------
class EditorHost;

class EditorPanel {
public:
    virtual ~EditorPanel() = default;

    // Имя для вкладки и для меню «Окно». Не переводится здесь: перевод — дело
    // того, кто показывает, а панель обязана иметь устойчивое имя.
    virtual const char* PanelId() const = 0;
    virtual const char* Title() const = 0;

    // Собрать дерево. Зовётся ОДИН раз при первом показе.
    virtual void Build(sage::ui::sui::UIContext& ui, sage::ui::sui::UIElement* root) = 0;
    // Обновить значения. Зовётся каждый кадр. Здесь не создают узлов — если
    // содержимое зависит от данных (список объектов, строки лога), панель
    // сравнивает и правит ровно то, что изменилось.
    virtual void Sync(float dt) { (void)dt; }

    bool Built() const { return m_root != nullptr; }
    sage::ui::sui::UIElement* Root() const { return m_root; }

    // Собрать при первом показе. Идемпотентно.
    void EnsureBuilt(sage::ui::sui::UIContext& ui, sage::ui::sui::UIElement* parent) {
        if (m_root) return;
        m_root = ui.CreateIn<sage::ui::sui::UIElement>(parent);
        m_root->SetName(PanelId());
        m_root->SetStretch(true, true);
        Build(ui, m_root);
    }

private:
    sage::ui::sui::UIElement* m_root = nullptr;
};
