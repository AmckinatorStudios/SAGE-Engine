#pragma once
#include <vector>

#include "imgui.h"

// ---------------------------------------------------------------------------
// ЛИНИИ ДЕРЕВА — ОДНИ НА ВЕСЬ РЕДАКТОР.
//
// Деревьев в редакторе два — объекты сцены и элементы интерфейса, — и рисовать
// им связи по-разному незачем: это одно и то же дерево, просто с разным
// содержимым. Пока линии жили внутри панели иерархии, у второго дерева их не
// было вовсе: элементы интерфейса висели отдельными строками, и понять, кто
// чей ребёнок, можно было только по отступу.
//
// ПОЧЕМУ НЕ ВСТРОЕННЫЕ ЛИНИИ ImGui. Он ведёт горизонтальную чёрточку до
// СТРЕЛКИ раскрытия, а значок и подпись начинаются дальше — за отступом до
// подписи. Между чёрточкой и значком оставался провал в полтора десятка
// пикселей: линия будто обрывается на полпути, и дерево выглядит
// недорисованным.
//
// ЧТО ЗДЕСЬ:
//   • горизонталь доходит ДО ЗНАЧКА (а у строки со стрелкой — до стрелки, не
//     влезая в неё: перечёркнутая стрелка читается как поломка);
//   • вертикаль идёт от родителя до СЕРЕДИНЫ ПОСЛЕДНЕГО ребёнка, а не до конца
//     поддерева — иначе она свисает под последней строкой в пустоту;
//   • у последнего ребёнка угол СКРУГЛЁН: прямой угол в конце ветки выглядит
//     обрубком, а скруглённый читается как «ветка закончилась».
//
// КАК ПОЛЬЗОВАТЬСЯ. Панель зовёт Row() на каждую нарисованную строку, а после
// того как поддерево отрисовано целиком, — Draw() с положением родителя.
// Строки использованного уровня при этом забываются: иначе вертикаль тянулась
// бы через чужие ветки.
// ---------------------------------------------------------------------------
namespace sage::editor::treelines {

class Lines {
public:
    // Строка дерева: где она, на какой глубине, где у неё стрелка и значок.
    void Row(float y, int depth, float arrowX, float iconX, bool hasArrow) {
        m_rows.push_back({y, iconX, arrowX, hasArrow, depth});
    }

    // Связи от родителя ко всем его прямым детям. parentPos — левый верхний
    // угол строки родителя, indent — отступ до подписи (ImGui::
    // GetTreeNodeToLabelSpacing), childDepth — глубина детей.
    void Draw(const ImVec2& parentPos, float indent, int childDepth);

    // Между кадрами ничего не переносится: строки прошлого кадра — это
    // координаты, которых уже нет.
    void Clear() { m_rows.clear(); }

private:
    struct RowInfo {
        float Y = 0.0f;
        float IconX = 0.0f;
        float ArrowX = 0.0f;
        bool Arrow = false;
        int Depth = 0;
    };
    std::vector<RowInfo> m_rows;
};

} // namespace sage::editor::treelines
