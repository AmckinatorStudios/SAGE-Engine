#pragma once
#include <functional>
#include <string>

#include "sage/scene/SceneReflect.h"
#include "sage/ui/sageui/SageUI.h"

// ---------------------------------------------------------------------------
// ОПИСАНИЕ СВОЙСТВА -> СТРОКА ИНСПЕКТОРА.
//
// Одно место, где решается, каким виджетом правят поле. Раньше это решение
// принималось заново в каждой из восемнадцати секций инспектора, и потому
// одинаковые поля выглядели по-разному: угол где-то ползунок, где-то поле; путь
// к ассету где-то слот с приёмом броска, где-то строка.
//
// ЗДЕСЬ НЕТ НИ ОДНОГО ИМЕНИ КОМПОНЕНТА. Строку делает ТИП свойства и его
// пометки (границы, перечисление, «это путь к ассету») — то есть то, что
// описано у самого поля в движке. Добавили поле в компонент — оно появилось в
// инспекторе; ничего дописывать не надо.
// ---------------------------------------------------------------------------
namespace editor {

// Что делать после правки. Отдельным объектом, а не двумя аргументами: правка
// поля — это ещё и точка отмены, и пометка «сцена изменена», и забыть любую из
// них означает потерять работу человека.
struct PropertyHooks {
    // Зовётся ОДИН раз перед первым изменением подряд идущей серии (тянут
    // ползунок — снимок один, а не сорок).
    std::function<void()> BeginEdit;
    // Зовётся после каждого изменения значения.
    std::function<void()> Changed;
    // Выбрать ассет через диалог (для Widget::Asset). Пусто — кнопки не будет.
    std::function<void(const sage::scene::Property&, std::string& value)> PickAsset;
};

// Построить строку под одно свойство в готовой секции таблицы.
//
// data — не указатель, а СПОСОБ его получить, и это не педантизм. Компоненты
// лежат в пулах ECS, и удаление компонента У ДРУГОЙ СУЩНОСТИ переставляет
// оставшиеся: сохранённый в замыкании указатель после этого показывает на чужие
// байты. Строка спрашивает адрес заново на каждое обращение — там же он и
// проверяется на nullptr, если компонент успели убрать.
using DataFn = std::function<void*()>;

void BuildPropertyRow(sage::ui::sui::UIContext& ui, sage::ui::sui::PropertyGrid* grid,
                      sage::ui::sui::UIElement* section, const sage::scene::Property& prop,
                      DataFn data, const PropertyHooks& hooks);

} // namespace editor
