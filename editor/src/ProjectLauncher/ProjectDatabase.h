#pragma once
#include <filesystem>
#include <string>
#include <vector>

// ---------------------------------------------------------------------------
// БАЗА ПРОЕКТОВ СТАРТОВОГО ОКНА.
//
// ЧТО ЭТО. Небольшой локальный список того, что человек уже открывал или
// принёс сам: путь, когда открывал, где лежит обложка. Живёт рядом с
// настройками редактора (~/.config/sage/projects.json; на Windows —
// %APPDATA%/sage/...), то есть переживает переустановку и пересборку.
//
// ЧЕГО ЗДЕСЬ НЕТ И БЫТЬ НЕ ДОЛЖНО — ВТОРОЙ КОПИИ САМОГО ПРОЕКТА. Имя, тип,
// описание и версия движка принадлежат ДЕСКРИПТОРУ (project.sageproj) и
// читаются оттуда при каждой загрузке списка. База хранит только то, чего в
// проекте нет по определению: факт «этот проект показывать в списке» и время
// последнего открытия. Иначе переименованный в дескрипторе проект показывал бы
// в стартовом окне старое имя — расхождение, которое человек читает как
// поломку, а починить может только удалением из списка.
//
// ПОЧЕМУ НЕ ПРЕЖНИЙ RecentProjects. Тот хранил ровно вектор строк и умел
// «добавить/убрать». Стартовому окну этого мало: нужны поиск, отбор по типу,
// сортировка, пометка «папки больше нет» и операции над проектом (импорт,
// дубликат, удаление). Список путей превращался бы в такую базу постепенно и
// по кусочкам — по одному полю в каждой панели.
//
// ДИСК СКАНИРОВАТЬ НЕЛЬЗЯ. Обход всех дисков в поисках project.sageproj — это
// минуты работы, чужие сетевые папки и внешние диски, которые от такого обхода
// просыпаются. В списке ровно то, что человек открывал сам, импортировал или
// создал.
// ---------------------------------------------------------------------------
namespace Sage::Launcher {

// Что это за проект. Тип объявляет САМ проект (поле "type" дескриптора), а
// стартовое окно по нему отбирает — «Игры», «Сцены», «Примеры».
//
// Перечислением, а не свободной строкой: на типе завязаны вкладки отбора, и
// опечатка в дескрипторе не должна порождать четвёртую вкладку-призрак.
// Неизвестное значение читается как Game — проект, у которого тип не указан
// (все, созданные до этой правки), это именно игра.
enum class ProjectKind { Game, Scene, Sample, Template, Count };

// Идентификатор для файла (не переводится) и подпись для показа — уже
// переведённая: ключ и его перевод обязаны стоять в одном месте, иначе строка
// молча выпадает из каталога (см. ProjectDatabase.cpp).
const char* ProjectKindId(ProjectKind kind);
ProjectKind ProjectKindFromId(const std::string& id);
const char* ProjectKindLabel(ProjectKind kind);

// Одна строка списка. Поля, приходящие из дескриптора, помечены: их правит
// проект, а не база.
struct ProjectEntry {
    std::string Path;          // корень проекта (папка с project.sageproj)
    std::string Name;          // дескриптор: отображаемое имя
    std::string Description;   // дескриптор: одна-две строки «про что это»
    ProjectKind Kind = ProjectKind::Game;   // дескриптор
    std::string EngineVersion; // дескриптор: чем создавали
    std::string Thumbnail;     // картинка-обложка проекта; пусто — рисуем сами
    long long Created = 0;     // дескриптор: время создания (unix, секунды)
    long long Modified = 0;    // файловая система: последняя правка проекта
    long long Opened = 0;      // база: когда открывали из стартового окна
    // Папки нет на месте. Не удаляем молча: диск мог быть просто не подключён,
    // и вычеркнуть проект из списка за человека — потерять его закладку.
    bool Missing = false;

    // Строка для поиска (имя + путь + тип, в нижнем регистре). Считается при
    // загрузке: поиск идёт на каждое нажатие клавиши, и приводить регистр
    // пятисот записей заново на каждый символ незачем.
    std::string SearchKey;
};

// Вкладки отбора в шапке списка.
enum class ProjectFilter { All, Games, Scenes, Samples, Count };
const char* ProjectFilterLabel(ProjectFilter filter);

// Порядок показа. По умолчанию — «недавние сверху»: чаще всего открывают то,
// что открывали вчера.
enum class ProjectSort { Recent, Name, Modified, Count };
const char* ProjectSortLabel(ProjectSort sort);

class ProjectDatabase {
public:
    // Читает список с диска и сверяет его с реальностью: дескрипторы,
    // отсутствующие папки, время правки. Отсутствие файла — не ошибка (первый
    // запуск), испорченный файл — тоже: пустой список честнее отказа запуска.
    void Load();
    void Save() const;
    static std::string StoragePath();

    const std::vector<ProjectEntry>& All() const { return m_items; }
    bool Empty() const { return m_items.empty(); }

    // Отбор для показа: вкладка + строка поиска + порядок. Возвращает индексы
    // в All(), а не копии: список перерисовывается каждый кадр, и копировать
    // пятьсот структур со строками на каждый кадр — ровно та трата, из-за
    // которой стартовые окна и становятся тяжёлыми.
    std::vector<int> Query(ProjectFilter filter, const std::string& search,
                           ProjectSort sort) const;

    int IndexOf(const std::string& path) const;
    const ProjectEntry* Find(const std::string& path) const;

    // Проект открыли или создали: поднять в списке и запомнить время. Если его
    // в списке не было — появится (так в базу попадают проекты, открытые из
    // меню File, а не из стартового окна).
    void Touch(const std::string& path);

    // Убрать из СПИСКА. Проект на диске остаётся — это разные действия, и
    // путать их нельзя (см. DeleteFromDisk).
    void Forget(const std::string& path);

    // Перечитать дескриптор одной записи (после переименования, дубликата).
    void Refresh(const std::string& path);

    // --- операции над проектом на диске -------------------------------------

    // Это вообще проект SAGE? Проверяется наличие и читаемость дескриптора:
    // «выбрал не ту папку» — самая частая ошибка импорта, и отвечать на неё
    // надо словами, а не пустой карточкой в списке.
    static bool IsProject(const std::filesystem::path& fileOrDir);

    // Импорт существующего проекта: проверка -> чтение дескриптора -> запись в
    // базу. false + err, если это не проект. В outPath — путь записи в том
    // виде, в каком он лёг в список: вызывающему нужно выделить именно этот
    // проект, а сам он привести путь к тому же виду не может (на вход могли
    // дать и файл дескриптора, и папку с хвостовым разделителем).
    bool Import(const std::filesystem::path& fileOrDir, std::string& err,
                std::string* outPath = nullptr);

    // Копия проекта рядом с оригиналом под новым именем. Возвращает путь копии
    // в outPath. Копируется ВСЁ содержимое папки: проект — это папка, и
    // «дубликат без ассетов» был бы не дубликатом.
    bool Duplicate(const std::string& path, const std::string& newName, std::string& err,
                   std::string* outPath = nullptr);

    // Переименование меняет ИМЯ В ДЕСКРИПТОРЕ, а не папку.
    //
    // Папка — это путь, на который ссылаются ярлыки, сборки игры, чужие
    // проекты и сам этот список; переименовав её, мы бы порвали всё это ради
    // косметики. Имя проекта на экране приходит из дескриптора, поэтому в
    // стартовом окне и в заголовке редактора смена видна сразу.
    bool Rename(const std::string& path, const std::string& newName, std::string& err);

    // Удаление ПАПКИ ПРОЕКТА с диска. Отдельно от Forget и только после
    // подтверждения — это единственная необратимая операция окна.
    bool DeleteFromDisk(const std::string& path, std::string& err);

    // Дописать в дескриптор поля, которых он не знает: тип и описание.
    // Их выбирают в диалоге создания, а сам дескриптор пишет Project::CreateNew
    // (см. Project.cpp) — расширять ради двух полей контракт создания проекта
    // через весь редактор было бы дороже, чем дописать их здесь.
    static bool WriteMetadata(const std::filesystem::path& dir, ProjectKind kind,
                              const std::string& description, std::string& err);

    // Чтение дескриптора — ЕДИНСТВЕННОЕ место, где стартовое окно знает его
    // формат. false — файла нет или он испорчен.
    static bool ReadDescriptor(const std::filesystem::path& dir, ProjectEntry& out);

private:
    std::vector<ProjectEntry> m_items;
};

// --- время в человеческом виде ----------------------------------------------
//
// Живёт здесь, а не в карточке: одну и ту же дату показывают и карточка, и
// панель подробностей, и они обязаны говорить одинаково.

// «26.08.2026, 14:32». Пусто, если времени нет (0).
std::string FormatStamp(long long unixTime);
// «Сегодня, 18:42», «Вчера, 09:12», дальше — дата. Для колонки «изменён»:
// человек сверяет её с памятью, а не с календарём.
std::string HumanStamp(long long unixTime);

// Открыть файл или папку ТЕМ, ЧЕМ ИХ ОТКРЫВАЕТ СИСТЕМА: папку — проводником,
// .lua — назначенным текстовым редактором. false — система отказала (нет файла
// или нет программы для него).
bool OpenWithSystem(const std::filesystem::path& target);

// Открыть папку в файловом менеджере системы. false — система отказала.
bool RevealInFileManager(const std::filesystem::path& dir);

} // namespace Sage::Launcher
