#pragma once
#include "imgui.h"

namespace Sage::Launcher {

struct ProjectEntry;
class ProjectThumbnail;

// ---------------------------------------------------------------------------
// КАРТОЧКА ПРОЕКТА — одна запись списка, в сетке или строкой.
//
// СЕТКА И СПИСОК — ОДНА КАРТОЧКА, А НЕ ДВЕ РЕАЛИЗАЦИИ. Соблазн сделать их
// разными функциями велик: рисунок и правда разный. Но всё остальное у них
// общее — что показывать, как отзываться на клик, что делать по двойному
// клику, где живёт меню «•••», как выглядит выбранная запись. Разойдясь один
// раз, эти две функции расходятся дальше при каждой правке: в сетке появляется
// подсказка, в списке — нет; в списке чинится двойной клик, в сетке — нет.
// Поэтому вид — это ПАРАМЕТР (CardLayout), а не отдельный код.
//
// Карточка НИЧЕГО НЕ ДЕЛАЕТ с проектом. Она сообщает, что с ней случилось
// (выбрали, открыли, позвали меню); что это значит — знает стартовое окно.
// ---------------------------------------------------------------------------

enum class CardLayout { Grid, List };

// Что случилось с карточкой в этом кадре.
struct CardEvent {
    bool Selected = false;       // одиночный клик — показать в панели подробностей
    bool Activated = false;      // двойной клик — открыть проект
    bool MenuRequested = false;  // «•••» или правая кнопка
};

// --- размеры (одно место на рисование и на виртуализацию) -------------------
//
// Считать размеры карточки дважды — в отрисовке и в подсчёте видимых строк —
// значит однажды посчитать по-разному и получить список, который «прыгает» при
// прокрутке.

// Сколько колонок влезает в ширину при желаемой ширине карточки.
int CardColumns(float availWidth, float targetWidth, float gap);
// Итоговая ширина карточки, чтобы колонки заняли всю ширину без остатка.
float CardWidth(float availWidth, int columns, float gap);
float CardHeight(CardLayout layout, float width);

CardEvent DrawProjectCard(CardLayout layout, const ProjectEntry& entry, bool selected,
                          const ImVec2& size, ProjectThumbnail& thumbs);

// --- контекстное меню -------------------------------------------------------

enum class ProjectAction {
    None,
    Open,
    OpenFolder,
    Rename,
    Duplicate,
    Forget,   // убрать из списка (проект на диске остаётся)
    Delete,   // удалить папку проекта с диска
};

// Пункты меню внутри уже открытого popup'а. Возвращает выбранное действие.
//
// Удаление проекта с диска стоит ОТДЕЛЬНО от «убрать из списка», через
// разделитель и красным: это единственное необратимое действие окна, и оно не
// имеет права стоять соседней строкой с безобидным «убрать».
ProjectAction DrawProjectMenuItems(const ProjectEntry& entry);

} // namespace Sage::Launcher
