#pragma once
#include <filesystem>

// ---------------------------------------------------------------------------
// ГРАНИЦА ПУТИ: лежит ли путь внутри папки.
//
// Отдельным файлом, а не строчкой в файловом диалоге, по двум причинам.
//
// ПЕРВАЯ — ЭТО ПРАВИЛО, А НЕ ПОДРОБНОСТЬ ДИАЛОГА. Ассет выбирается ВНУТРИ
// проекта (см. CLAUDE.md и AssetSlot.h): ссылка на файл в «Загрузках» работает
// ровно до сборки игры и до переноса проекта на другую машину, а потом молча
// становится пустым слотом. Спрашивают об этом и диалог, и приём брошенного
// файла, и запись пути в компонент — а ответ обязан быть один.
//
// ВТОРАЯ — ЭТО ЧИСТАЯ ФУНКЦИЯ, и проверяется она тестом, а не глазами. Тонкость
// здесь ровно одна, и она не видна: сравнивать НАЧАЛО СТРОКИ нельзя. У
// «/home/user/assets2» то же начало, что у «/home/user/assets», и проверка
// подстрокой пускает в соседнюю папку — то есть ровно туда, куда не должна.
// ---------------------------------------------------------------------------
namespace sage::editor::pathscope {

// Лежит ли p внутри root (сам root считается «внутри»). Пустой root — границы
// нет, внутри всё: так диалог импорта ходит по всему диску.
//
// Пути приводятся к каноничному виду: «..», лишние разделители и ссылки — это
// записи ОДНОГО пути, и сравнивать их как разные значит запрещать переход туда,
// где человек уже стоит.
bool Within(const std::filesystem::path& root, const std::filesystem::path& p);

} // namespace sage::editor::pathscope
