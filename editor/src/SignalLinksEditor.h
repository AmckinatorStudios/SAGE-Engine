#pragma once
#include <string>
#include <vector>

class EditorHost;
class GameObject;

// ---------------------------------------------------------------------------
// СЕКЦИЯ «EVENTS» ИНСПЕКТОРА.
//
//     Events
//         On Click
//             → [Menu]  [start_game()]
//         + Add Event
//
// Только оболочка над данными SignalLinksComponent (sage/scene/Signals.h): при
// запуске игры каждая строка становится обычным соединением шины — тем же, что
// заводит `button.clicked:connect(...)` в скрипте. Логики здесь нет, и её
// нарочно негде написать: связь — это «кого и что позвать», а всё, что сложнее
// (условия, аргументы, цепочки), — код, и живёт он в скрипте.
//
// Добавление связи — ровно два выбора: объект (Target) и метод его скрипта
// (Method). Метод выбирается из списка, прочитанного из текста скрипта, а не
// набирается по буквам: опечатка в имени метода — связь, которая молча не
// работает.
// ---------------------------------------------------------------------------
namespace sage::editor {

// Рисует связи объекта. Возвращает true, если что-то изменилось.
bool DrawSignalLinks(EditorHost& host, GameObject obj);

// Методы скрипта объекта (для списка Method). Кэш по пути и времени правки:
// инспектор спрашивает каждый кадр, а читать файл каждый кадр незачем.
std::vector<std::string> ScriptMethodsOf(EditorHost& host, GameObject target);

} // namespace sage::editor
