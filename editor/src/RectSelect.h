#pragma once
#include <imgui.h>

// ---------------------------------------------------------------------------
// РАМКА ВЫДЕЛЕНИЯ (rect select) — одна на весь редактор.
//
// ЗАЧЕМ. Выделить два десятка объектов можно было только Ctrl-кликом по
// каждому: двадцать точных попаданий подряд, и любой промах начинал всё
// заново. Жест «обвести рамкой» — то, чем это делают везде: в проводнике, в
// любом редакторе сцен, в любом графическом пакете. Его отсутствие читается не
// как «такой возможности нет», а как «мышь не работает»: человек ведёт рамку,
// на экране ничего не происходит.
//
// ОДИН МЕХАНИЗМ НА ТРИ ПАНЕЛИ. Вьюпорт, иерархия и ассеты выделяют разное
// (сущности по лучу, строки дерева, файлы), но ведут рамку одинаково: нажали в
// пустом месте, потянули, отпустили. Разойтись этим трём в мелочах (порог
// «это был клик, а не рамка», подсветка, поведение с Ctrl) — значит получить
// три похожих, но по-разному капризных жеста.
//
// КАК ПОЛЬЗОВАТЬСЯ (порядок важен):
//     const bool active = rectselect::Begin(m_rect);       // в начале окна
//     ... рисуя элементы: if (active && rectselect::Hits(m_rect, mn, mx)) ...
//     rectselect::End(m_rect, canStartHere);               // в конце окна
//     if (m_rect.Finished && rectselect::Meaningful(m_rect)) применить набор;
//     rectselect::Draw(m_rect);
// ---------------------------------------------------------------------------
namespace sage::editor::rectselect {

struct State {
    bool Dragging = false;  // рамку ведут прямо сейчас
    bool Finished = false;  // кнопку отпустили В ЭТОМ кадре — пора применять набор
    bool Additive = false;  // на момент начала держали Ctrl или Shift: добавить к набору
    ImVec2 Start{0.0f, 0.0f};   // экранные координаты нажатия
    ImVec2 Current{0.0f, 0.0f}; // экранные координаты курсора
};

// Ведёт рамку: обновляет угол под курсором и ловит отпускание кнопки.
// Возвращает true, пока рамка жива, — ВКЛЮЧАЯ кадр отпускания, иначе набор
// применять было бы не из чего: элементы в этом кадре уже нарисованы.
bool Begin(State& s);

// Пересекается ли прямоугольник элемента с рамкой. Именно ПЕРЕСЕКАЕТСЯ, а не
// «лежит целиком внутри»: обводя список, рамку ведут по диагонали и краевые
// строки задевают краем — требовать полного покрытия значит терять ровно те
// элементы, до которых человек тянулся.
bool Hits(const State& s, const ImVec2& itemMin, const ImVec2& itemMax);

// Начать рамку, если в этом кадре нажали ЛКМ и canStart. Зовётся ПОСЛЕ
// элементов: пока они не нарисованы, неизвестно, было ли нажатие по пустому
// месту.
void End(State& s, bool canStart);

// Рамка это была или клик. Порог в несколько пикселей: рука дрожит, и без него
// каждый обычный клик заканчивался бы «выделением пустоты», то есть снятием
// выбора.
bool Meaningful(const State& s);

// Прямоугольник рамки, нормализованный (min/max независимо от направления).
void Bounds(const State& s, ImVec2& outMin, ImVec2& outMax);

// Рисует рамку поверх содержимого окна.
void Draw(const State& s);

} // namespace sage::editor::rectselect
