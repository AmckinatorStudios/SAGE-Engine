#pragma once
#include <cstdint>
#include <filesystem>
#include <string>
#include <vector>

class AssetPreview;

// ---------------------------------------------------------------------------
// Файловый диалог редактора.
//
// ЗАЧЕМ. До этого КАЖДЫЙ путь в редакторе вводился руками в текстовое поле:
// открыть проект, сохранить сцену, собрать игру, выбрать модель, выбрать
// текстуру. Это не неудобство, а неработоспособность: человек не помнит
// абсолютный путь к своей модели, а ошибиться в нём на один символ — обычное
// дело, и единственной обратной связью была строчка в консоли.
//
// ПОЧЕМУ СВОЙ, А НЕ СИСТЕМНЫЙ. Системный диалог (GetOpenFileName / GTK / Cocoa)
// выглядит роднее, но тянет за собой по реализации на платформу, на Linux ещё и
// зависимость от того, какой тулкит стоит у пользователя, а в headless-прогоне
// (CI, автотесты редактора) не открывается вовсе. Диалог на ImGui рисуется тем
// же кодом на всех платформах, работает в offscreen-прогоне и не может
// заблокировать поток ожиданием ответа оконной системы.
//
// Использование:
//     FileBrowser::Config cfg;
//     cfg.Title = "Открыть проект";
//     cfg.Mode  = FileBrowser::PickMode::OpenFile;
//     cfg.Filters = {".sageproj"};
//     browser.Open(cfg);
//     ...
//     if (browser.Draw()) { /* browser.Result() — выбранный путь */ }
// ---------------------------------------------------------------------------
class FileBrowser {
public:
    enum class PickMode {
        OpenFile,    // выбрать существующий файл
        SaveFile,    // указать имя (файла может ещё не быть)
        PickFolder,  // выбрать каталог
        // Файл ИЛИ каталог — одним диалогом.
        //
        // ЗАЧЕМ. Внести в проект надо то, что скачали, а скачивают по-разному:
        // одним файлом, папкой с моделью и текстурами, архивом. Два режима
        // означали бы две кнопки («Внести файл…» и «Внести папку…») и вопрос
        // «а мой zip — это что?» ровно там, где человек и так не уверен.
        OpenAny,
    };

    struct Config {
        std::string Title = "Выбор файла";
        PickMode Mode = PickMode::OpenFile;
        std::filesystem::path StartDir;      // пусто — текущий каталог
        std::string DefaultName;             // для SaveFile
        // Расширения с точкой (".sage", ".png"). Пусто — показывать все файлы.
        std::vector<std::string> Filters;
        std::string FilterLabel;             // подпись фильтра, напр. "Сцены (*.sage)"
    };

    void Open(const Config& config);
    bool IsOpen() const { return m_open; }

    // Откуда брать обложки моделей, материалов и префабов.
    //
    // КАРТИНКАМ ЭТО НЕ НУЖНО: текстура и есть своя обложка, её диалог показывает
    // всегда. Указатель нужен только для того, что приходится РИСОВАТЬ — модели,
    // материала, префаба; без него они остаются со значком типа. Поэтому свой
    // AssetPreview диалог не заводит: он живёт в модальном окне, открыт по
    // одному за раз, и второй набор буферов в видеопамяти ради этого не нужен —
    // панель, открывшая диалог, обычно свой уже имеет.
    void SetPreview(AssetPreview* preview) { m_preview = preview; }

    // Каким видом сейчас открывается диалог: сеткой обложек или строками.
    // Выбор человека, прочитанный из настроек редактора при первом открытии.
    bool GridView() const { return m_grid; }

    // Рисует диалог. true — пользователь подтвердил выбор; путь в Result().
    bool Draw();

    const std::filesystem::path& Result() const { return m_result; }

private:
    struct Entry {
        std::string Name;
        bool IsDir = false;
        uintmax_t Size = 0;
    };

    void Refresh();
    void GoTo(const std::filesystem::path& dir);
    bool PassesFilter(const std::filesystem::path& p) const;
    void DrawPlaces();
    void DrawBreadcrumbs();
    // Два вида одного и того же списка. Возвращают true, если выбор подтверждён
    // двойным щелчком (тогда путь уже лежит в m_result).
    bool DrawList();
    bool DrawGrid();
    // Что произошло со строкой или плиткой: выбрали, открыли папку, открыли файл.
    // Общая на оба вида: иначе двойной клик в сетке и в списке разошлись бы в
    // поведении при первой же правке.
    enum class Hit { None, Selected, EnterDir, Confirm };
    Hit DrawEntryCommon(int index, const Entry& entry, bool doubleClicked);

    // Чем кончилась попытка показать обложку. Ответ нужен именно такой, а не
    // «нарисовали или нет»: «ещё читается» и «не открылась» — разные вещи для
    // человека, и рисовать их одинаково значит врать. Пустая площадка читается
    // как «файл битый», крутилка — как «подожди», а значок с восклицательным
    // знаком честно говорит «эта картинка не открылась» и объясняет почему.
    enum class Cover { None, Loading, Drawn, Failed };
    // Координаты — числами, а не ImVec2: заголовок не тянет за собой imgui.h
    // ради двух float, и панели, которым нужен только FileBrowser, не начинают
    // зависеть от версии ImGui.
    Cover DrawCover(const std::filesystem::path& full, bool isDir, float x0, float y0, float x1,
                    float y1, float rounding);

    // Крупное превью под курсором: сама картинка во много раз больше плитки,
    // размеры, вес и тип. Плитка отвечает на «который из них», превью — на «то
    // ли это, что мне нужно», и второй вопрос по плитке 80x80 не решается.
    void DrawHoverPreview(const std::filesystem::path& full, const Entry& entry);

    Config m_cfg;
    bool m_open = false;
    bool m_needsOpen = false;   // отложенный OpenPopup: звать его можно только в кадре
    std::filesystem::path m_dir;
    std::filesystem::path m_result;
    std::vector<Entry> m_entries;
    std::string m_error;
    char m_name[512] = {0};
    char m_search[128] = {0};
    char m_newFolder[128] = {0};
    int m_selected = -1;
    bool m_showHidden = false;
    // Сетка или строки. ЗАПОМИНАЕТСЯ МЕЖДУ ЗАПУСКАМИ (editor_prefs.json): выбор
    // вида — привычка человека, а не свойство конкретного диалога. Картинки
    // ищут глазами в сетке, а файл с известным именем — в строках, где видно
    // размер; заставлять переключаться заново при каждом открытии значит
    // отнимать этот выбор.
    bool m_grid = false;
    bool m_viewLoaded = false;   // настройки прочитаны (один раз за сеанс)
    AssetPreview* m_preview = nullptr;
    // Куда можно прыгнуть одним кликом. Считается при открытии: перечитывать
    // список дисков каждый кадр незачем, а на Windows это ещё и обращение к
    // диску, которое на пустом приводе даёт заметную паузу.
    // Пункт быстрого доступа. Заголовок группы — тот же тип с пустым путём:
    // отдельный список групп пришлось бы держать в согласии с этим, а порядок
    // всё равно один.
    struct Place {
        std::string Label;
        std::filesystem::path Path;
        bool IsGroup = false;
    };
    std::vector<Place> m_places;
};
