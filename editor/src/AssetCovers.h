#pragma once
#include <cstdint>
#include <filesystem>
#include <string>

#include "imgui.h"

class AssetPreview;

// ---------------------------------------------------------------------------
// ОБЛОЖКИ АССЕТОВ — ОДИН НАБОР ПРАВИЛ НА ВЕСЬ РЕДАКТОР.
//
// Обложку файла рисуют в трёх местах: файловый диалог, панель ассетов и слот
// ассета в инспекторе. Правила у неё одни и те же, а лежали они в одном месте
// — в файловом диалоге: вписывание по пропорциям, шахматка под прозрачностью,
// крутилка на ещё не прочитанной картинке, превью под курсором. Панель ассетов
// ничего этого не знала и растягивала обложку в квадрат: панорама 4096x1024
// показывалась квадратом, тайл-лист 1:4 — квадратом, скриншот 16:9 —
// квадратом. Обложку смотрят затем, чтобы УЗНАТЬ свой файл, и растянутая
// делает ровно обратное.
// ---------------------------------------------------------------------------
namespace sage::editor::covers {

// Прямоугольник, в который картинка w:h вписана внутрь площадки a..b по центру
// (пропорции сохраняются, пустое место остаётся по бокам).
struct FitRect {
    ImVec2 A, B;
};
FitRect Fit(const ImVec2& a, const ImVec2& b, int w, int h);

// Шахматка под картинкой с прозрачностью: без неё дырки в альфе неотличимы от
// фона, и текстура выглядит просто рваной.
void DrawChecker(ImDrawList* dl, const ImVec2& a, const ImVec2& b);

// Крутилка на месте ещё не прочитанной обложки. Пустая площадка означала бы
// «здесь ничего нет», а её тут просто ещё нет.
void DrawSpinner(ImDrawList* dl, const ImVec2& center, float radius, ImU32 color);

// Размер файла словами («4.2 MiB»).
std::string HumanSize(uintmax_t bytes);

// ПРЕВЬЮ ПОД КУРСОРОМ — содержимое подсказки вместе с её обёрткой.
//
// Плитка 80x80 отвечает на вопрос «который из этих файлов», и на этом её
// возможности кончаются. «Та ли это картинка», «что на ней написано», «какого
// она размера», «почему она весит сорок мегабайт» — по плитке не видно, и
// ответ добывался открыванием файла. Превью показывает ту же картинку в
// шесть-семь раз крупнее и подписывает то, что по ней не прочитать.
//
// preview — кэш съёмок редактора для материала, модели и префаба (nullptr —
// показать только картинки и подпись).
void DrawHoverPreview(const std::filesystem::path& full, bool isDir, const std::string& name,
                      uintmax_t bytes, AssetPreview* preview);

} // namespace sage::editor::covers
