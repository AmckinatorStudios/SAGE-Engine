#pragma once
#include <vector>

#include "imgui.h"

#include <glm/glm.hpp>

#include <entt/entt.hpp>

#include "UIToolSettings.h"
#include "sage/ui/UILayoutTools.h"

class EditorHost;
class Scene;

// ---------------------------------------------------------------------------
// Вёрстка игрового интерфейса мышью, прямо во вьюпорте.
//
// КАК БЫЛО. Интерфейс собирался числами в инспекторе: Offset, Size, Anchor — и
// посмотреть на результат можно было только переключившись в панель Game, где
// ничего нельзя ни выделить, ни подвинуть. То есть верстали вслепую: правишь
// число, идёшь смотреть, возвращаешься. Для одной панели это терпимо, для
// экрана из двадцати элементов — нет.
//
// ЧТО ЗДЕСЬ. Элементы рисуются поверх кадра рамками, выбираются кликом,
// двигаются перетаскиванием и меняют размер восемью ручками — то есть ровно
// так, как это делают в любом редакторе интерфейсов. Плюс то, без чего вёрстка
// мышью остаётся приблизительной:
//
//   • СЕТКА. Видимая и с настраиваемым шагом. Отдельно «показывать» и отдельно
//     «притягивать»: сетка как линейка нужна не реже, чем притяжка.
//   • ПРИВЯЗКА К КРАЯМ. Края и центры родителя и соседей; какая линия сработала
//     — видно (см. sage::ui::Snap). Без показанной направляющей притяжка
//     воспринимается как «редактор не даёт поставить куда надо».
//   • НАБОР. Тянется и выравнивается всё выделенное сразу, притяжка считается
//     по объединяющему прямоугольнику — набор ведёт себя как один элемент.
//   • РАМКА ВЫДЕЛЕНИЯ. Протяжка по пустому месту выбирает всё, что задела.
//   • СТРЕЛКИ. Сдвиг на пиксель, с Shift — на шаг сетки. Точная доводка мышью
//     невозможна в принципе.
//   • РАССТОЯНИЯ. Пока элемент тянут, показаны отступы до краёв родителя:
//     верстают по отступам, а не по абсолютным координатам.
//
// ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ЕЩЁ ОДИН КУСОК ViewportPanel. Панель вьюпорта уже
// отвечает за раскладку видов, полёт камеры, 3D-гизмо и пикинг. Вёрстка UI —
// самостоятельная задача со своим состоянием (что тащим, за какую ручку) и
// своей системой координат (пиксели экрана, а не мир). Смешать их значит
// получить ещё один файл, в который страшно заглядывать.
//
// ПОЧЕМУ МАТЕМАТИКА ПРИВЯЗКИ НЕ ЗДЕСЬ. Она в движке (sage/ui/UILayoutTools.h) и
// проверяется тестами по числам. Здесь остаётся мышь, рисование и запись в
// компоненты — то, что тестами не проверишь.
//
// СИСТЕМА КООРДИНАТ. Раскладка UI считается в пикселях кадра (screenW x
// screenH), а кадр показан в панели прямоугольником imgPos/imgSize. Всё
// преобразование — в ToScreen/ToUI, и больше нигде: смешение двух систем
// координат в вычислениях и есть источник «мышь тянет не туда».
// ---------------------------------------------------------------------------
class UICanvas {
public:
    // Рисует рамки и обрабатывает мышь. Зовётся из панели вьюпорта, когда
    // включён режим вёрстки и активный слот перспективный.
    //
    // imgPos/imgSize — прямоугольник кадра на экране; frameW/frameH — размер
    // кадра в пикселях (в них считается раскладка UI). hovered — курсор над
    // этим слотом.
    void Draw(EditorHost& host, ImDrawList* dl, ImVec2 imgPos, ImVec2 imgSize, int frameW,
              int frameH, bool hovered);

    // Тащим ли мы что-то прямо сейчас — вьюпорт не должен в это время
    // обрабатывать выбор объектов и полёт камеры.
    bool IsUsing() const { return m_drag != Drag::None || m_marquee; }

private:
    // Что именно тащим. Ручки нумеруются по сторонам света, чтобы код
    // изменения размера читался, а не расшифровывался.
    enum class Drag { None, Move, N, S, W, E, NW, NE, SW, SE };

    // Прямоугольник элемента в пикселях кадра плюс всё, что нужно, чтобы его
    // записать обратно. Собирается раз в кадр: и рисование, и попадание, и
    // привязка смотрят на один и тот же список, а не пересчитывают раскладку
    // каждый по-своему.
    struct Item {
        entt::entity Entity = entt::null;
        int Id = -1;
        sage::ui::UIRect Rect{};
        sage::ui::UIRect Parent{};
        // Масштаб холста: прямоугольник — в пикселях экрана, а Offset/Size
        // хранятся в опорных единицах, и записать правку без него нельзя.
        float Scale = 1.0f;
        // Родитель раскладывает детей сам (ui::Layout) — тащить такой элемент
        // мышью бессмысленно: раскладка вернёт его на место тем же кадром.
        bool InLayout = false;
        bool Selected = false;
        bool Visible = true;
    };

    void Collect(Scene& scene, EditorHost& host, int frameW, int frameH);
    void DrawGrid(ImDrawList* dl, ImVec2 imgPos, ImVec2 imgSize, const UIToolSettings& tools,
                  float sx, float sy) const;
    // Записывает новый прямоугольник в компонент (Offset/Size через якорь),
    // переводя пиксели экрана обратно в опорные единицы холста.
    void Apply(Scene& scene, const Item& item, glm::vec2 topLeft, glm::vec2 size,
               bool sizeChanged);
    // Сдвиг всего выделения на delta пикселей кадра (стрелки, выравнивание).
    void MoveSelection(EditorHost& host, Scene& scene, glm::vec2 delta);

    std::vector<Item> m_items;      // пересобирается каждый кадр

    Drag m_drag = Drag::None;
    int m_dragId = -1;              // сущность, за которую взялись
    ImVec2 m_dragStartMouse{0, 0};
    sage::ui::UIRect m_dragStartRect{};      // прямоугольник взятого элемента
    sage::ui::UIRect m_dragStartUnion{};     // и всего набора (по нему привязка)
    // Стартовые прямоугольники всего набора: двигать набор надо от исходных
    // положений, а не накапливать дельту покадрово — накопление уводит.
    std::vector<std::pair<int, sage::ui::UIRect>> m_dragStart;
    bool m_pushedUndo = false;      // одна запись undo на всё перетаскивание

    bool m_marquee = false;         // тянем рамку выделения
    ImVec2 m_marqueeStart{0, 0};

    std::vector<sage::ui::SnapGuide> m_guides; // что показывать в этом кадре
};
