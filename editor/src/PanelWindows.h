// ПАНЕЛЬ — ОКНО СИСТЕМЫ, КОГДА ЕЁ ВЫТАЩИЛИ ИЗ РАБОЧЕЙ ОБЛАСТИ.
//
// ЧТО БЫЛО НЕ ТАК. Отдельное окно было отдельным СОСТОЯНИЕМ с переключателем в
// меню, и состояние жило в трёх местах (флаг меню, настройки, ImGui) — они
// расходились. Заодно система рисовала заголовок окна сама
// (ConfigViewportsNoDecoration = false), а за системный заголовок ImGui не
// умеет показывать док-узлы: вытащенную панель нечем было вернуть перетаскиванием.
//
// ЧТО ЗДЕСЬ. Состояния нет вообще: правда одна — вьюпорт окна в ImGui, а он
// помнится в imgui.ini вместе с позицией, размером и доком (поэтому перезапуск и
// пользовательские раскладки работают без отдельной памяти).
//
//   • Вытащил вкладку из рабочей области — окно становится окном системы и
//     остаётся им: класс окна несёт ImGuiViewportFlags_NoAutoMerge, и ImGui не
//     вливает его обратно в главное окно, стоит на него наехать.
//   • Вернуть — перетащить заголовок или вкладку на нужный узел редактора
//     (ImGui показывает док-цели; заголовок рисует сам ImGui).
//   • Если окно потеряно (монитор отключили) — оно возвращается само, а пункт
//     меню «Окно > Вернуть все окна в редактор» делает это по требованию.
// ---------------------------------------------------------------------------
namespace panelwindows {

// Зовётся перед Begin панели, которая умеет жить своим окном (PanelSpec::Detachable):
// ставит класс окна и, если окно надо вернуть, док главного окна.
void Before(const char* id);

// Док-пространство главного окна текущего рабочего места: туда возвращаются окна.
void SetHomeDock(ImGuiID dockspace);

// Окно панели живёт отдельным окном системы (или плавает без дока) сейчас.
bool IsFloating(const char* id);

// Вернуть окно в главное на ближайшем кадре (его Before ещё должен быть вызван).
void RequestReturn(const char* id);

} // namespace panelwindows
