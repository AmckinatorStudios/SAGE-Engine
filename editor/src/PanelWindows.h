#pragma once
#include "imgui.h"

// ---------------------------------------------------------------------------
// ПАНЕЛЬ ОТДЕЛЬНЫМ ОКНОМ СИСТЕМЫ (multi-window).
//
// ЧТО БЫЛО НЕ ТАК. Вытащить панель из дока мышью ImGui умел и раньше
// (ImGuiConfigFlags_ViewportsEnable), но пользы от этого почти не было:
//
//   • ПАНЕЛЬ ПРИЛИПАЛА ОБРАТНО. Плавающее окно, наехавшее на главное, ImGui
//     СЛИВАЕТ в его вьюпорт (авто-слияние). Для системы такого окна больше
//     нет: оно не поднимается поверх других программ, не сворачивается
//     отдельно, не переносится на второй монитор и не живёт, пока главное
//     окно свёрнуто. Человек «вытащил окно», а получил прямоугольник, который
//     плавает ВНУТРИ редактора.
//   • ЭТОГО НЕ БЫЛО В МЕНЮ. Единственным способом оставалось перетаскивание
//     за вкладку, а обратного пути не было вовсе — кроме сброса всей
//     раскладки, то есть потери расстановки панелей заодно.
//   • ОКНО ТЕРЯЛОСЬ. Вытащенное на второй монитор окно после отключения этого
//     монитора остаётся за краем рабочего стола: панель «есть», но её не
//     видно и вернуть нечем.
//
// ЧТО ЗДЕСЬ. Состояние «панель живёт своим окном ОС» стало ЯВНЫМ и
// управляемым: галочка в меню (Окна > В отдельном окне), память между
// запусками (настройки редактора) и — главное — флаг
// ImGuiViewportFlags_NoAutoMerge, пока состояние включено. Именно он
// запрещает ImGui слить окно с главным, то есть делает окно НАСТОЯЩИМ окном
// системы, а не плавающим прямоугольником поверх редактора.
//
// Мышь остаётся равноправным способом: вытащил рукой — галочка встала сама,
// вернул в док — снялась (см. After). Два источника правды тут недопустимы:
// меню, расходящееся с тем, что человек видит на экране, хуже отсутствующего
// меню.
// ---------------------------------------------------------------------------
namespace panelwindows {

// Идентификатор панели — строка ПОСЛЕ "###" в её имени ImGui ("UIEditor" для
// окна "Интерфейс###UIEditor"). Видимая часть имени переводится и меняется от
// языка к языку, идентификатор — нет; по нему же окно ищется в ImGui.
bool Detached(const char* id);
void SetDetached(const char* id, bool detached);
// Собрать все отдельные окна обратно в главное. Это путь назад для случая
// «окно уехало на монитор, которого больше нет».
void AttachAll();
// Вернуть панелям их состояние по умолчанию (редактор интерфейса — своим
// окном, остальные в доке). Зовётся при сбросе раскладки.
void ResetToDefaults();

// Док-пространство главного окна: туда возвращается панель, у которой галочку
// сняли.
void SetHomeDock(ImGuiID dockspace);

// Обрамляют отрисовку панели: Before готовит окно (класс вьюпорта и, в кадре
// переезда, док с позицией), After сверяет состояние с тем, что человек
// сделал мышью.
void Before(const char* id);
void After(const char* id);

// Прочитать сохранённое из настроек редактора. Зовётся один раз при запуске,
// ДО первого кадра.
void Load();

} // namespace panelwindows
