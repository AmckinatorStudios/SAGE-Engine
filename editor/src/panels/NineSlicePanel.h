#pragma once
#include <memory>
#include <string>

#include "imgui.h"

#include "sage/ui/NineSlice.h"

class EditorHost;
class Texture;
class AssetPreview;

// ---------------------------------------------------------------------------
// РЕДАКТОР ДЕВЯТИНЫ — отдельный инструмент под отдельную задачу.
//
// ЧТО БЫЛО НЕ ТАК. Нарезка задавалась четырьмя числами в инспекторе: «9-slice
// (l,t,r,b)». Чтобы их подобрать, человек открывал картинку в стороннем
// просмотрщике, увеличивал её, считал пиксели уголка глазами, возвращался в
// редактор, вбивал числа — и шёл смотреть, что получилось, на элемент в
// сцене, размер которого к делу отношения не имеет. Ошибся на пиксель — весь
// круг заново. При этом самой картинки в этот момент на экране НЕ БЫЛО НИ
// РАЗУ: числа правились вслепую.
//
// Числа при этом ещё и принадлежали элементу, а не картинке. Одна и та же
// рамка на десяти элементах означала десять копий одних и тех же четырёх
// чисел, и поправить нарезку значило найти все десять.
//
// ЧТО ЗДЕСЬ. Одно окно, в котором видно то, что правят:
//   • СЛЕВА — САМА КАРТИНКА, крупно, с четырьмя направляющими поверх неё.
//     Направляющие ТАЩАТ мышью; курсор меняется на «двигать», ближайшая
//     подсвечивается. Колесо — увеличение (до 32x, с ближайшим соседом:
//     считать пиксели на размытой картинке нельзя), средняя кнопка — сдвиг.
//     Углы, края и середина закрашены разными оттенками — из чего состоит
//     нарезка, видно без объяснений.
//   • СПРАВА СВЕРХУ — числа. Те же четыре поля, что были в инспекторе, но
//     рядом с картинкой и связанные с направляющими в обе стороны.
//   • СПРАВА СНИЗУ — ПРЕДПРОСМОТР: та же картинка, растянутая в прямоугольник
//     ПРОИЗВОЛЬНОГО размера, который тянут за угол. Ровно то, ради чего
//     девятина и нужна, — видно сразу и без сцены.
//   • «Подобрать» — догадка по самой картинке (см. sage::ui::GuessBorder).
//     Предложение, а не ответ: результат виден и правится.
//
// ОПИСАНИЕ ЖИВЁТ РЯДОМ С КАРТИНКОЙ. Кнопка «Сохранить» кладёт .sage9 рядом с
// файлом, «Загрузить» читает его же; окно подхватывает его само при выборе
// картинки. Так нарезка описана ОДИН раз, а элементы к ней применяются.
//
// «Применить к выбранному» переносит нарезку в компонент Image выбранного
// элемента — с записью в историю отката, как любая правка сцены.
// ---------------------------------------------------------------------------
class NineSlicePanel {
public:
    void Draw(EditorHost& host, bool& open);

    // Открыть окно на конкретной картинке (кнопка в инспекторе части «Картинка»).
    void OpenFor(const std::string& imagePath);

    // Смена проекта: путь ассета в новом проекте ведёт к другому файлу.
    void ForgetProject();

private:
    void DrawToolbar(EditorHost& host);
    void DrawCanvas(EditorHost& host);
    void DrawFields(EditorHost& host);
    void DrawPreview();

    // Загружает картинку и, если рядом лежит .sage9, её описание.
    void LoadImage(const std::string& path);

    std::string m_path;                  // путь картинки (относительно проекта)
    std::shared_ptr<Texture> m_tex;      // она же, загруженная
    sage::ui::NineSlice m_slice;

    // --- холст ---
    float m_zoom = 0.0f;                 // 0 — «вписать», пересчитывается при загрузке
    ImVec2 m_pan{0.0f, 0.0f};
    int m_dragEdge = -1;                 // какую направляющую тащим (0..3), -1 — никакую
    bool m_showCheckers = true;          // шахматка под прозрачностью

    // --- предпросмотр ---
    ImVec2 m_previewSize{220.0f, 120.0f};
    float m_previewScale = 1.0f;         // множитель пикселя исходника
    bool m_previewResizing = false;

    std::string m_status;                // что случилось после последнего действия
};
