#pragma once

class EditorHost;

// ---------------------------------------------------------------------------
// Панель «Вёрстка» — инструменты сборки игрового интерфейса.
//
// ЧЕГО НЕ ХВАТАЛО. Мышью во вьюпорте элемент можно было двигать и растягивать,
// и на этом всё. Три вещи, без которых вёрстка остаётся приблизительной:
//
//   1. ПРИВЯЗКИ. Их не было вовсе, кроме общего шага гизмо, который к пикселям
//      интерфейса отношения не имеет. Поставить кнопку ровно под кнопкой можно
//      было только числами в инспекторе.
//   2. ВЫРАВНИВАНИЕ НАБОРА. Выделить пять кнопок и сказать «по левому краю» —
//      самая частая операция вёрстки, и делалась она пятью правками Offset.
//   3. ЯКОРЬ КАРТИНКОЙ. Якорь выбирался выпадающим списком из девяти строк
//      («TopLeft», «CenterRight»), хотя это девять клеток и есть.
//
// ПОЧЕМУ ПАНЕЛЬ, А НЕ ПОЛОСА ВНУТРИ ВЬЮПОРТА. Инструментов много (сетка,
// привязки, шесть выравниваний, два распределения, якорь, растяжение), и
// полоса поверх кадра закрыла бы как раз то, что верстают. Панель ставится
// куда удобно и живёт рядом с инспектором.
//
// Панель работает и с выключенным режимом вёрстки: настроить сетку заранее —
// нормальный порядок действий. Но если он выключен, панель об этом говорит и
// предлагает включить: иначе непонятно, почему во вьюпорте ничего не меняется.
// ---------------------------------------------------------------------------
class UIToolsPanel {
public:
    // focus — вывести панель вперёд (её вкладку сделать активной). Нужно в тот
    // момент, когда панель открывается сама вместе с режимом вёрстки: она
    // приходит вкладкой к иерархии, и без этого включение режима выглядит как
    // «инструменты не появились» — их просто не видно за соседней вкладкой.
    void Draw(EditorHost& host, bool* open, bool focus);
};
