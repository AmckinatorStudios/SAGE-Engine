#pragma once

#include <entt/entt.hpp>

class EditorHost;
class Scene;

// Панель Hierarchy — ДЕРЕВО сущностей сцены с иерархией родитель/ребёнок:
// выбор, создание (ПКМ по пустому месту), Create Child / Duplicate / Unparent /
// Delete (ПКМ по сущности), перетаскивание одной сущности на другую для смены
// родителя (drag-drop) и перетаскивание в пустую зону — открепление в корень.
// Своё состояние — только строка поиска: она про ПРОСМОТР, а не про сцену.
class HierarchyPanel {
public:
    void Draw(EditorHost& host, bool* open);

private:
    // leaf — рисовать строку без поддерева (нужно плоскому списку поиска).
    void DrawNode(EditorHost& host, Scene& scene, entt::entity e, bool leaf = false);
    // Плоский список совпавших с фильтром. Именно плоский, а не дерево: у
    // отфильтрованного дерева пришлось бы показывать родителей, которые сами
    // под фильтр не подошли, — и список из двух совпадений выглядел бы как
    // список из десяти.
    void DrawFiltered(EditorHost& host, Scene& scene);

    // Строка поиска по имени. Живёт в панели, а не в хосте: это состояние
    // ПРОСМОТРА, оно не относится к сцене и не должно попадать в undo.
    char m_filter[64] = {0};
};
