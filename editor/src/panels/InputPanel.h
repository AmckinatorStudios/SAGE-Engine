#pragma once
#include <string>

#include "sage/input/Binding.h"
#include "sage/input/InputSystem.h"

class EditorHost;

// ---------------------------------------------------------------------------
// Панель «Управление» — раскладка проекта: какие у игры есть ДЕЙСТВИЯ и чем
// они вызываются.
//
// Зачем она нужна отдельно от кода и скриптов. Раскладку можно объявить из
// Lua (BindAction), и до сих пор это был единственный способ. Значит, чтобы
// посмотреть, что и на чём висит, приходилось читать скрипты; чтобы поменять
// клавишу — править код; а увидеть, что два действия дерутся за одну клавишу,
// было нельзя вообще ничем, кроме как поиграв и удивившись. Раскладка — это
// данные проекта, и место им там же, где остальным данным: в редакторе,
// в файле, под глазами.
//
// Что панель РЕДАКТИРУЕТ: документ (host.ProjectInput()), а не работающий
// ввод. Сохраняется он в <проект>/input.sageinput и применяется к настоящему
// вводу при запуске игры — одинаково в Play-режиме и в собранной игре.
// Поэтому правка раскладки не действует «прямо сейчас, на лету»: это не
// настройка редактора, а содержимое игры.
//
// Назначение клавиши сделано ЛОВЛЕЙ, а не выбором из списка. Список известных
// источников — под сотню пунктов, и найти в нём «правый Alt» дольше, чем
// нажать его. Ловля же отвечает ровно на тот вопрос, который человек себе и
// задаёт: «пусть будет вот эта кнопка».
// ---------------------------------------------------------------------------
class InputPanel {
public:
    void Draw(EditorHost& host, bool& open);

private:
    // Что рисуем для одного действия (тело раскрытого узла).
    void DrawAction(EditorHost& host, sage::input::Context& context,
                    sage::input::Action& action, const std::string& contextName);
    // Строка одной привязки: источник, кнопка «переназначить», удаление.
    // Возвращает true, если привязку попросили удалить.
    bool DrawBinding(EditorHost& host, sage::input::Action& action, int index,
                     const std::string& contextName);
    // Модалка ловли. Возвращает true в тот кадр, когда источник пойман.
    bool DrawCaptureModal(EditorHost& host, sage::input::Binding& caught);
    // Кто ещё занял этот источник (пусто, если никто). Отдельной функцией,
    // потому что вопрос задаётся и при показе привязки, и при назначении новой.
    std::string ConflictWith(sage::input::InputSystem& input, const sage::input::Binding& binding,
                             const sage::input::Action* self) const;

    // Куда положить пойманный источник: имя контекста + имя действия + номер
    // привязки (−1 — добавить новую). Строками, а не указателями: пока открыта
    // модалка, человек не трогает список, но указатель на действие пережил бы
    // не всякую правку, а имя переживает.
    std::string m_captureContext;
    std::string m_captureAction;
    int m_captureBinding = -1;
    bool m_captureOpen = false;

    // Выбранный контекст (по имени — по той же причине).
    std::string m_selectedContext;

    char m_newContextName[64] = {0};
    char m_newActionName[64] = {0};
    int m_newActionType = 0;
    int m_newContextPriority = 10;
};
