class EditorHost;
class Scene;

// ---------------------------------------------------------------------------
// РЕДАКТОР ИНТЕРФЕЙСА — отдельный инструмент, а не режим вьюпорта.
//
// ЧТО БЫЛО НЕ ТАК. Интерфейс верстался в «режиме вёрстки»: вьюпорт переставал
// быть вьюпортом и превращался в холст. Из этого следовало всё остальное:
//   • режим приходилось ВКЛЮЧАТЬ и ВЫКЛЮЧАТЬ, и половина вопросов «почему не
//     работает» сводилась к тому, что он не в том положении;
//   • включённый, он отбирал у сцены клик, гизмо и полёт камеры — работать
//     одновременно со сценой и с интерфейсом было нельзя в принципе;
//   • инструменты жили в третьем месте (панель «Вёрстка»), свойства — в
//     четвёртом (инспектор), а холст — в чужом окне;
//   • и главное: холст показывал кадр РЕДАКТОРСКОЙ камеры, то есть не то
//     разрешение и не то соотношение сторон, в которых интерфейс увидит игрок.
//     Вёрстка «на глаз» под чужой экран — это и есть причина, по которой
//     собранная игра выглядела иначе, чем редактор.
//
// ЧТО ЗДЕСЬ. Одно окно, в котором есть всё нужное и ничего лишнего:
//   • ХОЛСТ — игровой кадр в ЕГО СОБСТВЕННОМ разрешении и соотношении сторон
//     (из настроек игры), вписанный в панель. Всё, что видно здесь, игрок
//     увидит в точности так же. Правки видны сразу: кадр рисуется каждый раз
//     заново, а не по кнопке.
//   • СЛЕВА — дерево элементов: создать, выбрать, спрятать, поменять порядок,
//     удалить. Порядок в дереве и есть порядок отрисовки (Layer среди соседей).
//   • СПРАВА — свойства выбранного (те же, что в инспекторе: общий модуль
//     UIElementProperties) и инструменты вёрстки: якорь, выравнивание,
//     распределение, растянуть по родителю.
//   • СВЕРХУ — то, что относится к самому холсту: масштаб, фон, сетка,
//     привязки.
//
// ПОЧЕМУ НЕ РЕЖИМ И НЕ ОВЕРЛЕЙ. Верстают интерфейс подолгу и отдельно от
// расстановки объектов; окно можно открыть, пришвартовать рядом со сценой или
// вытащить на второй монитор — и вьюпорт при этом остаётся вьюпортом.
// ---------------------------------------------------------------------------
class UIEditorPanel {
public:
    void Draw(EditorHost& host, bool* open);

    // Вывести окно вперёд (после создания элемента из меню Create).
    void RequestFocus() { m_focusFrames = 3; }

private:
    void DrawTopBar(EditorHost& host);
    void DrawTree(EditorHost& host, float width);
    void DrawCanvas(EditorHost& host);
    void DrawSide(EditorHost& host, float width);
    void DrawTreeNode(EditorHost& host, Scene& scene, int id, int depth);
    void DrawAlignTools(EditorHost& host);
    void DrawCreateMenu(EditorHost& host);

    UICanvas m_canvas;
    AssetPreview m_preview;    // обложки для слотов ассетов в свойствах
    FileBrowser m_browser;     // выбор картинки элемента
    std::string* m_browseTarget = nullptr;

    // Показ холста. Масштаб и сдвиг — свойства ПОКАЗА, а не вёрстки: сам кадр
    // всегда рисуется в разрешении игры, меняется только то, как крупно его
    // видно. Так и должно быть: иначе, отдалив холст, человек правил бы
    // раскладку под другое разрешение.
    float m_zoom = 1.0f;
    ImVec2 m_pan{0.0f, 0.0f};
    bool m_fitOnce = true;     // первый показ вписывает кадр в панель

    int m_focusFrames = 0;
    float m_treeWidth = 260.0f;
    float m_sideWidth = 340.0f;
};
