#pragma once
#include "../ProjectTemplates.h"
#include <filesystem>
#include <string>

#include "FileBrowser.h"

class EditorHost;
class RecentProjects;

// ---------------------------------------------------------------------------
// Стартовое окно проектов — первое, что видит человек, и до сих пор оно было
// худшей частью редактора.
//
// ЧТО БЫЛО НЕ ТАК.
//   • Путь приходилось ПЕЧАТАТЬ. Три поля ввода — «Location», «Path» — и ни
//     одной кнопки обзора, при том что файловый диалог в редакторе есть и
//     используется везде остальным. Человек, который только что установил
//     редактор, не знает наизусть ни одного подходящего пути.
//   • Проект по умолчанию создавался в ТЕКУЩЕЙ ПАПКЕ, то есть внутри установки
//     движка (рядом с SageEditor.exe). Там его потом не найти, а распаковка
//     следующей версии поверх — снесёт.
//   • Три раздела шли простынёй сверху вниз: недавние, создать, открыть. Самое
//     частое действие (открыть вчерашний проект) визуально ничем не выделено и
//     тонет между двумя формами.
//   • Список недавних — кнопка с именем, рядом серым весь путь, рядом «x».
//     Строки разной длины, ничего не выровнено, «x» стоит вплотную к пути и
//     нажимается по ошибке.
//   • Всё по-английски, тогда как остальной редактор по-русски.
//   • Ошибки не показывались до нажатия: пустое имя, занятая папка и
//     несуществующий путь выяснялись только по факту.
//
// ЧТО СТАЛО. Два столбца: слева список недавних (главное действие), справа —
// то, что делают редко: создать и открыть. У каждого пути кнопка обзора, у
// нового проекта — предпросмотр итоговой папки и проверка ДО нажатия.
// ---------------------------------------------------------------------------
class LauncherPanel {
public:
    // Рисует окно. Возвращает true, пока окно нужно показывать.
    void Draw(EditorHost& host, RecentProjects& recent);

    bool Dismissed() const { return m_dismissed; }
    void Dismiss() { m_dismissed = true; } // headless-режимы (AUTOPLAY) скрывают hub

private:
    void DrawRecent(EditorHost& host, RecentProjects& recent, float width);
    void DrawCreate(EditorHost& host);
    void DrawOpen(EditorHost& host);
    // Почему новый проект создать нельзя (пусто — можно). Считается каждый
    // кадр: человек должен видеть препятствие, а не натыкаться на него.
    std::string CreateBlockedReason() const;

    char m_newName[128] = "MyGame";
    // Шаблон нового проекта (см. ProjectTemplates.h).
    std::string m_templateId = DefaultProjectTemplate();
    char m_newDir[512] = "";
    char m_openPath[512] = "";
    std::string m_error;
    bool m_dismissed = false; // «Работать без проекта»

    // Диалог обзора общий на оба поля: открыт он может быть только один, а
    // куда положить ответ — помнит указатель.
    FileBrowser m_browser;
    char* m_browseTarget = nullptr;
    size_t m_browseTargetSize = 0;
    // Выбирали файл проекта (тогда в поле кладём папку, а не .sageproj).
    bool m_browseIsProjectFile = false;
};
