#pragma once

class EditorHost;

// ---------------------------------------------------------------------------
// TopBar — верхняя панель БЫСТРОГО ДОСТУПА (не инструменты).
//
// ЧТО ЗДЕСЬ БЫЛО НЕ ТАК. Полоса под меню называлась «тулбаром» и мешала в себе
// две разные вещи: инструменты работы с объектом (гизмо, привязка, выравнивание,
// режим показа) и управление приложением (Play, окна). Инструменты нужны там,
// где ими работают, — во вьюпорте, под курсором; окна нужны везде и всегда.
// Собранные вместе, они мешали друг другу: строка переполнялась, блоки
// наезжали, а чтобы включить сетку, приходилось вести мышь через весь экран от
// объекта к верхнему краю.
//
// Теперь разделено по назначению:
//   • ЗДЕСЬ — Play/Pause/Stop и кнопки окон: Среда, Настройки игры, иерархия,
//     инспектор, ассеты, консоль, код, профайлер, вёрстка. То есть «что
//     показать» и «запустить/остановить».
//   • ИНСТРУМЕНТЫ — виджетом ПОВЕРХ вьюпорта (см. ViewportTools.cpp): гизмо,
//     привязка, пространство, показ сетки и габаритов, режим отрисовки,
//     раскладка видов.
//
// ОДНА СТРОКА, БЕЗ ЗАГОЛОВКОВ ГРУПП. Раньше над каждой группой стояла мелкая
// подпись — «Панели», «Настройки», «Виды», — и полоса была на самом деле
// ДВУХСТРОЧНОЙ. Высоты на две строки не хватало: подписи прижимались к верхнему
// краю и срезались, а кнопки вылезали снизу за панель. Объясняли они при этом
// немногое: что кнопка с солнцем открывает среду, видно из подсказки при
// наведении, а не из слова «Настройки» над ней.
//
// Теперь группы разделены тонкой чертой, всё стоит по центру строки, а место,
// которое занимали подписи, отдано самим кнопкам: полоса стала НИЖЕ и при этом
// просторнее внутри.
//
// Кнопка окна — ПЕРЕКЛЮЧАТЕЛЬ и подсвечена, когда окно открыто: по верхней
// панели видно состав рабочего места, а не только список того, что бывает.
//
// В узком окне сначала пропадают подписи у кнопок, потом имя сцены справа:
// лучше панель без слов, чем панель, у которой правый край уехал за экран
// вместе с кнопкой Play.
// ---------------------------------------------------------------------------
class TopBarPanel {
public:
    // Высота полосы. Здесь, а не константой в EditorLayer: высоту задаёт
    // содержимое панели, и знать её должна сама панель.
    //
    // ОДНА строка кнопок плюс поля. Было 54: панель держала ещё строку подписей
    // над кнопками, из-за которой подписи срезались краем, а кнопки вылезали
    // снизу. Подписей больше нет — см. TopBarPanel.cpp.
    static constexpr float kHeight = 40.0f;

    // Рисует полосу высотой height внутри текущего окна-хоста (child-регион).
    void Draw(EditorHost& host, float height);
};
