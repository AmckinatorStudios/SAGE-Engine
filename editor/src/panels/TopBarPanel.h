#pragma once

class EditorHost;

// ---------------------------------------------------------------------------
// TopBar — верхняя панель БЫСТРОГО ДОСТУПА (не инструменты).
//
// ЧТО ЗДЕСЬ БЫЛО НЕ ТАК. Полоса под меню называлась «тулбаром» и мешала в себе
// две разные вещи: инструменты работы с объектом (гизмо, привязка, выравнивание,
// режим показа) и управление приложением (Play, окна). Инструменты нужны там,
// где ими работают, — во вьюпорте, под курсором; окна нужны везде и всегда.
// Собранные вместе, они мешали друг другу: строка переполнялась, блоки
// наезжали, а чтобы включить сетку, приходилось вести мышь через весь экран от
// объекта к верхнему краю.
//
// Теперь разделено по назначению:
//   • ЗДЕСЬ — Play/Pause/Stop и кнопки окон: Environment, Game Settings,
//     иерархия, инспектор, ассеты, консоль, код, профайлер, вёрстка. То есть
//     «что показать» и «запустить/остановить».
//   • ИНСТРУМЕНТЫ — виджетом ПОВЕРХ вьюпорта (см. ViewportTools): гизмо,
//     привязка, пространство, показ сетки и габаритов, режим отрисовки,
//     раскладка видов.
//
// Кнопка окна — ПЕРЕКЛЮЧАТЕЛЬ и подсвечена, когда окно открыто: по верхней
// панели видно состав рабочего места, а не только список того, что бывает.
// ---------------------------------------------------------------------------
class TopBarPanel {
public:
    // Рисует полосу высотой height внутри текущего окна-хоста (child-регион).
    void Draw(EditorHost& host, float height);
};
