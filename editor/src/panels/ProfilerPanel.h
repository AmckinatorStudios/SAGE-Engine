#pragma once
#include <cstdint>

#include "sage/rhi/ResourceLedger.h"

namespace sage { class SystemScheduler; }

// ---------------------------------------------------------------------------
// Панель «Профилировщик» — то, чего у профилировщика не было: читателя.
//
// Механизм замеров (sage/core/Profiler.h) существовал целиком: метки времени
// GPU, отложенное чтение через три кадра, усреднение, честный отказ на
// драйвере без таймеров. Не существовало двух вещей — участков в кадре и
// того, кто показал бы результат. Поэтому SetEnabled(true) не вызывался НИ
// РАЗУ, и на вопрос «почему просело» ответить было нечем при полностью
// готовом для этого коде.
//
// Панель включает профилирование, ПОКА ОНА ОТКРЫТА, и выключает при закрытии:
// метки времени не бесплатны, и платить за них, когда на них никто не
// смотрит, незачем.
// ---------------------------------------------------------------------------
class ProfilerPanel {
public:
    // open — флаг видимости из меню Window; панель сама включает и выключает
    // профилировщик по нему.
    // systems — планировщик систем кадра (граф ECS на вкладке «Потоки»).
    void Draw(bool* open, sage::SystemScheduler* systems = nullptr);

private:
    void DrawFrameTab();
    // Вкладка «Потоки»: система задач — потоки, очереди, подсистемы, замки,
    // зависшие задачи, ошибки, шкала времени и граф систем кадра
    // (ProfilerPanel_Threads.cpp).
    void DrawThreadsTab(sage::SystemScheduler* systems);
    void DrawTimeline();

    // Пропускная способность — по разнице между кадрами панели.
    uint64_t m_lastCompleted = 0;
    double m_lastStatsMs = 0.0;
    double m_jobsPerSecond = 0.0;
    bool m_threadsTabOpen = false;
    bool m_timeline = true;
    float m_timelineWindowMs = 50.0f;

    // Показывать усреднённые значения, а не покадровые. По умолчанию да:
    // покадровые скачут на десятки процентов от планировщика ОС, и читать их
    // невозможно — цифра меняется быстрее, чем взгляд её схватывает.
    bool m_averaged = true;
    bool m_wasEnabled = false;

    // Сколько GPU-объектов было живо в момент открытия панели. Само по себе
    // число живых объектов ни о чём не говорит (их всегда несколько десятков),
    // а вот его РОСТ при неизменной сцене — это утечка, и увидеть её иначе
    // нечем: она не роняет программу и ничего не пишет в лог, а проявляется
    // через полчаса работы как «редактор начал тормозить и портить картинку».
    sage::rhi::ResourceCounts m_gpuBaseline;
    bool m_hasGpuBaseline = false;
};
