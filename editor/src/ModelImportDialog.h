#pragma once
#include <filesystem>
#include <functional>
#include <vector>

#include "sage/render/ModelLoader.h"

// ---------------------------------------------------------------------------
// Окно настроек импорта 3D-модели — ДО того, как модель попадёт в проект или в
// сцену.
//
// ЗАЧЕМ. Чужая модель почти никогда не встаёт «как надо» с первого раза: лежит
// на боку (Z вверх), в сто раз крупнее, вывернута наизнанку, листва квадратами,
// текстура вверх ногами. Всё это чинится настройками ассета (.sageimport, см.
// ModelLoader::ImportSettings), но раньше их можно было найти только в
// инспекторе — уже ПОСЛЕ того, как модель встала в сцену неправильно, и зная,
// что искать. Здесь их спрашивают в момент, когда модель впервые попадает в
// работу: при внесении в проект и при первой постановке в сцену.
//
// Спрашивается только у модели БЕЗ .sageimport: ответ пишется в сайдкар, и
// второй раз та же модель вопросов не задаёт. Панели зовут Ask, самопроверка
// и сценарии — нет (они ставят модели методами хоста напрямую).
// ---------------------------------------------------------------------------
namespace sage::editor::modelimport {

// Нужно ли спросить настройки: это модель, и настроек у неё ещё нет.
bool NeedsSettings(const std::filesystem::path& model);

// Показать окно для списка моделей. then — что сделать после подтверждения
// (поставить модель в сцену); при отмене не зовётся. Пустой список — then
// сразу.
void Ask(std::vector<std::filesystem::path> models, std::function<void()> then = {});

// Модели без настроек внутри файла или папки (рекурсивно) — то, о чём надо
// спросить после внесения в проект.
std::vector<std::filesystem::path> ModelsNeedingSettings(const std::filesystem::path& fileOrDir);

// Рисует окно (раз за кадр, на уровне окна-хоста).
void Draw();

// Открыто ли окно сейчас.
bool IsOpen();

// Виджеты настроек — те же в окне и в инспекторе модели. overwriteMaterials —
// «пересоздать материалы» (действие, а не настройка: в сайдкар не пишется);
// nullptr — не показывать. true — что-то поменяли.
bool DrawSettings(ModelLoader::ImportSettings& s, bool* overwriteMaterials);

} // namespace sage::editor::modelimport
